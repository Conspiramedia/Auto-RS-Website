'use client';

// ============================================================
// RS AUTO — Ссылка «Войти» в десктопной шапке.
// ============================================================
// Client Component по той же причине, что и useBadgeCounts: шапка
// рендерится сервером и попадает в кэш каталога и карточек
// (revalidate 300–3600). Чтение cookie сессии прямо в ней перевело бы
// КАЖДУЮ страницу сайта в динамический рендер — цена одной ссылки.
// Поэтому состояние сессии узнаётся в браузере, а сама шапка остаётся
// серверной и статичной.
//
// ПОКАЗЫВАЕТСЯ ТОЛЬКО ГОСТЮ. Вошедшему «Войти» в шапке — ошибка: он
// уже вошёл, и ссылка читалась бы как предложение сменить аккаунт.
// Его личные страницы живут в меню, там же и выход.
//
// ПОКА СЕССИЯ ПРОВЕРЯЕТСЯ (signedIn === null) не рисуем ничего:
// мелькнувшее «Войти» у вошедшего читается как разлогин. Место при
// этом не резервируем — ссылка стоит в ряду nav, и пустая колонка
// шириной в слово выглядела бы дырой в навигации.
//
// ТОЛЬКО ДЕСКТОП: на мобильном «Войти» уже есть первым пунктом
// бургер-меню, и второй вход в шапке отнимал бы место у CTA
// продавцу — единственного акцентного элемента.
//
// ?redirect= НЕ ПЕРЕДАЁТСЯ: ссылка стоит на любой странице сайта, и
// возвращать человека на страницу «О площадке» после входа
// бессмысленно. Без параметра AuthGate уводит в кабинет — туда, зачем
// в шапке и нажимают «Войти».
// ============================================================

import Link from 'next/link';

import type { Locale } from '@/lib/i18n';
import { getT, localeHref } from '@/lib/i18n';
import { useBadgeCounts } from '@/lib/useBadgeCounts';

export default function HeaderLoginLink({ locale }: { locale: Locale }) {
  const t = getT(locale);
  // Тот же хук, что питает бейдж меню: отдельная проверка сессии
  // означала бы второй запрос и возможность разойтись с меню в том,
  // вошёл человек или нет.
  const { signedIn } = useBadgeCounts();

  if (signedIn !== false) return null;

  return (
    <Link
      href={localeHref(locale, '/login')}
      className="whitespace-nowrap hover:underline"
    >
      {t('nav_login')}
    </Link>
  );
}
