'use client';

// ============================================================
// RS AUTO — Полоса владельца над витриной. Client Component.
// ============================================================
// Строка «Страница салона для покупателей» с крестиком, которая
// появляется на /dealer/{id} ТОЛЬКО У ХОЗЯИНА страницы. Оформлена так
// же, как заголовок кабинета (MyLayoutView): та же ступень заголовка,
// тот же крестик 44px справа, тот же вертикальный ритм.
//
// Продавец приходит сюда ИЗ РЕДАКТОРА (/my/showcase, кнопка «Страница
// салона для покупателей») — посмотреть, что получилось. Полоса
// говорит ему, что он смотрит публичный вид, а крестик возвращает к
// правке. Без неё это выглядело бы как выход неизвестно куда.
//
// ------------------------------------------------------------
// ПОЧЕМУ КЛИЕНТСКИЙ КОМПОНЕНТ, А НЕ ПРОВЕРКА НА СЕРВЕРЕ
// ------------------------------------------------------------
// Витрина кэшируется: revalidate = 300 в app/dealer/[id]/page.tsx.
// Кэш общий для всех посетителей — страница обязана быть одинаковой
// для покупателя и для краулера, ради SEO она и генерируется заранее.
//
// Прочитай мы сессию на сервере, произошло бы одно из двух: либо в
// кэш попал бы вариант ПЕРВОГО зашедшего (и посторонний увидел бы
// чужую надпись «Моя витрина» с крестиком), либо Next отключил бы
// кэширование целиком — витрина стала бы динамической и потеряла ту
// самую скорость, ради которой кэш и включён.
//
// Поэтому решение то же, что у ViewedBadge: серверная разметка
// остаётся общей и кэшируемой, а личная деталь дорисовывается в
// браузере после проверки сессии. До ответа Supabase полосы нет — это
// осознанно: мигание «пусто → полоса» дешевле, чем потеря кэша на
// публичной странице.
//
// SEO не затронуто: блок появляется после гидратации, в исходном HTML
// его нет, и краулер видит витрину ровно такой, какой она была.
// ============================================================

import { useEffect, useState } from 'react';

import MyCloseButton from '@/components/MyCloseButton';
import type { Locale } from '@/lib/i18n';
import { getT } from '@/lib/i18n';
import { getBrowserClient } from '@/lib/supabaseClient';

export default function DealerOwnerBar({
  locale,
  // Чей это профиль. Сравнивается с id вошедшего: совпало — страница
  // своя. Сравнение идёт в браузере, но подделка ничего не даёт —
  // блок носит навигационный характер и никаких данных не открывает.
  dealerId,
}: {
  locale: Locale;
  dealerId: string;
}) {
  const t = getT(locale);
  const [isOwner, setIsOwner] = useState(false);

  useEffect(() => {
    // Флаг отмены: пользователь может уйти со страницы раньше, чем
    // ответит Supabase, и setState на размонтированном компоненте
    // React встретит предупреждением.
    let cancelled = false;

    void (async () => {
      try {
        const supabase = getBrowserClient();
        const { data } = await supabase.auth.getUser();
        if (!cancelled) setIsOwner(data.user?.id === dealerId);
      } catch {
        // Сессии нет или сеть недоступна — значит посетитель не
        // владелец. Полосы просто не будет; сообщать здесь не о чем,
        // это не ошибка страницы.
      }
    })();

    return () => {
      cancelled = true;
    };
  }, [dealerId]);

  if (!isOwner) return null;

  return (
    // Разметка повторяет шапку кабинета (MyLayoutView): заголовок
    // слева, контролы справа, min-w-0 у h1 — при нехватке места
    // сжимается заголовок, а не кнопка, промахнуться по которой
    // нельзя.
    //
    // ЭТО НЕ h1. Главный заголовок страницы — название салона ниже, и
    // оно обязано им остаться: витрина индексируется, а два h1
    // ломают структуру документа. Здесь достаточно обычного текста
    // той же ступени — визуально одинаково, семантически честно.
    <div className="mb-4 flex items-center justify-between gap-x-4">
      <span className="min-w-0 truncate text-h2 font-bold sm:text-h1">
        {t('showcase_public')}
      </span>

      {/* Крестик ведёт В РЕДАКТОР ВИТРИНЫ, а не на главную, — этим он
          отличается от кабинетного, хотя выглядит так же. Владелец
          попадает на публичную страницу из редактора (кнопка
          «Страница салона для покупателей»), посмотреть результат, и
          «закрыть» для него значит вернуться к правке. Увод на
          главную выбросил бы его из кабинета целиком.

          -mr-2 втягивает область нажатия в боковой отступ страницы,
          чтобы сам знак встал на одну вертикаль с содержимым ниже. */}
      <MyCloseButton
        locale={locale}
        className="-mr-2"
        href="/my/showcase"
        labelKey="showcase_close"
      />
    </div>
  );
}
