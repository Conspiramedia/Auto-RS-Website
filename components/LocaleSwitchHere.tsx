'use client';

// ============================================================
// RS AUTO — Переключатель языка, знающий текущий адрес.
// ============================================================
// Обёртка над LocaleSwitch для случая, когда шапку рендерит НЕ страница,
// а layout. Такое место на сайте одно — кабинет /my (MyLayoutView).
//
// ЗАЧЕМ ОНА НУЖНА. LocaleSwitch собирает href из пропа pathname, и на
// остальных страницах его передаёт сама страница: она свой адрес знает
// («/about», «/car/{id}»). Layout же получает страницу через children и
// пропсов от неё не видит, поэтому в кабинете стояло захардкоженное
// '/my' — и смена языка с любого раздела кабинета выбрасывала в «Мои
// объявления», теряя открытый диалог.
//
// Тот же приём, что у MyTabs и MyHeaderBack в этом же каркасе: адрес
// берётся из usePathname, а не прокидывается сверху. Клиентский
// компонент здесь ничего не стоит — личные страницы noindex, и
// настоящие <a href> для краулера, ради которых LocaleSwitch сделан
// серверным, в кабинете не нужны.
//
// САМ LocaleSwitch ОСТАЁТСЯ СЕРВЕРНЫМ и не меняется: здесь только
// вычисление пути. Ссылки по-прежнему рисует он, поэтому переключение
// остаётся полным переходом браузера — это обязательное условие для
// cookie NEXT_LOCALE (см. комментарий в LocaleSwitch.tsx).
// ============================================================

import { usePathname } from 'next/navigation';

import LocaleSwitch from './LocaleSwitch';
import type { Locale } from '@/lib/i18n';
import { stripLocale } from '@/lib/i18n';

type Props = {
  locale: Locale;
};

export default function LocaleSwitchHere({ locale }: Props) {
  const pathname = usePathname();

  // Путь без префикса локали — ровно то, что ждёт LocaleSwitch: он
  // подставит префикс нужного языка сам. Со '/ru/my/messages/<id>'
  // получаем '/my/messages/<id>', то есть сегмент chatId сохраняется
  // как часть адреса, и после смены языка открытым остаётся тот же
  // диалог, а не список чатов.
  const { path } = stripLocale(pathname);

  return <LocaleSwitch locale={locale} pathname={path} />;
}
