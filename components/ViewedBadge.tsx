'use client';

// ============================================================
// RS AUTO — Метка «Просмотрено» на карточке объявления.
// ============================================================
// Показывает, что объявление уже открывали. В приложении такая метка
// есть с самого начала, и без неё лента на сайте ощущается иначе:
// в длинной выдаче человек повторно открывает то же объявление.
//
// ВИД: КРУГЛАЯ СИНЯЯ ПЛАШКА СО ЗНАЧКОМ ГЛАЗА, без подписи. Геометрия
// и цвет общие с остальными метками на фотографии (ui/RentBadge,
// ui/ConditionBadge с iconOnly): 24px, rounded-pill, значок 14px,
// обводка 2. Подробности решения — у самой разметки ниже.
//
// ПОЧЕМУ КЛИЕНТСКИЙ КОМПОНЕНТ. История просмотров живёт в localStorage
// браузера (RecentlyViewed) — сервер её не видит и увидеть не может.
// CarCard при этом остаётся Server Component: метка дорисовывается
// поверх фотографии уже после гидратации, разметка карточки и её
// серверный рендер не меняются, SEO не затрагивается.
//
// До гидратации метки нет — это осознанно. Мигание «пусто → метка»
// заметно меньше, чем блокировка рендера ради второстепенной пометки.
// ============================================================

import { useEffect, useState } from 'react';

import type { Locale } from '@/lib/i18n';
import { getT } from '@/lib/i18n';
import { isCarViewed } from './RecentlyViewed';

export default function ViewedBadge({
  locale,
  carId,
  className = '',
}: {
  locale: Locale;
  carId: string;
  // Позиционирование задаёт РОДИТЕЛЬ. Собственного absolute у метки
  // больше нет: она стоит в общем flex-ряду бейджей карточки, и
  // абсолютное позиционирование выдернуло бы её из потока — ровно то,
  // из-за чего она накладывалась на бейдж аренды на узких экранах.
  className?: string;
}) {
  const t = getT(locale);
  const [viewed, setViewed] = useState(false);

  useEffect(() => {
    setViewed(isCarViewed(carId));
  }, [carId]);

  if (!viewed) return null;

  return (
    // ЗНАЧОК ВМЕСТО СЛОВА. Раньше здесь стояла подпись «Просмотрено» /
    // «Pogledano» — слова длинные, и на карточке 360px (фото ~156px)
    // плашка занимала половину ряда бейджей либо уезжала на вторую
    // строку. Круг 24px не зависит от длины перевода и ведёт себя
    // одинаково в обеих локалях.
    //
    // ПОДЛОЖКА brand-blue, ТА ЖЕ, ЧТО У МЕТКИ АРЕНДЫ. Раньше здесь
    // стоял нейтральный тёмный (bg-neutral-60) — он остался от
    // текстовой плашки, где читался как «констатация, а не акцент».
    // На фотографии же тёмно-серый круг выглядел грязным пятном и
    // спорил с чёрными участками кадра, тогда как синий одинаково
    // читается и на светлом небе, и на тёмном асфальте.
    //
    // Общий цвет с арендой допустим: метки стоят в разных углах
    // (аренда слева, просмотрено справа), не встречаются вплотную, и
    // различать их по цвету не требуется — каждая объясняется своим
    // значком и подписью в aria-label.
    //
    // Компонент Badge не используется: его отступы (px-1.5 py-0.5) и
    // rounded-sm рассчитаны на текст, а под значок нужен ровный круг.
    //
    // shrink-0 — круг не должен сжиматься в овал, когда в ряду рядом
    // стоит метка аренды.
    //
    // aria-label на самой плашке: текста внутри больше нет, и без
    // подписи метка осталась бы доступна только зрячим. role="img"
    // объявляет её осмысленным элементом, а не декоративной точкой.
    <span
      role="img"
      aria-label={t('car_viewed')}
      className={`inline-flex h-6 w-6 shrink-0 items-center justify-center rounded-pill bg-brand-blue text-white ${className}`}
    >
      {/* Каркас тот же, что у остальных наборов значков проекта
          (ui/ConditionIcons, ui/MetricIcons, ui/NavIcons): viewBox 24,
          обводка 2, скруглённые концы и стыки. Значки из разных
          наборов встречаются на одном экране, и разная толщина линии
          сразу выдавала бы, что они нарисованы порознь.

          aria-hidden: подпись несёт родитель, и озвучивать значок
          отдельно значило бы прочитать метку дважды. */}
      <svg
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth={2}
        strokeLinecap="round"
        strokeLinejoin="round"
        aria-hidden="true"
        className="h-3.5 w-3.5"
      >
        <path d="M2 12s3.6-7 10-7 10 7 10 7-3.6 7-10 7-10-7-10-7Z" />
        <circle cx="12" cy="12" r="3" />
      </svg>
    </span>
  );
}
