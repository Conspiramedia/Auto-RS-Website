// ============================================================
// RS AUTO — Метка «VIP» продвигаемого объявления.
// ============================================================
// Заменила текстовый бейдж тона promoted (золотая заливка + подпись
// «Продвигается» / «Izdvojeno»).
//
// ПОЧЕМУ КОРОНА И ЛАТИНСКОЕ «VIP». Прежняя подпись описывала
// МЕХАНИКУ площадки («объявление продвигается»), а не выгоду для
// смотрящего, и была длинной: на плитке 360px фотография выходит
// ~156px, и слово «Продвигается» занимало её половину. «VIP» читается
// одинаково в обеих локалях — латиница в сербском родная, в русском
// заимствование давно устоялось, — поэтому подпись НЕ переводится и
// не заводится ключом в словаре. Корона даёт узнавание раньше, чем
// прочитано слово.
//
// ПОЧЕМУ ТЁМНАЯ КАПСУЛА, А НЕ ЗОЛОТАЯ ЗАЛИВКА. Золотой на белой
// карточке — светлый цвет, и белый текст по нему держался на грани
// читаемости. Здесь роли развёрнуты: тёмный фон brand-dark, золото
// (brand-gold) отдано короне и буквам. Контраст вырос, а цвет роли
// сохранён — VIP по-прежнему опознаётся золотым, как и раньше.
//
// ПАЛИТРА — токены бренда: bg-brand-dark (#2B2B2E) и text-brand-gold
// (#E8A73C). Исходный макет предлагал #0f172a и #f59e0b; заводить
// ради одной метки второй тёмный и второй золотой в палитру не стали.
//
// ГЕОМЕТРИЯ. rounded-pill и высота 24px — общий контракт бейджей на
// фотографии (ui/RentBadge, ui/ViewedBadge, ui/ConditionBadge с
// iconOnly). Соседи по кадру — круги 24px, и метка обязана стоять с
// ними на одной линии.
// ============================================================

type Props = {
  // Размер по месту, где метка стоит:
  //   sm — поверх фотографии в каталоге и рядом с заголовком в
  //        кабинете. Высота 24px — та же, что у соседних кругов;
  //   md — страница объявления: там метка не пометка поверх кадра,
  //        а сообщение, и мельче читается как случайный ярлык.
  size?: 'sm' | 'md';
  // Позиционирование задаёт РОДИТЕЛЬ: метка стоит в общем flex-ряду
  // бейджей карточки, собственного absolute у неё нет.
  className?: string;
};

const SIZES = {
  sm: { box: 'h-6 gap-1 px-2', icon: 'h-3.5 w-3.5', text: 'text-micro' },
  md: { box: 'h-7 gap-1.5 px-2.5', icon: 'h-4 w-4', text: 'text-small' },
} as const;

export default function VipBadge({ size = 'sm', className = '' }: Props) {
  const s = SIZES[size];

  return (
    <span
      role="img"
      // Подпись «VIP» нарисована текстом и читается скринридером сама,
      // но без aria-label он озвучил бы три буквы порознь («в-и-пи»).
      aria-label="VIP"
      title="VIP"
      className={`inline-flex shrink-0 items-center rounded-pill bg-brand-dark text-brand-gold ${s.box} ${className}`}
    >
      {/* Корона. Заливка, а не обводка: на 14px контурный значок с
          толщиной 2 сливается в пятно, а сплошной силуэт остаётся
          короной. Пять зубцов на общей подошве — форма из макета. */}
      <svg
        viewBox="0 0 24 24"
        fill="currentColor"
        aria-hidden="true"
        className={s.icon}
      >
        <path d="M3 18.5h18v2H3z" />
        <path d="M2.6 6.2l4.1 3.4 4.2-6.1a1.3 1.3 0 0 1 2.2 0l4.2 6.1 4.1-3.4a1 1 0 0 1 1.6 1l-2.1 8.3H3.1L1 7.2a1 1 0 0 1 1.6-1z" />
      </svg>

      {/* tracking-wide повторяет letter-spacing макета: три заглавные
          подряд без разрядки читаются как слипшийся блок. */}
      <span className={`font-bold leading-none tracking-wide ${s.text}`}>
        VIP
      </span>
    </span>
  );
}
