// ============================================================
// RS AUTO — Бейдж состояния объявления.
// ============================================================
// Небольшая плашка поверх фотографии или рядом с заголовком. Роли
// закреплены за цветами и менять их произвольно нельзя — пользователь
// узнаёт статус по цвету раньше, чем читает слово:
//   promoted — золотой, продвигаемое объявление (VIP);
//   rent     — синий, аренда в смешанном фиде;
//   sold     — зелёный, продано;
//   new      — зелёный, зарезервирован под «новое поступление».
//
// СТАТУСЫ ОБЪЯВЛЕНИЯ В КАБИНЕТЕ (компонент StatusBadge) используют
// семантические тона ниже. Они названы по РОЛИ, а не по цвету:
//   warning       — на проверке;
//   success-soft  — опубликовано;
//   error         — отклонено;
//   success       — продано;
//   neutral       — в архиве.
//
// ПОЧЕМУ ПРОДАНО ЗЕЛЁНОЕ. Раньше оно было красным поверх фотографии и
// тёмным в кабинете — оба цвета читаются как проблема. Продажа —
// результат, ради которого объявление и подавали, то есть хорошая
// новость, и цвет обязан говорить то же самое.
//
// ПОЧЕМУ «ОПУБЛИКОВАНО» СТАЛО СВЕТЛЫМ. Зелёный в палитре один
// (#22C063), и две сплошные зелёные плашки в одном списке стали бы
// неразличимы по цвету. Поэтому завершённая сделка получает сплошную
// заливку — она сильнее, а идущая публикация — ту же зелень
// разбавленной (10%) с зелёным текстом: цвет тот же, вес разный.
//
// Радиус sm, а не control: на плашке высотой ~24px радиус 12 превращает
// её в капсулу, а нужен прямоугольник со скруглением.
//
// РАЗМЕРЫ — по месту, где плашка стоит, а не по вкусу:
//   xs — поверх фотографии в плитке каталога. Ступень micro (11px):
//        карточка на 360px узкая, и плашка обязана оставлять видимой
//        саму фотографию.
//   sm — рядом с текстом: статусы в кабинете, промо в списке владельца.
//   md — ключевой факт об объявлении на его собственной странице
//        («Продано»). Там плашка не пометка поверх кадра, а сообщение,
//        и мельче она читается как случайный ярлык.
// ============================================================

import type { ReactNode } from 'react';

type Tone =
  | 'promoted'
  | 'rent'
  | 'sold'
  | 'new'
  | 'warning'
  | 'success'
  | 'success-soft'
  | 'error'
  | 'dark'
  | 'neutral'
  // Информационная плашка: факт о состоянии, а не оценка. Плашка
  // «ваше устройство» на /install.
  | 'info-soft'
  // Личная метка посетителя «Просмотрено». Нейтральная тёмная плашка:
  // это констатация, а не акцент, и спорить с промо и арендой она не
  // должна.
  | 'viewed';

type Size = 'xs' | 'sm' | 'md';

const TONES: Record<Tone, string> = {
  promoted: 'bg-brand-gold text-white',
  rent: 'bg-brand-blue text-white',
  sold: 'bg-brand-green text-white',
  new: 'bg-brand-green text-white',
  // Статусы объявления в кабинете.
  warning: 'bg-warning text-white',
  success: 'bg-success text-white',
  // Разбавленная зелень с зелёным текстом — та же пара, что у Alert
  // тона success: единая трактовка «зелёный на своём светлом фоне».
  'success-soft': 'bg-status-success text-brand-green',
  // Разбавленный primary с primary-текстом — та же пара, что у
  // success-soft: цвет на своей светлой подложке.
  'info-soft': 'bg-status-info text-brand-primary',
  error: 'bg-error text-white',
  dark: 'bg-brand-dark text-white',
  // Архив — единственный тон без заливки: архивное объявление не
  // требует внимания, и цветная плашка тянула бы взгляд туда, где
  // ничего делать не нужно.
  neutral: 'bg-surface-muted text-neutral-60',
  viewed: 'bg-neutral-60 text-white',
};

const SIZES: Record<Size, string> = {
  xs: 'px-1.5 py-0.5 text-micro',
  sm: 'px-2 py-1 text-small',
  md: 'px-3 py-1 text-caption',
};

type Props = {
  tone: Tone;
  size?: Size;
  children: ReactNode;
  className?: string;
};

export default function Badge({
  tone,
  size = 'sm',
  children,
  className = '',
}: Props) {
  return (
    <span
      className={`inline-flex items-center rounded-sm font-semibold ${SIZES[size]} ${TONES[tone]} ${className}`}
    >
      {children}
    </span>
  );
}
