// ============================================================
// RS AUTO — Логотип. ЕДИНСТВЕННОЕ место сборки знака.
// ============================================================
// Вариант mark — квадратный фирменный знак для тесных мест: смарт-баннер,
// аватар-заглушка. Рисуется тем же PNG, что уходит в favicon, PWA-иконку
// и на домашний экран приложения (public/icon-192.png), — знак в баннере
// обязан совпадать с иконкой, которую пользователь увидит после установки.
// Раньше здесь были буквы «RS» на синем квадрате, и баннер обещал не ту
// иконку, что стояла в сторе.
//
// Вариант full — название целиком (векторного логотипа-надписи у проекта
// пока нет; когда дизайнер отдаст файл, заменить надо только эту ветку).
// ============================================================

import Image from 'next/image';

import { brand } from '@/lib/brand';

type Props = {
  // full — название целиком (шапка, подвал);
  // mark — квадратный знак (смарт-баннер).
  variant?: 'full' | 'mark';
  // Инвертированный знак для тёмного фона (баннер, тёмная плашка).
  inverted?: boolean;
  className?: string;
};

export default function Logo({
  variant = 'full',
  inverted = false,
  className = '',
}: Props) {
  if (variant === 'mark') {
    return (
      // Размер 36px (h-9) — как было у текстового знака, чтобы высота
      // баннера не поехала. sizes не нужен: размер фиксированный.
      <Image
        src="/icon-192.png"
        alt={brand.name}
        width={36}
        height={36}
        className={`h-9 w-9 shrink-0 rounded-control ${className}`}
      />
    );
  }

  return (
    <span
      className={`shrink-0 font-bold ${className}`}
      // На тёмном фоне брендовый синий читается плохо, поэтому там
      // знак белый. Цвет берётся из токенов, а не из класса Tailwind:
      // при замене на SVG эта ветка уйдёт целиком.
      style={{ color: inverted ? '#FFFFFF' : brand.colors.primary }}
    >
      {brand.name}
    </span>
  );
}
