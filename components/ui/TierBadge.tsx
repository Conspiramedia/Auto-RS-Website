// ЧЕМ ОТЛИЧАЕТСЯ ОТ ui/VipBadge. Корона «VIP» означает «за ЭТО
// ОБЪЯВЛЕНИЕ заплатили» и живёт поверх фотографии. Эта плашка
// означает «ЭТОТ ПРОДАВЕЦ давно и честно работает» и стоит у его
// имени. Оси независимы: платное продвижение покупает кто угодно,
// уровень зарабатывается объявлениями и продажами.
//
// ПОЧЕМУ НЕ КОРОНА И ПОЧЕМУ НЕ В КАТАЛОГЕ. На странице объявления обе
// метки могут встретиться, и вторая корона читалась бы как удвоение
// первой. Поэтому здесь другой значок (щит — «проверено, надёжно») и
// другое место в макете. В каталоге плашки нет вовсе: на плитке 360px
// имя продавца и так теряется, а рядом с золотой короной вторая
// золотая метка сбивала бы с толку сильнее, чем помогала.
//
// ПАЛИТРА — те же токены brand.vip, что у короны, новых констант не
// заведено. Совпадение намеренное: бронза, серебро и золото читаются
// как призовые места до всякого объяснения правил, и разводить для
// них два набора металла значило бы придумать второй язык там, где
// работает первый.
//
// ПОДПИСЬ ОБЯЗАТЕЛЬНА. У короны подпись «VIP» одинакова в обеих
// локалях, а здесь смысл несёт именно текст: цвет металла сам по себе
// не объясняет, чем надёжный продавец отличается от активного. Цвет —
// не единственный носитель смысла (WCAG 1.4.1).
//
// УРОВЕНЬ 0 ПЛАШКИ НЕ ПОЛУЧАЕТ — компонент возвращает null. Это
// состояние по умолчанию у большинства профилей, и метка «без уровня»
// была бы шумом, да ещё и обидным.
// ============================================================

import type { Locale } from '@/lib/i18n';
import { getT } from '@/lib/i18n';
import type { DictKey } from '@/lib/i18n';
import type { SellerTier } from '@/lib/types';

type Size = 'sm' | 'md';

const SIZES: Record<Size, { box: string; icon: string; text: string }> = {
  // sm — шапка чата и витрина: плашка стоит в строке с именем.
  sm: { box: 'h-6 gap-1 px-2', icon: 'h-3.5 w-3.5', text: 'text-micro' },
  // md — страница объявления: там уровень не пометка, а довод в
  // пользу продавца, и мельче читается как случайный ярлык.
  md: { box: 'h-7 gap-1.5 px-2.5', icon: 'h-4 w-4', text: 'text-small' },
};

// Металл ступени. Подложка общая (bg-vip-surface) — три плашки
// обязаны читаться как один ряд, а не как три разные сущности.
const METAL: Record<Exclude<SellerTier, 0>, string> = {
  1: 'text-vip-bronze',
  2: 'text-vip-silver',
  3: 'text-vip-gold',
};

type Props = {
  locale: Locale;
  tier: SellerTier | null | undefined;
  // Салон или частник. Влияет ТОЛЬКО на подпись золота: салону оно
  // достаётся за проверенную компанию, частнику — за объём и продажи,
  // и обещать покупателю проверенную компанию там, где компании нет,
  // нельзя.
  isDealer?: boolean;
  size?: Size;
  className?: string;
};

// Подпись ступени. Вынесена из разметки: её же использует title,
// и две копии условия разошлись бы при первой правке.
export function tierLabelKey(tier: SellerTier, isDealer: boolean): DictKey {
  if (tier === 3) return isDealer ? 'tier_gold_dealer' : 'tier_gold_private';
  if (tier === 2) return 'tier_silver';
  return 'tier_bronze';
}

export default function TierBadge({
  locale,
  tier,
  isDealer = false,
  size = 'sm',
  className = '',
}: Props) {
  if (tier !== 1 && tier !== 2 && tier !== 3) return null;

  const t = getT(locale);
  const s = SIZES[size];
  const label = t(tierLabelKey(tier, isDealer));

  return (
    <span
      // role="img" с aria-label: значок и подпись вместе образуют одну
      // смысловую единицу, и скринридер должен прочитать её целиком, а
      // не «щит, активный продавец».
      role="img"
      aria-label={label}
      title={label}
      className={`inline-flex shrink-0 items-center rounded-pill bg-vip-surface ${METAL[tier]} ${s.box} ${className}`}
    >
      {/* Щит с галочкой — «проверено». Заливка, а не обводка: на 14px
          контурный значок сливается в пятно. Форма намеренно НЕ
          корона: корона занята платным продвижением. */}
      <svg
        viewBox="0 0 24 24"
        fill="currentColor"
        aria-hidden="true"
        className={s.icon}
      >
        <path d="M12 2.2l7.5 3v6.1c0 4.6-3.1 8.7-7.5 10.5-4.4-1.8-7.5-5.9-7.5-10.5V5.2l7.5-3zm3.8 6.6l-1.5-1.4-3.6 3.9-1.9-1.8-1.4 1.5 3.4 3.2 5-5.4z" />
      </svg>

      <span className={`font-semibold leading-none ${s.text}`}>{label}</span>
    </span>
  );
}
