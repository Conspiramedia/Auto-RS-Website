// ============================================================
// RS AUTO — Переключатель (Switch).
// ============================================================
// Общий контрол для настроек с двумя состояниями. Первым потребителем
// стал переключатель писем о новых сообщениях в профиле, но компонент
// намеренно не знает ничего про почту: настройки в кабинете будут
// появляться и дальше, а второй такой же переключатель, собранный
// по месту из div-ов, разъехался бы с этим по размеру и поведению.
//
// ПОЧЕМУ НЕ <input type="checkbox"> СО СТИЛЯМИ, А КНОПКА.
// Нативный чекбокс невозможно оформить как «дорожку с бегунком» без
// appearance:none и подпорок под каждый браузер, а его собственная
// семантика (checked) для настройки-переключателя менее точна, чем
// role="switch": скринридер называет состояние «включено/выключено»,
// а не «отмечено». Кнопка с aria-checked даёт правильное объявление
// и полностью управляемый вид.
//
// ДОСТУПНОСТЬ. role="switch" + aria-checked обязательны — без них
// контрол читается как обычная кнопка без состояния. Подпись связана
// с кнопкой через aria-labelledby, пояснение — через aria-describedby:
// скринридер называет, что именно включается, а не просто «переключатель».
// ============================================================

'use client';

import { useId } from 'react';

type Props = {
  checked: boolean;
  onChange: (next: boolean) => void;
  // Подпись слева от переключателя. Обязательна: контрол без подписи
  // не читается ни глазами, ни скринридером.
  label: string;
  // Пояснение под подписью: что именно перестанет приходить.
  description?: string;
  // Блокировка на время сохранения. Отдельного состояния «сохраняется»
  // у контрола нет: мигание индикатора в настройке, которая
  // применяется мгновенно, отвлекает сильнее, чем помогает.
  disabled?: boolean;
};

export default function Switch({
  checked,
  onChange,
  label,
  description,
  disabled = false,
}: Props) {
  const labelId = useId();
  const descId = useId();

  return (
    <div className="flex items-start justify-between gap-4">
      <div className="min-w-0">
        <div id={labelId} className="text-body text-neutral-80">
          {label}
        </div>
        {description ? (
          <p id={descId} className="mt-0.5 text-small text-neutral-50">
            {description}
          </p>
        ) : null}
      </div>

      {/* type="button" обязателен: контрол живёт внутри <form> профиля,
          и кнопка по умолчанию отправила бы форму при каждом клике.

          РАЗМЕРЫ ВЗЯТЫ ИЗ iOS: дорожка 51×31pt, бегунок 27pt с зазором
          2pt по кругу. Это не подражание ради подражания — у системного
          переключателя бегунок занимает почти всю высоту дорожки, и
          именно по этой пропорции контрол читается как переключатель, а
          не как индикатор загрузки. Прежние 44×24 с бегунком 20 давали
          заметный «воротник» пустой дорожки сверху и снизу.

          ЦВЕТ ВКЛЮЧЁННОГО — brand-green, а не brand-primary. Синий у нас
          занят действиями (кнопки, ссылки), а зелёный на переключателе
          означает ровно одно: «включено». Тот же цвет, что у iOS, и он
          уже есть в палитре бренда.

          -mt-1 ПРИ items-start: дорожка (31px) выше строки подписи
          (24px), и без компенсации переключатель выпирал бы над
          текстом. Тянуть его вниз к описанию нельзя — привязан он
          к подписи, а описание бывает и в две строки. */}
      <button
        type="button"
        role="switch"
        aria-checked={checked}
        aria-labelledby={labelId}
        aria-describedby={description ? descId : undefined}
        disabled={disabled}
        onClick={() => onChange(!checked)}
        className={`relative -mt-1 h-[31px] w-[51px] shrink-0 rounded-pill transition-colors duration-fast ease-out disabled:cursor-not-allowed disabled:opacity-40 ${
          checked ? 'bg-brand-green' : 'bg-neutral-15'
        }`}
      >
        {/* Бегунок. translate-x вместо left: анимация трансформацией не
            вызывает пересчёт раскладки на каждом кадре.

            Тень — двойная, как у системной: широкая мягкая даёт объём,
            узкая плотная у самого края отделяет белый круг от светло-
            серой дорожки в выключенном состоянии. Одной тенью это не
            получается: мягкая на светлом фоне не видна, а плотная без
            мягкой выглядит наклейкой. */}
        <span
          className={`absolute left-0.5 top-0.5 h-[27px] w-[27px] rounded-pill bg-white transition-transform duration-fast ease-out ${
            checked ? 'translate-x-5' : 'translate-x-0'
          }`}
          style={{
            boxShadow:
              '0 3px 8px rgba(0,0,0,0.15), 0 1px 1px rgba(0,0,0,0.16)',
          }}
        />
      </button>
    </div>
  );
}
