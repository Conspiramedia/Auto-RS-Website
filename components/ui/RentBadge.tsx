// аренды метка не нужна: все объявления там одного типа.
//
// ЗНАЧОК ВМЕСТО СЛОВА. Раньше здесь стоял бейдж с подписью «Аренда» /
// «Izdavanje». На карточке 360px фотография выходит ~156px, и три
// подписи в углах (аренда, просмотрено, состояние) занимали её
// заметную часть. Календарь читается как «посуточно» без перевода и
// одинаков в обеих локалях, где сербское «Izdavanje» заметно длиннее
// русского.
//
// ГЕОМЕТРИЯ ОБЩАЯ С СОСЕДЯМИ — 24px, rounded-pill, значок 14px,
// обводка 2 (ui/ViewedBadge, ui/ConditionBadge с iconOnly). На одном
// кадре стоят до трёх таких кругов, и разный размер или скругление
// сразу выдали бы, что они рисовались порознь.
//
// ЦВЕТ — brand-blue, тот же, что был у бейджа тоном rent: синий за
// арендой закреплён и в приложении, и на сайте, и менять его вместе
// с формой значило бы менять две вещи разом.
//
// Подпись уходит в aria-label и title: значок календаря сам по себе
// не обязан читаться как «аренда», а для скринридера метка вообще
// осталась бы пустой.
// ============================================================

import type { Locale } from '@/lib/i18n';
import { getT } from '@/lib/i18n';

export default function RentBadge({
  locale,
  className = '',
}: {
  locale: Locale;
  // Позиционирование задаёт РОДИТЕЛЬ: метка стоит в общем flex-ряду
  // бейджей карточки, и собственного absolute у неё нет.
  className?: string;
}) {
  const label = getT(locale)('badge_rent');

  return (
    <span
      role="img"
      aria-label={label}
      title={label}
      className={`inline-flex h-6 w-6 shrink-0 items-center justify-center rounded-pill bg-brand-blue text-white ${className}`}
    >
      {/* Calendar из lucide. aria-hidden: подпись несёт родитель, и
          озвучивать значок отдельно значило бы прочитать метку
          дважды. */}
      <svg
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth={2}
        strokeLinecap="round"
        strokeLinejoin="round"
        aria-hidden="true"
        className="h-3.5 w-3.5"
      >
        <path d="M8 2v4" />
        <path d="M16 2v4" />
        <rect width="18" height="18" x="3" y="4" rx="2" />
        <path d="M3 10h18" />
      </svg>
    </span>
  );
}
