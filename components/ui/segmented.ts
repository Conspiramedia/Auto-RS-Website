// ============================================================
// Форма подачи держит три таких селектора подряд: тип объявления
// («Продаю / Сдаю»), доступность у салона и состояние автомобиля.
// Раньше каждый нёс свою копию классов, и выбранный вариант заливался
// тёмным (bg-brand-dark).
//
// ПОЧЕМУ УШЛИ ОТ ТЁМНОЙ ЗАЛИВКИ. На двух-трёх коротких вариантах она
// читалась нормально, но у состояния вариантов шесть, и подписи у них
// длинные — сетка превращалась в чёрные плашки во всю ширину шага.
// Хуже того, тёмным заливался и вариант ПО УМОЛЧАНИЮ («Обычное авто»):
// умолчание кричало громче всех остальных, хотя сообщать ему нечего.
//
// ЧТО ВМЕСТО. Рамка 1.5px акцентным цветом и его же подложка — ровно
// тот приём, которым сайт уже подсвечивает выбор в двух местах:
//   * ui/InstallGuide — карточка «ваше устройство»;
//   * admin/ModerationGallery — выбранное фото.
// Новой сущности в дизайн-системе не появляется, а выбранный вариант
// читается мгновенно, не перетягивая на себя вес всего экрана.
//
// Рамка задана точным значением 1.5px: у Tailwind между border (1px) и
// border-2 промежутка нет, а 2px на кнопке высотой 42px уже грубит.
// Невыбранные варианты держат border 1px — толщина меняется вместе с
// цветом, поэтому кнопка не «прыгает» на пиксель при выборе:
// компенсируем разницу padding'ом (py-[9px] против py-2.5).
// ============================================================

// Общая часть: геометрия и поведение, одинаковые у всех состояний.
const BASE =
  'rounded-control px-3 text-caption transition-colors duration-fast ease-out';

// Выбранный вариант.
export const SEGMENTED_ACTIVE = `${BASE} border-[1.5px] border-brand-primary bg-brand-primary/[0.08] py-[9px] font-semibold text-brand-primary`;

// Невыбранный: нейтральная рамка, отклик на наведение.
export const SEGMENTED_IDLE = `${BASE} border border-neutral-15 py-2.5 text-neutral-75 hover:border-neutral-30 hover:bg-surface-hover`;

// Готовый класс по признаку выбора — чтобы в разметке не повторялся
// один и тот же тернарник.
export function segmentedClass(active: boolean): string {
  return active ? SEGMENTED_ACTIVE : SEGMENTED_IDLE;
}
