// ------------------------------------------------------------
// ДВЕ ФОРМЫ ОДНОГО ПРИЁМА
// ------------------------------------------------------------
// selectedClass() — для элементов, у которых НЕТ рамки в невыбранном
//   состоянии: вкладки, сортировка, язык, пагинация. Рамка появляется
//   вместе с выбором, поэтому её ширина берётся обычная (1px), а
//   геометрию держит сам вызывающий.
//
// segmentedClass() — для СЕТКИ РАВНЫХ КНОПОК, где рамка есть всегда
//   (форма подачи, причины отклонения). Там выбранная рамка толще
//   (1.5px), иначе разница между «выбрано» и «не выбрано» теряется
//   среди соседних контуров. Разница толщин компенсируется
//   padding'ом, чтобы кнопка не прыгала на пиксель при выборе:
//   у Tailwind между border (1px) и border-2 промежутка нет.
// ============================================================

// ------------------------------------------------------------
// Форма 1: элемент без постоянной рамки.
// ------------------------------------------------------------
// Геометрия (padding, размер шрифта, скругление) НЕ задаётся здесь:
// вкладка кабинета, номер страницы и чипс сортировки имеют разные
// размеры, и навязывать им общий вид значило бы ломать вёрстку ради
// единообразия цвета. Отсюда — только цвет и рамка.
export const SELECTED =
  'border border-selection bg-selection-surface font-semibold text-selection';

// Невыбранный вариант той же группы. Прозрачная рамка того же
// размера — чтобы элемент не менял ширину при выборе.
export const UNSELECTED =
  'border border-transparent text-neutral-60 hover:bg-surface-hover';

export function selectedClass(active: boolean): string {
  return active ? SELECTED : UNSELECTED;
}

// ------------------------------------------------------------
// Форма 2: сетка равных кнопок с постоянной рамкой.
// ------------------------------------------------------------
const SEGMENTED_BASE =
  'rounded-control px-3 text-caption transition-colors duration-fast ease-out';

export const SEGMENTED_ACTIVE = `${SEGMENTED_BASE} border-[1.5px] border-selection bg-selection-surface py-[9px] font-semibold text-selection`;

export const SEGMENTED_IDLE = `${SEGMENTED_BASE} border border-neutral-15 py-2.5 text-neutral-75 hover:border-neutral-30 hover:bg-surface-hover`;

export function segmentedClass(active: boolean): string {
  return active ? SEGMENTED_ACTIVE : SEGMENTED_IDLE;
}
