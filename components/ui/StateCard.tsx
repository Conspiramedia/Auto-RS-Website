// ============================================================
// RS AUTO — Пустое состояние и состояние ошибки. Один компонент.
// ============================================================
// До этого паттерн «карточка + крупный вертикальный отступ + заголовок
// + пояснение + действия» был скопирован в восьми местах, и заголовки
// в копиях разъехались по ступеням шкалы: text-h3 в каталоге и text-h4
// во всех разделах кабинета. Одна и та же по смыслу карточка выглядела
// на соседних вкладках по-разному.
//
// ДВА РЕЖИМА, потому что это два разных сообщения:
//   empty — «здесь пока ничего нет». Штатное состояние: ни диалогов,
//           ни объявлений у нового продавца просто ещё не появилось.
//   error — «не удалось загрузить». Сбой, и у него ОБЯЗАНО быть
//           действие: раньше ошибка RPC рисовалась голым абзацем без
//           заголовка и без выхода — тупик посреди кабинета.
//
// Заголовок — ступень h3 во всех режимах: карточка занимает весь блок
// содержимого и по весу равна секции страницы, а не подблоку.
//
// ДЕЙСТВИЯ передаются пропсами, а не зашиты внутрь: у пустого каталога
// это «Сбросить фильтры», у пустого кабинета — «Подать объявление», у
// уведомлений действия нет вовсе (они приходят сами, звать некуда).
// Режим error свои кнопки собирает сам — они одинаковы везде.
// ============================================================

import type { ReactNode } from 'react';

import Button from './Button';
import Card from './Card';
import type { Locale } from '@/lib/i18n';
import { getT, localeHref } from '@/lib/i18n';

type Props = {
  locale: Locale;
  // 'error' подставляет собственные заголовок, текст и действия —
  // сообщение о сбое одинаково на всех экранах, и расписывать его
  // на каждой странице заново значит снова получить восемь копий.
  variant?: 'empty' | 'error';
  // Заголовок и пояснение для режима empty.
  title?: string;
  text?: string;
  // Действия под текстом: кнопки, ссылки. В режиме error игнорируются.
  actions?: ReactNode;
  // Куда ведёт «Повторить» в режиме error — путь БЕЗ префикса локали.
  // По умолчанию корень кабинета. Передаётся тем разделом, который
  // упал: повтор на вкладке диалогов обязан вернуть в диалоги, а не
  // выбросить в список объявлений.
  retryPath?: string;
  // Подпись под кнопками мелким шрифтом (пояснение к действию).
  hint?: string;
  className?: string;
};

export default function StateCard({
  locale,
  variant = 'empty',
  title,
  text,
  actions,
  retryPath = '/my',
  hint,
  className = '',
}: Props) {
  const t = getT(locale);
  const isError = variant === 'error';

  return (
    // padding="none" с собственным px-6 py-12: у этой карточки свой
    // крупный вертикальный отступ — она единственный блок на экране и
    // должна дышать сильнее обычной карточки формы.
    <Card padding="none" className={`px-6 py-12 text-center ${className}`}>
      <h2 className="text-h3 font-semibold">
        {isError ? t('err_title') : title}
      </h2>

      <p className="mx-auto mt-2 max-w-md text-neutral-60">
        {isError ? t('my_action_error') : text}
      </p>

      {isError ? (
        // «Повторить» — обычная ссылка на текущий раздел, а не кнопка
        // с обработчиком: страницы кабинета серверные, и повтор для
        // них означает повторный запрос страницы. Клиентский reset
        // потребовал бы делать компонент клиентским ради одной кнопки.
        <div className="mt-6 inline-grid grid-cols-1 gap-3 sm:flex sm:flex-row sm:items-center sm:justify-center">
          <Button size="sm" href={localeHref(locale, retryPath)}>
            {t('err_retry')}
          </Button>
          <Button
            variant="secondary"
            size="sm"
            href={localeHref(locale, '/cars')}
          >
            {t('nav_catalog')}
          </Button>
        </div>
      ) : (
        actions && (
          <div className="mt-6 flex flex-wrap items-center justify-center gap-3">
            {actions}
          </div>
        )
      )}

      {hint && (
        <p className="mx-auto mt-3 max-w-md text-caption text-neutral-50">
          {hint}
        </p>
      )}
    </Card>
  );
}
