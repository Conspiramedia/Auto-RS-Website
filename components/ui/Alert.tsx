// ============================================================
// RS AUTO — Статусное сообщение под формой или в карточке.
// ============================================================
// Плашка «не получилось / получилось»: цветной текст на его же сильно
// разбавленной заливке. Набор классов «rounded-control bg-brand-red/10
// px-3 py-2 text-caption text-brand-red» был скопирован в двенадцать
// мест — во все формы сайта, в чат, в действия над объявлением и в
// причину отклонения модератором. Любая правка вида сообщения
// означала двенадцать одинаковых изменений, и заливки при этом уже
// жили хардкодом прозрачности в обход шкалы бренда.
//
// ТОНЫ названы по исходу действия, а не по цвету: в разметке должно
// читаться намерение (tone="error"), а не оттенок.
//   error   — действие не удалось: сеть, валидация, отказ сервера.
//             Сюда же причина отклонения модератором — для продавца
//             это то, что нужно исправить.
//   success — действие удалось: профиль сохранён, код отправлен.
//   warning — не ошибка, но требует внимания. Тон заведён для
//             полноты семантики (error/success/warning — один набор
//             с ролями Badge и semantic в lib/brand.ts).
//
// ЭТО НЕ ПУСТОЕ СОСТОЯНИЕ. StateCard занимает весь блок содержимого и
// объясняет, почему экран пуст; Alert — узкая строка рядом с полем или
// кнопкой, сообщающая об исходе конкретного действия. Разные размеры,
// разные места, разные компоненты.
//
// role="status" читается скринридером при появлении: сообщение об
// исходе действия должно быть услышано, а не найдено глазами.
// Для ошибки — role="alert": она перебивает текущее чтение, потому
// что дальше без исправления не пройти.
// ============================================================

import type { ReactNode } from 'react';

type Tone = 'error' | 'success' | 'warning';

// Заливка и цвет текста одной парой: тон меняется целиком, разъехаться
// цвету текста и подложке нельзя.
const TONES: Record<Tone, string> = {
  error: 'bg-status-error text-brand-red',
  success: 'bg-status-success text-brand-green',
  warning: 'bg-status-warning text-brand-gold',
};

type Props = {
  tone: Tone;
  children: ReactNode;
  className?: string;
  // Нужен, когда на плашку ссылаются поля через aria-describedby:
  // форма подачи держит одну общую строку ошибки внизу, и незаполненные
  // поля указывают на неё. Необязателен — прежние вызовы не трогаем.
  id?: string;
};

export default function Alert({ tone, children, className = '', id }: Props) {
  return (
    <p
      id={id}
      role={tone === 'error' ? 'alert' : 'status'}
      className={`rounded-control px-3 py-2 text-caption ${TONES[tone]} ${className}`}
    >
      {children}
    </p>
  );
}
