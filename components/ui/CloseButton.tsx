// ============================================================
// RS AUTO — Кнопка закрытия («крестик»). Единый паттерн для всех
// слоёв, которые пользователь может закрыть: шторка фильтров, список
// выбора, форма подачи, галерея объявления.
// ============================================================
// Зачем отдельный компонент. Раньше крестик был написан заново в каждом
// оверлее, и расходились три вещи сразу: цвет (neutral-40 против
// neutral-60), сам символ (текстовый «×» вместо знака) и aria-label —
// в двух местах там стояло «×», из-за чего скринридер зачитывал имя
// символа, а не действие. Подпись обязана приходить из словаря.
//
// ВАРИАНТЫ (по подложке, на которой лежит крестик):
//   plain   — на белом фоне панели: шторка фильтров, список выбора,
//             форма подачи. Ничего не рисует вокруг знака.
//   overlay — поверх фотографии: галерея объявления. Тёмный знак на
//             белом круге — единственный вариант, который читается
//             и на светлом небе, и на чёрном кузове.
//   onDark  — на сплошной тёмной заливке: смарт-баннер (bg-brand-dark).
//             Знак берёт ступень on-dark-60 — ту же, что стояла у
//             самодельного крестика баннера до перевода на компонент.
//             Круга здесь нет: подложка ровная и знак на ней читается
//             без подставки, а белый круг в узкой полосе баннера
//             выглядел бы кнопкой действия, а не отказом.
//
// Знак — inline-SVG, а не текстовый символ «×»: у текстового варианта
// метрики зависят от шрифта, и он смещается относительно центра.
// Тем же приёмом собраны бургер в шапке и значок фильтров.
//
// ------------------------------------------------------------
// ГДЕ ЕЩЁ В ПРОЕКТЕ ЕСТЬ КРЕСТИК — и почему не этот компонент.
// ------------------------------------------------------------
// Два места рисуют тот же знак своими руками, и оба обязаны остаться
// такими. Список нужен, чтобы правка формы знака не забыла про них:
//
//   FilterChips — знак снятия фильтра ВНУТРИ ссылки-чипса. Кнопка
//     внутри ссылки недопустима, поэтому компонент сюда не встаёт;
//   PhotoPicker — удаление фотографии, значок 24px в углу миниатюры.
//     У компонента область 40px, она накрыла бы саму миниатюру.
//
// Геометрия знака у всех трёх ОДНА (viewBox 24, линии 6,6→18,18,
// скруглённые концы) — расходится только толщина, и намеренно:
// на 20px это strokeWidth 2 (1.67px на экране), на 12px — 3 (1.50px).
// Тот же коэффициент дал бы 3.33 и на мелком знаке залил бы просвет
// между линиями. Менять форму — во всех трёх местах сразу.
//
// Знак overlay (16px при том же strokeWidth 2) даёт 1.33px — тоньше
// прочих, и это допустимо: он лежит на белом круге с тенью, где
// контраст со знаком максимальный, тогда как 12px-крестик
// PhotoPicker'а стоит прямо на фотографии и требует запаса толщины.
// ============================================================

type Variant = 'plain' | 'overlay' | 'onDark';

type Props = {
  onClick: () => void;
  // Подпись для скринридера. Обязательна и всегда из словаря: у кнопки
  // нет текста, и без неё она озвучивается как «кнопка».
  label: string;
  variant?: Variant;
  // Закрытие запрещено, пока идёт необратимое действие: в диалоге
  // выхода запрос уже ушёл на сервер, и убирать окно с индикатором
  // происходящего нельзя.
  disabled?: boolean;
  className?: string;
};

// Размер кликабельной области — 40px. Это минимум, при котором в
// крестик попадают пальцем: тот же размер, что у бургера в шапке.
// У overlay видимый круг меньше (32px), но область нажатия та же —
// разница добрана прозрачной рамкой, см. комментарий у варианта.
const VARIANTS: Record<Variant, string> = {
  plain:
    'inline-flex h-10 w-10 items-center justify-center rounded-control ' +
    'text-neutral-60 transition-colors hover:bg-surface-hover hover:text-neutral-100',
  // shadow-modal — та же тень, что у всплывающих панелей: круг обязан
  // отделяться от фотографии, иначе на светлом кадре он сливается с ней.
  //
  // ПОДСВЕТКИ НАВЕДЕНИЯ ЗДЕСЬ НЕТ, и это не упущение. Раньше стояло
  // hover:bg-surface-hover — как у plain. Но surface-hover это
  // ПОЛУПРОЗРАЧНЫЙ ЧЁРНЫЙ (rgba(0,0,0,0.03), lib/brand.ts): на белой
  // панели он читается как лёгкое затемнение, а поверх фотографии
  // ложится на белый круг и пропускает кадр сквозь себя — кнопка под
  // курсором выглядела линялой и грязной, будто теряет фон.
  //
  // Непрозрачную заливку взамен подбирать не нужно: круг и так белый
  // на пёстром фоне, наведение на нём читается курсором и тенью.
  // Плотный серый вместо неё сделал бы кнопку заметно темнее именно
  // в момент, когда на неё смотрят.
  //
  // РАЗМЕР КРУГА 32px ПРОТИВ 40px У ОСТАЛЬНЫХ. Крестик здесь лежит
  // поверх фотографии и конкурирует с ней за внимание: сорокапиксельный
  // круг на кадре читался как элемент интерфейса поверх содержимого, а
  // не как скромный выход. У plain и onDark такой задачи нет — они
  // стоят на ровной подложке, где размер ничему не мешает.
  //
  // ОБЛАСТЬ НАЖАТИЯ ПРИ ЭТОМ ОСТАЛАСЬ 40px: круг ужат до 32px, а
  // недостающие 4px с каждой стороны добраны прозрачной рамкой
  // (border-4 border-transparent + box-content). Так палец по-прежнему
  // попадает в кнопку, хотя белого на кадре стало меньше. Просто
  // уменьшить h/w значило бы отобрать у мобильного пользователя
  // четверть площади цели — а именно на телефоне фотография занимает
  // весь первый экран и крестик единственный выход с него.
  //
  // background-clip: padding-box обязателен: без него белый фон залил
  // бы и прозрачную рамку, и круг снова стал бы сорокапиксельным.
  overlay:
    'inline-flex h-8 w-8 box-content border-4 border-transparent ' +
    '[background-clip:padding-box] items-center justify-center rounded-full ' +
    'bg-white text-neutral-100 shadow-modal',
  // Зеркало plain для тёмной подложки. Подсветка наведения у plain —
  // surface-hover, то есть ПРОЗРАЧНЫЙ ЧЁРНЫЙ: на brand-dark он не даёт
  // ничего видимого. Поэтому здесь белые полупрозрачные заливки —
  // те же 0.03/0.06, что в шкале surface, но от белого. Цвет знака
  // на наведении доводится до чистого белого, как plain доводит свой
  // до neutral-100.
  onDark:
    'inline-flex h-10 w-10 items-center justify-center rounded-control ' +
    'text-on-dark-60 transition-colors hover:bg-white/[0.06] hover:text-white ' +
    'active:bg-white/[0.12]',
};

export default function CloseButton({
  onClick,
  label,
  variant = 'plain',
  disabled = false,
  className = '',
}: Props) {
  // См. комментарий у <svg> ниже.
  const iconSize = variant === 'overlay' ? 16 : 20;

  return (
    <button
      type="button"
      onClick={onClick}
      disabled={disabled}
      aria-label={label}
      title={label}
      className={`${VARIANTS[variant]} disabled:cursor-not-allowed disabled:opacity-40 ${className}`.trim()}
    >
      {/* Знак пропорционален кругу: 20px в круге 40px, 16px в
          уменьшенном круге overlay (32px). Оставив здесь 20px, мы
          получили бы поле всего в 6px по краям — крестик распирал бы
          круг изнутри. Отношение знака к кругу при этом сохраняется
          прежним (1:2). */}
      <svg
        width={iconSize}
        height={iconSize}
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth="2"
        strokeLinecap="round"
        aria-hidden="true"
      >
        <line x1="6" y1="6" x2="18" y2="18" />
        <line x1="18" y1="6" x2="6" y2="18" />
      </svg>
    </button>
  );
}
