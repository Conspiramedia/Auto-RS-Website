// ============================================================
// RS AUTO — Контейнер-карточка.
// ============================================================
// Обёртка «граница + радиус контейнера + внутренний отступ», которая
// в разметке встречалась россыпью: формы, блок цены на карточке
// объявления, пустое состояние, экран успеха подачи.
//
// Тень по умолчанию НЕ включена: на сайте карточки разделяются
// границей, а тень появляется только у кликабельной карточки
// объявления при наведении (hoverable). Тень «на всякий случай»
// сделала бы страницу шумной.
// ============================================================

import Link from 'next/link';
import type { ReactNode } from 'react';

type Props = {
  children: ReactNode;
  // Внутренний отступ. none — когда содержимое само управляет
  // отступами (карточка объявления с фотографией во всю ширину).
  //   sm — плотные карточки списка (кабинет владельца);
  //   lg — блоки на странице объявления: цена, условия аренды. Отступ
  //        не растёт с шириной, потому что блок и так стоит в узкой
  //        колонке, а на мобильном занимает всю ширину экрана;
  //   md — формы: там поля должны отступать от края сильнее.
  padding?: 'none' | 'sm' | 'lg' | 'md';
  // Реакция на наведение для кликабельных карточек.
  hoverable?: boolean;
  // Карточка целиком — ссылка (плитка объявления в каталоге). Рендерится
  // настоящим <Link>, а не div с обработчиком: краулер обязан видеть
  // ссылку, а человек — открывать её в новой вкладке.
  // Карточку с кнопками внутри так оформлять нельзя (интерактивный
  // элемент внутри интерактивного) — там href не передаётся.
  href?: string;
  className?: string;
};

const PADDINGS = {
  none: '',
  sm: 'p-3',
  lg: 'p-4',
  // Прежнее «p-4 sm:p-6» форм — самый частый вариант.
  md: 'p-4 sm:p-6',
} as const;

export default function Card({
  children,
  padding = 'md',
  hoverable = false,
  href,
  className = '',
}: Props) {
  const classes = [
    'rounded-card border border-neutral-10',
    PADDINGS[padding],
    // hover:shadow-card после включения hoverOnlyWhenSupported
    // (tailwind.config.ts) живёт только под мышью — на телефоне тень
    // больше не залипает на карточках, через которые прошёл палец при
    // прокрутке.
    //
    // Взамен пальцу нужен СВОЙ отклик на нажатие, иначе карточка
    // перестала бы отзываться вовсе. Это active:bg-* — заливка, а НЕ
    // тень и НЕ сдвиг: любое движение геометрии при касании читается
    // как «страница поехала» и мешает отличить нажатие от начала
    // прокрутки. Заливка сообщает то же самое, оставаясь на месте.
    //
    // ПОДЪЁМ ПРИ НАВЕДЕНИИ. Карточка отрывается от полотна на 4px и
    // получает тень — вместе они читаются как «её можно взять», тогда
    // как одна тень без движения выглядит просто подсветкой.
    //
    // Сдвиг делается transform, а НЕ отступами и не top: transform
    // считается на композиторе и не трогает раскладку, поэтому
    // соседние карточки в сетке остаются на местах и CLS не растёт.
    // Тот же сдвиг через margin-top перекроил бы весь ряд.
    //
    // ПОД МЫШЬЮ И ТОЛЬКО. hoverOnlyWhenSupported (tailwind.config.ts)
    // оборачивает hover-утилиты в @media (hover: hover), поэтому на
    // телефоне карточка не подпрыгивает от прикосновения при
    // прокрутке. Пальцу остаётся свой отклик — active:bg-*, заливка
    // без движения: любой сдвиг геометрии при касании читается как
    // «страница поехала» и мешает отличить нажатие от начала скролла.
    //
    // transition перечисляет свойства поимённо. transition-all на
    // карточке ленты анимировал бы и размеры при перерисовке списка —
    // отсюда явный список из трёх.
    hoverable
      ? 'overflow-hidden transition-[box-shadow,background-color,transform] duration-hover ease-out hover:-translate-y-1 hover:shadow-card active:bg-surface-hover'
      : '',
    className,
  ]
    .filter(Boolean)
    .join(' ');

  if (href) {
    return (
      <Link href={href} className={classes}>
        {children}
      </Link>
    );
  }

  return <div className={classes}>{children}</div>;
}
