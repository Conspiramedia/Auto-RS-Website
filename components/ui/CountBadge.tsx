// ============================================================
// RS AUTO — Счётчик непрочитанного. Красный кружок с белой цифрой.
// ============================================================
// Используется в двух положениях, отсюда проп floating:
//   floating — кружок поверх кнопки бургера (абсолютное
//              позиционирование, привязан к её углу);
//   обычный  — плашка в строке пункта меню, стоит в потоке справа
//              от подписи.
//
// Красный — роль «требует внимания», та же, что у бейджа вкладки
// «Сообщения» в кабинете. Это не декоративный цвет: другого красного
// в шапке нет, и спутать его не с чем.
//
// 99+ вместо точного трёхзначного числа: разница между 100 и 137
// непрочитанными не влияет ни на одно решение, а ширина бейджа
// ограничена размером кнопки.
// ============================================================

type Props = {
  count: number;
  // Поверх кнопки (true) или в строке списка (false).
  floating?: boolean;
  className?: string;
};

export default function CountBadge({
  count,
  floating = false,
  className = '',
}: Props) {
  // Нулевой счётчик не рисуется вовсе: пустой кружок сообщал бы
  // о наличии непрочитанного там, где его нет.
  if (count <= 0) return null;

  const label = count > 99 ? '99+' : String(count);

  // min-w вместо фиксированной ширины: однозначное число даёт круг,
  // двузначное и «99+» растягивают его в пилюлю, оставаясь читаемыми.
  const base =
    'min-w-[18px] rounded-pill bg-brand-red px-1 text-center text-small font-semibold leading-[18px] text-white';

  if (floating) {
    return (
      <span
        // -right-0.5 -top-0.5 сажают кружок на угол кнопки, слегка
        // выступая за него — так он читается как метка НА кнопке,
        // а не как её часть.
        className={`pointer-events-none absolute -right-0.5 -top-0.5 ${base} ${className}`}
      >
        {label}
      </span>
    );
  }

  return <span className={`${base} ${className}`}>{label}</span>;
}
