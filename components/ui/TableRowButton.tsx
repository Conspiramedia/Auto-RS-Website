'use client';

// ============================================================
// RS AUTO — Кликабельная строка таблицы. Client Component.
// ============================================================
// Вынесена из Table.tsx ОТДЕЛЬНЫМ ФАЙЛОМ ради одного свойства: сама
// таблица обязана остаться серверной. Обработчик onClick требует
// 'use client' у того компонента, где он стоит в разметке; напиши мы
// его прямо в Table, клиентской стала бы вся таблица — вместе с
// каждой страницей админки, которая её выводит, и SSR-разметка
// превратилась бы в гидрируемый на клиенте список.
//
// Так граница проходит по одной строке: серверная таблица рендерит
// клиентский <tr> только там, где вызывающая сторона реально
// передала onRowClick. Ни один вызов без него ничего клиентского в
// сборку не тянет.
//
// НАПОМИНАНИЕ О НАЗНАЧЕНИИ: для НАВИГАЦИИ это не нужно. Ссылка внутри
// колонки (<Link> в render) работает лучше по всем статьям — SSR,
// средняя кнопка мыши, копирование адреса, фокус с клавиатуры.
// Этот файл существует для действий, у которых адреса нет: выделение
// строки в массовых операциях и подобное.
// ============================================================

import type { ReactNode } from 'react';

type Props = {
  children: ReactNode;
  onClick: () => void;
  className?: string;
};

export default function TableRowButton({
  children,
  onClick,
  className = '',
}: Props) {
  return (
    <tr
      onClick={onClick}
      // Строка-кнопка обязана слушаться клавиатуры. role="button" +
      // tabIndex дают фокус и Enter/Space; без них действие доступно
      // только мышью, а модератор работает с клавиатуры.
      role="button"
      tabIndex={0}
      onKeyDown={(e) => {
        if (e.key === 'Enter' || e.key === ' ') {
          e.preventDefault();
          onClick();
        }
      }}
      className={`cursor-pointer transition-colors duration-fast hover:bg-surface-hover focus-visible:bg-surface-hover ${className}`}
    >
      {children}
    </tr>
  );
}
