'use client';

// ============================================================
// RS AUTO — Всплеск у сердечка при добавлении в избранное.
// ============================================================
// ЧТО ПРОИСХОДИТ. В момент, когда объявление СОХРАНЯЕТСЯ, сердце
// коротко подрастает и от него разлетаются шесть искр. При снятии
// закладки не происходит ничего: праздновать отказ незачем, а
// одинаковая анимация на оба действия стёрла бы разницу между ними.
//
// ЗАЧЕМ ВООБЩЕ. Сердце на карточке 20×20, и смена контура на заливку
// — изменение мелкое: на телефоне палец в момент нажатия закрывает
// сам значок, и человек не видит, сработало ли. Всплеск выходит
// за пределы пальца и подтверждает действие.
//
// ГЕОМЕТРИЯ ЧАСТИЦ. Шесть искр по кругу с шагом 60°, направление
// задаётся поворотом (--burst-angle), разлёт — сдвигом по своей оси
// (--burst-distance). Так одному кадру анимации хватает на все шесть
// частиц: они различаются только переменными, а не собственными
// keyframes. Первая искра поднята на -90°, то есть строго вверх, —
// иначе крайние искры ложились бы на горизонталь и читались бы как
// подчёркивание.
//
// БЕЗ СДВИГА ВЁРСТКИ. Слой частиц — absolute inset-0 с
// pointer-events: none поверх кнопки, размеров ей не добавляет и
// нажатия не перехватывает. Сама кнопка не двигается: масштабируется
// только её содержимое (иконка), и transform: scale не влияет на
// раскладку соседей.
//
// ПОЧЕМУ КЛЮЧ, А НЕ ФЛАГ. Всплеск перезапускается по key: снятая и
// заново поставленная закладка обязана дать новую анимацию, а один и
// тот же DOM-узел повторно её не проигрывает. Ключ — счётчик
// срабатываний, приходит снаружи.
//
// ПРИ prefers-reduced-motion ЧАСТИЦ НЕТ ВОВСЕ. Общее правило в
// globals.css сжимает длительность до 0.01мс, и искры мелькнули бы
// на кадр; здесь они просто не рисуются — компонент проверяет
// настройку сам.
// ============================================================

import { useEffect, useState } from 'react';

// Шесть искр по кругу. Число из задания; больше на значке 20×20
// сливается в кольцо.
const PARTICLES = 6;

// Разлёт. 14px — чуть больше половины иконки: искры выходят за её
// край, но остаются в пределах области нажатия 32px и не наезжают на
// соседний текст карточки.
const DISTANCE = '14px';

type Props = {
  // Счётчик добавлений в избранное. Растёт на единицу при каждом
  // сохранении; ноль означает, что всплеска ещё не было.
  burstKey: number;
  children: React.ReactNode;
};

export default function FavoriteBurst({ burstKey, children }: Props) {
  const [reduced, setReduced] = useState(false);

  useEffect(() => {
    const mq = window.matchMedia?.('(prefers-reduced-motion: reduce)');
    if (!mq) return;

    setReduced(mq.matches);
    const onChange = () => setReduced(mq.matches);
    mq.addEventListener('change', onChange);
    return () => mq.removeEventListener('change', onChange);
  }, []);

  // Всплеска ещё не было (страница только открылась, закладка стоит
  // с прошлого визита) — рисуем содержимое как есть. Иначе анимация
  // проигрывалась бы у каждого сохранённого объявления при загрузке
  // списка избранного.
  const active = burstKey > 0 && !reduced;

  return (
    <span className="relative inline-flex">
      {/* Сама иконка. key перезапускает подскок при каждом новом
          сохранении. */}
      <span
        key={active ? `pop-${burstKey}` : 'pop'}
        className={active ? 'inline-flex animate-heart-pop' : 'inline-flex'}
      >
        {children}
      </span>

      {active && (
        <span
          key={`burst-${burstKey}`}
          aria-hidden="true"
          className="pointer-events-none absolute inset-0 flex items-center justify-center"
        >
          {Array.from({ length: PARTICLES }, (_, i) => (
            <span
              key={i}
              className="absolute h-1 w-1 rounded-full bg-brand-red animate-heart-particle"
              style={
                {
                  // Первая искра — строго вверх (-90°), остальные с
                  // шагом 60° по кругу.
                  '--burst-angle': `${-90 + (360 / PARTICLES) * i}deg`,
                  '--burst-distance': DISTANCE,
                  // Разлёт вразнобой: одновременный старт всех шести
                  // читается как одно расширяющееся кольцо, а не как
                  // искры. Разброс мелкий — 24мс на всю очередь.
                  animationDelay: `${i * 4}ms`,
                } as React.CSSProperties
              }
            />
          ))}
        </span>
      )}
    </span>
  );
}
