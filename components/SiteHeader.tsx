// ============================================================
// Состав намеренно минимальный: логотип, переключатель языка и CTA
// продавцу. На 360px это ровно то, что помещается в одну строку без
// переполнения.
//
// Тумблера «Продажа / Аренда» здесь НЕТ: тип объявления — это фильтр
// выдачи, а не раздел сайта, и живёт он в панели фильтров. Раньше он
// стоял в шапке и на узких экранах выдавливал CTA за край.
//
// Разделы сайта на десктопе стоят в самой шапке, на мобильном живут
// в меню (HeaderMenu). В подвале они продублированы: это ещё и
// перелинковка для краулера с любой страницы сайта.
//
// Личные страницы (объявления, сообщения, уведомления, профиль) —
// ТОЛЬКО в меню, на всех ширинах: отдельной иконки кабинета в шапке
// больше нет.
//
// Исключение одно — «Войти» в конце десктопного ряда разделов
// (HeaderLoginLink) и только для гостя. Вход — не личная страница, а
// порог к ней, и прятать его на десктопе в бургер значит требовать
// лишнего клика от того, кто ещё ничего о сайте не знает. Вошедшему
// ссылка не показывается: ему нужен кабинет, а он в меню.
//
// Логотип рендерит components/ui/Logo — там же он и меняется, когда
// появится векторный файл. Здесь знак только вставляется в шапку.
// ============================================================

import Link from 'next/link';

import Logo from './ui/Logo';
import type { Locale, DictKey } from '@/lib/i18n';
import { getT, localeHref } from '@/lib/i18n';
import { isSectionActive } from '@/lib/navigation';
import LocaleSwitch from './LocaleSwitch';
import LocaleSwitchHere from './LocaleSwitchHere';
import HeaderLoginLink from './HeaderLoginLink';
import HeaderMenu from './HeaderMenu';
import Button from './ui/Button';

type Props = {
  locale: Locale;
  // Путь текущей страницы без префикса локали — нужен переключателю языка,
  // чтобы остаться на том же месте при смене языка.
  //
  // 'auto' — для случая, когда шапку рендерит layout, а не страница:
  // layout своего адреса не знает (страница приходит к нему через
  // children), и путь тогда определяется на клиенте через usePathname
  // (LocaleSwitchHere). Такое место одно — кабинет /my.
  //
  // Обычным страницам передавать 'auto' НЕ НУЖНО: они свой адрес знают,
  // а явная строка оставляет переключатель серверным, то есть даёт
  // краулеру настоящие <a href> на языковое зеркало.
  pathname: string | 'auto';
};

// Разделы десктопного ряда. Порядок и состав те же, что были заданы
// ссылками по одной: сначала вид сделки (продажа, аренда), потом
// дилеры и приложение.
//
// «Все авто» (/all) здесь НЕТ намеренно — подтверждённое решение
// b0a58bf: ряд короткий, и в нём нужен выбор вида сделки, а не третья
// витрина. Смешанная витрина остаётся в бургер-меню (HeaderMenu),
// где список полный.
const NAV_LINKS: { path: string; label: DictKey }[] = [
  // nav_catalog_menu, а не nav_catalog: в ряду с «Арендой» это выбор
  // вида сделки, а не название раздела (см. словарь lib/i18n).
  { path: '/cars', label: 'nav_catalog_menu' },
  { path: '/rent', label: 'nav_rent' },
  { path: '/dealers', label: 'nav_dealers' },
  { path: '/app', label: 'nav_app' },
];

export default function SiteHeader({ locale, pathname }: Props) {
  const t = getT(locale);

  // Путь для сравнения с адресами разделов. Из pathname отсекается
  // строка запроса: на выдаче сюда приходит '/cars?brand=bmw' (её
  // передают страницы каталога, чтобы переключатель языка сохранял
  // фильтры), а раздел определяется одним лишь путём.
  //
  // 'auto' — кабинет, где layout своего адреса не знает. Разделы сайта
  // там не подсвечиваются ни один: пользователь находится на личной
  // странице, а не в витрине. Пустая строка не совпадёт ни с одним
  // адресом раздела и ни с одним префиксом.
  const currentPath =
    pathname === 'auto' ? '' : pathname.split('?')[0];

  return (
    <header className="sticky top-0 z-header border-b border-neutral-10 bg-white">
      {/* gap-2 на мобильных и gap-4 с sm: на 360px каждый пиксель между
          элементами решает, поместится CTA или уедет за край.
          Отступы px-4 — те же, что у контейнера содержимого на всех
          страницах: логотип обязан стоять на одной вертикали с
          заголовком страницы под ним. Раньше здесь было асимметричное
          pl-3 pr-2, и знак съезжал влево относительно контента.
          Справа те же 16px компенсируются внутренним отступом
          последнего элемента (бургер на мобильном, CTA на десктопе),
          поэтому визуальный зазор у края не удваивается: -mr-1.5
          подтягивает кнопку с её собственным padding обратно к краю. */}
      <div className="mx-auto flex h-14 max-w-6xl items-center gap-2 px-4 sm:gap-4">
        <Link href={localeHref(locale, '/')} className="shrink-0">
          <Logo className="text-body sm:text-h4" />
        </Link>

        {/* Разделы сайта. Показываются только на десктопе (sm:flex):
            на мобильном места нет, там навигация живёт в подвале, а в
            шапке остаётся лого + язык + CTA. */}
        <nav className="hidden flex-1 items-center gap-5 text-caption sm:flex">
          {NAV_LINKS.map((link) => {
            // То же правило, что в бургер-меню и вкладках кабинета
            // (lib/navigation): раздел остаётся активным на своих
            // вложенных страницах — '/cars' горит и на '/cars/bmw'.
            const active = isSectionActive(currentPath, link.path);

            return (
              <Link
                key={link.path}
                href={localeHref(locale, link.path)}
                // aria-current — единственный признак текущего раздела
                // для скринридера: ни цвет, ни подчёркивание он не
                // читает.
                aria-current={active ? 'page' : undefined}
                className={
                  active
                    ? 'font-semibold text-brand-primary'
                    : 'hover:underline'
                }
              >
                {t(link.label)}
              </Link>
            );
          })}

          {/* «Войти» — последним в ряду разделов и только гостю.
              Клиентский компонент: состояние сессии нельзя читать в
              серверной шапке, не переведя весь сайт в динамический
              рендер (см. комментарий внутри). */}
          <HeaderLoginLink locale={locale} />
        </nav>

        <div className="-mr-1.5 ml-auto flex shrink-0 items-center gap-1.5 sm:mr-0 sm:gap-3">
          {pathname === 'auto' ? (
            <LocaleSwitchHere locale={locale} />
          ) : (
            <LocaleSwitch locale={locale} pathname={pathname} />
          )}

          {/* Сильный CTA продавцу — главная бизнес-цель сайта, поэтому он
              единственный акцентный элемент в шапке.
              whitespace-nowrap обязателен: «Prodaj auto» в две строки
              ломает высоту шапки. */}
          <Button
            size="xs"
            href={localeHref(locale, '/sell')}
            className="whitespace-nowrap"
          >
            {t('nav_sell')}
          </Button>

          {/* Меню — последним, у самого края: это край, до которого
              дотягивается большой палец.
              ОТДЕЛЬНОЙ ССЫЛКИ НА КАБИНЕТ В ШАПКЕ БОЛЬШЕ НЕТ. Раньше
              здесь стояла иконка человечка со счётчиком непрочитанных,
              и разделы кабинета были доступны только через неё —
              безымянный знак, за которым пряталась половина личных
              страниц. Теперь вход, кабинет и счётчик живут в меню:
              бейдж с общим числом непрочитанного висит на самой
              кнопке, а внутри цифры разложены по разделам.
              Меню показывается на ВСЕХ ширинах: на десктопе разделы
              сайта продублированы в nav выше, но личные страницы
              есть только здесь. */}
          <HeaderMenu locale={locale} />
        </div>
      </div>
    </header>
  );
}
