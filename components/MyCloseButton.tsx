// ============================================================
// RS AUTO — Крестик «закрыть кабинет». Server Component.
// ============================================================
// Уводит на ГЛАВНУЮ САЙТА по фиксированному адресу.
//
// ПОЧЕМУ НЕ BackCloseButton, который стоит на справочных страницах.
// Тот возвращает назад по истории, и для /about это верно: туда
// приходят из меню с разных разделов, и «назад» отдаёт человека ровно
// туда, откуда он пришёл.
//
// В кабинете такое поведение непредсказуемо. Внутри него ходят вглубь
// (список объявлений → объявление → правка), и шаг назад вернул бы
// В КАБИНЕТ, а не вывел из него — то есть крестик означал бы разное в
// зависимости от того, как человек сюда попал. Фиксированный адрес
// снимает вопрос: крестик здесь всегда значит «закрыть кабинет».
//
// ДВА КОНТРОЛА — ДВА НАМЕРЕНИЯ, и они не пересекаются:
//   «←» (MyHeaderBack) — навигация ВНУТРИ кабинета, из диалога к
//     списку диалогов;
//   «×» (этот) — выход ИЗ кабинета на витрину.
// Поэтому в открытом диалоге видны оба, и это не дублирование.
//
// ССЫЛКА, А НЕ КНОПКА. Адрес известен заранее, значит это переход, а
// не действие: <Link> открывается средней кнопкой, копируется,
// показывает адрес в строке состояния и работает до загрузки скрипта.
// Отсюда же Server Component — обработчик клика не нужен.
//
// КУДА ВЕДЁТ — НАСТРАИВАЕТСЯ, но по умолчанию на главную. Пропы href
// и labelKey остались от полосы владельца на витрине салона: там тем
// же знаком закрывался просмотр витрины, и вести он должен был в
// профиль. Полоса с тех пор переписана и стоит на BackCloseButton
// (возврат по истории), так что сейчас у компонента один вызов — из
// кабинета, со значениями по умолчанию. Пропы сохранены: они ничего
// не стоят, а следующему такому случаю не придётся их заводить заново.
//
// ТАЧ-ЦЕЛЬ 44px, а не 40px как у общего CloseButton. Тот размер
// задан для крестиков ВНУТРИ слоёв (шторка фильтров, галерея), где
// палец уже наведён на панель. Здесь крестик стоит в углу экрана, у
// самой кромки, и промах по нему означает случайный тап по заголовку
// или по вкладке. 44px — минимум из рекомендаций Apple HIG и
// Material, и то же число требует наш чек-лист доступности.
// ============================================================

import Link from 'next/link';

import type { DictKey, Locale } from '@/lib/i18n';
import { getT, localeHref } from '@/lib/i18n';

type Props = {
  locale: Locale;
  className?: string;
  // Куда уводит крестик. Путь БЕЗ префикса локали — его добавит
  // localeHref, как и для любого внутреннего перехода на сайте.
  href?: string;
  // Подпись для скринридера и всплывающей подсказки. Ключ словаря, а
  // не готовая строка: сайт двуязычный, и текст обязан приходить
  // через getT. По умолчанию — «закрыть кабинет».
  labelKey?: DictKey;
};

export default function MyCloseButton({
  locale,
  className = '',
  href = '/',
  labelKey = 'my_close',
}: Props) {
  const t = getT(locale);

  return (
    <Link
      href={localeHref(locale, href)}
      // Подпись своя, не common_close: крестик уводит со страницы, и
      // тот, кто слушает её скринридером, должен знать куда. Раз
      // назначение настраивается, вместе с ним обязана меняться и
      // подпись — иначе крестик на витрине обещал бы закрыть кабинет,
      // а вёл бы в профиль.
      aria-label={t(labelKey)}
      title={t(labelKey)}
      className={[
        'inline-flex size-11 shrink-0 items-center justify-center rounded-control',
        'text-neutral-60 transition-colors duration-fast',
        'hover:bg-surface-hover hover:text-neutral-100',
        className,
      ]
        .join(' ')
        .trim()}
    >
      {/* Знак — inline-SVG с той же геометрией, что у общего
          CloseButton (viewBox 24, линии 6,6→18,18, скруглённые концы).
          Расходиться им нельзя: два разных крестика на одном сайте
          читаются как элементы разных продуктов. Размер знака тот же
          20px — увеличена область нажатия, а не сам символ. */}
      <svg
        width="20"
        height="20"
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth="2"
        strokeLinecap="round"
        aria-hidden="true"
      >
        <line x1="6" y1="6" x2="18" y2="18" />
        <line x1="18" y1="6" x2="6" y2="18" />
      </svg>
    </Link>
  );
}
