// ============================================================
// RS AUTO — QR-код на объявление. Server Component.
// ============================================================
// Код генерируется НА СЕРВЕРЕ в inline-SVG и попадает в HTML вместе со
// страницей. Причины: не нужен клиентский JS ради статичной картинки,
// нет запроса к стороннему сервису QR (это утечка URL и лишняя точка
// отказа), и код виден сразу, без «прыжка» вёрстки после гидратации.
//
// Показывается на десктопе: с телефона пользователь жмёт кнопку
// «Продолжить в приложении», сканировать код ему нечем.
// ============================================================

import QRCode from 'qrcode';

type Props = {
  url: string;
  size?: number;
};

export default async function AppQr({ url, size = 148 }: Props) {
  // Уровень коррекции M — запас на случай печати/бликов при съёмке экрана,
  // при этом код не становится слишком плотным.
  const svg = await QRCode.toString(url, {
    type: 'svg',
    errorCorrectionLevel: 'M',
    margin: 1,
    width: size,
  });

  return (
    <div
      className="inline-block rounded-card border border-black/10 bg-white p-2"
      // Содержимое — SVG, сгенерированный библиотекой из нашего же URL;
      // пользовательский ввод сюда не попадает.
      dangerouslySetInnerHTML={{ __html: svg }}
    />
  );
}
