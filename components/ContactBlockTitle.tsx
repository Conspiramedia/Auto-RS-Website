'use client';

// ============================================================
// RS AUTO — Заголовок блока «Связь с продавцом».
// ============================================================
// Клиентский компонент ради одной строки текста — и на то есть
// причина.
//
// ПРОБЛЕМА. Обе кнопки связи (CallSellerButton, ContactSellerButton)
// скрывают себя у ВЛАДЕЛЬЦА объявления: звонить и писать самому себе
// незачем. Решение принимается на клиенте — серверный рендер идёт под
// анонимным ключом ради кэша и о том, кто смотрит страницу, не знает.
//
// Заголовок же рендерился на сервере безусловно, и владелец своей
// карточки видел подпись «Связь с продавцом», под которой не было
// ничего, кроме кнопки «Поделиться». Выглядело это как поломка
// страницы, а не как осознанное поведение.
//
// РЕШЕНИЕ. Тот же признак «я владелец», что и у кнопок, применяется к
// заголовку. Компонент не пытается угадать состояние кнопок — он
// повторяет их условие, и все три элемента исчезают вместе.
//
// ПОЧЕМУ НЕ СКРЫВАЕМ ВЕСЬ БЛОК. Внутри него стоит ещё «Поделиться», а
// она нужна и владельцу: ссылку на своё объявление отправляют
// покупателю чаще, чем куда-либо ещё. Поэтому скрывается ровно
// заголовок с разделительной чертой, а контейнер остаётся.
//
// До завершения проверки сессии заголовок НЕ рисуется: появиться и
// исчезнуть он не должен, а дождаться его владельцу нечего — он и так
// увидит только «Поделиться».
// ============================================================

import { useEffect, useState } from 'react';

import type { Locale } from '@/lib/i18n';
import { getT } from '@/lib/i18n';
import { getBrowserClient } from '@/lib/supabaseClient';

export default function ContactBlockTitle({
  locale,
  sellerId,
}: {
  locale: Locale;
  sellerId: string;
}) {
  const t = getT(locale);
  // undefined — проверка не завершена, null — гость.
  const [userId, setUserId] = useState<string | null | undefined>(undefined);

  useEffect(() => {
    let cancelled = false;

    getBrowserClient()
      .auth.getSession()
      .then(({ data }) => {
        if (!cancelled) setUserId(data.session?.user.id ?? null);
      });

    return () => {
      cancelled = true;
    };
  }, []);

  // Проверка не завершена — не показываем ничего.
  if (userId === undefined) return null;

  // Своё объявление: кнопок связи под заголовком не будет.
  if (userId === sellerId) return null;

  return <div className="font-semibold">{t('car_contact_title')}</div>;
}
