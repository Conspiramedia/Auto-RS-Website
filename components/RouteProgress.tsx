'use client';

// ============================================================
// RS AUTO — Индикатор перехода между страницами: бегущая «дорога».
// ============================================================
// ЧТО ВИДИТ ЧЕЛОВЕК. Тонкая синяя полоса у самого верха окна, по
// которой слева направо бежит белая прерывистая разметка — дорожная
// осевая линия. Появляется, когда переход занял заметное время, и
// исчезает, когда новая страница отрисована.
//
// ПОЧЕМУ ДОРОГА, А НЕ ОБЫЧНЫЙ ПРОГРЕСС-БАР. Полоска-прогресс обязана
// показывать ДОЛЮ выполненного, а у навигации App Router такой доли
// нет: сервер отдаёт готовый ответ целиком, промежуточных процентов
// не существует. Все библиотеки-индикаторы рисуют выдуманную кривую,
// которая ползёт к 90% и там замирает, — то есть врут. Бегущая
// разметка ничего не обещает: она сообщает «идём», и это правда.
//
// ПОЧЕМУ НЕ useLinkStatus. Штатный хук Next работает только внутри
// конкретного <Link> и знает лишь о своей ссылке. Индикатор же нужен
// один на весь сайт и обязан срабатывать на любой переход — по
// карточке объявления, по пункту меню, по кнопке пагинации, по
// «назад» в браузере. Держать хук в каждой ссылке сайта значило бы
// обойти всю разметку и всё равно забыть половину мест.
//
// КАК ОПРЕДЕЛЯЕТСЯ НАЧАЛО ПЕРЕХОДА. Слушаем клики на документе в
// фазе всплытия и смотрим, попал ли клик во внутреннюю ссылку. Это
// не патч History API и не обезьяний патч роутера: и то и другое
// ломается при обновлении Next. Обычный слушатель события переживёт
// любую версию.
//
// КАК ОПРЕДЕЛЯЕТСЯ КОНЕЦ. Смена usePathname/useSearchParams: React
// перерисовывает дерево новым адресом ровно тогда, когда страница
// готова к показу. Это тот же сигнал, по которому исчезает
// loading.tsx.
//
// ЗАДЕРЖКА ПЕРЕД ПОКАЗОМ обязательна. Большинство переходов на сайте
// мгновенны — маршруты статические и предзагружены, — и полоса,
// мелькнувшая на 40мс, читается как дефект отрисовки, а не как
// индикатор. Показываем её только если переход не уложился в
// SHOW_AFTER.
//
// БЕЗ СДВИГА ВЁРСТКИ. Полоса position: fixed поверх шапки, места в
// потоке не занимает: её появление и исчезновение не двигают ни
// пикселя содержимого, и CLS остаётся нулевым.
// ============================================================

import { usePathname, useSearchParams } from 'next/navigation';
import { useEffect, useRef, useState } from 'react';

// Порог показа. 120мс — граница, за которой человек замечает
// задержку: до неё переход воспринимается мгновенным, и индикатор
// только мешал бы миганием.
const SHOW_AFTER = 120;

export default function RouteProgress() {
  const pathname = usePathname();
  const searchParams = useSearchParams();
  const [visible, setVisible] = useState(false);

  // Таймер отложенного показа. В ref, а не в состоянии: его смена не
  // должна вызывать перерисовку.
  const timerRef = useRef<ReturnType<typeof setTimeout> | null>(null);

  // ------------------------------------------------------------
  // Конец перехода: адрес сменился — прячем.
  // ------------------------------------------------------------
  // Эффект срабатывает и при первом рендере страницы, и это верно:
  // недоведённый переход (человек нажал «назад» до его завершения)
  // иначе оставил бы полосу бежать навсегда.
  useEffect(() => {
    if (timerRef.current) {
      clearTimeout(timerRef.current);
      timerRef.current = null;
    }
    setVisible(false);
  }, [pathname, searchParams]);

  // ------------------------------------------------------------
  // Начало перехода: клик по внутренней ссылке.
  // ------------------------------------------------------------
  useEffect(() => {
    const onClick = (e: MouseEvent) => {
      // Клик с модификатором открывает ссылку в новой вкладке или
      // окне — текущая страница остаётся на месте, и полоса на ней
      // висела бы до следующего перехода.
      if (e.metaKey || e.ctrlKey || e.shiftKey || e.altKey) return;
      // Только основная кнопка мыши: средняя тоже открывает вкладку.
      if (e.button !== 0) return;
      // Обработчик выше по дереву мог отменить переход (так делают
      // значки на карточке — см. CardActions).
      if (e.defaultPrevented) return;

      const link = (e.target as Element | null)?.closest?.('a');
      if (!(link instanceof HTMLAnchorElement)) return;

      // Внешние ссылки и скачивание уводят из приложения — переход
      // маршрута не начинается.
      if (link.target && link.target !== '_self') return;
      if (link.hasAttribute('download')) return;

      const href = link.getAttribute('href');
      if (!href) return;
      // Якоря, tel:, mailto: и прочие схемы страницу не меняют.
      if (href.startsWith('#')) return;

      const url = new URL(link.href, window.location.href);
      if (url.origin !== window.location.origin) return;
      // Тот же адрес — навигации не будет, ждать нечего.
      if (url.href === window.location.href) return;

      if (timerRef.current) clearTimeout(timerRef.current);
      timerRef.current = setTimeout(() => setVisible(true), SHOW_AFTER);
    };

    document.addEventListener('click', onClick);
    return () => {
      document.removeEventListener('click', onClick);
      if (timerRef.current) clearTimeout(timerRef.current);
    };
  }, []);

  // Полоса рисуется ТОЛЬКО когда нужна. Постоянный элемент с
  // opacity: 0 держал бы на странице вечно работающую анимацию
  // фона — она тратит кадры даже невидимой.
  if (!visible) return null;

  return (
    <div
      // role=progressbar без aria-valuenow — «неопределённый»
      // прогресс: доли у навигации нет (см. шапку файла), и
      // выдуманное число ввело бы скринридер в заблуждение.
      role="progressbar"
      aria-busy="true"
      // Полосу человек видит, а слышать её незачем: об окончании
      // загрузки скринридеру сообщит смена содержимого страницы.
      aria-hidden="true"
      className="route-road animate-road fixed inset-x-0 top-0 z-tooltip h-[3px]"
    />
  );
}
