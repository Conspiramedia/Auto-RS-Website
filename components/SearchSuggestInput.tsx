// ------------------------------------------------------------
// ТАЙМИНГИ ЭФФЕКТА ПЕЧАТАЮЩЕЙ МАШИНКИ.
// ------------------------------------------------------------
// Подсказка не подменяется целиком, а НАБИРАЕТСЯ по символу, держится
// на экране, затем СТИРАЕТСЯ backspace-ом, и приходит следующая.
// Мгновенная подмена фразы читалась как сбой отрисовки — глаз ловил
// смену, но не успевал прочесть; набор же сам показывает, что в поле
// вводят текст, и заодно объясняет, ЧТО именно сюда пишут.
//
// Темп подобран под чтение, а не под демонстрацию скорости: фраза
// набирается за 2–3 секунды, полный цикл занимает 11–13. Быстрый
// набор превращал подсказку в мельтешение — фразу дочитывали уже
// после того, как она замирала.
//
// Стирание быстрее набора: живой человек тоже удаляет быстрее, чем
// печатает (backspace зажимают), и обратный ход, равный по темпу
// набору, ощущается неестественно затянутым.
const TYPE_MS = 110; // средняя задержка между символами при наборе
const ERASE_MS = 55; // то же при стирании
const HOLD_MS = 8000; // пауза на готовой фразе — успеть прочитать
const PAUSE_MS = 600; // пауза на пустом поле перед следующей фразой

// ------------------------------------------------------------
// НЕРАВНОМЕРНОСТЬ — то, что отличает живой набор от метронома.
// ------------------------------------------------------------
// Постоянный интервал между символами читается как машина, даже когда
// он медленный: глаз ловит идеальную периодичность быстрее, чем
// успевает прочесть текст. Поэтому каждая пауза берётся случайной в
// диапазоне ±JITTER от средней.
//
// 0.5 означает разброс от половины до полутора интервалов: у реального
// человека разница между соседними нажатиями куда больше, но на
// коротких фразах сильный разброс выглядит уже не живым, а рваным.
const JITTER = 0.5;

// Пауза после знаков, на которых человек естественно притормаживает:
// конец слова, запятая. Множитель к обычному интервалу.
const WORD_BREAK_FACTOR = 2.6;

// Случайная задержка вокруг среднего значения.
function humanDelay(base: number): number {
  return base * (1 + (Math.random() * 2 - 1) * JITTER);
}

// Сколько чипсов показываем на широком экране. На 768+ ряд всегда
// трёхместный: там ширины хватает даже под самые длинные фразы.
const CHIP_COUNT = 3;

// ------------------------------------------------------------
// БЮДЖЕТ РЯДА ЧИПСОВ НА МОБИЛЬНОМ — в символах, а не в пикселях.
// ------------------------------------------------------------
// Ряд обязан быть РОВНО В ОДНУ СТРОКУ: перенос третьего чипса вниз
// («Mercedes-Benz E klasa» + «Nissan Qashqai» + «Opel Astra») ломает
// вертикальный ритм страницы и на каждой ротации дёргает высоту.
//
// Откуда 38. На 360px за вычетом полей страницы (px-4 с обеих сторон)
// остаётся 328px. Чипс шире своего текста на 22px: px-2.5 с двух
// сторон плюс рамка. Три чипса съедают 3×22 + 2×6 (gap-1.5) = 78px,
// значит на текст остаётся 250px. В Montserrat 12px (text-small)
// средний символ этих фраз — марки, модели, «do 9.000 €» — занимает
// около 6.5px, откуда 250/6.5 ≈ 38.
//
// Почему символы, а не измерение через canvas или DOM. Реальная
// ширина известна только после отрисовки, и подгонять состав ряда по
// факту значило бы показать сначала переносящийся вариант, а потом
// схлопнуть его — то самое мигание, которого требуется избежать.
// Оценка по длине строки решает ту же задачу до первой отрисовки.
// Промах оценки закрыт CSS-предохранителем на самом ряду.
//
// 36, а не расчётные 38. Ровно 38 давало худший ряд в 327px при
// доступных 328 — запас в один пиксель держится на оценке ширины
// символа и рассыпался бы от любой неточности метрики. 36 оставляет
// 17px и при этом не роняет ни один ряд до одиночного чипса: на
// текущем пуле составы распределяются как 0/44/28 (один/два/три).
const MOBILE_CHIP_BUDGET = 36;

// Ширина, ниже которой действует бюджет. Совпадает с границей
// мобильного правила в globals.css: 768px — вход планшета.
const MOBILE_QUERY = '(max-width: 767px)';

// ------------------------------------------------------------
// Отбор чипсов под бюджет строки.
// ------------------------------------------------------------
// Жадно, по порядку пула: пул уже отсортирован ротацией (активная
// фраза первой), и переставлять его ради плотности упаковки нельзя —
// связь «плейсхолдер ↔ первый чипс» человек видит и читает.
//
// Три исхода, ровно как в правиле:
//   * влезают три — показываем три;
//   * не влезают — пробуем пару «первый + самый короткий из
//     оставшихся»: длинная фраза информативнее, а короткий сосед
//     добирает остаток строки;
//   * не влезла и пара — остаётся один чипс. Обрезать его нечем и
//     незачем: одна подсказка честнее пустого места.
function pickChips(
  pool: SearchSuggestion[],
  locale: Locale,
  mobile: boolean,
): SearchSuggestion[] {
  if (!mobile) return pool;

  const len = (s: SearchSuggestion) => s.text[locale].length;

  // Три — если суммарная длина укладывается в бюджет.
  const three = pool.slice(0, 3);
  if (three.length === 3 && three.reduce((sum, s) => sum + len(s), 0) <= MOBILE_CHIP_BUDGET) {
    return three;
  }

  // Пара: первый плюс кратчайший из остальных. Именно кратчайший, а
  // не следующий по порядку: при длинной активной фразе следующий
  // сосед часто тоже длинный, и пара не собралась бы вовсе там, где
  // подходящий короткий вариант в пуле есть.
  const [first, ...rest] = pool;
  if (first && rest.length > 0) {
    const shortest = rest.reduce((best, s) => (len(s) < len(best) ? s : best));
    if (len(first) + len(shortest) <= MOBILE_CHIP_BUDGET) {
      return [first, shortest];
    }
  }

  // Один.
  return first ? [first] : [];
}

type Props = {
  locale: Locale;
  // Уже применённые фильтры. Нужны целиком, а не только q: строка
  // поиска — САМОСТОЯТЕЛЬНАЯ GET-форма, и без скрытых полей отправка
  // запроса сбрасывала бы выбранную марку, цену и сортировку.
  filters: CatalogFilters;
  // Куда отправляется поиск и куда ведут чипсы: '/cars' или '/rent'.
  // Подсказки строятся по объявлениям на продажу, но в разделе аренды
  // клик обязан оставить человека в аренде, а не выбросить в общий
  // каталог.
  basePath?: string;
};

// Случайный индекс, отличный от текущего. Возврат той же фразы читался
// бы как «ротация сломалась»: человек видит неподвижное поле и не
// понимает, живое оно или нет.
function nextIndex(current: number, total: number): number {
  if (total <= 1) return 0;

  let candidate = Math.floor(Math.random() * total);
  // Максимум одна повторная попытка: цикл while здесь не нужен,
  // достаточно сдвинуть индекс на единицу по кругу.
  if (candidate === current) candidate = (candidate + 1) % total;
  return candidate;
}

export default function SearchSuggestInput({
  locale,
  filters,
  basePath = '/cars',
}: Props) {
  const t = getT(locale);

  // Есть ли вообще что показывать. Считается один раз на модуле:
  // список статичен и внутри сессии не меняется.
  const total = SEARCH_SUGGESTIONS.length;
  const hasSuggestions = total > 0;

  // Индекс активной подсказки. null — до гидратации И при пустом
  // списке: в обоих случаях показываем нейтральный плейсхолдер.
  const [index, setIndex] = useState<number | null>(null);

  // Собственный ввод пользователя. Как только он непустой, ротация
  // останавливается: подсказка под набранным текстом отвлекает, а
  // плейсхолдер за ним всё равно не виден.
  const [value, setValue] = useState(filters.q ?? '');

  // ------------------------------------------------------------
  // СИНХРОНИЗАЦИЯ ПОЛЯ С АДРЕСОМ. Обязательна, а не "на всякий случай".
  // ------------------------------------------------------------
  // useState берёт filters.q ТОЛЬКО при монтировании. Переходы внутри
  // каталога («Сбросить фильтры», клик по чипсу подсказки, кнопка
  // «Назад») — клиентская навигация Next: страница перерисовывается
  // новыми пропсами, но компонент НЕ размонтируется, и старый стейт
  // переживает переход. Из-за этого сброс фильтров очищал выдачу, а
  // текст в поле оставался на месте: человек видел полный каталог и
  // свой запрос над ним одновременно.
  //
  // Синхронизируем по filters.q, а не по каждому нажатию клавиши:
  // эффект срабатывает лишь когда адрес РАЗОШЁЛСЯ с полем, поэтому
  // набор текста он не трогает — там value меняется, а filters.q нет.
  const urlQ = filters.q ?? '';
  const [syncedQ, setSyncedQ] = useState(urlQ);

  if (urlQ !== syncedQ) {
    // Правка стейта прямо при рендере — штатный приём React для
    // «производного от пропсов» состояния: он дешевле useEffect,
    // потому что React перезапускает рендер сразу, не показывая
    // промежуточный кадр со старым текстом.
    setSyncedQ(urlQ);
    setValue(urlQ);
  }

  // Сколько символов активной фразы уже «набрано». Именно это число, а
  // не готовая строка, держит состояние анимации: из него выводится и
  // текст плейсхолдера, и то, дошёл ли набор до конца.
  const [typed, setTyped] = useState(0);

  // Фаза автомата. Вынесена в стейт, потому что от неё зависит ход
  // следующего шага, а не только картинка. Пауза на готовой фразе
  // отдельной фазой НЕ выделена: она задаётся длиной таймера на
  // последнем шаге набора, и лишнее состояние пришлось бы удерживать
  // в согласии с typed при каждом переходе.
  const [phase, setPhase] = useState<'typing' | 'erasing'>('typing');

  const active: SearchSuggestion | null =
    index !== null && hasSuggestions ? SEARCH_SUGGESTIONS[index] : null;

  // Полный текст активной фразы на текущем языке.
  const fullText = active ? active.text[locale] : '';

  // ------------------------------------------------------------
  // СИСТЕМНАЯ НАСТРОЙКА «МЕНЬШЕ ДВИЖЕНИЯ» — полная заморозка.
  // ------------------------------------------------------------
  // При prefers-reduced-motion печатной машинки нет вовсе: поле
  // показывает статичный НЕЙТРАЛЬНЫЙ плейсхолдер из словаря, фразы
  // не набираются и не сменяются. Половинчатый вариант (показать
  // фразу целиком и заморозить) был хуже обоих концов: движения нет,
  // а поле при этом выглядит заполненным чужим текстом, который
  // никогда не изменится.
  //
  // Обнаруживаемость при этом НЕ теряется: ряд чипсов под полем
  // остаётся и показывает те же живые фразы из каталога — он статичен
  // по своей природе и настройке не противоречит.
  //
  // Читается в эффекте, а не при рендере: matchMedia на сервере нет,
  // и прямой вызов расходился бы с серверной разметкой при гидратации.
  // Слушатель нужен, потому что настройку меняют не перезагружая
  // страницу — на Android она включается автоматически вместе с
  // режимом энергосбережения.
  const [reducedMotion, setReducedMotion] = useState(false);

  useEffect(() => {
    const mq = window.matchMedia?.('(prefers-reduced-motion: reduce)');
    if (!mq) return;

    setReducedMotion(mq.matches);

    const onChange = (e: MediaQueryListEvent) => setReducedMotion(e.matches);
    mq.addEventListener('change', onChange);
    return () => mq.removeEventListener('change', onChange);
  }, []);

  // ------------------------------------------------------------
  // Узкий экран: от него зависит состав ряда чипсов.
  // ------------------------------------------------------------
  // Читается тем же способом, что и reduced motion, и по той же
  // причине: matchMedia на сервере не существует, поэтому значение
  // берётся ПОСЛЕ гидратации. Стартовое false означает «широкий» —
  // сервер и первый клиентский кадр отрисуют одинаковый ряд из трёх
  // чипсов, и React не сообщит о расхождении разметки.
  //
  // Мигания при этом нет, хотя на телефоне состав ряда после
  // гидратации меняется: до неё index равен null, а ряд чипсов при
  // null не рендерится вовсе (см. условие ниже). Первый ряд, который
  // человек увидит, уже посчитан под свой экран.
  //
  // Слушатель обязателен: поворот телефона и изменение размера окна
  // на планшете пересекают границу 768px без перезагрузки страницы.
  const [mobile, setMobile] = useState(false);

  useEffect(() => {
    const mq = window.matchMedia?.(MOBILE_QUERY);
    if (!mq) return;

    setMobile(mq.matches);

    const onChange = (e: MediaQueryListEvent) => setMobile(e.matches);
    mq.addEventListener('change', onChange);
    return () => mq.removeEventListener('change', onChange);
  }, []);

  // ------------------------------------------------------------
  // Первая фраза: выбирается ТОЛЬКО после гидратации.
  // ------------------------------------------------------------
  // Случайное значение на сервере и на клиенте не совпало бы, и React
  // сообщил бы о расхождении разметки — поэтому index стартует с null,
  // а сервер отдаёт нейтральный плейсхолдер из словаря.
  //
  // Индекс выбирается и при reduced motion: сами ЧИПСЫ строятся от
  // него, и без индекса под полем не было бы ни одной подсказки.
  useEffect(() => {
    if (!hasSuggestions) return;
    setIndex((current) => (current === null ? nextIndex(-1, total) : current));
  }, [hasSuggestions, total]);

  // ------------------------------------------------------------
  // Автомат печатающей машинки: набор → пауза → стирание → следующая.
  // ------------------------------------------------------------
  // Каждый шаг — ОДИН setTimeout, а не общий interval: у фаз разный
  // темп (набор, стирание и пауза различаются в разы), и одним
  // интервалом это выражалось бы счётчиком пропущенных тиков.
  //
  // Эффект перезапускается на каждый шаг — это и есть цикл: он ставит
  // ровно один таймер, меняет состояние, React вызывает его заново.
  useEffect(() => {
    if (!hasSuggestions || index === null) return;
    // Человек печатает сам — анимация обязана молчать: подсказка,
    // набирающаяся под чужим вводом, выглядит как помеха, а плейсхолдер
    // за набранным текстом всё равно не виден.
    //
    // index здесь НЕ сбрасывается — только замирает. На этом держится
    // неподвижный ряд чипсов под полем: пул считается от того же
    // индекса, и последний набор остаётся видимым, пока человек печатает.
    if (value.trim() !== '') return;

    // «Меньше движения» — таймеры не заводятся вовсе. typed остаётся
    // нулём, и плейсхолдер ниже сам отдаёт нейтральную подпись.
    if (reducedMotion) return;

    let delay: number;
    let step: () => void;

    if (phase === 'typing') {
      if (typed < fullText.length) {
        // Символ, который только что «нажали». На пробеле и запятой
        // человек притормаживает — доля секунды на конце слова делает
        // ритм узнаваемо живым, тогда как ровный интервал выдаёт
        // машину даже на медленной скорости.
        const justTyped = fullText[typed - 1] ?? '';
        const atWordBreak = justTyped === ' ' || justTyped === ',';

        delay = humanDelay(TYPE_MS * (atWordBreak ? WORD_BREAK_FACTOR : 1));
        step = () => setTyped((n) => n + 1);
      } else {
        // Фраза набрана — держим её на экране: это единственный момент,
        // когда её реально читают.
        delay = HOLD_MS;
        step = () => setPhase('erasing');
      }
    } else {
      if (typed > 0) {
        // Стирание тоже неравномерно, но разброс тут менее заметен:
        // при зажатом backspace символы уходят почти ровно.
        delay = humanDelay(ERASE_MS);
        step = () => setTyped((n) => n - 1);
      } else {
        // Поле опустело — короткая пауза и следующая фраза. Без паузы
        // новая строка начинала бы набираться в тот же кадр, в котором
        // исчезла прошлая, и переход читался бы как рывок.
        delay = PAUSE_MS;
        step = () => {
          setIndex((current) => nextIndex(current ?? -1, total));
          setPhase('typing');
        };
      }
    }

    const timer = window.setTimeout(step, delay);
    return () => window.clearTimeout(timer);
  }, [
    hasSuggestions,
    index,
    phase,
    typed,
    fullText,
    total,
    value,
    reducedMotion,
  ]);

  // Текст плейсхолдера на текущем кадре анимации.
  //
  // БЕЗ КУРСОРА. Он тут стоял и был лишним: в поле ввода уже есть свой
  // настоящий курсор — тот, что появляется при фокусе, — и второй,
  // нарисованный внутри плейсхолдера, читался как опечатка в подсказке,
  // а не как знак набора. Само движение текста показывает, что строку
  // печатают, и подпорка ему не нужна.
  //
  // Math.min страхует смену языка: fullText меняется мгновенно, а typed
  // остаётся от прежней фразы и может оказаться длиннее новой.
  //
  // reducedMotion проверяется ЯВНО, хотя при нём typed и так остаётся
  // нулём: связь «нет таймеров → нет текста» держится на совпадении
  // двух мест, и достаточно однажды выставить typed в другом эффекте,
  // чтобы в поле навсегда застыл обрывок фразы. Здесь это исключено.
  const animatedPlaceholder =
    active && typed > 0 && !reducedMotion
      ? fullText.slice(0, Math.min(typed, fullText.length))
      : null;

  // Чипсы: активная подсказка и следующие за ней по кругу. Берутся от
  // активного индекса, поэтому ряд меняется вместе с плейсхолдером и
  // человек видит связь между ними.
  //
  // При reduced motion индекс не сменяется, и ряд стоит неподвижно —
  // это и требуется: сами подсказки остаются на месте и остаются
  // кликабельными, теряется только движение.
  // Пул — те же CHIP_COUNT подсказок по кругу от активной. Сколько из
  // них реально поместится в строку, решает pickChips: на узком экране
  // ряд ужимается до пары или до одного чипса, на широком проходит
  // целиком. Пересчёт идёт на каждую ротацию — правило применяется к
  // текущему пулу заново, как и требуется, а высота ряда при этом не
  // скачет: строка всегда одна.
  const pool: SearchSuggestion[] =
    index === null
      ? []
      : Array.from({ length: Math.min(CHIP_COUNT, total) }, (_, offset) => {
          return SEARCH_SUGGESTIONS[(index + offset) % total];
        });

  const chips = pickChips(pool, locale, mobile);

  // Фильтры, которые нужно сохранить при отправке поиска. q исключён:
  // его несёт само поле. page тоже — новый запрос начинается с первой
  // страницы, иначе поиск открыл бы пустую пятую.
  const keep = { ...filters, q: undefined, page: undefined };

  // Пары «имя параметра → значение» для скрытых полей.
  const hiddenFields = Array.from(
    new URLSearchParams(buildQuery(keep).replace(/^\?/, '')),
  );

  return (
    <div>
      {/* САМОСТОЯТЕЛЬНАЯ GET-форма. Раньше поле входило в форму
          фильтров и уезжало вместе с ней; теперь строка стоит на
          странице отдельно, поэтому отправку она обеспечивает сама.
          Метод GET обязателен: фильтры каталога живут в адресе, это
          условие SSR и шаринга ссылки. */}
      <form
        method="get"
        action={localeHref(locale, basePath)}
        className="flex gap-2"
        onSubmit={(e) => {
          const input = e.currentTarget.querySelector<HTMLInputElement>(
            'input[name="q"]',
          );

          // ПУСТОЕ ПОЛЕ — ОТПРАВКИ НЕТ ВОВСЕ.
          //
          // Раньше здесь только отключался сам input, чтобы «?q=» не
          // попадало в адрес. Форма при этом всё равно уходила, и
          // нажатие «Поиск» на пустой строке перезагружало страницу с
          // тем же адресом: выдача моргала и возвращалась к тому же
          // состоянию. Человек видел перезагрузку без результата и не
          // понимал, сработало что-то или нет.
          //
          // preventDefault оставляет страницу на месте. Фильтры при
          // этом не теряются: они уже в адресе, а перезапрашивать ту
          // же выдачу незачем.
          if (!input || input.value.trim() === '') {
            e.preventDefault();
            return;
          }

          // Пробелы по краям в адрес тоже не нужны: «?q=%20bmw» и
          // «?q=bmw» — два URL с одной выдачей. Нормализуем прямо
          // перед отправкой.
          input.value = input.value.trim();
        }}
      >
        {/* Уже применённые фильтры переносятся скрытыми полями: поиск
            СУЖАЕТ текущую выдачу, а не начинает её заново. Без этого
            ввод текста сбрасывал бы выбранную марку и цену.
            Поля строятся из готовой строки запроса: buildQuery уже
            знает соответствие «ключ фильтра → имя параметра»
            (yearFrom → year_from), и повторять эту таблицу здесь
            значило бы завести второе место, где она может разойтись. */}
        {hiddenFields.map(([name, v]) => (
          <input key={name} type="hidden" name={name} value={v} />
        ))}

        <input
          id="catalog-q"
          type="text"
          name="q"
          value={value}
          onChange={(e) => setValue(e.target.value)}
          aria-label={t('filter_search')}
          // До гидратации и при пустом списке — нейтральная подпись из
          // словаря. Она же остаётся, когда человек начал печатать.
          // Пока анимация не началась (до гидратации, при пустом списке
          // подсказок или в паузе на опустевшем поле) — нейтральная
          // подпись из словаря. Пустой плейсхолдер в эти моменты
          // оставлял бы поле без всякой подписи.
          placeholder={animatedPlaceholder ?? t('filter_search_ph')}
          className={`${fieldClassCompact} min-w-0 flex-1`}
        />

        {/* Кнопка гаснет на пустом поле, а не молча отказывает при
            нажатии: отключённый вид (opacity 40% + курсор «нельзя»)
            сообщает о невозможности ДО клика. Проверка в onSubmit при
            этом остаётся — форму отправляет и Enter в поле, и он не
            обязан спрашивать разрешения у кнопки. */}
        {/* primary, а не dark: поиск — главное действие строки, и
            иерархия ряда держится на одном акценте. «Фильтры» рядом
            остаются secondary/тёмными, поэтому зелёная кнопка в ряду
            единственная — правило «один яркий CTA на экране» не
            нарушено. Отключённый вид отдельным цветом не красится:
            disabled:opacity-40 из BASE гасит любой вариант до
            нейтрального. */}
        <Button
          type="submit"
          variant="primary"
          size="sm"
          disabled={value.trim() === ''}
          className="shrink-0"
        >
          {t('filter_search')}
        </Button>
      </form>

      {/* Ряд подсказок. Не рендерится вовсе, пока список пуст или
          гидратация не прошла: пустой контейнер сдвигал бы вёрстку.

          НАБОР ТЕКСТА РЯД НЕ УБИРАЕТ. Раньше здесь стояло ещё условие
          value.trim() === '', и на первом же нажатии клавиши ряд
          пропадал, а вся выдача под ним прыгала вверх на его высоту.
          Печать останавливает РОТАЦИЮ (эффект печатающей машинки выходит
          при непустом поле), но index при этом сохраняется — значит пул
          считается от него по-прежнему, и последний показанный набор
          остаётся на месте и остаётся кликабельным. Ровно это и нужно:
          человек, который начал печатать, ещё может передумать и
          выбрать готовую подсказку.

          flex-nowrap + overflow-hidden — ПРЕДОХРАНИТЕЛЬ, а не основной
          механизм. Состав ряда подбирает pickChips; здесь разметка лишь
          гарантирует, что промах оценки по символам обернётся срезанным
          краем последнего чипса, а не переносом на вторую строку. Ряд
          остаётся одной строкой при любом составе пула — это и есть
          условие приёмки.

          min-w-0 на чипсах не нужен: они не сжимаются (shrink-0), и
          обрезать их частично лучше, чем сплющивать текст. */}
      {chips.length > 0 && (
        <div className="mt-2 flex flex-nowrap gap-1.5 overflow-hidden">
          {chips.map((suggestion, i) => (
            <Link
              // Индекс в ключе обязателен: одна и та же фраза может
              // попасть в ряд дважды, когда подсказок меньше трёх.
              key={`${suggestion.text.sr}-${i}`}
              // Клик — ГОТОВЫЕ ФИЛЬТРЫ, а не подстановка текста в поле.
              // Свободный текст в q не попадает: подсказка знает свои
              // brand/model/fuel/priceTo и уходит в тот же buildQuery,
              // которым пользуется вся выдача.
              href={`${localeHref(locale, basePath)}${buildQuery(
                suggestion.filters,
              )}`}
              className="inline-flex shrink-0 items-center whitespace-nowrap rounded-control border border-neutral-15 px-2.5 py-1 text-small text-neutral-60 transition-colors duration-fast ease-out hover:bg-surface-hover"
            >
              {suggestion.text[locale]}
            </Link>
          ))}
        </div>
      )}
    </div>
  );
}
