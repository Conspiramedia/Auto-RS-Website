// ============================================================
// RS AUTO — Широкая карточка автосалона. Server Component.
// ============================================================
// Плитка двойной ширины, которая стоит В ТОЙ ЖЕ СЕТКЕ, что и карточки
// объявлений (grid-cols-2 md:grid-cols-3 xl:grid-cols-4), занимая две
// колонки. Показывает салон целиком: логотип, название, город,
// описание, часы работы, телефон и счётчик машин.
//
// ------------------------------------------------------------
// ГЛАВНОЕ ОГРАНИЧЕНИЕ: ВЫСОТА РАВНА ВЫСОТЕ CarCard
// ------------------------------------------------------------
// Плитка живёт в общей сетке, а grid выравнивает строку по самому
// высокому элементу. Стань она хоть на пиксель выше обычной карточки —
// весь ряд вытянулся бы под неё, и под каждой карточкой объявления
// появилась бы пустая полоса. Поэтому высота здесь не «примерно
// такая же», а СОБРАНА ИЗ ТЕХ ЖЕ ДВУХ ЧАСТЕЙ, что у CarCard:
//
//   1) верхняя зона. У CarCard на её месте стоит фотография
//      aspect-[4/3] шириной в одну колонку. Здесь ширина двойная,
//      поэтому пропорция удваивается по горизонтали: aspect-[8/3]
//      даёт РОВНО ту же высоту, хотя внутри лежит не снимок, а
//      сведения о салоне. Единственная поправка — gap сетки (16px),
//      который при col-span-2 входит в ширину плитки: из-за него
//      зона получается на 6px выше (16 × 3/8). Это компенсировано
//      текстовой зоной, см. ниже;
//
//   2) текстовая зона ФИКСИРОВАННОЙ высоты. У CarCard она набирается
//      из строк известного размера (см. SHOWCASE_TEXT_H) и не
//      меняется от содержимого: длинный текст обрезается line-clamp,
//      а не растягивает карточку.
//
// ВАЖНО: эти две части задают только ОБЩУЮ высоту, но не деление
// содержимого. Внутри карточка режется РОВНО ПОПОЛАМ: верхняя
// половина — описание, нижняя — логотип с названием и контактами.
// Поэтому высота набирается невидимым спейсером, а обе половины
// лежат поверх него абсолютно и делят намеренное им место как
// flex-1. Прежде границы совпадали с частями (262px и 120px), и
// карточка выглядела разбалансированной: описание упиралось в свой
// край, а под контактами оставался воздух.
//
// Всё, что не помещается, обрезается (overflow-hidden + line-clamp).
// Карточка физически не может стать выше — это свойство разметки,
// а не договорённость с автором текста.
//
// ------------------------------------------------------------
// ПОЧЕМУ ОНА ВЫГЛЯДИТ КАК CarCard, А НЕ КАК БАННЕР
// ------------------------------------------------------------
// Плитка стоит в выдаче рядом с объявлениями, и её задача — сообщить
// «за этими машинами стоит салон», а не перетянуть внимание. Цветной
// баннер стал бы вторым акцентом на экране, а единственный акцент
// площадки — зелёный CTA (см. lib/brand.ts). Поэтому язык тот же, что
// у карточки объявления: те же радиус, граница, ритм текста и тон
// бейджа. Выделяет плитку двойная ширина — этого достаточно, чтобы
// её не пропустили, и на экране не появляется второго акцента.
//
// ------------------------------------------------------------
// КОМПОНЕНТ НЕ ЗНАЕТ О СЕРВЕРЕ
// ------------------------------------------------------------
// Все данные приходят в props. Это обязательное условие: та же
// карточка рендерится и в каталоге из результата RPC, и в редакторе
// витрины (/my/showcase) из состояния формы — там значений в базе ещё
// нет вовсе. Любое обращение к supabase внутри сделало бы живой
// предпросмотр невозможным.
// ============================================================

import Image from 'next/image';

import type { Locale } from '@/lib/i18n';
import { getT, localeHref } from '@/lib/i18n';
import Card from './ui/Card';

// ------------------------------------------------------------
// Высота текстовой зоны — ОБЩИЙ ТОКЕН С CarCard.
// ------------------------------------------------------------
// Считается по строкам карточки объявления при её текущей типографике
// (lib/brand.ts → typography):
//   p-3 сверху                 12
//   название (body 16/24)      24
//   mt-1 + цена (h4 18/28)   4+28
//   mt-1 + год·пробег (14/20) 4+20
//   mt-0.5 + город (14/20)    2+20
//   p-3 снизу                  12
//                            ----
//                             126
//
// Дальше вычитаются 6px, на которые зона изображения этой плитки выше
// (gap сетки 16px × 3/8 — см. шапку файла). В сумме обе карточки
// получают одинаковую полную высоту.
//
// ЧИСЛО ВЫНЕСЕНО В КОНСТАНТУ, а не вписано в класс, потому что оно
// связано с чужой вёрсткой: поменяется ступень text-h4 или отступ в
// CarCard — здесь придётся пересчитать, и найти это место нужно по
// имени, а не поиском по «h-[120px]» в разметке.
const SHOWCASE_TEXT_H = 120;

// ------------------------------------------------------------
// ВЫСОТА НИЖНЕЙ ПОЛОСЫ — МИНИМУМ, ЧТОБЫ ОБЛОЖКА БЫЛА МАКСИМУМ.
// ------------------------------------------------------------
// Полная высота плитки не обсуждается: она равна высоте CarCard,
// иначе grid растянет ряд выдачи. Значит обложка растёт ровно на
// столько, на сколько ужимается низ, — это игра с нулевой суммой.
//
// 84px — не «примерно так», а сумма того, что обязано поместиться:
//
//   p-3 сверху и снизу                    24
//   логотип 40px в строке с названием      40
//   зазор между строками (gap-1)            4
//   строка контактов, micro 11/14          14
//                                        ----
//                                          82  → округлено до 84
//
// Меньше нельзя: логотип упрётся в края. Больше незачем — каждый
// лишний пиксель здесь отнимается у картинки.
//
// Что это даёт: обложка вырастает со 121→159px на мобильном и со
// 164→243px на десктопе, то есть примерно в полтора раза.
const SHOWCASE_FOOT_H = 84;

// Тот же размер классом Tailwind. Держать его отдельной строкой
// приходится потому, что сканер Tailwind читает исходник как текст и
// не вычисляет выражения: `h-[${SHOWCASE_FOOT_H}px]` он не увидел бы
// и класс в сборку не попал. Значение продублировано осознанно, и
// расхождение поймает проверка ниже.
const SHOWCASE_FOOT_H_CLASS = 'h-[84px]';

export type DealerShowcaseData = {
  // Адрес витрины строится из id. В предпросмотре редактора id уже
  // известен (это профиль владельца), поэтому ссылка рабочая и там.
  id: string;
  name: string | null;
  city: string | null;
  description: string | null;
  logoUrl: string | null;
  // Часы работы и публичный телефон салона (миграция 0095). Показаны
  // в нижнем блоке, под названием. Необязательные: у салона, который
  // их не заполнил, строки просто не печатаются — блок не оставляет
  // пустых прочерков.
  openingHours?: string | null;
  dealerPhone?: string | null;
  // Обложка витрины (миграция 0098): кадр 8:3, занимающий верхнюю
  // половину плитки. Приходит уже кадрированной — обрезку делает
  // lib/imagePrepare.ts при загрузке. null означает, что салон её не
  // загрузил, и половину займёт описание.
  coverUrl?: string | null;
  // Слоган: одна фраза под названием, до 90 символов. Короче
  // описания намеренно — он обязан влезать в две строки нижней
  // половины даже на 360px.
  tagline?: string | null;
};

type Props = {
  locale: Locale;
  dealer: DealerShowcaseData;
  // Первая плитка в ленте грузит обложку с приоритетом: она может
  // попасть в область над сгибом и повлиять на LCP.
  priority?: boolean;
  // Предпросмотр в кабинете. Отличается ровно двумя вещами:
  //   * незаполненные поля показываются серыми подсказками, а не
  //     исчезают — редактор обязан показать, ЧТО именно останется
  //     пустым у посетителя;
  //   * карточка не ссылка. Внутри формы переход по клику уводил бы
  //     со страницы с несохранёнными правками.
  preview?: boolean;
};

export default function DealerShowcaseCard({
  locale,
  dealer,
  preview = false,
  priority = false,
}: Props) {
  const t = getT(locale);

  const name = dealer.name?.trim() || null;
  const city = dealer.city?.trim() || null;
  const description = dealer.description?.trim() || null;
  const coverUrl = dealer.coverUrl?.trim() || null;
  const tagline = dealer.tagline?.trim() || null;

  // Пустая строка приравнивается к отсутствию: из базы поле может
  // прийти пробелами, и строка контактов состояла бы из пустоты,
  // занимая место.
  const openingHours = dealer.openingHours?.trim() || null;
  const dealerPhone = dealer.dealerPhone?.trim() || null;

  // Контакты собираются в массив, а печатаются одной строкой через
  // разделитель. Незаполненные отсеиваются ЗДЕСЬ, а не в разметке:
  // иначе у салона без часов работы строка получила бы висячую точку
  // между городом и телефоном.
  const contacts = [city, openingHours, dealerPhone].filter(
    (v): v is string => Boolean(v),
  );

  const href = localeHref(locale, `/dealer/${dealer.id}`);

  const card = (
    // ------------------------------------------------------------
    // КАРКАС: две РАВНЫЕ половины по высоте.
    // ------------------------------------------------------------
    // Высота задаётся невидимым спейсером aspect-[8/3] плюс
    // SHOWCASE_TEXT_H (см. шапку файла) — ровно столько же набирает
    // CarCard, и ряд сетки не поедет. Спейсер вынесен из потока
    // (absolute у половин), потому что сам он растянут пропорцией и
    // делить его нельзя: делим то, что он намерил.
    //
    // ------------------------------------------------------------
    // НАПРАВЛЕНИЕ ДЕЛЕНИЯ ЗАВИСИТ ОТ ШИРИНЫ.
    // ------------------------------------------------------------
    // С планшета (md) плитка делится ПО ВЕРТИКАЛИ: обложка слева,
    // текст справа, по половине ширины. Картинка получает всю высоту
    // карточки, а не полосу под текстом.
    //
    // На мобильном деление остаётся ГОРИЗОНТАЛЬНЫМ, и это не
    // недоделка. Плитка там шириной 328px: разрезав её пополам
    // вертикально, мы дали бы тексту 164px, то есть ~22 символа в
    // строке — «Ежедневно с 9:00 до 20:00» не помещается, телефон
    // впритык. Обложка при этом стала бы вертикальной (0.67:1), под
    // неё понадобился бы отдельный кадр. Поэтому на узком экране
    // картинка сверху во всю ширину, текст полосой под ней.
    <div className="relative flex flex-col">
      {/* Спейсер: не рисует ничего, только задаёт высоту карточки. */}
      <div
        className="aspect-[8/3] w-full"
        style={{ marginBottom: SHOWCASE_TEXT_H }}
        aria-hidden
      />
      <div className="absolute inset-0 flex flex-col md:flex-row">
        {/* ------------------------------------------------------------
            ОБЛОЖКА.
            ------------------------------------------------------------
            На мобильном — flex-1 по высоте: забирает всё, что
            остаётся от нижней полосы. С планшета — ровно половина
            ШИРИНЫ (md:basis-1/2) во всю высоту карточки.

            min-h-0 и min-w-0 оба обязательны: во flex-контейнере
            элемент не даёт сжать себя ниже содержимого, и без них
            длинный текст соседней колонки растянул бы карточку,
            сломав совпадение высоты с CarCard. Какая из осей сработает
            — зависит от направления, поэтому нужны обе. */}
        <div className="relative flex min-h-0 min-w-0 flex-1 items-center overflow-hidden bg-surface-muted md:basis-1/2">
          {coverUrl ? (
            /* ОБЛОЖКА. Кадр приходит уже обрезанным под 8:3 — это
               делает lib/imagePrepare.ts при загрузке, а не разметка.
               object-cover здесь страховка на случай, если в базе
               лежит файл, загруженный до появления кадрирования.

               unoptimized по той же причине, что у логотипа: к адресу
               добавляется метка времени при каждой замене, и
               оптимизатор Next кэшировал бы каждую версию отдельно. */
            <>
              <Image
                src={coverUrl}
                alt=""
                fill
                // На мобильном обложка во всю ширину плитки, с
                // планшета — половина её ширины. Плитка занимает две
                // колонки сетки из 2/3/4 на 360/768/1280.
                sizes="(max-width: 767px) 100vw, (max-width: 1279px) 34vw, 25vw"
                className="object-cover"
                unoptimized
                priority={priority}
              />

              {/* СЛОГАН ПОВЕРХ ОБЛОЖКИ. Из нижней полосы он ушёл:
                  та сжата до 84px ради картинки, и третьей строке
                  там места нет. Здесь же он не отнимает у обложки
                  ничего — лежит поверх неё.

                  Читаемость держит градиент снизу, а не сплошная
                  заливка: тёмный край нужен только под текстом, и
                  затемнять ради двух строк весь кадр, ради которого
                  плитка и затевалась, было бы саботажем.

                  Белый по градиенту, а не токен neutral: под текстом
                  чужая фотография, и цвет обязан работать поверх
                  любого кадра, а не поверх подложки темы. */}
              {tagline && (
                <span className="pointer-events-none absolute inset-x-0 bottom-0 bg-gradient-to-t from-black/70 via-black/40 to-transparent px-3 pb-2 pt-8">
                  <span className="line-clamp-2 text-micro font-medium text-white drop-shadow-sm">
                    {tagline}
                  </span>
                </span>
              )}
            </>
          ) : (
            /* ЗАПАСНОЙ ВАРИАНТ: обложки нет — показываем текст.
               Пустая серая плита читалась бы как незагрузившаяся
               картинка, тогда как салон её просто не загрузил. Текст
               честно занимает место кадра, и плитка выглядит
               законченной в обоих состояниях.

               Слоган здесь идёт ПЕРВЫМ и полужирным: без обложки он
               остаётся единственной короткой фразой, за которую
               цепляется глаз, и теряться в сплошном описании ему
               нельзя.

               ЧИСЛО СТРОК ПОСЧИТАНО ПОД ХУДШИЙ СЛУЧАЙ — мобильный
               экран со слоганом. Зона там 159px, слоган с зазором
               забирает 44, описанию остаётся 115px = 5 строк по 20.
               На планшете и десктопе зона выше, поэтому с xl клэмп
               поднимается до 8 (там доступно 199px = 9 строк).

               Клэмп обязан срабатывать РАНЬШЕ overflow-hidden: иначе
               последняя строка рубится пополам и остаётся ряд
               срезанных букв вместо честного многоточия.

               px-3 живёт ЗДЕСЬ, а не на родителе: у обложки полей
               быть не должно — она идёт от края до края. */
            <span className="flex min-w-0 flex-col gap-1 px-3">
              {tagline && (
                <span className="line-clamp-2 text-caption font-semibold text-neutral-80">
                  {tagline}
                </span>
              )}
              <span className="line-clamp-5 text-caption text-neutral-80 md:line-clamp-7 xl:line-clamp-8">
                {description ??
                  (preview ? (
                    <span className="text-neutral-30">
                      {t('showcase_ph_desc')}
                    </span>
                  ) : null)}
              </span>
            </span>
          )}
        </div>

        {/* ------------------------------------------------------------
            ТЕКСТОВАЯ КОЛОНКА: логотип, название, слоган, контакты.
            ------------------------------------------------------------
            С планшета — правая половина ширины во всю высоту
            (md:basis-1/2). На мобильном — полоса под обложкой
            фиксированной высоты SHOWCASE_FOOT_H: там деление
            горизонтальное, и высота полосы сведена к минимуму, чтобы
            картинке досталось больше. Расчёт 84px — у самой константы.

            shrink-0 держит полосу на мобильном: во flex-колонке с
            растущей обложкой она иначе отдала бы картинке своё место.
            С планшета shrink-0 снимается (md:shrink), иначе колонка
            откажется сжиматься под длинным названием.

            md:flex-col — на широком экране логотип встаёт НАД
            названием, а не слева от него. Слева его держать незачем:
            колонка узкая, и квадрат 40px отъедал бы у текста пятую
            часть ширины в каждой строке.

            Переход «Все объявления» и счётчик машин убраны раньше:
            обе надписи были синими и стояли рядом, из-за чего правый
            край читался как набор ссылок внутри карточки, которая
            сама целиком уже ссылка. Переход даёт клик по плитке.

            overflow-hidden — последняя линия обороны: ни длинное
            название, ни длинная строка контактов не имеют права
            растянуть карточку. */}
        <div
          className={`flex ${SHOWCASE_FOOT_H_CLASS} shrink-0 items-center gap-3 overflow-hidden px-3 md:h-auto md:min-w-0 md:shrink md:basis-1/2 md:flex-col md:items-start md:gap-2 md:py-3`}
        >
          {/* ЛОГОТИП. Небольшой квадрат у названия — так же, как в блоке
              продавца на странице объявления. Логотип узнаётся мгновенно
              и половины плитки для этого не требует.
              object-contain, а НЕ cover: логотип не фотография, и
              обрезка срезала бы часть названия компании. */}
          <span className="relative size-10 shrink-0 overflow-hidden rounded-control border border-neutral-10 bg-surface-muted">
            {dealer.logoUrl ? (
              <Image
                src={dealer.logoUrl}
                alt=""
                fill
                sizes="40px"
                className="object-contain p-1"
                // unoptimized: к адресу логотипа добавляется метка
                // времени при каждой замене, и оптимизатор Next
                // кэшировал бы каждую версию отдельно.
                unoptimized
              />
            ) : (
              // Заглушка — первая буква названия, как в шапке витрины и
              // в админской плитке салона: пустой квадрат читается как
              // незагрузившаяся картинка, а не как «логотипа нет».
              <span className="flex h-full w-full items-center justify-center font-bold text-neutral-30">
                {(name?.[0] ?? 'A').toUpperCase()}
              </span>
            )}
          </span>

          {/* НАЗВАНИЕ, СЛОГАН И КОНТАКТЫ.
              min-w-0 обязателен: без него flex-элемент отказывается
              сжиматься, и длинное название вылезло бы за край.

              h-full на md: колонка занимает всю высоту карточки, и
              контакты можно прижать к её низу (mt-auto ниже). */}
          <div className="flex min-w-0 flex-col gap-1 md:h-full md:w-full">
            <span className="truncate font-semibold">
              {name ?? (
                <span className="text-neutral-30">{t('showcase_ph_name')}</span>
              )}
            </span>

            {/* СЛОГАН показывается ТОЛЬКО с планшета (hidden md:block).
                На мобильном плитка делится горизонтально, текстовая
                полоса там 84px, и третьей строке места нет — слоган
                уходит поверх обложки, см. ветку с картинкой выше.

                С планшета колонка занимает всю высоту, слоган
                возвращается в текст и стоит сразу под названием: там
                он читается как подпись к нему, а не как надпись на
                фотографии. */}
            {tagline && (
              <span className="hidden text-micro text-neutral-80 md:line-clamp-3 md:block">
                {tagline}
              </span>
            )}

            {/* КОНТАКТЫ. На мобильном — ОДНОЙ строкой через
                точки-разделители: полоса 84px не вместит три строки,
                они съели бы 42px, которые отняты у обложки.

                С планшета высоты вдоволь, и каждый контакт получает
                свою строку — читается заметно легче, чем цепочка
                через точки. Разделитель при этом прячется
                (md:before:hidden не нужен: строки печатаются разными
                элементами, см. ниже).

                mt-auto прижимает контакты к низу колонки: у салонов с
                разной длиной слогана они окажутся на одной линии, и
                ряд плиток не будет выглядеть рваным.

                Телефон — обычный текст, а НЕ ссылка tel:. Вся плитка
                целиком уже является ссылкой на витрину салона, и
                вложенная ссылка внутри неё недопустима: браузер такую
                разметку чинит по-своему, а клик становится
                непредсказуемым. Позвонить можно со страницы салона,
                куда плитка и ведёт.

                neutral-60 — 5.55:1 на белой подложке, выше нормы AA. */}
            {contacts.length > 0 ? (
              <>
                {/* Мобильный: одна строка, truncate. */}
                <span className="truncate text-micro text-neutral-60 md:hidden">
                  {contacts.join(' · ')}
                </span>

                {/* Планшет и шире: каждый контакт своей строкой. */}
                <span className="mt-auto hidden min-w-0 flex-col gap-0.5 text-micro text-neutral-60 md:flex">
                  {contacts.map((line) => (
                    <span key={line} className="truncate">
                      {line}
                    </span>
                  ))}
                </span>
              </>
            ) : preview ? (
              <span className="truncate text-micro text-neutral-30 md:mt-auto">
                {t('showcase_ph_city')}
              </span>
            ) : null}
          </div>
        </div>
      </div>
    </div>
  );

  // ------------------------------------------------------------
  // ОБОЛОЧКА: ссылка в выдаче, простой контейнер в предпросмотре.
  // ------------------------------------------------------------
  // Плитка однотонная: та же граница и тот же радиус, что у карточки
  // объявления, без цветной кромки сверху. От соседей её отличает
  // ширина и содержимое, а не подкрашенный край.
  //
  // col-span-2 задаётся здесь, а не снаружи: ширина в две колонки —
  // свойство самой плитки, и место вызова не должно о нём помнить.
  // На мобильном (grid-cols-2) две колонки и есть вся ширина экрана.
  //
  // xl:col-start-2 — плитка встаёт В СЕРЕДИНУ ряда из четырёх колонок,
  // а не прижимается к левому краю: слева от неё одна карточка машины,
  // справа другая. Так широкий блок не рассекает ряд надвое, а лежит
  // внутри него.
  //
  // Дыру в первой колонке, которую создаёт этот сдвиг, закрывает
  // grid-flow-row-dense у самой сетки (см. CatalogView): следующая по
  // потоку карточка подтягивается назад и занимает освободившееся
  // место. Один класс без другого работать не будет — они парные.
  //
  // На мобильном и планшете сдвига нет: там две колонки — это вся
  // ширина экрана, а в сетке из трёх сдвинутая плитка оставила бы
  // ряд из одной карточки и пустоты.
  const className = 'col-span-2 xl:col-start-2';

  if (preview) {
    return (
      <Card padding="none" className={className}>
        {card}
      </Card>
    );
  }

  return (
    <Card padding="none" hoverable href={href} className={`group block ${className}`}>
      {card}
    </Card>
  );
}
