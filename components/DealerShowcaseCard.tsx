// ============================================================
// RS AUTO — Широкая карточка автосалона. Server Component.
// ============================================================
// Плитка двойной ширины, которая стоит В ТОЙ ЖЕ СЕТКЕ, что и карточки
// объявлений (grid-cols-2 md:grid-cols-3 xl:grid-cols-4), занимая две
// колонки. Показывает салон целиком: логотип, название, город,
// описание, счётчик машин и живые миниатюры его объявлений.
//
// ------------------------------------------------------------
// ГЛАВНОЕ ОГРАНИЧЕНИЕ: ВЫСОТА РАВНА ВЫСОТЕ CarCard
// ------------------------------------------------------------
// Плитка живёт в общей сетке, а grid выравнивает строку по самому
// высокому элементу. Стань она хоть на пиксель выше обычной карточки —
// весь ряд вытянулся бы под неё, и под каждой карточкой объявления
// появилась бы пустая полоса. Поэтому высота здесь не «примерно
// такая же», а СОБРАНА ИЗ ТЕХ ЖЕ ДВУХ ЧАСТЕЙ, что у CarCard:
//
//   1) зона изображения. У CarCard это aspect-[4/3] на ширину одной
//      колонки. Здесь ширина двойная, поэтому пропорция удваивается
//      по горизонтали: aspect-[8/3] даёт РОВНО ту же высоту.
//      Единственная поправка — gap сетки (16px), который при
//      col-span-2 входит в ширину плитки: из-за него зона изображения
//      получается на 6px выше (16 × 3/8). Это компенсировано
//      текстовой зоной, см. ниже;
//
//   2) текстовая зона ФИКСИРОВАННОЙ высоты. У CarCard она набирается
//      из строк известного размера (см. SHOWCASE_TEXT_H) и не
//      меняется от содержимого: длинный текст обрезается line-clamp,
//      а не растягивает карточку.
//
// Всё, что не помещается, обрезается (overflow-hidden + line-clamp).
// Карточка физически не может стать выше — это свойство разметки,
// а не договорённость с автором текста.
//
// ------------------------------------------------------------
// ПОЧЕМУ ОНА ВЫГЛЯДИТ КАК CarCard, А НЕ КАК БАННЕР
// ------------------------------------------------------------
// Плитка стоит в выдаче рядом с объявлениями, и её задача — сообщить
// «за этими машинами стоит салон», а не перетянуть внимание. Цветной
// баннер стал бы вторым акцентом на экране, а единственный акцент
// площадки — зелёный CTA (см. lib/brand.ts). Поэтому язык тот же, что
// у карточки объявления: те же радиус, граница, ритм текста и тон
// бейджа. Выделяют плитку двойная ширина и тонкая кромка сверху
// цветом brand-primary — этого достаточно, чтобы её не пропустили.
//
// ------------------------------------------------------------
// КОМПОНЕНТ НЕ ЗНАЕТ О СЕРВЕРЕ
// ------------------------------------------------------------
// Все данные приходят в props. Это обязательное условие: та же
// карточка рендерится и в каталоге из результата RPC, и в редакторе
// витрины (/my/showcase) из состояния формы — там значений в базе ещё
// нет вовсе. Любое обращение к supabase внутри сделало бы живой
// предпросмотр невозможным.
// ============================================================

import Image from 'next/image';

import type { Locale } from '@/lib/i18n';
import { getT, localeHref } from '@/lib/i18n';
import { nounFor } from '@/lib/plural';
import Badge from './ui/Badge';
import Card from './ui/Card';

// ------------------------------------------------------------
// Высота текстовой зоны — ОБЩИЙ ТОКЕН С CarCard.
// ------------------------------------------------------------
// Считается по строкам карточки объявления при её текущей типографике
// (lib/brand.ts → typography):
//   p-3 сверху                 12
//   название (body 16/24)      24
//   mt-1 + цена (h4 18/28)   4+28
//   mt-1 + год·пробег (14/20) 4+20
//   mt-0.5 + город (14/20)    2+20
//   p-3 снизу                  12
//                            ----
//                             126
//
// Дальше вычитаются 6px, на которые зона изображения этой плитки выше
// (gap сетки 16px × 3/8 — см. шапку файла). В сумме обе карточки
// получают одинаковую полную высоту.
//
// ЧИСЛО ВЫНЕСЕНО В КОНСТАНТУ, а не вписано в класс, потому что оно
// связано с чужой вёрсткой: поменяется ступень text-h4 или отступ в
// CarCard — здесь придётся пересчитать, и найти это место нужно по
// имени, а не поиском по «h-[120px]» в разметке.
const SHOWCASE_TEXT_H = 120;

// Сколько миниатюр машин показываем. Три — столько влезает рядом с
// логотипом в зону высотой с фотографию карточки объявления, оставаясь
// узнаваемыми. Четвёртая на 360px превратилась бы в марку размером
// с бейдж.
const PREVIEW_LIMIT = 3;

export type DealerShowcaseData = {
  // Адрес витрины строится из id. В предпросмотре редактора id уже
  // известен (это профиль владельца), поэтому ссылка рабочая и там.
  id: string;
  name: string | null;
  city: string | null;
  description: string | null;
  logoUrl: string | null;
  activeCars: number;
  // Адреса фотографий машин салона. Приходят готовыми: и RPC
  // get_showcase_dealers, и превью редактора отдают именно ссылки.
  previewPhotos: string[];
};

type Props = {
  locale: Locale;
  dealer: DealerShowcaseData;
  // Предпросмотр в кабинете. Отличается ровно двумя вещами:
  //   * незаполненные поля показываются серыми подсказками, а не
  //     исчезают — редактор обязан показать, ЧТО именно останется
  //     пустым у посетителя;
  //   * карточка не ссылка. Внутри формы переход по клику уводил бы
  //     со страницы с несохранёнными правками.
  preview?: boolean;
  // Первая карточка в ленте грузит логотип с приоритетом: она попадает
  // в область над сгибом и влияет на LCP.
  priority?: boolean;
};

export default function DealerShowcaseCard({
  locale,
  dealer,
  preview = false,
  priority = false,
}: Props) {
  const t = getT(locale);

  const name = dealer.name?.trim() || null;
  const city = dealer.city?.trim() || null;
  const description = dealer.description?.trim() || null;

  // Миниатюры: пустые строки отсеиваем здесь, а не в разметке. Пустой
  // src у next/image — ошибка рендера, и одна битая ссылка из базы
  // уронила бы страницу целиком.
  const photos = dealer.previewPhotos
    .filter((url) => typeof url === 'string' && url.trim() !== '')
    .slice(0, PREVIEW_LIMIT);

  const href = localeHref(locale, `/dealer/${dealer.id}`);

  const card = (
    <div className="flex h-full flex-col">
      {/* ------------------------------------------------------------
          ЗОНА ИЗОБРАЖЕНИЯ: логотип + миниатюры машин.
          ------------------------------------------------------------
          aspect-[8/3] — двойная ширина при той же высоте, что у
          aspect-[4/3] карточки объявления (см. шапку файла).
          shrink-0 обязателен: во flex-колонке зона с фиксированной
          пропорцией иначе сжалась бы под текст. */}
      <div className="relative aspect-[8/3] shrink-0 overflow-hidden bg-surface-muted">
        <div className="flex h-full">
          {/* ЛОГОТИП — КВАДРАТ ВО ВСЮ ВЫСОТУ ЗОНЫ.
              aspect-square вместо фиксированной ширины: высота зоны
              зависит от брейкпоинта, и квадрат обязан следовать за
              ней, иначе на 1280px логотип занял бы половину плитки,
              а на 360px — угол.
              Подложка bg-surface-muted та же, что у заглушки фото в
              CarCard: логотипы часто с прозрачным фоном, и на белом
              они бы висели в воздухе. */}
          <div className="relative aspect-square h-full shrink-0 overflow-hidden border-r border-neutral-10 bg-surface-muted">
            {dealer.logoUrl ? (
              <Image
                src={dealer.logoUrl}
                alt={name ?? ''}
                fill
                // Логотип квадратный и равен высоте фотозоны: на
                // мобильном это ~123px (360/2 - отступы), на десктопе
                // ~216px. Границы те же, что у сетки карточек.
                sizes="(max-width: 767px) 40vw, (max-width: 1279px) 25vw, 20vw"
                // object-contain, а НЕ cover: логотип — не фотография.
                // cover обрезал бы вытянутые логотипы по краям, срезая
                // часть названия компании.
                className="object-contain p-2"
                priority={priority}
                // unoptimized по той же причине, что в форме профиля:
                // к адресу логотипа добавляется метка времени при
                // каждой замене, и оптимизатор Next кэшировал бы
                // каждую версию отдельно.
                unoptimized
              />
            ) : (
              // Заглушка — первая буква названия, как в шапке витрины
              // и в админской плитке салона: пустой серый квадрат
              // читается как незагрузившаяся картинка, а не как
              // «логотипа пока нет».
              <span className="flex h-full w-full items-center justify-center text-h1 font-bold text-neutral-30">
                {(name?.[0] ?? 'A').toUpperCase()}
              </span>
            )}
          </div>

          {/* РЯД МИНИАТЮР. Занимает остаток ширины.
              Схлопывается ЧЕСТНО: при отсутствии фотографий блок не
              рендерится вовсе, и логотип с текстом занимают всю зону.
              Пустые квадраты-заглушки здесь были бы хуже пустоты —
              они выглядят как не загрузившиеся снимки.

              overflow-x-auto + snap-x: на мобильном три миниатюры
              рядом с логотипом становятся узкими, и ряд прокручивается
              пальцем. На десктопе прокрутки не возникает — элементы
              помещаются. */}
          {photos.length > 0 && (
            <div className="flex min-w-0 flex-1 snap-x gap-px overflow-x-auto">
              {photos.map((url, i) => (
                <div
                  key={`${url}-${i}`}
                  className="relative aspect-square h-full shrink-0 snap-start bg-surface-muted"
                >
                  <Image
                    src={url}
                    alt=""
                    fill
                    sizes="(max-width: 767px) 40vw, (max-width: 1279px) 25vw, 20vw"
                    className="object-cover"
                  />
                </div>
              ))}
            </div>
          )}
        </div>

        {/* БЕЙДЖ «АВТОСАЛОН» — в том же ряду и на том же месте, что
            бейджи карточки объявления (inset-x-2 top-2). Совпадение
            позиции не косметика: в ряду выдачи глаз ищет метки на
            одной линии, и сдвинутый бейдж читался бы как элемент
            другого рода.
            Тон dark — тот же, что у метки салона на плитке
            объявления (см. Badge): это подпись «кто продаёт», а не
            акцент. */}
        <div className="pointer-events-none absolute inset-x-2 top-2 flex flex-wrap items-start gap-1.5">
          <Badge tone="dark" size="xs">
            {t('badge_dealer')}
          </Badge>
        </div>
      </div>

      {/* ------------------------------------------------------------
          ТЕКСТОВАЯ ЗОНА ФИКСИРОВАННОЙ ВЫСОТЫ.
          ------------------------------------------------------------
          Ритм строк повторяет CarCard: название → крупная цифра на
          месте цены → вторичный текст → город. Благодаря этому обе
          карточки в одном ряду читаются как один список, а не как
          плитка и вставка.
          overflow-hidden — последняя линия обороны: даже если текст
          неожиданно займёт больше строк, карточка не вырастет. */}
      <div
        className="flex shrink-0 flex-col overflow-hidden p-3"
        style={{ height: SHOWCASE_TEXT_H }}
      >
        {/* Название салона. truncate, а не перенос: имя в две строки
            съело бы строку описания. */}
        <div className="truncate font-semibold">
          {name ?? (
            <span className="text-neutral-30">{t('showcase_ph_name')}</span>
          )}
        </div>

        {/* Счётчик машин занимает место цены — самый заметный элемент
            карточки объявления. У салона роль «главной цифры» играет
            размер автопарка: именно он отвечает на вопрос «зачем сюда
            заходить».
            Подпись склоняется по числу (nounFor): «1 automobil»,
            «5 automobila» — та же функция, что в статистике главной. */}
        <div className="mt-1 text-h4 font-bold text-brand-primary">
          {dealer.activeCars} {nounFor(dealer.activeCars, 'car', locale)}
        </div>

        {/* Описание. line-clamp-2 — жёсткая граница: длинный текст
            обрезается многоточием, а не растягивает плитку.
            min-h-0 нужен внутри flex-колонки, иначе блок с обрезкой
            откажется сжиматься и вытеснит город. */}
        <div className="mt-1 min-h-0 line-clamp-2 text-caption text-neutral-60">
          {description ?? (
            <span className="text-neutral-30">{t('showcase_ph_desc')}</span>
          )}
        </div>

        {/* Город прижат к низу (mt-auto): у карточек с коротким и
            длинным описанием он окажется на одной линии, и ряд
            плиток не будет выглядеть рваным. */}
        <div className="mt-auto truncate pt-0.5 text-caption text-neutral-50">
          {city ?? (
            <span className="text-neutral-30">{t('showcase_ph_city')}</span>
          )}
        </div>
      </div>
    </div>
  );

  // ------------------------------------------------------------
  // ОБОЛОЧКА: ссылка в выдаче, простой контейнер в предпросмотре.
  // ------------------------------------------------------------
  // border-t-2 сверху — единственное цветовое отличие от карточки
  // объявления. Двойная толщина, а не заливка: кромка обозначает
  // «здесь другой тип строки», не претендуя на роль акцента.
  //
  // col-span-2 задаётся здесь, а не снаружи: ширина в две колонки —
  // свойство самой плитки, и место вызова не должно о нём помнить.
  // На мобильном (grid-cols-2) две колонки и есть вся ширина экрана.
  const className = 'col-span-2 border-t-2 border-t-brand-primary';

  if (preview) {
    return (
      <Card padding="none" className={className}>
        {card}
      </Card>
    );
  }

  return (
    <Card padding="none" hoverable href={href} className={`group block ${className}`}>
      {card}
    </Card>
  );
}
