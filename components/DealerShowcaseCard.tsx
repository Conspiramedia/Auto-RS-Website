// ============================================================
// RS AUTO — Широкая карточка автосалона. Server Component.
// ============================================================
// Плитка двойной ширины, которая стоит В ТОЙ ЖЕ СЕТКЕ, что и карточки
// объявлений (grid-cols-2 md:grid-cols-3 xl:grid-cols-4), занимая две
// колонки. Показывает салон целиком: логотип, название, город,
// описание, часы работы, телефон и счётчик машин.
//
// ------------------------------------------------------------
// ГЛАВНОЕ ОГРАНИЧЕНИЕ: ВЫСОТА РАВНА ВЫСОТЕ CarCard
// ------------------------------------------------------------
// Плитка живёт в общей сетке, а grid выравнивает строку по самому
// высокому элементу. Стань она хоть на пиксель выше обычной карточки —
// весь ряд вытянулся бы под неё, и под каждой карточкой объявления
// появилась бы пустая полоса. Поэтому высота здесь не «примерно
// такая же», а СОБРАНА ИЗ ТЕХ ЖЕ ДВУХ ЧАСТЕЙ, что у CarCard:
//
//   1) верхняя зона. У CarCard на её месте стоит фотография
//      aspect-[4/3] шириной в одну колонку. Здесь ширина двойная,
//      поэтому пропорция удваивается по горизонтали: aspect-[8/3]
//      даёт РОВНО ту же высоту, хотя внутри лежит не снимок, а
//      сведения о салоне. Единственная поправка — gap сетки (16px),
//      который при col-span-2 входит в ширину плитки: из-за него
//      зона получается на 6px выше (16 × 3/8). Это компенсировано
//      текстовой зоной, см. ниже;
//
//   2) текстовая зона ФИКСИРОВАННОЙ высоты. У CarCard она набирается
//      из строк известного размера (см. SHOWCASE_TEXT_H) и не
//      меняется от содержимого: длинный текст обрезается line-clamp,
//      а не растягивает карточку.
//
// Всё, что не помещается, обрезается (overflow-hidden + line-clamp).
// Карточка физически не может стать выше — это свойство разметки,
// а не договорённость с автором текста.
//
// ------------------------------------------------------------
// ПОЧЕМУ ОНА ВЫГЛЯДИТ КАК CarCard, А НЕ КАК БАННЕР
// ------------------------------------------------------------
// Плитка стоит в выдаче рядом с объявлениями, и её задача — сообщить
// «за этими машинами стоит салон», а не перетянуть внимание. Цветной
// баннер стал бы вторым акцентом на экране, а единственный акцент
// площадки — зелёный CTA (см. lib/brand.ts). Поэтому язык тот же, что
// у карточки объявления: те же радиус, граница, ритм текста и тон
// бейджа. Выделяет плитку двойная ширина — этого достаточно, чтобы
// её не пропустили, и на экране не появляется второго акцента.
//
// ------------------------------------------------------------
// КОМПОНЕНТ НЕ ЗНАЕТ О СЕРВЕРЕ
// ------------------------------------------------------------
// Все данные приходят в props. Это обязательное условие: та же
// карточка рендерится и в каталоге из результата RPC, и в редакторе
// витрины (/my/showcase) из состояния формы — там значений в базе ещё
// нет вовсе. Любое обращение к supabase внутри сделало бы живой
// предпросмотр невозможным.
// ============================================================

import Image from 'next/image';

import type { Locale } from '@/lib/i18n';
import { getT, localeHref } from '@/lib/i18n';
import { nounFor } from '@/lib/plural';
import Badge from './ui/Badge';
import Card from './ui/Card';

// ------------------------------------------------------------
// Высота текстовой зоны — ОБЩИЙ ТОКЕН С CarCard.
// ------------------------------------------------------------
// Считается по строкам карточки объявления при её текущей типографике
// (lib/brand.ts → typography):
//   p-3 сверху                 12
//   название (body 16/24)      24
//   mt-1 + цена (h4 18/28)   4+28
//   mt-1 + год·пробег (14/20) 4+20
//   mt-0.5 + город (14/20)    2+20
//   p-3 снизу                  12
//                            ----
//                             126
//
// Дальше вычитаются 6px, на которые зона изображения этой плитки выше
// (gap сетки 16px × 3/8 — см. шапку файла). В сумме обе карточки
// получают одинаковую полную высоту.
//
// ЧИСЛО ВЫНЕСЕНО В КОНСТАНТУ, а не вписано в класс, потому что оно
// связано с чужой вёрсткой: поменяется ступень text-h4 или отступ в
// CarCard — здесь придётся пересчитать, и найти это место нужно по
// имени, а не поиском по «h-[120px]» в разметке.
const SHOWCASE_TEXT_H = 120;

export type DealerShowcaseData = {
  // Адрес витрины строится из id. В предпросмотре редактора id уже
  // известен (это профиль владельца), поэтому ссылка рабочая и там.
  id: string;
  name: string | null;
  city: string | null;
  description: string | null;
  logoUrl: string | null;
  activeCars: number;
  // Часы работы и публичный телефон салона (миграция 0095). Показаны
  // в нижнем блоке, под названием. Необязательные: у салона, который
  // их не заполнил, строки просто не печатаются — блок не оставляет
  // пустых прочерков.
  openingHours?: string | null;
  dealerPhone?: string | null;
};

type Props = {
  locale: Locale;
  dealer: DealerShowcaseData;
  // Предпросмотр в кабинете. Отличается ровно двумя вещами:
  //   * незаполненные поля показываются серыми подсказками, а не
  //     исчезают — редактор обязан показать, ЧТО именно останется
  //     пустым у посетителя;
  //   * карточка не ссылка. Внутри формы переход по клику уводил бы
  //     со страницы с несохранёнными правками.
  preview?: boolean;
};

export default function DealerShowcaseCard({
  locale,
  dealer,
  preview = false,
}: Props) {
  const t = getT(locale);

  const name = dealer.name?.trim() || null;
  const city = dealer.city?.trim() || null;
  const description = dealer.description?.trim() || null;
  // Пустая строка приравнивается к отсутствию: из базы поле может
  // прийти пробелами, и строка контактов состояла бы из пустоты,
  // занимая место.
  const openingHours = dealer.openingHours?.trim() || null;
  const dealerPhone = dealer.dealerPhone?.trim() || null;

  const href = localeHref(locale, `/dealer/${dealer.id}`);

  const card = (
    <div className="flex h-full flex-col">
      {/* ------------------------------------------------------------
          ВЕРХНЯЯ ЗОНА: сведения о салоне на всю ширину.
          ------------------------------------------------------------
          aspect-[8/3] — двойная ширина при той же высоте, что у
          aspect-[4/3] карточки объявления. Это ядро всей конструкции:
          высота плитки обязана совпасть с высотой CarCard, иначе grid
          растянет весь ряд под неё и под каждой карточкой машины
          появится пустая полоса. Разбор арифметики — в шапке файла.

          shrink-0 обязателен: во flex-колонке зона с фиксированной
          пропорцией иначе сжалась бы под текст. */}
      <div className="relative aspect-[8/3] shrink-0 overflow-hidden bg-surface-muted">
        {/* ОПИСАНИЕ САЛОНА занимает верхнюю зону целиком.

            Здесь только рассказ о салоне и ничего больше. Город, часы
            работы и телефон переехали вниз, к логотипу: это короткие
            служебные строки, они не нуждаются в широкой зоне и раньше
            отнимали у описания половину высоты. Фотографий машин тоже
            нет — вокруг плитки и так стоит ряд карточек объявлений
            того же каталога. */}
        <div className="flex h-full min-w-0 flex-col overflow-hidden p-3">
          {/* Описание — главный текст блока, поэтому neutral-80: на
              подложке surface-muted это 11.7:1, уверенно выше нормы
              AA (4.5:1). Ступень 30, которой набраны подсказки,
              дала бы 2.1:1 и для содержательного текста не годится.

              ЧИСЛО СТРОК БОЛЬШЕ НЕ ТРИ. Раньше описание делило зону с
              контактами и обрывалось на третьей строке, хотя ниже
              оставался пустой воздух. Контакты ушли вниз, к логотипу,
              и текст занимает высоту целиком (flex-1).

              line-clamp-[9] — страховка, а не рабочая граница.
              Физический предел ставит overflow-hidden зоны: сколько
              строк влезло по высоте, столько и видно. Но обрезка по
              overflow рубит последнюю строку пополам, показывая ряд
              срезанных букв; clamp даёт вместо этого честное
              многоточие. Девять строк — заведомо больше, чем
              помещается на любом брейкпоинте
              (при 14/20 в зону 8/3 влезает 8 строк даже на самой
              широкой сетке), поэтому в норме срабатывает именно
              многоточие. */}
          <p className="line-clamp-[9] min-h-0 flex-1 text-caption text-neutral-80">
            {description ??
              (preview ? (
                <span className="text-neutral-30">{t('showcase_ph_desc')}</span>
              ) : null)}
          </p>
        </div>
      </div>

      {/* ------------------------------------------------------------
          НИЖНИЙ БЛОК: логотип, название с контактами, счётчик, переход.
          ------------------------------------------------------------
          Высота фиксирована (SHOWCASE_TEXT_H) и равна текстовой зоне
          CarCard — это условие всей конструкции: плитка обязана
          совпадать по высоте с соседями, иначе grid растянет или
          прижмёт весь ряд выдачи.

          Контакты стоят ЗДЕСЬ, а не в верхней зоне, куда их помещала
          прежняя вёрстка. Город, часы и телефон — короткие служебные
          строки, и широкая зона им не нужна; зато описанию, которое
          они оттуда вытесняли, ширина и высота нужны обе. В этом блоке
          они укладываются в уже существовавший запас: строка была
          одна, а по высоте отведено 120px, и лишнее просто уходило в
          воздух. Теперь воздух занят делом, а высота не изменилась.

          items-center → items-start: блок стал двухстрочным, и
          логотип выравнивается по верху названия, а не по середине
          пары «название + контакты».

          overflow-hidden — последняя линия обороны: ни длинное
          название, ни лишняя строка контактов не имеют права
          растянуть карточку. */}
      <div
        className="flex shrink-0 items-start gap-3 overflow-hidden px-3 py-3"
        style={{ height: SHOWCASE_TEXT_H }}
      >
        {/* ЛОГОТИП. Небольшой квадрат у названия — так же, как в блоке
            продавца на странице объявления. Логотип узнаётся мгновенно
            и половины плитки для этого не требует.
            object-contain, а НЕ cover: логотип не фотография, и
            обрезка срезала бы часть названия компании. */}
        <span className="relative size-10 shrink-0 overflow-hidden rounded-control border border-neutral-10 bg-surface-muted">
          {dealer.logoUrl ? (
            <Image
              src={dealer.logoUrl}
              alt=""
              fill
              sizes="40px"
              className="object-contain p-1"
              // unoptimized: к адресу логотипа добавляется метка
              // времени при каждой замене, и оптимизатор Next
              // кэшировал бы каждую версию отдельно.
              unoptimized
            />
          ) : (
            // Заглушка — первая буква названия, как в шапке витрины и
            // в админской плитке салона: пустой квадрат читается как
            // незагрузившаяся картинка, а не как «логотипа нет».
            <span className="flex h-full w-full items-center justify-center font-bold text-neutral-30">
              {(name?.[0] ?? 'A').toUpperCase()}
            </span>
          )}
        </span>

        {/* НАЗВАНИЕ, МЕТКА И КОНТАКТЫ — одна колонка.
            min-w-0 обязателен на обоих уровнях: без него flex-элемент
            отказывается сжиматься, и длинное название вытолкнуло бы
            счётчик с переходом за край. */}
        <div className="flex min-w-0 flex-col gap-1">
          <div className="flex min-w-0 items-center gap-2">
            <span className="truncate font-semibold">
              {name ?? (
                <span className="text-neutral-30">{t('showcase_ph_name')}</span>
              )}
            </span>

            {/* Метка переехала сюда с фотографии. Поверх снимка она
                спорила с бейджами карточек объявлений («Аренда»,
                «Просмотрено»), стоявшими на той же линии, — а здесь
                читается как подпись к названию, чем она и является.
                Тон dark: это указание, кто продаёт, а не акцент. */}
            <Badge tone="dark" size="xs" className="shrink-0">
              {t('badge_dealer')}
            </Badge>
          </div>

          {/* КОНТАКТЫ салона: город, часы работы, телефон.
              neutral-60 — 5.55:1 на белой подложке карточки, выше
              нормы AA. Ступень ниже названия: это уточнение, а не
              заголовок.

              text-micro (11/14): три строки занимают 42px и вместе с
              названием укладываются в отведённые 120px, не меняя
              высоту плитки.

              Каждая строка печатается только заполненной: пустые поля
              не заменяются заглушками — незаполненный телефон
              прочерком выглядел бы как ошибка загрузки. Исключение —
              предпросмотр редактора, где владельцу нужно видеть, что
              именно останется пустым у посетителя. */}
          <div className="min-w-0 text-micro text-neutral-60">
            {city ? (
              <div className="truncate">{city}</div>
            ) : preview ? (
              <div className="truncate text-neutral-30">
                {t('showcase_ph_city')}
              </div>
            ) : null}

            {openingHours && <div className="truncate">{openingHours}</div>}

            {/* Телефон — обычный текст, а НЕ ссылка tel:. Вся плитка
                целиком уже является ссылкой на витрину салона, и
                вложенная ссылка внутри неё недопустима: браузер такую
                разметку чинит по-своему, а клик становится
                непредсказуемым. Позвонить можно со страницы салона,
                куда плитка и ведёт. */}
            {dealerPhone && <div className="truncate">{dealerPhone}</div>}
          </div>
        </div>

        {/* Счётчик машин — синим, на месте цены карточки объявления.
            У салона роль «главной цифры» играет размер автопарка:
            именно он отвечает на вопрос, зачем сюда заходить.
            Подпись склоняется по числу (nounFor): «1 automobil»,
            «5 automobila».

            ml-auto прижимает счётчик и переход к правому краю. Блок
            выровнен по верху (items-start родителя), поэтому оба
            стоят на линии названия, а не съезжают к контактам под
            ним. */}
        <span className="ml-auto shrink-0 font-semibold text-brand-primary">
          {dealer.activeCars} {nounFor(dealer.activeCars, 'car', locale)}
        </span>

        {/* ПЕРЕХОД НА ВИТРИНУ. Не ссылка и не кнопка — обычный текст:
            вся плитка уже является ссылкой на витрину салона, и
            вложенный интерактивный элемент внутри ссылки — невалидная
            разметка, которую браузеры чинят каждый по-своему.
            Выглядит как призыв, работает как часть общей ссылки.

            На узких экранах прячется (hidden sm:inline): в ряду
            шириной 360px он вытеснял бы счётчик, а тот важнее — цифра
            сообщает факт, стрелка лишь повторяет то, что и так
            понятно из кликабельности карточки. */}
        <span className="hidden shrink-0 font-semibold text-brand-primary sm:inline">
          {t('showcase_all_listings')} →
        </span>
      </div>
    </div>
  );

  // ------------------------------------------------------------
  // ОБОЛОЧКА: ссылка в выдаче, простой контейнер в предпросмотре.
  // ------------------------------------------------------------
  // Плитка однотонная: та же граница и тот же радиус, что у карточки
  // объявления, без цветной кромки сверху. От соседей её отличает
  // ширина и содержимое, а не подкрашенный край.
  //
  // col-span-2 задаётся здесь, а не снаружи: ширина в две колонки —
  // свойство самой плитки, и место вызова не должно о нём помнить.
  // На мобильном (grid-cols-2) две колонки и есть вся ширина экрана.
  //
  // xl:col-start-2 — плитка встаёт В СЕРЕДИНУ ряда из четырёх колонок,
  // а не прижимается к левому краю: слева от неё одна карточка машины,
  // справа другая. Так широкий блок не рассекает ряд надвое, а лежит
  // внутри него.
  //
  // Дыру в первой колонке, которую создаёт этот сдвиг, закрывает
  // grid-flow-row-dense у самой сетки (см. CatalogView): следующая по
  // потоку карточка подтягивается назад и занимает освободившееся
  // место. Один класс без другого работать не будет — они парные.
  //
  // На мобильном и планшете сдвига нет: там две колонки — это вся
  // ширина экрана, а в сетке из трёх сдвинутая плитка оставила бы
  // ряд из одной карточки и пустоты.
  const className = 'col-span-2 xl:col-start-2';

  if (preview) {
    return (
      <Card padding="none" className={className}>
        {card}
      </Card>
    );
  }

  return (
    <Card padding="none" hoverable href={href} className={`group block ${className}`}>
      {card}
    </Card>
  );
}
