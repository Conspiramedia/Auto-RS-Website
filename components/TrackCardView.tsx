'use client';

// ============================================================
// RS AUTO — Отметка просмотра карточки объявления.
// ============================================================
// Делает две вещи при открытии страницы объявления:
//   1. событие аналитики card_view;
//   2. запись в историю «недавно просмотренные» (localStorage).
//
// Оба действия возможны только в браузере, а карточка (CarPageView) —
// серверный компонент. Этот компонент ничего не рендерит: он существует
// ради двух вызовов в useEffect.
//
// Почему не 'use client' на всей карточке: перевод страницы объявления
// в клиентский рендер лишил бы её SSR — того, ради чего она построена
// (SEO, OG-превью, скорость первой отрисовки).
// ============================================================

import { useEffect, useRef } from 'react';

import { rememberCar, type RecentCar } from './RecentlyViewed';
import { trackEvent } from '@/lib/analytics';

type Props = {
  // Снимок карточки для истории просмотров. Марка и модель из него же
  // уходят в аналитику — по ним видно, какие автомобили смотрят чаще.
  // Идентификатор объявления в АНАЛИТИКУ не передаём: он бесполезен
  // в отчётах и превращает событие в след конкретного пользователя.
  // В localStorage он нужен — это личная история самого посетителя.
  car: RecentCar;
  listingType: 'sale' | 'rent';
};

export default function TrackCardView({ car, listingType }: Props) {
  // Идентификатор объявления, по которому событие УЖЕ отправлено.
  //
  // ЗАЧЕМ. В режиме разработки React StrictMode монтирует компонент
  // дважды и дважды выполняет эффект — без защиты каждый просмотр
  // карточки давал бы два события card_view. В обычной сборке
  // StrictMode не работает, но полагаться на это нельзя: цифры
  // расходились бы между dev и prod, и заметить ошибку в разметке
  // целей стало бы невозможно.
  //
  // Почему ref, а не state: значение не влияет на разметку, и
  // перерисовка из-за него была бы лишней. Ref переживает повторный
  // вызов эффекта, потому что сам компонент при этом не размонтируется
  // (StrictMode переиспользует экземпляр).
  //
  // Сравнение по id, а не булев флаг: в каталоге переход между
  // карточками может переиспользовать компонент с новым объявлением —
  // тогда событие обязано уйти снова, но уже для другого id.
  const trackedId = useRef<string | null>(null);

  useEffect(() => {
    if (trackedId.current === car.id) return;
    trackedId.current = car.id;

    trackEvent('card_view', {
      brand: car.brand,
      model: car.model,
      listing_type: listingType,
    });

    rememberCar(car);
    // Зависимость только от id: объект car пересоздаётся при каждом
    // рендере, и полный список зависимостей вызывал бы эффект заново
    // без причины.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [car.id, listingType]);

  return null;
}
