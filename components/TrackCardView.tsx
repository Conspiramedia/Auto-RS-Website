'use client';

// ============================================================
// RS AUTO — Отметка просмотра карточки объявления.
// ============================================================
// Карточка (CarPageView) — серверный компонент, а событие аналитики
// можно отправить только из браузера. Этот компонент ничего не
// рендерит: он существует ровно ради одного вызова в useEffect.
//
// Почему отдельный компонент, а не 'use client' на всей карточке:
// перевод страницы объявления в клиентский рендер лишил бы её SSR,
// то есть ровно того, ради чего она построена (SEO, OG-превью).
// ============================================================

import { useEffect } from 'react';

import { trackEvent } from '@/lib/analytics';

type Props = {
  // Марка и модель — по ним видно, какие автомобили смотрят чаще.
  // Идентификатор объявления НЕ передаём: он бесполезен в отчётах и
  // превращает событие в след конкретного пользователя.
  brand: string;
  model: string;
  // Тип сделки: продажа или аренда.
  listingType: 'sale' | 'rent';
};

export default function TrackCardView({ brand, model, listingType }: Props) {
  useEffect(() => {
    trackEvent('card_view', {
      brand,
      model,
      listing_type: listingType,
    });
  }, [brand, model, listingType]);

  return null;
}
