// ============================================================
// RS AUTO — Строка над витриной салона. Server Component.
// ============================================================
// «Автосалон RS Auto» слева и крестик справа. Стоит над баннером
// витрины и служит двум разным людям одновременно:
//
//   покупателю — говорит, ЧЕЙ это раздел, до того как он дойдёт до
//     названия на самом баннере. Витрина открывается по клику из
//     выдачи, и первая строка страницы обязана подтвердить, куда
//     человек попал;
//
//   владельцу — даёт выход. Он приходит сюда кнопкой «Моя витрина»
//     из кабинета, и без крестика возвращаться пришлось бы кнопкой
//     браузера.
//
// ------------------------------------------------------------
// ПОЧЕМУ ТЕПЕРЬ ВИДНА ВСЕМ, А НЕ ТОЛЬКО ХОЗЯИНУ
// ------------------------------------------------------------
// Прежде здесь была надпись «Моя витрина», и показывать её
// постороннему было нельзя — отсюда клиентский компонент с проверкой
// сессии в браузере (см. историю DealerOwnerBar). Теперь текст
// нейтрален: «Автосалон N» верно для любого читателя, и личного в нём
// ничего нет.
//
// Это снимает всю прежнюю сложность. Компонент стал СЕРВЕРНЫМ:
// страница кэшируется (revalidate = 300 в app/dealer/[id]/page.tsx),
// и раз разметка одинакова для всех, она спокойно ложится в общий
// кэш. Исчезло и мигание «пусто → полоса» после гидратации, которым
// приходилось платить за проверку сессии.
//
// ------------------------------------------------------------
// ЭТО НЕ h1
// ------------------------------------------------------------
// Главный заголовок страницы — название салона на баннере ниже, и оно
// обязано им остаться: витрина индексируется, а два h1 ломают
// структуру документа. Здесь достаточно обычного текста той же
// ступени — визуально одинаково, семантически честно.
// ============================================================

import BackCloseButton from '@/components/BackCloseButton';
import type { Locale } from '@/lib/i18n';
import { getT } from '@/lib/i18n';

type Props = {
  locale: Locale;
  // Название салона. Приходит готовым из get_dealer_profile: там оно
  // уже подставлено запасным значением, если компания его не
  // заполнила, — пустым не бывает.
  name: string;
};

export default function DealerShowcaseTitleBar({ locale, name }: Props) {
  const t = getT(locale);

  return (
    // Разметка повторяет шапку кабинета (MyLayoutView): заголовок
    // слева, контрол справа, min-w-0 у текста — при нехватке места
    // сжимается заголовок, а не кнопка, промахнуться по которой
    // нельзя.
    <div className="mb-4 flex items-center justify-between gap-x-4">
      <span className="min-w-0 truncate text-h2 font-bold sm:text-h1">
        {t('car_seller_dealer')} {name}
      </span>

      {/* КРЕСТИК ВЕДЁТ НАЗАД ПО ИСТОРИИ, а не по фиксированному
          адресу. Прежде он всегда возвращал в профиль — это годилось,
          пока полосу видел только владелец, пришедший из кабинета.
          Теперь сюда попадают отовсюду: из выдачи каталога, из
          карточки объявления, из результатов поиска, — и единственный
          верный ответ на «закрыть» у каждого свой.

          BackCloseButton решает это тем же способом, что на
          справочных страницах: history.back(), а при прямом заходе (в
          истории вкладки ничего нет) — переход на каталог. Каталог, а
          не главная: человек, открывший витрину салона по ссылке,
          ищет машины, и список объявлений ближе к его намерению, чем
          промо-страница.

          size-11 (44px) вместо стандартных 40px: крестик стоит у
          самой кромки экрана, где промах означает случайный тап по
          заголовку. Это минимум из рекомендаций Apple HIG и Material.

          -mr-2 втягивает область нажатия в боковой отступ страницы,
          чтобы сам знак встал на одну вертикаль с содержимым ниже. */}
      <BackCloseButton
        locale={locale}
        fallbackPath="/cars"
        className="-mr-2 size-11"
      />
    </div>
  );
}
