'use client';

// ============================================================
// RS AUTO — Кнопка выхода из кабинета.
// ============================================================
// Client Component нужен ровно для трёх вещей: спросить подтверждение,
// показать промежуточное состояние («Выходим…» вместо мёртвой кнопки)
// и не дать нажать дважды. Сам выход выполняет Server Action
// (app/my/actions.ts) — только он может удалить cookie сессии.
//
// ПОЧЕМУ ВЫХОД СПРАШИВАЕТ ПОДТВЕРЖДЕНИЕ. Раньше он выполнялся с
// первого нажатия. Цена случайного нажатия здесь несоразмерна: вход
// в RS Auto — это SMS-код, то есть повторный вход стоит человеку
// ожидания сообщения и расхода суточной квоты (5 SMS на номер,
// миграция 0035). Кнопка при этом стоит в шапке кабинета рядом с
// вкладками, по которым переключаются постоянно.
//
// ПОЧЕМУ ДИАЛОГ, А НЕ ВОПРОС В СТРОКЕ. Сначала подтверждение было
// сделано переключением самой кнопки («Выйти из аккаунта? Да Отмена»),
// как у действий над объявлением. Для выхода этого мало: строка
// физически вмещает только вопрос, а объяснить нужно ПОСЛЕДСТВИЯ.
// Главное здесь — то, что НЕ происходит: аккаунт не удаляется,
// объявления и переписка остаются. Без этой строки выход выглядит
// опаснее, чем есть, и человек либо боится нажать, либо жмёт вслепую.
//
// window.confirm не годится: он выглядит как системная ошибка,
// не переводится на сербский и не поддаётся стилизации.
//
// Разметка диалога повторяет шторку фильтров (FilterPanel): затемнение
// на весь экран, снизу на мобильном и по центру с sm. Своего варианта
// модального окна заводить нельзя — два разных диалога на сайте
// читались бы как элементы разных продуктов.
//
// ВИД КНОПКИ. Ссылка без заливки: заливка поставила бы выход в один
// ряд с главными действиями кабинета, хотя это самое редкое из них.
// Но подпись — красная, а не нейтральная: красный здесь роль, а не
// акцент — он говорит «действие с последствиями», ровно то же, что
// подтверждающая кнопка в диалоге. Нейтральный серый терял выход
// среди соседних пунктов меню и не предупреждал ни о чём.
// Наведение слегка гасит подпись (opacity 80%): прежняя подсветка
// «серый → красный» при уже красном тексте ничего бы не показала,
// а второго красного в палитре нет.
// ============================================================

import { useState, useTransition } from 'react';

import { signOut } from '@/app/my/actions';
import type { Locale } from '@/lib/i18n';
import { getT } from '@/lib/i18n';
import { useDismissableLayer } from '@/lib/useDismissableLayer';
import Button from './ui/Button';
import CloseButton from './ui/CloseButton';
import { LogOutIcon } from './ui/NavIcons';

type Props = {
  locale: Locale;
  // Где стоит кнопка — от этого зависит только вид самой подписи,
  // диалог в обоих случаях один и тот же.
  //   'inline' — шапка кабинета: мелкая ссылка справа от заголовка;
  //   'menu'   — пункт списка в меню шапки: размер и начертание как
  //              у соседних разделов, иначе выход читался бы как
  //              подпись под ними, а не как равноправный пункт.
  variant?: 'inline' | 'menu';
};

export default function SignOutButton({
  locale,
  variant = 'inline',
}: Props) {
  const t = getT(locale);
  // useTransition, а не собственный useState: сюда попадает и время
  // серверного редиректа после выхода, поэтому кнопка остаётся
  // заблокированной до конца перехода, а не до конца запроса.
  const [pending, startTransition] = useTransition();
  const [open, setOpen] = useState(false);

  // Escape, блокировка прокрутки и возврат фокуса — общее поведение
  // закрываемых слоёв (lib/useDismissableLayer).
  //
  // locked={pending}: во время выхода Escape намеренно НЕ закрывает
  // окно — запрос уже ушёл, и убирать индикатор происходящего нельзя.
  //
  // stopEscapePropagation: диалог открывается ИЗ МЕНЮ, у которого свой
  // слушатель Escape. Без остановки одно нажатие закрыло бы оба слоя
  // разом — человек потерял бы и диалог, и список, из которого нажимал.
  // Флаг заодно переводит слушатель в фазу перехвата: только там
  // остановка успевает сработать раньше меню, подписанного на
  // всплытие. Событие гасится и во время запроса: закрывать меню
  // посреди выхода тем более нельзя.
  useDismissableLayer({
    open,
    onClose: () => setOpen(false),
    locked: pending,
    stopEscapePropagation: true,
  });

  return (
    <>
      <button
        type="button"
        onClick={() => setOpen(true)}
        className={
          variant === 'menu'
            ? // В меню: во всю ширину и с той же высотой строки, что у
              // пунктов рядом. text-left обязателен — по умолчанию
              // кнопка центрирует подпись, и выход выбивался бы из
              // левого края списка.
              // font-semibold — как у всех пунктов меню: выход стоит
              // в том же списке и бледнее соседей быть не должен.
              // Отличает его цвет (brand-red), а не начертание.
              'flex w-full items-center gap-2.5 py-3 text-left font-semibold text-brand-red transition-opacity duration-fast ease-out hover:opacity-80'
            : 'shrink-0 text-caption font-semibold text-brand-red transition-opacity duration-fast ease-out hover:opacity-80'
        }
      >
        {/* Значок только в меню: в строке кабинета (variant inline)
            выход стоит подписью рядом с другими ссылками, и иконка
            там была бы единственной на весь ряд.
            Цвет НЕ neutral-60, как у остальных пунктов меню, а
            унаследованный красный: выход — действие над аккаунтом,
            и приглушать его значок до цвета навигации значило бы
            спорить с подписью, которая красная. */}
        {variant === 'menu' && <LogOutIcon className="h-5 w-5 shrink-0" />}
        {t('my_logout')}
      </button>

      {open && (
        <div
          className="fixed inset-0 z-modal flex items-end justify-center bg-surface-overlay sm:items-center"
          // Клик по затемнению закрывает диалог, но не во время
          // выхода: запрос уже отправлен, и отменить его нечем.
          onClick={() => {
            if (!pending) setOpen(false);
          }}
          role="dialog"
          aria-modal="true"
          aria-labelledby="signout-title"
        >
          <div
            className="w-full rounded-t-card bg-white p-5 sm:max-w-sm sm:rounded-card"
            // Клик внутри окна не должен закрывать его: иначе нажатие
            // по тексту схлопывало бы диалог.
            onClick={(e) => e.stopPropagation()}
          >
            <div className="flex items-start justify-between gap-4">
              <h2 id="signout-title" className="text-h4 font-semibold">
                {t('my_logout_confirm')}
              </h2>
              <CloseButton
                onClick={() => setOpen(false)}
                label={t('common_close')}
                disabled={pending}
              />
            </div>

            {/* Объяснение последствий — то, ради чего диалог и заведён.
                Сначала о сохранности данных, затем о цене возврата. */}
            <p className="mt-2 text-caption text-neutral-60">
              {t('my_logout_confirm_text')}
            </p>

            {/* Кнопки столбиком на мобильном (равной ширины) и в строку
                с sm — тот же паттерн, что в карточках состояний.
                Порядок «Отмена, затем Выйти»: подтверждающее действие
                стоит последним, у края, где его ищет большой палец. */}
            <div className="mt-5 grid grid-cols-1 gap-3 sm:flex sm:justify-end">
              <Button
                variant="secondary"
                disabled={pending}
                onClick={() => setOpen(false)}
              >
                {t('my_confirm_no')}
              </Button>

              {/* Красный — роль «необратимое действие», та же, что у
                  деструктивных операций над объявлением. */}
              <Button
                variant="destructive"
                disabled={pending}
                onClick={() => startTransition(() => signOut(locale))}
              >
                {pending ? t('my_auth_checking') : t('my_logout_confirm_yes')}
              </Button>
            </div>
          </div>
        </div>
      )}
    </>
  );
}
