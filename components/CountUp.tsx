'use client';

// ============================================================
// RS AUTO — Счётчик площадки с прокруткой цифр (odometer).
// ============================================================
// Число в чипсе героя («142 автомобиля») докручивается от нуля к
// своему значению за 600мс, когда блок впервые попал в поле зрения.
//
// ЗАЧЕМ. Три цифры под кнопкой подачи — доказательство, что на
// площадке есть из чего выбирать. Статичное число человек читает как
// подпись; докрученное — замечает. Показатель тут ровно один и стоит
// в единственном месте страницы, поэтому приём не приедается.
//
// ГЛАВНОЕ ТРЕБОВАНИЕ — НУЛЕВОЙ СДВИГ ВЁРСТКИ. Ширина числа меняется
// по ходу прокрутки («7» уже, чем «142»), и растущая цифра толкала бы
// вправо подпись рядом с собой, а вместе с ней и соседний чипс: три
// счётчика стоят в сетке равных долей. Поэтому ширина резервируется
// заранее — под КОНЕЧНОЕ значение, оно известно с самого начала:
//
//   * невидимая копия финального числа лежит в потоке и держит
//     ширину (aria-hidden, visibility: hidden — место занимает, но
//     ни глазу, ни скринридеру не показывается);
//   * бегущее число лежит поверх неё абсолютом, то есть вне потока,
//     и на габариты не влияет вовсе.
//
// tabular-nums добивает остаток: в пропорциональном шрифте «1» уже
// «8», и число дрожало бы даже при постоянном количестве знаков.
//
// СКРИНРИДЕР СЛЫШИТ СРАЗУ КОНЕЧНОЕ ЗНАЧЕНИЕ, а не поток
// промежуточных: озвучивать шестьдесят кадров прокрутки — издевательство.
// Бегущая копия помечена aria-hidden, а держатель ширины несёт
// настоящий текст.
//
// БЕЗ СКРИПТА И ПРИ prefers-reduced-motion человек видит конечное
// число: начальное состояние компонента — САМО ЗНАЧЕНИЕ, а не ноль.
// Прокрутка стартует только после проверок в эффекте.
// ============================================================

import { useEffect, useRef, useState } from 'react';

import { brand } from '@/lib/brand';

// Длительность прокрутки — токен бренда (600мс).
const DURATION = Number.parseInt(brand.motion.odometer, 10);

// Порог показа тот же, что у RevealOnScroll: блок считается
// появившимся, когда в кадр вошла десятая его часть.
const THRESHOLD = 0.1;

type Props = {
  value: number;
  className?: string;
};

export default function CountUp({ value, className = '' }: Props) {
  // Начальное состояние — конечное число. Так его увидит и тот, у
  // кого скрипт не выполнился: React отдаёт в HTML именно это
  // значение, а прокрутка лишь ненадолго подменяет его в браузере.
  const [shown, setShown] = useState(value);
  const hostRef = useRef<HTMLSpanElement>(null);

  useEffect(() => {
    const host = hostRef.current;
    if (!host) return;

    // Уважаем системную настройку: при «уменьшить движение» число
    // просто стоит на месте. Проверяем здесь, а не только в CSS, —
    // CSS-выключатель гасит анимации, но не цикл на
    // requestAnimationFrame.
    const reduced = window.matchMedia?.(
      '(prefers-reduced-motion: reduce)',
    ).matches;
    if (reduced) return;

    if (typeof IntersectionObserver === 'undefined') return;

    // Ноль и единица не прокручиваются: докручивать «1» от нуля —
    // это один кадр, который выглядит сбоем отрисовки.
    if (value <= 1) return;

    let raf = 0;
    let started = false;

    const run = (startedAt: number) => {
      const step = (now: number) => {
        const p = Math.min(1, (now - startedAt) / DURATION);
        // Замедление к концу (ease-out кубической степени): цифры
        // разгоняются сразу и мягко встают на месте. Равномерная
        // прокрутка обрывается на финальном значении так, будто её
        // прервали.
        const eased = 1 - Math.pow(1 - p, 3);
        setShown(Math.round(value * eased));
        if (p < 1) raf = requestAnimationFrame(step);
      };
      raf = requestAnimationFrame(step);
    };

    const io = new IntersectionObserver(
      (entries) => {
        for (const entry of entries) {
          if (!entry.isIntersecting || started) continue;
          started = true;
          io.disconnect();
          // Обнуляем ровно в момент старта, а не в начальном
          // состоянии компонента: до
          // появления блока в кадре на экране обязано стоять
          // настоящее число.
          setShown(0);
          run(performance.now());
        }
      },
      { threshold: THRESHOLD },
    );

    io.observe(host);

    return () => {
      io.disconnect();
      cancelAnimationFrame(raf);
    };
  }, [value]);

  return (
    // relative + inline-block: держатель ширины остаётся в потоке,
    // бегущее число ложится поверх него абсолютом.
    <span ref={hostRef} className={`relative inline-block ${className}`}>
      {/* Держатель ширины. Несёт НАСТОЯЩЕЕ значение — его читает
          скринридер и его же видит человек с отключённым скриптом.
          invisible вместо hidden: элемент занимает место, но не
          рисуется. */}
      <span className="invisible tabular-nums">{value}</span>

      {/* Бегущая копия. Вне потока — ширину не двигает. */}
      <span
        aria-hidden="true"
        className="absolute inset-0 tabular-nums"
      >
        {shown}
      </span>
    </span>
  );
}
