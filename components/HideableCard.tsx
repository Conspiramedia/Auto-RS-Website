'use client';

// ============================================================
// RS AUTO — Обёртка карточки, умеющая исчезнуть. Client Component.
// ============================================================
// ЗАЧЕМ ОТДЕЛЬНАЯ ОБЁРТКА. Карточка (CarCard) — серверный компонент, и
// убрать себя из списка сама она не может: список приходит с сервера
// уже собранным. Значок «три точки» живёт ВНУТРИ карточки и знает
// только свой carId — спрятать всю карточку изнутри он тоже не может.
//
// Обёртка решает ровно это: подписывается на список скрытого
// (CardActionsProvider) и не рисует детей, если объявление или его
// город туда попали.
//
// ПОЧЕМУ ЭТО ВООБЩЕ НУЖНО. Каталог рендерится на сервере и кэшируется,
// а серверный рендер идёт БЕЗ сессии — фильтрация скрытого в БД
// (search_cars_public учитывает hidden_cars с 0031) на закэшированной
// странице не срабатывает. Без обёртки карточка, которую человек
// только что скрыл, оставалась бы на экране до перезагрузки, и клик
// выглядел бы как несработавший.
//
// ДЫРЫ В СЕТКЕ НЕ ОСТАЁТСЯ: возвращаем null, а не пустой div, —
// элемент уходит из потока grid целиком, и соседние карточки
// смыкаются.
// ============================================================

import type { CSSProperties, ReactNode } from 'react';

import { useCardActions } from './CardActionsProvider';

type Props = {
  carId: string;
  city: string;
  // Номер карточки в выдаче. Задаёт две вещи сразу:
  //   * попадает ли карточка в анимацию появления (первый ряд не
  //     анимируется — см. ниже);
  //   * с какой задержкой она проявляется, если попадает.
  //
  // Необязательный: обёртка используется и там, где карточки идут
  // не сеткой выдачи, и порядковый номер там ничего не значит.
  index?: number;
  children: ReactNode;
};

// Сколько карточек в начале выдачи НЕ анимируются.
// ------------------------------------------------------------
// Первый ряд стоит над сгибом и целиком состоит из кандидатов в LCP:
// это самые крупные изображения на странице. Анимация с opacity: 0 в
// первом кадре откладывает момент, когда браузер считает элемент
// отрисованным, — метрика выросла бы ровно на длительность
// появления. Поэтому первые карточки показываются сразу, как и
// заголовок героя на главной.
//
// Четыре — ширина ряда на самом широком брейкпоинте (xl:grid-cols-4).
// На узких экранах в первый ряд попадают две карточки, и ещё две
// «неанимированные» уходят под сгиб — там их отсутствие в каскаде
// незаметно, а перебирать число по брейкпоинтам можно только
// скриптом, то есть ценой ещё одного клиентского компонента.
//
// Совпадает с порогом priority у самих карточек (i < 4 в
// CatalogView): это один и тот же первый экран.
const EAGER_CARDS = 4;

// Шаг каскада внутри ряда. Задержка растёт не бесконечно: восьмая
// карточка ждала бы почти полсекунды, а двадцать четвёртая —
// полторы, и нижняя часть выдачи проявлялась бы уже после того, как
// человек до неё долистал. Остаток ряда появляется одновременно.
const MAX_STAGGER_STEPS = 7;

export default function HideableCard({
  carId,
  city,
  index,
  children,
}: Props) {
  const { hiddenCars, hiddenCities } = useCardActions();

  if (hiddenCars.has(carId) || hiddenCities.has(city)) return null;

  // Порядковый номер не передан или карточка в первом ряду —
  // отдаём содержимое как есть, без обёртки и без анимации. Лишний
  // div в сетке grid сломал бы раскладку: он стал бы ячейкой вместо
  // карточки только при display: contents, а его поддержка в старых
  // WebKit ломает доступность таблиц и списков. Проще не оборачивать.
  if (index === undefined || index < EAGER_CARDS) return <>{children}</>;

  const step = Math.min(index - EAGER_CARDS, MAX_STAGGER_STEPS);

  return (
    // ОБЁРТКА ЗДЕСЬ БЕЗОПАСНА: она сама становится ячейкой сетки на
    // месте карточки, а карточка внутри занимает её целиком (Card —
    // block). Габариты те же, дыр и сдвигов не возникает.
    //
    // Появление ведёт IntersectionObserver (RevealOnScroll): класса
    // reveal-on-scroll достаточно, импортировать сюда нечего.
    // Отсутствие скрипта карточку не прячет — см. комментарий о
    // .js-reveal-ready в globals.css.
    <div
      className="reveal-on-scroll"
      style={{ '--reveal-index': step } as CSSProperties}
    >
      {children}
    </div>
  );
}
