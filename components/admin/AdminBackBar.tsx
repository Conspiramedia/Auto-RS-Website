// ============================================================
// RS AUTO — Возврат на главную админки. Server Component.
// ============================================================
// Единственный способ вернуться в разделы после того, как навигация
// убрана. Стоит первым элементом на КАЖДОМ экране раздела и в окне
// салона — без него человек, провалившийся в очередь, выбирается
// оттуда только кнопкой «назад» браузера.
//
// ССЫЛКА, А НЕ history.back(). Шаг назад по истории ведёт туда, откуда
// пришли, а это не всегда главная: в карточку объявления попадают и
// из очереди, и из списка объявлений, и по прямой ссылке из журнала.
// Фиксированный адрес отвечает на вопрос «куда я вернусь» одинаково
// всегда.
//
// ХЛЕБНЫЕ КРОШКИ показываются с sm и только когда переданы: на
// мобильном для них нет ширины, а на десктопе они отвечают на второй
// вопрос — «где я внутри раздела». Разделены средней точкой, а не
// стрелками: стрелка здесь уже занята кнопкой возврата.
// ============================================================

import Link from 'next/link';

type Props = {
  // Название текущего экрана для крошек. Не показывается на мобильном.
  current?: string;
  // Промежуточное звено: раздел, внутри которого лежит экран.
  // Например: «Очередь» для карточки проверки объявления.
  parent?: { label: string; href: string };
};

export default function AdminBackBar({ current, parent }: Props) {
  return (
    <div className="flex items-center gap-2">
      {/* min-h 44px: кнопка возврата — самая частая цель нажатия в
          разделе после самого содержимого, и на телефоне в неё надо
          попадать не глядя. -ml-2 втягивает поле нажатия в отступ
          страницы, чтобы подпись осталась на одной вертикали с
          заголовком ниже. */}
      <Link
        href="/admin"
        className="
          -ml-2 flex min-h-[44px] shrink-0 items-center rounded-control px-2
          text-caption font-medium text-brand-blue-ink
          transition-colors duration-fast hover:bg-surface-hover
        "
      >
        ← На главную
      </Link>

      {(parent || current) && (
        <nav
          aria-label="Хлебные крошки"
          className="hidden min-w-0 items-center gap-2 text-caption text-neutral-50 sm:flex"
        >
          <span aria-hidden="true">·</span>

          {parent && (
            <>
              <Link
                href={parent.href}
                className="shrink-0 hover:text-neutral-100 hover:underline"
              >
                {parent.label}
              </Link>
              <span aria-hidden="true">·</span>
            </>
          )}

          {current && <span className="truncate">{current}</span>}
        </nav>
      )}
    </div>
  );
}
