'use client';

// ============================================================
// RS AUTO — Кнопка «Одобрить». Client Component.
// ============================================================
// БЕЗ ДИАЛОГА ПОДТВЕРЖДЕНИЯ, и это осознанно. Одобрение —
// недеструктивное действие: объявление становится видимым, а ошибку
// исправляет обратный ход (объявление можно снять). Модератор
// разбирает десятки карточек подряд, и лишний «Вы уверены?» на каждой
// превращается в рефлекс, который гасит внимание там, где оно
// действительно нужно, — в отклонении.
//
// Единственная акцентная кнопка на экране. Правило бренда: второго
// яркого CTA быть не должно, поэтому «Отклонить» рядом — контурная
// destructive, а не вторая заливка.
// ============================================================

import Button from '@/components/ui/Button';

type Props = {
  onApprove: () => void;
  // Пока идёт запрос — кнопка неактивна, чтобы двойное нажатие не
  // отправило второй approve_car. Второй всё равно упал бы с
  // check_violation (статус уже active), но показывать модератору
  // ошибку из-за собственного дребезга незачем.
  busy: boolean;
  disabled?: boolean;
};

export default function ApproveButton({ onApprove, busy, disabled }: Props) {
  return (
    <Button
      variant="primary"
      size="lg"
      onClick={onApprove}
      disabled={busy || disabled}
    >
      {busy ? 'Публикуем…' : 'Одобрить'}
    </Button>
  );
}
