// ============================================================
// RS AUTO — Карточка-«окно» админки. Server Component.
// ============================================================
// Единственный кирпич главного экрана. Раньше на дашборде было два
// разных элемента: плитка-счётчик (мёртвая, только число) и пункт
// меню в сайдбаре (живой, но без числа). Теперь это одно и то же:
// карточка показывает число И ведёт туда, где это число можно
// разобрать.
//
// Смысл объединения — в вопросе, который задаёт модератор, открывая
// админку: «есть работа?». Раньше ответ («в очереди 7») и действие
// (клик по пункту «Очередь» в панели слева) лежали в разных местах
// экрана. Теперь ответ и есть кнопка.
//
// ЦЕЛЬ НАЖАТИЯ ≥44px — требование задачи и обязательное условие для
// пальца. Обеспечивается min-h; реальная высота карточки со
// счётчиком заметно больше, но у карточек без числа (разделы вроде
// «Журнал») именно минимум и работает.
//
// tone управляет цветом ЧИСЛА, а не заливкой. Восемь цветных
// прямоугольников на экране превратили бы сводку в витрину и
// перестали бы что-либо выделять. Заливка появляется ровно один раз —
// у провалившихся писем, и именно поэтому её замечают.
// ============================================================

import Link from 'next/link';

type Props = {
  href: string;
  label: string;
  // Число. Не передаётся у карточек-разделов без счётчика.
  value?: number;
  // Пояснение под числом: что означает и что делать.
  hint?: string;
  tone?: 'plain' | 'accent' | 'alert';
};

export default function AdminTile({
  href,
  label,
  value,
  hint,
  tone = 'plain',
}: Props) {
  const valueClass =
    tone === 'alert'
      ? 'text-error'
      : tone === 'accent'
        ? 'text-brand-gold'
        : 'text-neutral-100';

  // Заливка — только у инцидента и только когда он есть. Ноль
  // провалившихся писем это норма, а не повод красить экран.
  const alerting = tone === 'alert' && (value ?? 0) > 0;

  return (
    <Link
      href={href}
      className={[
        'flex min-h-[44px] flex-col justify-between rounded-card border p-4',
        'transition-colors duration-fast',
        alerting
          ? 'border-error/30 bg-status-error hover:bg-status-error/70'
          : 'border-neutral-10 hover:bg-surface-hover',
      ].join(' ')}
    >
      <p className="text-small text-neutral-60">{label}</p>

      {value !== undefined && (
        <p className={`mt-1 text-h2 font-bold tabular-nums ${valueClass}`}>
          {value}
        </p>
      )}

      {hint && <p className="mt-1 text-micro text-neutral-50">{hint}</p>}
    </Link>
  );
}
