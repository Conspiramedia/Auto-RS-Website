'use client';

// ============================================================
// RS AUTO — Баннер согласия на куки. Client Component.
// ============================================================
// НЕ МОДАЛКА. Плашка прижата к низу экрана и НЕ перекрывает страницу:
// ни подложки, ни ловушки фокуса, ни блокировки прокрутки. Причина не
// вкусовая — модальное окно на первом экране мешает и посетителю, и
// краулеру, и метрике первого взаимодействия, а согласие на куки не
// является условием доступа к каталогу. Человек может листать
// объявления, не трогая баннер вовсе.
//
// ДВЕ КНОПКИ: «Принять» и «Отклонить». Раньше кнопка была одна —
// плашка лишь уведомляла о технических куки, отказываться было не от
// чего. С подключением GA4 она стала вопросом: аналитика с куки
// грузится только после согласия, а значит отказ обязан быть так же
// доступен, как согласие (требование GDPR). «Подробнее» по-прежнему
// нет: документы висят ссылками в подвале каждой страницы.
//
// ПОЧЕМУ РЕНДЕР ОТЛОЖЕН ДО useEffect. Решение по куки живёт в
// localStorage, а он недоступен на сервере. Отрисуй мы баннер
// сразу — серверная разметка (баннер есть) разошлась бы с клиентской
// (баннера нет у ответившего), и React выдал бы ошибку гидратации.
// Поэтому первый проход не рисует ничего, и лишь после монтирования
// компонент решает, показывать ли плашку. Мигания это не даёт:
// показываем не «сразу и потом прячем», а «только когда выяснили».
//
// ПЛАШКА СКРЫВАЕТСЯ ПО ЛЮБОМУ ОТВЕТУ, а не только по согласию:
// hasCookieDecision() отличает «ещё не спрашивали» от «ответил нет».
// Иначе отказавшийся видел бы вопрос при каждом заходе — давление до
// нужного нам ответа, ровно то, что GDPR и запрещает.
//
// ВЕРСИОННОСТЬ — в lib/consent: сохранённая версия сравнивается с
// текущей POLICY_VERSION. Обновилась редакция документов — баннер
// вернулся ко всем, включая ответивших на прежнюю: новая редакция
// это новый вопрос.
// ============================================================

import { usePathname } from 'next/navigation';
import { useEffect, useState } from 'react';

import {
  hasCookieDecision,
  setCookieConsent,
  type ConsentDecision,
} from '@/lib/consent';
import { getT, stripLocale } from '@/lib/i18n';
import { POLICY_VERSION } from '@/lib/legal';
import { getBrowserClient } from '@/lib/supabaseClient';

export default function CookieBanner() {
  // Язык берём из адреса, а не из пропа: баннер смонтирован в корневом
  // layout'е, общем для обоих зеркал, и локали там просто нет.
  // stripLocale — та же функция, которой пользуется переключатель
  // языка, поэтому /ru/* и корень разбираются одинаково.
  const pathname = usePathname();
  const { locale } = stripLocale(pathname || '/');
  const t = getT(locale);

  const [visible, setVisible] = useState(false);

  useEffect(() => {
    // См. шапку: до монтирования состояние хранилища неизвестно.
    if (!hasCookieDecision()) setVisible(true);
  }, []);

  // Админка живёт вне пользовательского интерфейса сайта: модератор
  // работает в служебном разделе, и плашка согласия закрывала бы ему
  // нижние строки таблицы очереди. Проверка префиксом — под /admin
  // лежат все разделы панели.
  if (pathname?.startsWith('/admin')) return null;

  if (!visible) return null;

  // Согласие: куки аналитики разрешены, GA4 подключается.
  function accept() {
    decide('accepted');
  }

  // Отказ. Баннер закрывается так же, как при согласии, и больше не
  // возвращается: решение сохранено, и переспрашивать его при каждом
  // заходе значило бы давить на пользователя до нужного нам ответа.
  // GA4 при этом не подключится, а Plausible продолжит считать —
  // он куки не ставит и согласия не требует.
  function reject() {
    decide('rejected');
  }

  function decide(decision: ConsentDecision) {
    // ПОРЯДОК ВАЖЕН: сначала прячем плашку и пишем локальное решение,
    // и только потом идём в сеть. Интерфейс не должен ждать базу —
    // кнопка обязана срабатывать мгновенно, в том числе на плохой
    // связи и при офлайне.
    //
    // setCookieConsent заодно рассылает событие, по которому слой GA4
    // в этой же вкладке подключает скрипт, не дожидаясь перезагрузки
    // (см. lib/consent → CONSENT_CHANGE_EVENT).
    setVisible(false);
    setCookieConsent(decision);

    // Запись доказательства. Ошибка НЕ возвращает баннер и никак не
    // показывается пользователю: человек своё решение выразил, и
    // требовать его повторно из-за сбоя на нашей стороне неправильно.
    // Диагностика уходит в консоль — там её увидит разработчик, а не
    // посетитель.
    //
    // Одна повторная попытка через 3 секунды покрывает типичный случай
    // потери записи: короткий сетевой сбой или холодный старт функции.
    // Больше не пробуем — очередь ретраев в браузере, который человек
    // закроет через секунду, всё равно недостоверна, а задача
    // «не потерять ни одного согласия любой ценой» решается не здесь.
    void sendConsent(1, decision);
  }

  async function sendConsent(
    attemptsLeft: number,
    decision: ConsentDecision,
  ): Promise<void> {
    try {
      const supabase = getBrowserClient();

      // Версия передаётся из lib/legal — единственного источника.
      // Именно она попадёт в policy_version записи, а не текущее
      // значение на момент чтения журнала: доказывать нужно ту
      // редакцию, которую человеку показали.
      // В журнал уходит РЕАЛЬНОЕ решение, а не всегда true: отказ —
      // такой же факт, который нужно уметь доказать. Раньше здесь
      // стоял литерал true, потому что отказаться было нельзя.
      const { data, error } = await supabase.rpc('record_cookie_consent', {
        p_policy_version: POLICY_VERSION,
        p_consents: { cookies: decision === 'accepted' },
      });

      // RPC отвечает {ok: true} либо {ok: false, error: '<код>'}.
      // Отказ по коду — тоже неудача записи, и он так же достоин
      // повтора: rate_limited проходит через минуту, а не навсегда.
      const ok =
        !error && Boolean((data as { ok?: boolean } | null)?.ok);

      if (ok) return;

      if (attemptsLeft > 0) {
        setTimeout(() => void sendConsent(attemptsLeft - 1, decision), 3000);
        return;
      }

      console.warn('[cookie-consent] запись согласия не удалась', error ?? data);
    } catch (e) {
      if (attemptsLeft > 0) {
        setTimeout(() => void sendConsent(attemptsLeft - 1, decision), 3000);
        return;
      }

      console.warn('[cookie-consent] запись согласия не удалась', e);
    }
  }

  return (
    // role="region" с подписью, а не role="dialog": диалог обязывает
    // скринридер увести в него фокус и запереть там, а плашка ничего
    // не блокирует. Регион читается как ориентир, к которому можно
    // перейти, — ровно то, чем баннер и является.
    //
    // Слой ниже шторки фильтров и модальных окон (z-header): открытые
    // фильтры на мобильном обязаны перекрывать плашку, иначе она
    // повисает поверх их кнопки «Показать».
    //
    // pb с safe-area: на iPhone нижние 34 пикселя занимает системная
    // полоса жеста, и без отступа кнопка «Хорошо» оказывается прямо
    // под ней — палец попадает в жест «домой», а не в кнопку.
    //
    // ПЛАШКА ПОДНЯТА НА 50px ОТ НИЗА ЭКРАНА. Прижатая к самому краю,
    // она сливалась с системными элементами телефона — панелью
    // браузера и полосой жеста, — и читалась как часть интерфейса
    // устройства, а не страницы. Отступ добавлен К safe-area, а не
    // вместо неё: 50px отсчитываются от безопасной границы, иначе на
    // iPhone подъём частично съедала бы та же полоса жеста, ради
    // которой safe-area и введена.
    <div
      role="region"
      aria-label={t('cookie_banner_aria')}
      className="fixed inset-x-0 bottom-0 z-header p-3 pb-[calc(0.75rem+50px+env(safe-area-inset-bottom))] sm:p-4 sm:pb-[calc(1rem+50px+env(safe-area-inset-bottom))]"
    >
      {/* max-w-3xl и mx-auto: на мониторе плашка во всю ширину экрана
          выглядела бы системным уведомлением ОС, а не элементом сайта.
          На телефоне ограничение не срабатывает — там ширина и так
          меньше.

          КНОПКА ПОД ТЕКСТОМ, ПО ЦЕНТРУ. Прежде она стояла справа от
          текста в один ряд — и на узком экране это разваливалось:
          текст не помещался в остаток ширины, переносился на две
          строки, а кнопка висела сбоку по центру этих двух строк.
          Плашка получалась высокой, а её правый край — рваным.

          Теперь два уровня: сверху ряд «иконка + текст», под ним
          кнопка по центру. Текст занимает всю ширину плашки и на
          телефоне укладывается в одну-две строки без обтекания, а
          кнопка стоит на собственной строке — её положение больше не
          зависит от того, сколько строк занял текст.

          p-3 вместо p-4: внутренние поля на ступень меньше — вслед за
          кнопкой. Уведомление должно занимать полосу, а не блок. */}
      <div className="mx-auto flex max-w-3xl flex-col gap-3 rounded-card border border-neutral-10 bg-white p-3 shadow-modal sm:p-4">
        {/* Ряд «иконка + текст», ОТЦЕНТРОВАННЫЙ ЦЕЛИКОМ.
            justify-center ставит пару в середину плашки: на широком
            экране прижатая влево строка при кнопке по центру
            выглядела бы как две несвязанные детали, а не как одно
            уведомление.

            items-center, а НЕ items-start. Прежнее выравнивание по
            верху было нужно, пока текст мог занять две строки:
            печенье, выровненное по центру блока, съезжало бы вниз от
            первой строки, к которой относится. Теперь текст всегда в
            одну строку (whitespace-nowrap ниже), и по центру иконка
            встаёт ровно на его оптическую линию.

            gap-2 вместо gap-3: зазор в 12px при иконке, подтянутой к
            строке, читался как разрыв между двумя элементами —
            печенье относится к фразе и должно стоять при ней. */}
        <div className="flex items-center justify-center gap-2">
          {/* Иконка отдельным span с aria-hidden: эмодзи «печенье»
              скринридер прочитал бы как «печенье» посреди фразы, а
              смысла тексту оно не добавляет — это украшение.

              text-h3, а не h2: иконка уменьшена вслед за кнопкой и
              полями — в полосе высотой с одну строку печенье размером
              с заголовок перетягивало на себя всё внимание. shrink-0 —
              эмодзи не должно сжиматься на узком экране. */}
          <span aria-hidden className="shrink-0 text-h3 leading-none">
            🍪
          </span>

          {/* ТЕКСТ В ОДНУ СТРОКУ НА ЛЮБОЙ ШИРИНЕ.
              Раньше стоял text-caption (14px) с обычным переносом, и
              на телефоне фраза из сорока символов не помещалась в
              доступные ~280px (360px экрана минус внешние и
              внутренние поля, иконка и зазор) — она рвалась на две
              строки, а плашка становилась вдвое выше.

              Решение из двух частей:
                * whitespace-nowrap запрещает перенос — фраза остаётся
                  цельной;
                * размер шрифта задан clamp'ом и сам подстраивается
                  под ширину экрана: 10.5px на самых узких (320px),
                  дальше он растёт вместе с шириной и упирается в
                  потолок 13px около 420px. Формула привязана к vw,
                  поэтому между границами текст масштабируется плавно,
                  без ступенек на промежуточных ширинах.

              Числа подобраны по САМОЙ ДЛИННОЙ из двух локалей
              (русская, 40 символов): на 320px строка занимает ~93%
              доступной ширины, на массовых 360–414px — 80–85%. Запас
              оставлен намеренно: фактическая ширина глифов зависит от
              системного шрифта устройства, и подгонка «впритык»
              порвалась бы на Android с другим начертанием.

              Почему clamp, а не ступень токена: ни одна ступень шкалы
              не решает задачу целиком — 12px (small) на 320px уже
              рвётся, 11px (micro) на 414px выглядит неоправданно
              мелким. Здесь размер не роль в иерархии текста, а
              функция от ширины, и выразить его ступенью нельзя.

              С sm (640px) место есть с запасом, и текст возвращается
              на свою штатную ступень text-caption. */}
          <p className="whitespace-nowrap text-[clamp(0.656rem,3.1vw,0.813rem)] leading-snug text-neutral-70 sm:text-caption">
            {t('cookie_banner_text')}
          </p>
        </div>

        {/* Компонент Button здесь НЕ используется: он рендерит либо
            <button>, либо <Link>, и оба варианта тянут за собой
            next/link в клиентский бандл ради одной кнопки на каждой
            странице сайта. Цвет, радиус и переход взяты из тех же
            токенов, что у варианта dark; размер — свой (см. ниже),
            в шкалу Button он не входит.

            Тон dark, а не primary: зелёный на сайте занят главным
            действием («Опубликовать», «Позвонить»), и второй зелёной
            кнопкой на первом экране баннер спорил бы с ним за
            внимание. Правило бренда — один акцент на экране.

            РАЗМЕР — ПО СОДЕРЖИМОМУ, А НЕ ВО ВСЮ ШИРИНУ. Кнопка во всю
            ширину плашки выглядела бы как главное действие страницы,
            хотя это отказ от уведомления. Ширину задаёт содержимое, а
            по центру её ставит self-center: строка кнопки — отдельный
            уровень колонки, и без него кнопка растянулась бы на всю
            ширину, как любой flex-элемент в колонке.

            px-6 при этом ШИРЕ обычного px-4: у короткого слова из семи
            букв воздух по бокам нужен больше обычного, иначе кнопка
            выглядит обрубленной по буквам. py-2 и text-small — на
            ступень ниже прежних py-2.5 и text-caption: плашка
            уведомления не должна нести кнопку размером с
            «Опубликовать». */}
        {/* ДВЕ КНОПКИ, РАВНОПРАВНЫЕ ПО ВЕСУ.
            С подключением GA4 баннер перестал быть уведомлением и стал
            вопросом: аналитика с куки грузится ТОЛЬКО после согласия.
            А раз так, отказ обязан быть ровно так же доступен, как
            согласие, — это прямое требование GDPR, и «Принять» яркой
            кнопкой при отказе в виде мелкой ссылки его нарушает.

            Поэтому обе кнопки одного размера и в одном ряду. Различает
            их только заливка: «Принять» тёмная (тон dark — зелёный на
            сайте занят главным действием страницы), «Отклонить» —
            контурная. Это допустимая разница: она подсказывает
            ожидаемый ответ, но не мешает нажать второй. */}
        <div className="flex justify-center gap-2">
          <button
            type="button"
            onClick={reject}
            className="rounded-control border border-neutral-15 bg-white px-5 py-2 text-small font-semibold transition-colors duration-fast ease-out hover:bg-surface-hover"
          >
            {t('cookie_banner_reject')}
          </button>

          <button
            type="button"
            onClick={accept}
            className="rounded-control bg-brand-dark px-5 py-2 text-small font-semibold text-white transition-colors duration-fast ease-out hover:brightness-110"
          >
            {t('cookie_banner_accept')}
          </button>
        </div>
      </div>
    </div>
  );
}
