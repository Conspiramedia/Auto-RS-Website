'use client';

// ============================================================
// RS AUTO — Баннер согласия на куки. Client Component.
// ============================================================
// НЕ МОДАЛКА. Плашка прижата к низу экрана и НЕ перекрывает страницу:
// ни подложки, ни ловушки фокуса, ни блокировки прокрутки. Причина не
// вкусовая — модальное окно на первом экране мешает и посетителю, и
// краулеру, и метрике первого взаимодействия, а согласие на куки не
// является условием доступа к каталогу. Человек может листать
// объявления, не трогая баннер вовсе.
//
// ОДНА КНОПКА. «Подробнее» нет по требованию задачи: документы и так
// висят ссылками в подвале каждой страницы, а вторая кнопка на плашке
// в две строки на телефоне съедала бы всю её ширину.
//
// ПОЧЕМУ РЕНДЕР ОТЛОЖЕН ДО useEffect. Признак «согласие уже дано»
// живёт в localStorage, а он недоступен на сервере. Отрисуй мы баннер
// сразу — серверная разметка (баннер есть) разошлась бы с клиентской
// (баннера нет у принявшего), и React выдал бы ошибку гидратации.
// Поэтому первый проход не рисует ничего, и лишь после монтирования
// компонент решает, показывать ли плашку. Мигания это не даёт:
// показываем не «сразу и потом прячем», а «только когда выяснили».
//
// ВЕРСИОННОСТЬ — в lib/consent: hasCookieConsent() сравнивает
// сохранённую версию с текущей POLICY_VERSION, а не проверяет булев
// флаг. Обновилась редакция документов — баннер вернулся ко всем,
// включая принявших прежнюю.
// ============================================================

import { usePathname } from 'next/navigation';
import { useEffect, useState } from 'react';

import { acceptCookieConsent, hasCookieConsent } from '@/lib/consent';
import { getT, stripLocale } from '@/lib/i18n';
import { POLICY_VERSION } from '@/lib/legal';
import { getBrowserClient } from '@/lib/supabaseClient';

export default function CookieBanner() {
  // Язык берём из адреса, а не из пропа: баннер смонтирован в корневом
  // layout'е, общем для обоих зеркал, и локали там просто нет.
  // stripLocale — та же функция, которой пользуется переключатель
  // языка, поэтому /ru/* и корень разбираются одинаково.
  const pathname = usePathname();
  const { locale } = stripLocale(pathname || '/');
  const t = getT(locale);

  const [visible, setVisible] = useState(false);

  useEffect(() => {
    // См. шапку: до монтирования состояние хранилища неизвестно.
    if (!hasCookieConsent()) setVisible(true);
  }, []);

  // Админка живёт вне пользовательского интерфейса сайта: модератор
  // работает в служебном разделе, и плашка согласия закрывала бы ему
  // нижние строки таблицы очереди. Проверка префиксом — под /admin
  // лежат все разделы панели.
  if (pathname?.startsWith('/admin')) return null;

  if (!visible) return null;

  function accept() {
    // ПОРЯДОК ВАЖЕН: сначала прячем плашку и ставим локальный флаг,
    // и только потом идём в сеть. Интерфейс не должен ждать базу —
    // «Хорошо» обязано срабатывать мгновенно, в том числе на плохой
    // связи и при офлайне.
    setVisible(false);
    acceptCookieConsent();

    // Запись доказательства. Ошибка НЕ возвращает баннер и никак не
    // показывается пользователю: человек своё согласие выразил, и
    // требовать его повторно из-за сбоя на нашей стороне неправильно.
    // Диагностика уходит в консоль — там её увидит разработчик, а не
    // посетитель.
    //
    // Одна повторная попытка через 3 секунды покрывает типичный случай
    // потери записи: короткий сетевой сбой или холодный старт функции.
    // Больше не пробуем — очередь ретраев в браузере, который человек
    // закроет через секунду, всё равно недостоверна, а задача
    // «не потерять ни одного согласия любой ценой» решается не здесь.
    void sendConsent(1);
  }

  async function sendConsent(attemptsLeft: number): Promise<void> {
    try {
      const supabase = getBrowserClient();

      // Версия передаётся из lib/legal — единственного источника.
      // Именно она попадёт в policy_version записи, а не текущее
      // значение на момент чтения журнала: доказывать нужно ту
      // редакцию, которую человеку показали.
      const { data, error } = await supabase.rpc('record_cookie_consent', {
        p_policy_version: POLICY_VERSION,
        p_consents: { cookies: true },
      });

      // RPC отвечает {ok: true} либо {ok: false, error: '<код>'}.
      // Отказ по коду — тоже неудача записи, и он так же достоин
      // повтора: rate_limited проходит через минуту, а не навсегда.
      const ok =
        !error && Boolean((data as { ok?: boolean } | null)?.ok);

      if (ok) return;

      if (attemptsLeft > 0) {
        setTimeout(() => void sendConsent(attemptsLeft - 1), 3000);
        return;
      }

      console.warn('[cookie-consent] запись согласия не удалась', error ?? data);
    } catch (e) {
      if (attemptsLeft > 0) {
        setTimeout(() => void sendConsent(attemptsLeft - 1), 3000);
        return;
      }

      console.warn('[cookie-consent] запись согласия не удалась', e);
    }
  }

  return (
    // role="region" с подписью, а не role="dialog": диалог обязывает
    // скринридер увести в него фокус и запереть там, а плашка ничего
    // не блокирует. Регион читается как ориентир, к которому можно
    // перейти, — ровно то, чем баннер и является.
    //
    // Слой ниже шторки фильтров и модальных окон (z-header): открытые
    // фильтры на мобильном обязаны перекрывать плашку, иначе она
    // повисает поверх их кнопки «Показать».
    //
    // pb с safe-area: на iPhone нижние 34 пикселя занимает системная
    // полоса жеста, и без отступа кнопка «Хорошо» оказывается прямо
    // под ней — палец попадает в жест «домой», а не в кнопку.
    <div
      role="region"
      aria-label={t('cookie_banner_aria')}
      className="fixed inset-x-0 bottom-0 z-header p-3 pb-[calc(0.75rem+env(safe-area-inset-bottom))] sm:p-4"
    >
      {/* max-w-3xl и mx-auto: на мониторе плашка во всю ширину экрана
          выглядела бы системным уведомлением ОС, а не элементом сайта.
          На телефоне ограничение не срабатывает — там ширина и так
          меньше. */}
      <div className="mx-auto flex max-w-3xl flex-col gap-3 rounded-card border border-neutral-10 bg-white p-4 shadow-modal sm:flex-row sm:items-center sm:gap-4">
        {/* Иконка отдельным span с aria-hidden: эмодзи «печенье»
            скринридер прочитал бы как «печенье» посреди фразы, а
            смысла тексту оно не добавляет — это украшение. */}
        <span aria-hidden className="text-h2 leading-none">
          🍪
        </span>

        <p className="flex-1 text-caption text-neutral-70">
          {t('cookie_banner_text')}
        </p>

        {/* Компонент Button здесь НЕ используется: он рендерит либо
            <button>, либо <Link>, и оба варианта тянут за собой
            next/link в клиентский бандл ради одной кнопки на каждой
            странице сайта. Классы взяты из тех же токенов — dark и
            размер sm, один в один с вариантом кнопки.

            Тон dark, а не primary: зелёный на сайте занят главным
            действием («Опубликовать», «Позвонить»), и второй зелёной
            кнопкой на первом экране баннер спорил бы с ним за
            внимание. Правило бренда — один акцент на экране.

            w-full на телефоне: кнопка во всю ширину плашки попадает
            под палец без прицеливания. shrink-0 на десктопе не даёт
            ей сжаться под длинной сербской фразой. */}
        <button
          type="button"
          onClick={accept}
          className="w-full shrink-0 rounded-control bg-brand-dark px-4 py-2.5 text-caption font-semibold text-white transition-colors duration-fast ease-out hover:brightness-110 sm:w-auto"
        >
          {t('cookie_banner_accept')}
        </button>
      </div>
    </div>
  );
}
