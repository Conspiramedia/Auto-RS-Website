// ============================================================
// RS AUTO — Шапка публичной страницы салона. Server Component.
// ============================================================
// Баннер во всю ширину страницы: обложка салона и размытая полоса по
// нижнему краю с названием, слоганом и контактами.
//
// ------------------------------------------------------------
// ПОЧЕМУ ТА ЖЕ ФОРМА, ЧТО У ПЛИТКИ В КАТАЛОГЕ
// ------------------------------------------------------------
// Покупатель попадает сюда кликом по плитке салона в выдаче
// (DealerShowcaseCard). Если бы страница встречала его другой
// раскладкой — логотипом в углу и заголовком, — переход читался бы
// как попадание на чужой сайт. Одна и та же обложка с одной и той же
// полосой внизу продолжает плитку, а не заменяет её: человек видит,
// что кликнул правильно.
//
// Отсюда и общий источник кадра: cover_url, обрезанный при загрузке
// под COVER_ASPECT (lib/imagePrepare.ts). Отдельной «обложки для
// страницы» нет намеренно — второй файл салон загружал бы второй раз,
// и половина витрин осталась бы с одной из двух картинок.
//
// ------------------------------------------------------------
// ЧЕМ ОТЛИЧАЕТСЯ ОТ ПЛИТКИ
// ------------------------------------------------------------
//   1) ПРОПОРЦИЯ. Плитка обязана совпадать по высоте с карточкой
//      объявления — она стоит в общей сетке выдачи. Здесь такого
//      ограничения нет, и баннер задаётся отдельной пропорцией:
//      3:1 на десктопе (широкая полоса под шапкой сайта) и 2:1 на
//      мобильном, где 3:1 выродилось бы в ленточку высотой 120px.
//
//   2) ТЕЛЕФОН — ЖИВАЯ ССЫЛКА. В плитке он обычный текст: вся
//      плитка целиком уже является ссылкой на витрину, и вложенная
//      ссылка внутри ссылки — невалидная разметка. Здесь внешней
//      обёртки нет, поэтому tel: работает как положено.
//
// Логотипа и адреса сайта в баннере нет. Салон опознаётся обложкой и
// названием: логотип дублировал первое, а ссылка на чужой сайт уводила
// покупателя с площадки ровно там, где он до неё дошёл.
//
// Счётчиков объявлений в полосе нет — ни здесь, ни в плитке
// каталога. Число машин посетитель видит прямо под баннером, в самой
// сетке витрины, и подпись «3 активных объявления» повторяла бы то,
// что и так лежит перед глазами.
//
// ------------------------------------------------------------
// БЕЗ ОБЛОЖКИ — ФИРМЕННЫЙ ГРАДИЕНТ
// ------------------------------------------------------------
// Тот же приём, что в плитке: раскладка не меняется, вместо
// фотографии фирменный фон из токенов бренда. Серый прямоугольник
// читался бы как незагрузившаяся картинка, а страница без шапки
// вовсе — как недоделанная.
// ============================================================

import Image from 'next/image';

import type { DealerProfile } from '@/lib/types';

// Компонент НЕ ПРИНИМАЕТ locale, и это не упущение: всё, что он
// показывает, — контентные поля салона (название, слоган, город, часы,
// телефон, сайт). Они хранятся на языке, который выбрал сам владелец,
// и переводу не подлежат — то же правило, что у названия марки или
// описания объявления. Ни одной строки интерфейса здесь не осталось
// после того, как из полосы убрали счётчики объявлений.
type Props = {
  profile: DealerProfile;
};

export default function DealerShowcaseHero({ profile }: Props) {
  // Пустая строка приравнивается к отсутствию: из базы поле может
  // прийти пробелами, и строка контактов состояла бы из пустоты,
  // занимая место.
  const coverUrl = profile.cover_url?.trim() || null;
  const tagline = profile.tagline?.trim() || null;
  const city = profile.company_city?.trim() || null;
  const openingHours = profile.opening_hours?.trim() || null;
  const dealerPhone = profile.dealer_phone?.trim() || null;

  return (
    <div className="relative overflow-hidden rounded-card border border-neutral-10">
      {/* ------------------------------------------------------------
          ФОН: обложка салона, а без неё — фирменный градиент.
          ------------------------------------------------------------
          aspect-[2/1] на мобильном, 3:1 с планшета: широкая полоса
          хороша на десктопе, но на 360px она дала бы ленточку в
          120px, в которой не разглядеть ни шоурум, ни вывеску. */}
      <div className="relative aspect-[2/1] w-full sm:aspect-[3/1]">
        {coverUrl ? (
          <Image
            src={coverUrl}
            alt=""
            fill
            // Баннер во всю ширину контейнера страницы (max-w-6xl).
            sizes="(max-width: 1151px) 100vw, 1120px"
            className="object-cover"
            // unoptimized: к адресу добавляется метка времени при
            // каждой замене, и оптимизатор Next кэшировал бы каждую
            // версию отдельно.
            unoptimized
            // Шапка витрины — главный элемент над сгибом, от неё
            // зависит LCP страницы.
            priority
          />
        ) : (
          <div className="h-full w-full bg-gradient-to-br from-brand-primary to-brand-dark" />
        )}
      </div>

      {/* ------------------------------------------------------------
          ПОЛОСА С ДАННЫМИ САЛОНА — поверх обложки, по нижнему краю.
          ------------------------------------------------------------
          backdrop-blur размывает НЕ полосу, а кадр под ней: текст
          получает спокойную подложку, но фотография остаётся
          фотографией, просто не в фокусе. Одного размытия мало —
          светлый кадр (снег, белая стена) оставил бы белый текст на
          белом, — поэтому поверх идёт ещё и затемнение. Вместе они
          держат контраст на любом снимке.

          Полоса прижата к низу, а не растянута на весь баннер:
          закрасить кадр целиком значило бы потерять то, ради чего
          обложку и заводили. */}
      <div className="absolute inset-x-0 bottom-0 bg-black/45 px-4 py-3 backdrop-blur-md sm:px-6 sm:py-4">
        {/* Текст белый, а не токеном neutral: под ним чужая
            фотография, и цвет обязан работать поверх любого кадра, а
            не поверх подложки темы. drop-shadow добавляет отрыв от
            фона там, где размытия и затемнения не хватило.

            Логотипа в полосе больше нет — он переехал в угол кадра,
            см. выше. Поэтому здесь простой блок, а не flex-строка с
            картинкой слева. */}
        <div className="min-w-0 drop-shadow-sm">
          {/* H1 страницы — название салона. Единственный на странице:
              заголовки секций ниже идут h2. */}
          <h1 className="truncate text-h3 font-bold text-white sm:text-h2">
            {profile.display_name}
          </h1>

          {/* Слоган — под названием, как в плитке. Одна строка: на
              баннере он подпись к названию, а не абзац. */}
          {tagline && (
            <p className="mt-0.5 line-clamp-1 text-caption text-white/90">
              {tagline}
            </p>
          )}

          {/* КОНТАКТЫ. Город и часы — обычный текст, телефон и сайт —
              живые ссылки: в отличие от плитки каталога, здесь нет
              внешней ссылки, внутрь которой их нельзя вкладывать.

              Разделители рисуются частью самих элементов (before), а
              не join по массиву: элементы разнородны — текст и ссылки,
              — и собрать их одной строкой уже нельзя.

              flex-wrap: на узком экране четыре пункта переносятся, а
              не выдавливают друг друга за край. */}
          <div className="mt-1 flex flex-wrap items-center gap-x-3 gap-y-0.5 text-micro text-white/75 sm:text-caption">
            {city && <span className="truncate">{city}</span>}

            {openingHours && <span className="truncate">{openingHours}</span>}

            {dealerPhone && (
              <a
                href={`tel:${dealerPhone.replace(/[^\d+]/g, '')}`}
                className="truncate underline-offset-2 transition-colors hover:text-white hover:underline"
              >
                {dealerPhone}
              </a>
            )}
          </div>
        </div>
      </div>
    </div>
  );
}
