'use client';

// ============================================================
// RS AUTO — Вкладки кабинета.
// ============================================================
// Client Component ради ОДНОГО: подсветки активного раздела. Определить
// её можно только по текущему адресу (usePathname), а Server Component
// адреса не знает.
//
// Сами вкладки остаются настоящими ссылками <Link>: переход между
// разделами кабинета — навигация, а не действие на странице. Это даёт
// работающие «назад», открытие в новой вкладке и предзагрузку Next.
//
// ВИД. Тот же паттерн чипсов, что у сортировки каталога
// (components/SortSelect.tsx): скруглённый контрол, активный — общим
// выделением сайта (ui/segmented), остальные — контурные со светлым
// наведением. Роль разделов повторяет нижнюю навигацию приложения
// (my_cars, chats, profile), поэтому и порядок тот же.
// ============================================================

import Link from 'next/link';
import { usePathname } from 'next/navigation';

import type { Locale } from '@/lib/i18n';
import { getT, localeHref, stripLocale } from '@/lib/i18n';
import { isParentSectionActive, isSectionActive } from '@/lib/navigation';
import { SELECTED } from './ui/segmented';

type Props = {
  locale: Locale;
};

export default function MyTabs({ locale }: Props) {
  const t = getT(locale);
  const pathname = usePathname();

  // Адрес без префикса локали: на /ru/my/messages сравнивать нужно
  // '/my/messages', иначе ни одна вкладка не подсветится на русской
  // версии сайта.
  const { path } = stripLocale(pathname);

  const tabs = [
    { href: '/my', label: t('my_tab_listings') },
    // «Избранное» сразу за своими объявлениями и до переписки — тот же
    // порядок, что в меню шапки и в приложении.
    { href: '/my/favorites', label: t('favorites_title') },
    { href: '/my/messages', label: t('my_tab_messages') },
    // Уведомления стоят между сообщениями и профилем: это лента
    // системных событий, по смыслу ближе к переписке, чем к настройкам.
    // Именно здесь продавец видит решение модерации, если письмо не
    // дошло или почта в профиле не указана вовсе.
    { href: '/my/notifications', label: t('my_tab_notifications') },
    { href: '/my/profile', label: t('my_tab_profile') },
  ];

  return (
    // НА МОБИЛЬНОМ ВКЛАДОК НЕТ (hidden sm:inline-grid). Разделы кабинета
    // теперь стоят отдельными пунктами в меню шапки, и на узком
    // экране лента чипсов их дублировала: четыре вкладки не влезали
    // в 360px, уезжали в горизонтальную прокрутку и съедали строку
    // над содержимым. Ориентир, ради которого они были нужны,
    // обеспечивает подсветка активного пункта в самом меню.
    //
    // С sm вкладки остаются: там они видны целиком и переключают
    // разделы в один клик, без открытия меню.
    //
    // ВКЛАДКИ ОДИНАКОВОЙ ШИРИНЫ — по самой длинной подписи, а не по
    // содержимому каждой. Прежде каждый чипс был шириной своего
    // текста, и полоса выглядела рваной: «Мои объявления» вдвое шире
    // «Профиля».
    //
    // РАСТЯГИВАТЬ НА ВСЮ СТРОКУ (flex-1) НЕЛЬЗЯ: контейнер кабинета —
    // max-w-6xl, и четыре доли по ~280px превратили бы вкладки в
    // широкие полосы с подписью, потерянной посередине. Ширину задаёт
    // содержимое самой длинной вкладки.
    //
    // inline-grid, а не grid: полоса занимает ровно столько, сколько
    // нужно вкладкам, и не растягивается по контейнеру.
    // grid-flow-col раскладывает их в строку, auto-cols-fr делает
    // колонки одинаковыми — а в inline-контейнере эта одинаковая
    // ширина берётся от самой широкой вкладки, а не от контейнера.
    //
    // overflow-x-auto снят вместе с растяжением: ширина полосы теперь
    // определяется текстом, и на планшете она помещается — подписи
    // короткие, а с sm полоса и так не обязана занимать всю ширину.
    <nav className="mt-4 hidden auto-cols-fr grid-flow-col gap-2 pb-1 sm:inline-grid">
      {tabs.map((tab) => {
        // Правило то же, что в меню шапки (HeaderMenu), и физически
        // это одна функция: lib/navigation. Раньше здесь стояло
        // точное совпадение для '/my', и на /my/listing/{id}/edit не
        // подсвечивалась ни одна вкладка — хотя правка объявления
        // относится именно к «Моим объявлениям».
        const active =
          tab.href === '/my'
            ? isParentSectionActive(
                path,
                tab.href,
                tabs.map((other) => other.href),
              )
            : isSectionActive(path, tab.href);

        return (
          <Link
            key={tab.href}
            href={localeHref(locale, tab.href)}
            // aria-current — единственный признак активного раздела для
            // скринридера: цвет фона он не читает.
            aria-current={active ? 'page' : undefined}
            className={[
              // text-center — подпись по центру своей ячейки: в
              // колонке шириной по «Мои объявления» короткий
              // «Профиль» иначе прижимался бы влево, и полоса снова
              // читалась бы неровной.
              'whitespace-nowrap rounded-control px-4 py-2.5 text-center text-caption font-semibold transition-colors duration-fast ease-out',
              // Выбранная вкладка — общий приём выделения сайта
              // (ui/segmented). Невыбранные держат свою рамку и белый
              // фон: полоса вкладок читается как ряд кнопок, а не как
              // текст, и терять контур им нельзя.
              active
                ? SELECTED
                : 'border border-neutral-15 bg-white hover:bg-surface-hover',
            ].join(' ')}
          >
            {tab.label}
          </Link>
        );
      })}
    </nav>
  );
}
