'use client';

// ============================================================
// RS AUTO — Появление блоков при попадании в поле зрения.
// ============================================================
// ОДИН НАБЛЮДАТЕЛЬ НА ВСЮ СТРАНИЦУ, а не по одному на элемент. В
// выдаче каталога 24 карточки, на главной к ним добавляются витрина
// аренды и блок «недавно просмотренные» — полсотни независимых
// IntersectionObserver означали бы полсотни подписок в самом горячем
// месте (прокрутка ленты). Один наблюдатель обходит те же элементы
// пачкой и снимает с себя каждый сразу после срабатывания.
//
// РАЗМЕТКА НИЧЕГО НЕ ИМПОРТИРУЕТ. Элемент участвует в анимации, если
// у него есть класс reveal-on-scroll, — и всё. Это принципиально:
// карточки каталога рисует СЕРВЕРНЫЙ CarCard, обернуть каждую в
// клиентский компонент значило бы отправить в браузер два десятка
// лишних обёрток. Класс же не стоит ничего.
//
// САМОЕ ВАЖНОЕ ЗДЕСЬ — БЕЗОПАСНОСТЬ ПРИ ОТКАЗЕ. Начальное состояние
// прячет элемент (opacity: 0), и если скрипт не выполнился, контент
// пропал бы совсем — это уже не потеря анимации, а потеря страницы.
// Поэтому скрывающее правило в globals.css действует только внутри
// .js-reveal-ready, и класс этот ставит на <html> сам наблюдатель,
// первым же делом. Не запустился он — не спрятал и содержимое.
//
// ПОЧЕМУ НЕ ЧИСТЫЙ CSS. animation-timeline: view() решала бы задачу
// без единой строки скрипта, но Safari её не поддерживает (сентябрь
// 2026), а на Safari приходится половина мобильного трафика в
// Сербии. Показывать анимацию только части посетителей и молча
// ронять её у остальных нельзя: элементы у них остались бы в
// начальном состоянии.
//
// НОВЫЕ ЭЛЕМЕНТЫ ПОДХВАТЫВАЮТСЯ САМИ. За разметкой следит
// MutationObserver: страницы догружают карточки (бесконечная лента),
// и без него дозагруженная порция осталась бы невидимой навсегда —
// ровно тот отказ, который описан выше.
// ============================================================

import { useEffect } from 'react';

// Порог: элемент считается показавшимся, когда в кадр вошла хотя бы
// его десятая часть. Ноль срабатывал бы по первому пикселю — карточка
// начинала бы проявляться, ещё не появившись из-за края экрана.
const THRESHOLD = 0.1;

// Нижняя граница кадра поднята на 40px: анимация запускается чуть
// раньше, чем элемент реально виден, и к моменту, когда человек
// доводит до него взгляд, движение уже закончилось. Без этого запаса
// появление всегда «догоняет» прокрутку.
const ROOT_MARGIN = '0px 0px -40px 0px';

export default function RevealOnScroll() {
  useEffect(() => {
    // Старые браузеры без наблюдателя: класс не ставим, элементы
    // остаются видимыми в своём конечном виде. Анимации нет — контент
    // на месте.
    if (typeof IntersectionObserver === 'undefined') return;

    const root = document.documentElement;

    // Разрешаем CSS прятать элементы только теперь, когда точно есть
    // кому их показать обратно.
    root.classList.add('js-reveal-ready');

    const io = new IntersectionObserver(
      (entries) => {
        for (const entry of entries) {
          if (!entry.isIntersecting) continue;
          entry.target.classList.add('is-visible');
          // Появление одноразовое: элемент, уехавший вверх и
          // вернувшийся, повторно не мигает. Повтор при каждом
          // проходе превратил бы длинную ленту в мельтешение.
          io.unobserve(entry.target);
        }
      },
      { threshold: THRESHOLD, rootMargin: ROOT_MARGIN },
    );

    const observeAll = (scope: ParentNode) => {
      const nodes = scope.querySelectorAll?.(
        '.reveal-on-scroll:not(.is-visible)',
      );
      nodes?.forEach((node) => io.observe(node));
    };

    observeAll(document);

    // Догруженные карточки. Наблюдаем только добавление узлов и
    // только в поддереве body: атрибуты и текст нас не касаются, а
    // подписка на них дала бы поток пустых срабатываний при каждой
    // перерисовке.
    const mo = new MutationObserver((mutations) => {
      for (const m of mutations) {
        m.addedNodes.forEach((node) => {
          if (!(node instanceof Element)) return;
          if (node.matches('.reveal-on-scroll:not(.is-visible)')) {
            io.observe(node);
          }
          observeAll(node);
        });
      }
    });

    mo.observe(document.body, { childList: true, subtree: true });

    return () => {
      io.disconnect();
      mo.disconnect();
      root.classList.remove('js-reveal-ready');
    };
  }, []);

  return null;
}
