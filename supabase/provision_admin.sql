-- 0.1. Структура auth.users: какие поля обязательны (is_nullable = NO
--      и без default). Именно их обязана заполнить часть 2.
select
  column_name,
  data_type,
  is_nullable,
  column_default,
  case
    when is_nullable = 'NO' and column_default is null
    then '<<< ОБЯЗАТЕЛЬНО ЗАПОЛНИТЬ'
    else ''
  end as note
from information_schema.columns
where table_schema = 'auth'
  and table_name   = 'users'
order by ordinal_position;

-- 0.2. Триггеры на auth.users — что сработает при вставке.
--      Ожидается как минимум on_auth_user_created (миграция 0002).
--      Если в списке есть чужие триггеры, о которых вы не знаете, —
--      разберитесь с ними ДО прогона части 2.
select
  t.tgname                        as trigger_name,
  case t.tgtype::integer & 1 when 0 then 'AFTER' else 'BEFORE' end as timing,
  case
    when t.tgtype::integer &  4 > 0 then 'INSERT'
    when t.tgtype::integer &  8 > 0 then 'DELETE'
    when t.tgtype::integer & 16 > 0 then 'UPDATE'
    else 'OTHER'
  end                             as event,
  n.nspname || '.' || p.proname   as function_name,
  t.tgenabled                     as enabled
from pg_trigger t
join pg_class c     on c.oid = t.tgrelid
join pg_namespace cn on cn.oid = c.relnamespace
join pg_proc p      on p.oid = t.tgfoid
join pg_namespace n on n.oid = p.pronamespace
where cn.nspname = 'auth'
  and c.relname  = 'users'
  and not t.tgisinternal
order by t.tgname;

-- 0.3. Действующие администраторы. Проверьте, что список — тот,
--      который вы ожидаете увидеть.
select
  p.id,
  p.email,
  p.phone,
  p.full_name,
  p.created_at,
  u.last_sign_in_at
from public.profiles p
left join auth.users u on u.id = p.id
where p.is_admin
order by p.created_at;


