-- ############################################################
-- ЧАСТЬ 2. СОЗДАТЬ ПОЛЬЗОВАТЕЛЯ НАПРЯМУЮ (стенд / служебная запись)
-- ############################################################
-- ПЕРЕЧИТАЙТЕ ПРЕДУПРЕЖДЕНИЕ В ШАПКЕ: войти под таким пользователем
-- на сайте, скорее всего, не выйдет. Это не дефект скрипта — так
-- устроен вход по SMS.
--
-- Скрипт идемпотентен: повторный прогон ничего не ломает и не
-- создаёт дублей.
--
-- ЧТО СРАБОТАЕТ ПРИ ВСТАВКЕ: триггер on_auth_user_created
-- (создан в 0002, функция переписана в 0035) →
-- public.handle_new_user() → INSERT в public.profiles
-- (id, email, phone, full_name). Профиль создастся САМ, вместе с
-- телефоном. Поэтому ниже профиль не вставляется вручную, а
-- ОБНОВЛЯЕТСЯ: ручной INSERT конфликтовал бы с триггером по
-- первичному ключу.
--
-- Имя профиля триггер берёт из raw_user_meta_data ->> 'full_name' —
-- поэтому в INSERT ниже оно кладётся именно туда, иначе профиль
-- создался бы безымянным.
--
-- Проверьте вывод запроса 0.2: если триггера on_auth_user_created в
-- вашей базе нет, сработает страховочная вставка в шаге 2.3.

do $$
declare
  -- ---------- ЗАПОЛНИТЕ ЭТИ ТРИ ЗНАЧЕНИЯ ----------
  v_email text := 'admin@rsauto.rs';        -- <<< почта администратора
  v_phone text := '3816XXXXXXXX';           -- <<< E.164 БЕЗ «+» и пробелов
  v_name  text := 'Имя Фамилия';            -- <<< как показывать в журнале
  -- ------------------------------------------------

  v_user_id uuid;
  v_created boolean := false;
begin
  -- ---------- 2.1. Пользователь уже есть? ----------
  -- Ищем и по почте, и по телефону: человек мог войти на сайте по
  -- SMS (тогда есть phone, а email пуст) либо быть заведён раньше.
  select id into v_user_id
    from auth.users
   where (v_email is not null and email = v_email)
      or (v_phone is not null and phone = v_phone)
   limit 1;

  -- ---------- 2.2. Создать, если нет ----------
  if v_user_id is null then
    v_user_id := gen_random_uuid();

    insert into auth.users (
      id,
      instance_id,
      aud,
      role,
      email,
      phone,
      encrypted_password,
      email_confirmed_at,
      phone_confirmed_at,
      raw_app_meta_data,
      raw_user_meta_data,
      created_at,
      updated_at
    )
    values (
      v_user_id,

      -- instance_id: в однопроектной инсталляции Supabase всегда
      -- нулевой uuid. Поле NOT NULL без default в большинстве версий
      -- GoTrue — пропустив его, получите ошибку вставки.
      '00000000-0000-0000-0000-000000000000',

      -- aud и role: GoTrue проверяет их при выдаче токена. Значение
      -- 'authenticated' — то же, что получает любой вошедший
      -- пользователь. Роль администратора здесь НИ ПРИ ЧЁМ: права
      -- живут в profiles.is_admin, а не в токене (см. ниже).
      'authenticated',
      'authenticated',

      v_email,
      v_phone,

      -- encrypted_password: пустая строка, а не NULL и не хеш.
      -- Пароля у пользователя нет и не будет: вход на сайте только
      -- по SMS. Пустая строка не соответствует ни одному паролю —
      -- bcrypt-сравнение с ней не пройдёт никогда, поэтому это
      -- безопаснее, чем поставить хеш от известной строки.
      -- Тот же приём использован в миграции 0054 для демо-продавца.
      '',

      -- email_confirmed_at: без него GoTrue считает адрес
      -- неподтверждённым и может блокировать вход, если в проекте
      -- включено «Confirm email». Мы заводим пользователя сами,
      -- письмо подтверждения слать некому и незачем.
      now(),

      -- phone_confirmed_at: то же самое для телефона. Именно по
      -- подтверждённому телефону работает вход по SMS, и без этой
      -- отметки строка для входа бесполезна заведомо.
      now(),

      -- raw_app_meta_data: метаданные приложения, которые GoTrue
      -- пишет сам при обычной регистрации. provider/providers
      -- сообщают, каким способом человек входит; ставим phone —
      -- единственный способ входа на сайте.
      --
      -- ЗДЕСЬ НЕТ И НЕ ДОЛЖНО БЫТЬ РОЛИ АДМИНИСТРАТОРА. Права
      -- проекта живут в profiles.is_admin и читаются функцией
      -- is_admin() на каждом запросе. Роль в токене жила бы до
      -- истечения токена: снятый администратор сохранял бы доступ
      -- ещё час после того, как вы его убрали.
      '{"provider":"phone","providers":["phone"]}'::jsonb,

      -- raw_user_meta_data: данные, которые пользователь передаёт о
      -- себе при регистрации. Триггер handle_new_user (0002) берёт
      -- отсюда full_name для профиля — поэтому имя кладём именно
      -- сюда, иначе профиль создастся безымянным.
      jsonb_build_object('full_name', v_name),

      now(),
      now()
    );

    v_created := true;
    raise notice 'Создан пользователь auth.users: % (%)', v_user_id, v_email;
  else
    raise notice 'Пользователь уже существует: % — создавать не нужно', v_user_id;
  end if;

  -- ---------- 2.3. Профиль ----------
  -- В штатном случае профиль уже создал триггер. Эта вставка —
  -- страховка на случай, если триггера в вашей базе нет (проверьте
  -- запросом 0.2) или пользователь существовал до его появления.
  --
  -- ВАЖНО ПРО on conflict (id): он покрывает только первичный ключ.
  -- На profiles есть ЕЩЁ ДВА уникальных индекса — profiles_email_unique
  -- и profiles_phone_unique (оба частичные, из 0035). Если тот же
  -- телефон или почта уже записаны за ДРУГИМ профилем, вставка упадёт
  -- на них, и это правильно: один номер = один аккаунт, и молча
  -- перевешивать его на новую строку нельзя. Разбирайтесь с дублем
  -- вручную — почти наверняка нужному человеку надо просто поднять
  -- флаг частью 1.
  insert into public.profiles (id, email, phone, full_name)
  values (v_user_id, v_email, v_phone, v_name)
  on conflict (id) do nothing;

  -- ---------- 2.4. Поднять флаг ----------
  -- ОТДЕЛЬНЫМ UPDATE, а не полем в INSERT профиля: строку создаёт
  -- триггер, и до неё INSERT выше не доберётся. UPDATE отрабатывает
  -- в обоих случаях — и когда профиль сделал триггер, и когда
  -- страховочная вставка.
  --
  -- Имя обновляем только если оно пустое: у человека, который уже
  -- пользовался площадкой, могло быть заполнено своё, и затирать
  -- его назначением прав незачем.
  update public.profiles
     set is_admin  = true,
         full_name = coalesce(nullif(btrim(full_name), ''), v_name)
   where id = v_user_id;

  raise notice 'Флаг is_admin поднят для % (новый пользователь: %)',
    v_user_id, v_created;

  if v_created then
    raise notice 'ВНИМАНИЕ: вход по SMS под этой записью может не работать — см. шапку скрипта, часть 2.';
  end if;
end;
$$;


