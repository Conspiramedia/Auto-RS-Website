-- ############################################################
-- Ожидается: строка с is_admin = true, заполненными email и phone.
-- last_sign_in_at пуст у только что созданного пользователя — он
-- заполнится при первом успешном входе. Если после нескольких
-- попыток входа он остаётся пустым, значит, сработало ровно то, о
-- чём предупреждает шапка: GoTrue не признал собранную вручную
-- строку. Лечится частью 1 — обычным входом с последующим UPDATE.
select
  p.id,
  p.email,
  p.phone       as profile_phone,
  u.phone       as auth_phone,
  p.full_name,
  p.is_admin,
  u.email_confirmed_at,
  u.phone_confirmed_at,
  u.last_sign_in_at
from public.profiles p
join auth.users u on u.id = p.id
where p.is_admin
order by p.created_at;


-- ############################################################
-- СНЯТЬ ПРАВА
-- ############################################################
-- Действует немедленно: is_admin() читает profiles на каждом
-- запросе, а не берёт роль из токена. Уволенный модератор теряет
-- доступ сразу, не дожидаясь истечения сессии.
--
-- update public.profiles set is_admin = false
--  where id = '00000000-0000-0000-0000-000000000000';   -- <<< id
--
-- Пользователя при этом НЕ УДАЛЯЙТЕ: на его id ссылается
-- admin_action_log.actor_id с on delete restrict (0078), и удаление
-- упрётся в журнал. Так и задумано — журнал должен пережить
-- увольнение того, чьи решения в нём записаны.
