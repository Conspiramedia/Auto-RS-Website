  is 'Удаление своего аккаунта: объявления, диалоги, заявки и прочие следы удаляются, профиль обезличивается, учётные данные в auth.users освобождаются, вход запрещается (deleted_at). Требует p_confirm = DELETE. Необратимо (0126, 0127)';

