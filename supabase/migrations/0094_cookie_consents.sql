-- ============================================================
-- Кто, когда, с какого адреса и с какой версией — за период.
-- Время приведено к белградской зоне: спор о согласии решается
-- по местному времени оператора, а не по UTC.
--
--   select
--     c.id,
--     c.user_id,
--     coalesce(p.phone, p.email, '— гость —')      as who,
--     to_char(c.consent_at at time zone 'Europe/Belgrade',
--             'YYYY-MM-DD HH24:MI:SS')             as consent_at_belgrade,
--     host(c.ip)                                   as ip,
--     c.user_agent,
--     c.policy_version,
--     c.consents
--   from public.cookie_consents c
--   left join public.profiles p on p.id = c.user_id
--   where c.consent_at >= '2026-01-01'
--   order by c.consent_at desc;
--
-- Экспорт в CSV: тот же запрос, кнопка «Download CSV» в SQL Editor
-- либо \copy (…) to 'consents.csv' with csv header из psql.
--
-- Проверка после применения:
--
--   -- 1) Гость (роль anon, без JWT):
--   select public.record_cookie_consent('2026-08-26.2');
--   -- {"ok": true, "id": "…"}, строка с user_id = null
--
--   -- 2) Прямая вставка в обход RPC запрещена RLS:
--   insert into public.cookie_consents (policy_version) values ('x');
--   -- ERROR: new row violates row-level security policy
--
--   -- 3) Пустая версия отклоняется:
--   select public.record_cookie_consent('  ');
--   -- {"ok": false, "error": "invalid_version"}
-- ============================================================
