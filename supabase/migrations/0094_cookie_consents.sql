-- ============================================================
-- RS AUTO — Миграция 0094: юридически значимая фиксация согласия на куки.
-- ============================================================
-- ЗАЧЕМ ТАБЛИЦА, А НЕ ОДИН ЛОКАЛЬНЫЙ ФЛАГ. Локальный флаг в браузере
-- (localStorage) решает задачу интерфейса — «баннер больше не
-- показывать» — и НИЧЕГО не доказывает: он лежит на устройстве
-- пользователя, редактируется им же из консоли за две секунды и
-- исчезает при очистке данных сайта. Регулятору предъявить нечего.
--
-- Доказуемость требует записи НА СТОРОНЕ ОПЕРАТОРА, и в ней должно
-- быть ровно четыре вещи: КТО (user_id либо анонимная строка), КОГДА
-- (consent_at с часовым поясом), ОТКУДА (ip, user_agent) и С ЧЕМ
-- СОГЛАСИЛСЯ (policy_version — версия редакции документов, показанной
-- в момент клика, и consents — перечень принятых категорий).
--
-- ГОСТЬ ТОЖЕ ДАЁТ СОГЛАСИЕ. Куки ставятся до всякого входа, поэтому
-- user_id объявлен nullable: у большинства записей его не будет вовсе.
-- Это не дефект схемы, а суть события — согласие даёт посетитель,
-- а не аккаунт.
--
-- ИСТОРИЯ, А НЕ ТЕКУЩЕЕ СОСТОЯНИЕ. Каждый клик пишет НОВУЮ строку,
-- существующие не обновляются и не удаляются. Апдейт «последнего
-- согласия» уничтожил бы доказательство предыдущего: при споре о
-- редакции от марта запись, переписанная в августе, не подтверждает
-- ничего. Уникальных индексов и on conflict здесь нет намеренно.
--
-- СВЯЗЬ С lib/legal.ts. policy_version НЕ вычисляется в базе и не
-- имеет значения по умолчанию: единственный источник версии —
-- POLICY_VERSION в lib/legal.ts, рядом с самим текстом документов.
-- База принимает версию параметром и лишь проверяет, что она не
-- пустая. Продублировать константу в SQL значило бы завести второй
-- источник истины, который разойдётся с первым при ближайшей правке
-- текста политики.
-- ============================================================

create table if not exists public.cookie_consents (
  id uuid primary key default gen_random_uuid(),

  -- Кто согласился, если он был в сессии. NULL — гость, и это
  -- нормальный, а не исключительный случай (см. шапку).
  -- ON DELETE SET NULL, а не CASCADE: удаление аккаунта не отменяет
  -- того факта, что согласие было дано. Строка остаётся как
  -- обезличенное доказательство события — ровно то поведение, которого
  -- требует принцип минимизации: личность убрана, факт сохранён.
  user_id uuid references auth.users (id) on delete set null,

  -- Момент согласия. timestamptz, а не timestamp: доказательство без
  -- часового пояса бессмысленно — «14:30» без указания зоны не
  -- определяет момент времени. Хранится в UTC, отдаётся в любой зоне.
  consent_at timestamptz not null default now(),

  -- IP-адрес обращения. Тип inet, а не text: он валидирует значение
  -- (мусор в колонку не ляжет) и позволяет искать по подсети.
  -- Nullable: за прокси-слоем заголовок может отсутствовать или быть
  -- недоверенным, и записать «неизвестно» честнее, чем выдумать адрес.
  ip inet,

  -- User-Agent браузера: модель устройства и версия браузера. Вместе с
  -- IP образует техническую привязку записи к обращению.
  user_agent text,

  -- Версия редакции документов, действовавшая в момент клика. NOT NULL
  -- и без default: запись без версии не доказывает ничего — неизвестно,
  -- с ЧЕМ человек согласился.
  policy_version text not null,

  -- Что именно принято. jsonb, а не набор булевых колонок: категории
  -- куки со временем меняются (появится аналитика, реклама,
  -- персонализация), и каждая новая категория означала бы миграцию с
  -- ALTER TABLE и перезаписью смысла старых строк. В jsonb старая
  -- запись честно показывает, какие категории вообще предлагались
  -- на тот момент.
  --
  -- Текущий баннер предлагает одну кнопку «Хорошо» и, соответственно,
  -- один ключ: {"cookies": true}. Технические куки (сессия, язык)
  -- согласия не требуют по существу, аналитика Plausible куки не
  -- ставит вовсе — выбора «принять частично» на сайте пока нет.
  consents jsonb not null default '{"cookies": true}'::jsonb,

  -- Версия документов не может быть пустой строкой: NOT NULL этого
  -- не гарантирует, а '' в доказательстве равносильно его отсутствию.
  constraint chk_cookie_consents_version
    check (length(btrim(policy_version)) > 0),

  -- consents обязан быть объектом, а не массивом, числом или строкой:
  -- выгрузка и любой будущий разбор читают его по ключам категорий.
  constraint chk_cookie_consents_object
    check (jsonb_typeof(consents) = 'object')
);

comment on table public.cookie_consents is
  'Журнал согласий на использование куки. Только вставка через RPC record_cookie_consent, история не перезаписывается.';

comment on column public.cookie_consents.policy_version is
  'Версия редакции документов на момент согласия. Источник — POLICY_VERSION в lib/legal.ts, база значение не вычисляет.';

comment on column public.cookie_consents.ip is
  'IP обращения из заголовков PostgREST. NULL, если заголовок недоступен.';

-- ------------------------------------------------------------
-- Индексы.
-- ------------------------------------------------------------
-- По пользователю: главный запрос доказательства — «покажи все
-- согласия вот этого человека». Частичный (where user_id is not null):
-- гостевых строк подавляющее большинство, и класть их NULL в индекс
-- значило бы раздуть его ради значений, по которым не ищут.
create index if not exists idx_cookie_consents_user
  on public.cookie_consents (user_id, consent_at desc)
  where user_id is not null;

-- По времени: выгрузка за период и лента админки «сначала новые».
-- desc в определении совпадает с порядком чтения — планировщик берёт
-- индекс без отдельной сортировки.
create index if not exists idx_cookie_consents_at
  on public.cookie_consents (consent_at desc);

-- ------------------------------------------------------------
-- RLS.
-- ------------------------------------------------------------
-- Прямая вставка ЗАПРЕЩЕНА всем, включая anon и authenticated:
-- политики insert нет ни одной. Причина принципиальная — писать
-- доказательство должен сервер, а не клиент. Будь insert открыт,
-- любой посетитель заполнил бы журнал строками с чужими user_id,
-- произвольными датами и версией политики, которой не существует,
-- и вся доказательная ценность таблицы обнулилась бы.
--
-- Единственный путь записи — SECURITY DEFINER функция ниже: она сама
-- проставляет user_id из auth.uid(), время из now() и берёт IP из
-- заголовков запроса, то есть подделать эти поля клиент не может.
--
-- Чтение — только админ. Журнал согласий содержит IP и User-Agent
-- посетителей, то есть персональные данные; отдавать его anon нельзя
-- ни в каком виде. Сервисная роль (service_role) обходит RLS по
-- определению — выгрузка из панели Supabase и из SQL Editor работает.
alter table public.cookie_consents enable row level security;

drop policy if exists cookie_consents_select_admin on public.cookie_consents;
create policy cookie_consents_select_admin
  on public.cookie_consents
  for select
  to authenticated
  using (public.is_admin());

-- ------------------------------------------------------------
-- RPC записи согласия.
-- ------------------------------------------------------------
-- Возвращает jsonb {ok: true, id: <uuid>} либо {ok: false, error: '<код>'}.
-- Форма ответа та же, что у subscribe_app_waitlist (0076) и
-- submit_contact_message (0058): фронтенд разбирает коды, а не
-- сообщения СУБД.
--
-- p_policy_version передаётся КЛИЕНТОМ, и это осознанное решение.
-- Доказывать нужно не «какая версия действует сейчас», а «какую
-- версию человеку показали в момент клика»: если владелец обновит
-- политику через минуту после согласия, запись обязана сохранить
-- старую версию, а не подтянуть новую. Единственный источник самой
-- константы — lib/legal.ts, и клиент отдаёт именно её.
--
-- ЧТО КЛИЕНТ ПОДДЕЛАТЬ НЕ МОЖЕТ: user_id (берётся из проверенного
-- JWT через auth.uid()), consent_at (now() на сервере), ip и
-- user_agent (заголовки запроса, которые ставит не JS страницы,
-- а сеть и браузер). Подмена версии политики в свою пользу лишена
-- смысла: она сделала бы собственное согласие пользователя
-- недействительным для актуальной редакции, то есть вернула бы ему
-- баннер.
create or replace function public.record_cookie_consent(
  p_policy_version text,
  p_consents jsonb default '{"cookies": true}'::jsonb
)
returns jsonb
language plpgsql
security definer
-- Пустой search_path обязателен для SECURITY DEFINER: иначе вызывающий
-- подменит схему и заставит функцию писать в свою таблицу.
set search_path = ''
as $$
declare
  v_version text := btrim(coalesce(p_policy_version, ''));
  v_consents jsonb := coalesce(p_consents, '{"cookies": true}'::jsonb);
  v_headers jsonb;
  v_forwarded text;
  v_ip inet;
  v_user_agent text;
  v_recent int;
  v_id uuid;
begin
  -- ---------- Валидация ----------
  -- Версия обязательна: строка без неё не доказывает, с чем согласился
  -- человек, и лучше отказать, чем записать пустое доказательство.
  if v_version = '' then
    return jsonb_build_object('ok', false, 'error', 'invalid_version');
  end if;

  -- Разумный потолок длины: версия — короткая метка редакции
  -- ('2026-08-26.2'), а не место для произвольного текста от клиента.
  if length(v_version) > 64 then
    return jsonb_build_object('ok', false, 'error', 'invalid_version');
  end if;

  if jsonb_typeof(v_consents) <> 'object' then
    return jsonb_build_object('ok', false, 'error', 'invalid_consents');
  end if;

  -- ---------- Заголовки запроса ----------
  -- PostgREST кладёт заголовки HTTP в GUC request.headers. Второй
  -- аргумент true у current_setting означает «нет переменной — верни
  -- NULL, а не ошибку»: функцию можно вызвать и из SQL Editor, где
  -- никакого HTTP-запроса нет, и она не упадёт.
  v_headers := nullif(current_setting('request.headers', true), '')::jsonb;

  if v_headers is not null then
    -- x-forwarded-for содержит цепочку прокси через запятую; настоящий
    -- адрес клиента — ПЕРВЫЙ элемент, остальные добавлены
    -- балансировщиками. btrim обязателен: без него приведение к inet
    -- упало бы на ' 10.0.0.1' с ведущим пробелом.
    v_forwarded := btrim(
      split_part(coalesce(v_headers ->> 'x-forwarded-for', ''), ',', 1)
    );

    -- Приведение к inet — в отдельном блоке с перехватом исключения.
    -- Заголовок приходит снаружи, и мусор в нём («unknown», обрезанный
    -- IPv6, подставленное клиентом значение) уронил бы всю функцию, а
    -- вместе с ней и запись согласия. Отсутствие IP — приемлемая
    -- потеря, потеря самой записи — нет.
    if v_forwarded <> '' then
      begin
        v_ip := v_forwarded::inet;
      exception
        when others then
          v_ip := null;
      end;
    end if;

    -- User-Agent обрезается до 500 символов: реальные строки короче,
    -- а колонка не должна становиться местом для мегабайта от клиента.
    v_user_agent := left(
      nullif(btrim(coalesce(v_headers ->> 'user-agent', '')), ''),
      500
    );
  end if;

  -- ---------- Rate-лимит ----------
  -- Живой посетитель нажимает «Хорошо» один раз за визит. Ограничиваем
  -- поток строк с одного IP: скрипт, зовущий RPC в цикле, иначе надует
  -- журнал до нечитаемости, а вместе с ним и его доказательную
  -- ценность. Лимит намеренно щедрый — за общим NAT (офис, кафе,
  -- мобильный оператор) с одного адреса приходят десятки разных людей.
  --
  -- Обращения без распознанного IP под лимит не попадают: считать их
  -- не по чему, а отказывать всем сразу — значит потерять согласия
  -- там, где заголовок недоступен.
  if v_ip is not null then
    select count(*)
      into v_recent
      from public.cookie_consents
     where ip = v_ip
       and consent_at > now() - interval '1 minute';

    if v_recent >= 60 then
      return jsonb_build_object('ok', false, 'error', 'rate_limited');
    end if;
  end if;

  -- ---------- Запись ----------
  -- Всегда INSERT. Ни on conflict, ни update: повторное согласие того
  -- же человека — отдельное событие со своим временем, и история
  -- обязана сохранить оба (см. шапку миграции).
  insert into public.cookie_consents (
    user_id, ip, user_agent, policy_version, consents
  )
  values (
    auth.uid(), v_ip, v_user_agent, v_version, v_consents
  )
  returning id into v_id;

  return jsonb_build_object('ok', true, 'id', v_id);
end;
$$;

comment on function public.record_cookie_consent is
  'Фиксация согласия на куки: user_id из auth.uid(), время из now(), IP и User-Agent из заголовков. Всегда вставка, история не перезаписывается.';

-- Право вызова: аноним и вошедший. Согласие на куки даёт любой
-- посетитель, в том числе никогда не входивший, — иначе баннер
-- работал бы вхолостую для большинства аудитории. Защита — валидация
-- и лимит внутри функции, а поля доказательства клиент не задаёт.
revoke all on function public.record_cookie_consent(text, jsonb) from public;
grant execute on function public.record_cookie_consent(text, jsonb) to anon, authenticated;

