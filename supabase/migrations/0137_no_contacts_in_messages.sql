-- ============================================================
-- AUTO.RS — Миграция 0137: запрет ссылок и контактов в сообщениях.
-- ============================================================
-- ЗАЧЕМ. Увод переписки из чата — типовой первый шаг мошенничества:
-- «продолжим в вайбере», дальше ссылка на поддельную страницу оплаты
-- или доставки, и никаких следов на площадке. Пока разговор идёт в
-- чате RS Auto, у обеих сторон и у поддержки остаётся история, по
-- которой видно, что и кому обещали.
--
-- ЧЕСТНОЙ СДЕЛКЕ ЗАПРЕТ НЕ МЕШАЕТ. Номер продавца показан в самой
-- карточке объявления по кнопке «Позвонить» (0116/0117): покупателю
-- незачем просить его в переписке, он и так на виду. Запрещается не
-- обмен контактами как таковой, а перенос разговора туда, где он
-- никем не наблюдается.
--
-- ГДЕ ЭТО ЖИВЁТ И ПОЧЕМУ НЕ В RPC. Сообщения пишутся ОБЫЧНЫМ INSERT
-- под RLS — у чата не было бизнес-правил, и RPC для него намеренно не
-- заводили (см. комментарий в app/my/actions.ts). Теперь правило
-- появилось, но заводить ради него RPC всё равно не нужно: барьер в
-- BEFORE-триггере ловит ЛЮБОЙ путь записи, включая прямой INSERT с
-- anon-ключом в обход Server Action. RPC пришлось бы ещё и защищать от
-- того же обхода.
--
-- ПРАВИЛА ТЕ ЖЕ, ЧТО У ОПИСАНИЯ (0135/0136), и переиспользуются
-- функции оттуда — f_has_contact_info и f_has_external_link. Держать
-- два набора регулярок для одного и того же значило бы однажды
-- поправить их в одном месте и забыть про другое.
--
-- РАЗМЕТКУ В СООБЩЕНИЯХ НЕ ПРОВЕРЯЕМ, в отличие от описания.
-- Сообщения выводятся как текст, без dangerouslySetInnerHTML, поэтому
-- теги в них безобидны, а разговор «поставь <b> для жирного» вполне
-- возможен. Правило, которое не защищает, но мешает, не нужно.
--
-- СТАРУЮ ПЕРЕПИСКУ НЕ ТРОГАЕМ. Проверка стоит только на INSERT:
-- сообщения не редактируются в принципе, а UPDATE по ним бывает ровно
-- один — отметка is_read получателем (колоночный грант из 0069).
-- Проверять текст при этом UPDATE значило бы сломать прочтение всех
-- старых сообщений, где ссылка уже есть.
-- ============================================================


-- ------------------------------------------------------------
-- 1. ФУНКЦИЯ ТРИГГЕРА
-- ------------------------------------------------------------
create or replace function public.trg_check_message_text()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  -- Пустые сообщения отсекает клиент, но проверка дешёвая, а NULL в
  -- регулярках дал бы NULL вместо false и пропустил бы строку дальше.
  if new.text is null or btrim(new.text) = '' then
    raise exception 'Пустое сообщение'
      using errcode = 'check_violation', hint = 'empty_message';
  end if;

  -- КОНТАКТЫ: телефон, почта, @никнейм, ссылка на мессенджер.
  -- Переиспользуем функцию из 0135 — правила обязаны совпадать с теми,
  -- что применяются к описанию.
  if public.f_has_contact_info(new.text) then
    raise exception
      'В сообщениях нельзя отправлять контактные данные'
      using
        errcode = 'check_violation',
        -- hint читается клиентом: по нему он подставляет текст на
        -- языке пользователя (chat_err_contacts в обеих локалях).
        hint = 'contacts_in_message';
  end if;

  -- ЛЮБАЯ ДРУГАЯ ВНЕШНЯЯ ССЫЛКА (функция из 0136).
  if public.f_has_external_link(new.text) then
    raise exception
      'В сообщениях нельзя отправлять ссылки на другие сайты'
      using
        errcode = 'check_violation',
        hint = 'contacts_in_message';
  end if;

  return new;
end;
$$;

comment on function public.trg_check_message_text()
  is 'BEFORE-триггер messages: отклоняет сообщения со ссылками и контактными данными. Правила общие с описанием объявления — f_has_contact_info (0135) и f_has_external_link (0136)';


-- ------------------------------------------------------------
-- 2. ТРИГГЕР
-- ------------------------------------------------------------
-- ТОЛЬКО INSERT. Единственный UPDATE по сообщениям — отметка is_read
-- получателем; проверять при нём текст значило бы сделать
-- непрочитываемой всю старую переписку, где ссылка уже есть.
drop trigger if exists trg_messages_check_text on public.messages;

create trigger trg_messages_check_text
  before insert on public.messages
  for each row
  execute function public.trg_check_message_text();
