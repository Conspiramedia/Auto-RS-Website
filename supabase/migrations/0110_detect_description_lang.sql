-- ============================================================
-- AUTO.RS — Миграция 0110: определение языка описания
-- ============================================================
-- ЗАЧЕМ. Описание объявления пишется на языке автора (это правило
-- проекта, и менять его незачем: продавец может сознательно писать
-- по-сербски, целясь в сербских покупателей). Но сайт двуязычный, и
-- карточка обязана честно показать читателю, на каком языке текст,
-- а позже — предложить перевод.
--
-- Спрашивать язык у продавца в форме подачи мы не будем: это лишний
-- шаг в воронке, а ответ всё равно ненадёжен — люди пишут вперемешку
-- и путают «язык интерфейса» с «языком текста». Определяем сами.
--
-- ГДЕ ЭТО ЖИВЁТ. В базе, а не в клиенте: нормализация данных —
-- обязанность бэкенда, и тогда язык проставится одинаково для
-- объявлений с сайта и из мобильного приложения, которые ходят в одни
-- и те же RPC. Клиенты не делают ничего.
--
-- ЧТО ИМЕННО РАЗЛИЧАЕМ. Ровно два языка — сербский и русский. Это
-- сильно проще общего определителя языка: готовые библиотеки знают
-- сотню языков и на коротких текстах объявлений ошибаются чаще, чем
-- три правила ниже, заточенные под эту пару и под лексику авторынка.
--
-- ТРИ ПРИЗНАКА, ПО УБЫВАНИЮ НАДЁЖНОСТИ:
--   1. Уникальные буквы алфавита. В сербской кириллице есть ђ ј љ њ ћ џ,
--      которых нет в русской; в русской — ы э щ ъ ё й, которых нет в
--      сербской. Одна такая буква решает вопрос почти наверняка.
--   2. Сербская латиница: č ć ž š đ и диграфы nj/lj/dž. Половина
--      сербов пишет латиницей, и там признак №1 не работает.
--   3. Частотные слова. Диакритику часто не проставляют («ocuvan»
--      вместо «očuvan»), и тогда остаётся словарь. Тексты объявлений
--      шаблонны, поэтому двух-трёх десятков слов хватает с запасом.
--
-- ПОЧЕМУ ВОЗВРАЩАЕМ NULL. Если признаков нет или счёт близкий
-- (смешанный текст: сербское описание с русской припиской «пишите в
-- телеграм»), функция честно отвечает «не знаю». Угадывать здесь
-- вреднее, чем промолчать: на неверном языке перевод исказит смысл, а
-- пометка в карточке соврёт читателю.
--
-- СОВМЕСТИМОСТЬ. Колонка добавляется как nullable, без дефолта:
-- существующие вызовы create_car_v3 / update_car_v3 её не знают и
-- знать не обязаны — заполняет триггер. Ни одна сигнатура RPC не
-- меняется, приложение продолжает работать как раньше.
-- ============================================================

-- ------------------------------------------------------------
-- 1. КОЛОНКА
-- ------------------------------------------------------------
alter table public.cars
  add column if not exists description_lang text;

-- Допустимы только известные локали сайта либо NULL («не определён»).
-- Constraint, а не enum: значение техническое, а новый язык интерфейса
-- добавляется обычной миграцией без ALTER TYPE и блокировок.
do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'chk_cars_description_lang'
  ) then
    alter table public.cars
      add constraint chk_cars_description_lang
      check (description_lang is null or description_lang in ('sr', 'ru'));
  end if;
end $$;

comment on column public.cars.description_lang
  is 'Язык описания: sr | ru | NULL (не определён). Заполняется триггером trg_cars_detect_lang, руками не задаётся';

-- ------------------------------------------------------------
-- 2. ФУНКЦИЯ ОПРЕДЕЛЕНИЯ ЯЗЫКА
-- ------------------------------------------------------------
-- IMMUTABLE: результат зависит только от аргумента. Это позволяет при
-- необходимости построить по ней индекс и вызывать её в generated-полях.
create or replace function public.f_detect_lang(txt text)
returns text
language plpgsql
immutable
set search_path = public
as $$
declare
  v_raw   text := coalesce(txt, '');
  v_low   text;         -- нижний регистр, диакритика СОХРАНЕНА
  v_flat  text;         -- нормализованный (unaccent + lower) — для словаря
  v_sr    integer := 0; -- очки в пользу сербского
  v_ru    integer := 0; -- очки в пользу русского
  v_word  text;
  -- Частотные слова сербских объявлений — в нормализованном виде, без
  -- диакритики: словарь должен срабатывать и на «očuvan», и на «ocuvan».
  v_sr_words text[] := array[
    'prodajem','godiste','kilometraza','menjac','karoserija','cena',
    'registrovan','ocuvan','vlasnik','gorivo','automatik','rucni',
    'stanje','vozilo','placen','zamena','hitno','povoljno',
    'kupljen','polovan','benzin','dizel','snaga',
    'boja','vrata','sedista','pogon','veoma','odlicno'
  ];
  -- Русские аналоги. Тот же принцип: слова, которых почти не бывает в
  -- сербском тексте об автомобиле.
  v_ru_words text[] := array[
    'продаю','продам','пробег','коробка','кузов','цена',
    'состояние','владелец','топливо','автомат','механика','машина',
    'обмен','срочно','торг','куплен','новый','бензин',
    'дизель','мощность','цвет','двери','привод','отличное','хорошее',
    'обслужен','вложений','требует','крашеная','птс','растаможен'
  ];
begin
  if length(btrim(v_raw)) = 0 then
    return null;
  end if;

  v_low  := lower(v_raw);
  v_flat := public.f_normalize(v_raw);

  -- --- Признак 1: буквы, уникальные для одного из алфавитов ---
  -- Вес 3: подделать такую букву случайно практически невозможно.
  -- Считаем не вхождения, а сам факт — десять «ј» не весомее одной,
  -- иначе одно длинное слово перевесило бы весь остальной текст.
  if v_low ~ '[ђјљњћџ]' then
    v_sr := v_sr + 3;
  end if;
  if v_low ~ '[ыэщъёй]' then
    v_ru := v_ru + 3;
  end if;

  -- --- Признак 2: сербская латиница ---
  -- Вес 2: диакритика однозначно сербская, но её часто не проставляют,
  -- поэтому её отсутствие ничего не доказывает.
  if v_low ~ '[čćžšđ]' then
    v_sr := v_sr + 2;
  end if;
  -- Диграфы — более слабый признак: «nj» встречается и в других
  -- языках, поэтому вес 1 и только при латинском написании.
  if v_low ~ '(nj|lj|dž)' then
    v_sr := v_sr + 1;
  end if;

  -- Кириллица без сербских спецбукв и без русских спецбукв ничего не
  -- решает сама по себе — оба алфавита пересекаются. Отдельного очка
  -- за неё намеренно НЕТ.

  -- --- Признак 3: словарь частотных слов ---
  -- Вес 1 за слово, с потолком: длинный текст не должен набирать
  -- десятки очков и обесценивать признаки 1–2 в смешанном описании.
  foreach v_word in array v_sr_words loop
    -- \m и \M — границы слова в POSIX-регулярках PostgreSQL. Без них
    -- «cena» нашлось бы внутри «procena», а «дизель» — внутри
    -- «дизельный».
    if v_flat ~ ('\m' || v_word || '\M') then
      v_sr := v_sr + 1;
      exit when v_sr >= 8;
    end if;
  end loop;

  foreach v_word in array v_ru_words loop
    if v_flat ~ ('\m' || v_word || '\M') then
      v_ru := v_ru + 1;
      exit when v_ru >= 8;
    end if;
  end loop;

  -- --- Решение ---
  -- Ни одного признака — язык неизвестен. Текст вроде «2.0 TDI 4x4»
  -- языка не имеет, и приписывать ему сербский было бы выдумкой.
  if v_sr = 0 and v_ru = 0 then
    return null;
  end if;

  -- Близкий счёт — смешанный текст. Требуем перевес хотя бы вдвое:
  -- при «6 против 5» честнее не знать, чем ошибиться.
  if v_sr > 0 and v_ru > 0 and greatest(v_sr, v_ru) < least(v_sr, v_ru) * 2 then
    return null;
  end if;

  return case when v_sr > v_ru then 'sr' else 'ru' end;
end;
$$;

comment on function public.f_detect_lang(text)
  is 'Определяет язык текста: sr | ru | NULL (не определён). Три признака: уникальные буквы алфавита, сербская латиница, частотные слова авторынка';

-- ------------------------------------------------------------
-- 3. ТРИГГЕР
-- ------------------------------------------------------------
-- Пересчитываем только когда описание реально изменилось: на каждый
-- UPDATE объявления (смена статуса, продвижение, счётчик просмотров)
-- гонять словарь незачем.
create or replace function public.trg_set_description_lang()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if tg_op = 'INSERT'
     or new.description is distinct from old.description then
    new.description_lang := public.f_detect_lang(new.description);
  end if;
  return new;
end;
$$;

comment on function public.trg_set_description_lang()
  is 'BEFORE-триггер cars: проставляет description_lang при вставке и при изменении описания';

drop trigger if exists trg_cars_detect_lang on public.cars;

-- UPDATE OF description сужает срабатывание до правок описания, но на
-- INSERT колонку в списке указывать нельзя — вставка затрагивает все.
create trigger trg_cars_detect_lang
  before insert or update of description on public.cars
  for each row
  execute function public.trg_set_description_lang();

-- ------------------------------------------------------------
-- 4. ЗАПОЛНЕНИЕ УЖЕ СУЩЕСТВУЮЩИХ ОБЪЯВЛЕНИЙ
-- ------------------------------------------------------------
-- Триггер срабатывает только на новые изменения, поэтому проставляем
-- язык разом. Идемпотентно: повторный накат перезапишет тем же
-- значением. Строк в таблице сейчас единицы, батчи не нужны.
update public.cars
   set description_lang = public.f_detect_lang(description)
 where description is not null;
