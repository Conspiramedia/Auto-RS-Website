-- ============================================================
-- 0124 — ТАЙМАУТ ВЫЗОВА daily-cleanup: 5 СЕКУНД → 2 МИНУТЫ
-- ============================================================
-- ЧТО БЫЛО СЛОМАНО. Ежедневное обслуживание не выполнялось НИ РАЗУ,
-- хотя и функция, и расписание существовали и были активны:
--
--   cron.job                  daily-cleanup-job, '0 3 * * *', active
--   cron.job_run_details      7 запусков, все «succeeded»
--   Edge Function daily-cleanup   ACTIVE
--   Панель Supabase           Total invocations: 0
--
-- Противоречие объясняется тем, что означает «succeeded» у cron:
-- задание считается успешным, если net.http_post ПОСТАВИЛ запрос в
-- очередь, — ответ HTTP к этому моменту ещё не получен. Реальный итог
-- лежит в net._http_response, и там было:
--
--   status_code  null
--   timed_out    true
--   error_msg    Timeout of 5000 ms reached. Total time: 5001 ms
--
-- ПРИЧИНА — ЗНАЧЕНИЕ ПО УМОЛЧАНИЮ. У net.http_post параметр
-- timeout_milliseconds равен 5000, и прежнее задание его не
-- передавало. Пяти секунд функции не хватает: она последовательно
-- вызывает пять RPC и чистит бакет пачками по 100 файлов. Соединение
-- рвалось раньше, чем функция успевала ответить, — до неё запрос
-- фактически не доходил, отсюда ноль вызовов в панели.
--
-- Накопившийся эффект: 136 осиротевших файлов из 174 в бакете
-- car-images, то есть три четверти хранилища было мусором.
--
-- ЧТО ДЕЛАЕМ. Пересоздаём задание с тем же расписанием и тем же
-- ключом, добавляя timeout_milliseconds := 120000.
--
-- ПОЧЕМУ ДВЕ МИНУТЫ. Потолок работы за запуск известен: пять RPC плюс
-- до пяти батчей по 100 файлов (ORPHAN_MAX_PER_RUN в самой функции).
-- Ручной прогон этой же нагрузки на 136 файлах занял около двадцати
-- секунд. Две минуты — запас на порядок к худшему случаю, при этом
-- предел остаётся: если функция зависнет, вызов оборвётся, а не будет
-- висеть до бесконечности.
--
-- ПОЧЕМУ ЗАДАНИЕ ПЕРЕСОЗДАЁТСЯ, А НЕ ПРАВИТСЯ. cron.alter_job умеет
-- менять команду целиком, но не её кусок; переписывать команду всё
-- равно пришлось бы, а unschedule + schedule читается однозначно.
--
-- КЛЮЧ БЕРЁТСЯ ИЗ ПРЕЖНЕГО ЗАДАНИЯ, а не вписывается заново: service_role
-- key — секрет, и его место в базе, а не в файле миграции, который
-- лежит в репозитории. Регулярное выражение достаёт его из старой
-- команды до того, как та будет удалена.
-- ============================================================

do $$
declare
  v_key text;
begin
  -- Ключ из действующего задания. Если задания нет (свежая база,
  -- накатывающая миграции с нуля), делать нечего: расписание там
  -- создаётся вручную при развёртывании вместе с секретами.
  select (regexp_match(j.command, 'Bearer ([A-Za-z0-9._-]+)'))[1]
    into v_key
    from cron.job j
   where j.jobname = 'daily-cleanup-job';

  if v_key is null then
    raise notice 'daily-cleanup-job не найден или без ключа — расписание не изменено';
    return;
  end if;

  perform cron.unschedule('daily-cleanup-job');

  perform cron.schedule(
    'daily-cleanup-job',
    '0 3 * * *',
    format(
      $job$
      select net.http_post(
        url := 'https://nedjfdswonnbhuxaxjsv.supabase.co/functions/v1/daily-cleanup',
        headers := jsonb_build_object(
          'Authorization', 'Bearer %s',
          'Content-Type', 'application/json'
        ),
        timeout_milliseconds := 120000
      );
      $job$,
      v_key
    )
  );
end
$$;
