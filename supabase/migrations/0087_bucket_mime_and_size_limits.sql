-- ============================================================
-- RS AUTO — Миграция 0087: лимиты формата и размера у бакетов фото.
-- ============================================================
-- ПРОБЛЕМА. Бакеты car-images (0014) и avatars (0038) заводились одной
-- строкой `insert into storage.buckets (id, name, public)`, то есть без
-- allowed_mime_types и без file_size_limit. Ограничения «только JPG/PNG/
-- WebP» и «не больше 10 МБ» существовали ИСКЛЮЧИТЕЛЬНО в JavaScript
-- формы подачи, а у аватара не было и их — там стоял только атрибут
-- accept, который является подсказкой файловому диалогу, а не проверкой.
--
-- Клиентская проверка обходится тривиально: у авторизованного
-- пользователя есть токен, и прямой вызов Storage API минует форму
-- целиком. То есть любой зарегистрированный человек мог положить
-- в публичный бакет файл произвольного типа весом до глобального
-- предела (50 MiB, config.toml) — включая то, что картинкой не
-- является вовсе. Публичный бакет с произвольным содержимым — это
-- бесплатный хостинг чужих файлов за наш счёт и на нашем домене.
--
-- РЕШЕНИЕ. Те же правила переносятся на сторону Storage, где их
-- нельзя обойти. Клиентские проверки при этом ОСТАЮТСЯ: они дают
-- быструю обратную связь до отправки байтов (см. lib/imagePrepare.ts),
-- но перестают быть единственным рубежом.
--
-- ------------------------------------------------------------
-- ПОЧЕМУ ИМЕННО ЭТИ ЧИСЛА
-- ------------------------------------------------------------
-- car-images = 5 МБ. После пережатия на клиенте (длинная сторона
-- 1600px, JPEG 0.82) снимок весит 300–500 КБ. Пять мегабайт — это
-- десятикратный запас: предел обязан ловить злоупотребление, а не
-- граничный случай честного продавца с очень детальным кадром.
-- Клиентский порог на выходе вдвое ниже (2 МБ), поэтому нормальный
-- путь упирается в понятное сообщение формы, а не в отказ Storage
-- с техническим текстом.
--
-- avatars = 2 МБ. Аватар показывается кружком 32–96px, и даже
-- двух мегабайт для него избыточно много.
--
-- MIME-типы: image/jpeg, image/png, image/webp — ровно то, что
-- умеет отдать браузер. HEIC в списке НЕТ намеренно: клиент
-- перекодирует его в JPEG ещё до отправки (Safari декодирует
-- нативно), и разрешать в бакете формат, который половина браузеров
-- не покажет, значило бы завести в публичном хранилище файлы,
-- нерабочие для части посетителей.
--
-- ------------------------------------------------------------
-- ЧТО БУДЕТ С УЖЕ ЗАГРУЖЕННЫМИ ФАЙЛАМИ
-- ------------------------------------------------------------
-- Ничего. Ограничения проверяются при ЗАПИСИ нового объекта, к
-- существующим строкам storage.objects они не применяются задним
-- числом. Приложение всегда клало в car-images image/jpeg
-- (fileOptions в cars_repository.dart), сайт — jpeg/png/webp,
-- так что и на будущие перезаписи это не влияет.
--
-- ОТКАТ: см. хвост файла.
-- ============================================================

-- ------------------------------------------------------------
-- 1) car-images — фотографии объявлений.
-- ------------------------------------------------------------
-- update, а не insert ... on conflict: бакет заведомо существует
-- (0014), и запись его заново означала бы дублировать источник
-- истины о его публичности.
update storage.buckets
set
  file_size_limit = 5 * 1024 * 1024,
  allowed_mime_types = array['image/jpeg', 'image/png', 'image/webp']
where id = 'car-images';

-- ------------------------------------------------------------
-- 2) avatars — фотографии профилей и логотипы салонов.
-- ------------------------------------------------------------
update storage.buckets
set
  file_size_limit = 2 * 1024 * 1024,
  allowed_mime_types = array['image/jpeg', 'image/png', 'image/webp']
where id = 'avatars';

-- ------------------------------------------------------------
-- 3) ПРОВЕРКА ПРИМЕНЕНИЯ.
-- ------------------------------------------------------------
-- Молчаливое несрабатывание здесь особенно опасно: миграция
-- «прошла», а лимитов нет, и об этом никто не узнает до инцидента.
-- Поэтому падаем громко, если update не нашёл бакет.
do $$
declare
  missing text;
begin
  select string_agg(expected.id, ', ')
  into missing
  from (values ('car-images'), ('avatars')) as expected(id)
  where not exists (
    select 1
    from storage.buckets b
    where b.id = expected.id
      and b.file_size_limit is not null
      and b.allowed_mime_types is not null
  );

  if missing is not null then
    raise exception
      'Лимиты не установлены для бакетов: %. Проверьте, что миграции 0014 и 0038 применены.',
      missing;
  end if;
end $$;

