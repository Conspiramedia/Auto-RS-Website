-- ============================================================
-- AUTO.RS — Миграция 0112: статус expired в enum car_status
-- ============================================================
-- ЗАЧЕМ ОТДЕЛЬНАЯ МИГРАЦИЯ РАДИ ОДНОЙ СТРОКИ. PostgreSQL не позволяет
-- использовать новое значение enum в той же транзакции, где оно
-- добавлено: ALTER TYPE ... ADD VALUE фиксирует значение только по
-- коммиту, а до него любое сравнение с ним падает с ошибкой
-- «unsafe use of new value of enum type». Supabase CLI выполняет
-- каждый файл миграции в отдельной транзакции, поэтому добавление
-- значения обязано жить в своём файле, а всё, что им пользуется, —
-- в следующем (0113).
--
-- ПОЧЕМУ ОТДЕЛЬНЫЙ СТАТУС, А НЕ ПОВТОРНОЕ ИСПОЛЬЗОВАНИЕ 'archived'.
-- Архив — осознанное действие продавца («снял с публикации»),
-- expired — следствие бездействия. Их нужно различать в трёх местах:
--   * в кабинете: у просроченного показывается кнопка «Продлить»,
--     у архивного — «Вернуть в публикацию»;
--   * в письмах: продавцу пишут про истёкший срок, а не про архив,
--     который он сделал сам;
--   * в статистике: доля объявлений, потерянных из-за молчания
--     продавца, — отдельная величина, и склеив её с архивом, мы
--     перестанем её видеть.
--
-- МЕСТО В ПОРЯДКЕ ENUM. Добавляем после 'archived': значение по
-- смыслу соседнее, а порядок элементов enum влияет на сортировку
-- ORDER BY status. Существующих сортировок по статусу в проекте нет,
-- но соседство с архивом делает будущую сортировку осмысленной.
--
-- IF NOT EXISTS — миграция идемпотентна и переживает повторный накат.
-- ============================================================

alter type car_status add value if not exists 'expired' after 'archived';
