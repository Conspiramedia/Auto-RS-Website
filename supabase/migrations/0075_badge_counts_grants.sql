-- ============================================================
-- RS AUTO — 0075. Отзыв публичных прав у get_badge_counts().
-- ============================================================
-- Исправление к 0074. Там функция получила grant для authenticated,
-- но НЕ потеряла права PUBLIC, которые PostgreSQL выдаёт всякой новой
-- функции по умолчанию: revoke из миграции 0065 сработал разово, по
-- функциям, существовавшим на тот момент, и на созданные позже не
-- распространяется.
--
-- Следствие было проверено на живой базе: аноним успешно вызывал
-- get_badge_counts() и получал строку с нулями. Утечки данных при
-- этом нет — функция целиком построена на auth.uid(), у анонима он
-- пуст, — но security definer функция на публичном эндпоинте без
-- необходимости открыта быть не должна.
--
-- Правки в 0074 недостаточно: она уже применена к удалённой базе,
-- и повторный push её не переиграет.
-- ============================================================

revoke execute on function public.get_badge_counts() from public;
revoke execute on function public.get_badge_counts() from anon;

-- Подтверждаем нужное право явно: revoke от public мог задеть и его,
-- если бы authenticated получала доступ только по наследству.
grant execute on function public.get_badge_counts() to authenticated;
