-- ============================================================
-- 0121 — ЗАПИСЬ ЯЗЫКА ПРОДАВЦА В ПРОФИЛЬ
-- ============================================================
-- ЧТО СЛОМАНО. Причина отклонения объявления приходила продавцу на
-- сербском, даже если он всё время работал с русской версией сайта.
-- То же и с письмами: очередь берёт язык из profiles.locale, а при
-- NULL честно подставляет сербский (0071).
--
-- ПОЧЕМУ КОЛОНКА ПУСТА У ВСЕХ. Единственное место, где locale
-- записывался, — RPC set_my_contact_email (0071), которую вызывала
-- форма смены почты в кабинете. С переходом на почтовый вход (0106)
-- поле почты стало нередактируемым, вызов ушёл вместе с формой, и
-- язык перестал записываться вообще. На момент этой миграции
-- profiles.locale = NULL у ВСЕХ профилей.
--
-- ЧТО ДЕЛАЕМ. Узкая функция, которую сайт зовёт в тех местах, где
-- язык человека известен достоверно: при входе и при подаче
-- объявления. Оба сценария происходят на конкретной локали, и гадать
-- не приходится.
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ RPC, А НЕ ПРЯМОЙ UPDATE. Та же причина, что у
-- set_profile_phone (0106): прямая запись в profiles потребовала бы
-- политики RLS на UPDATE, а та открыла бы клиенту всю строку —
-- включая is_admin и role. Definer-функция меняет ровно одно поле.
--
-- ПОЧЕМУ НЕ ПЕРЕЗАПИСЫВАЕМ МОЛЧА ПРИ КАЖДОМ ЗАХОДЕ. Перезаписываем:
-- язык интерфейса — это и есть предпочтение человека, и если он
-- перешёл на русскую версию и вошёл там, писать ему по-сербски не
-- нужно. Отдельного выбора «язык писем» в интерфейсе нет, и заводить
-- его ради одного поля незачем.
-- ============================================================

create or replace function public.set_profile_locale(p_locale text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_locale  text := nullif(btrim(coalesce(p_locale, '')), '');
begin
  -- Гость язык не сохраняет: профиля ещё нет.
  if v_user_id is null then
    raise exception 'Potrebna je prijava.'
      using errcode = 'insufficient_privilege';
  end if;

  -- Неизвестный язык игнорируем МОЛЧА, а не падаем: значение приходит
  -- из адреса страницы, и опечатка в нём не повод ронять вход. Пусть
  -- лучше останется прежнее значение, чем пользователь не войдёт.
  if v_locale is null or v_locale not in ('sr', 'ru') then
    return;
  end if;

  -- Пишем только при РЕАЛЬНОЙ смене: функция зовётся при каждом входе,
  -- и лишний UPDATE трогал бы updated_at на ровном месте.
  update public.profiles
     set locale     = v_locale,
         updated_at = now()
   where id = v_user_id
     and locale is distinct from v_locale;
end;
$$;

comment on function public.set_profile_locale(text)
  is 'Сохраняет язык интерфейса вызывающего в профиль: на нём приходят письма и причины отклонения (0121)';

revoke all on function public.set_profile_locale(text) from public, anon;
grant execute on function public.set_profile_locale(text) to authenticated;
