-- ============================================================
-- RS AUTO — лимит фотографий объявления на стороне базы.
-- ============================================================
-- ЧТО БЫЛО. Максимум фотографий держался ТОЛЬКО на клиентах: константа
-- MAX_PHOTOS в форме подачи сайта и AppConstants.maxCarImages в
-- приложении. У базы ограничения не было вовсе — прямой вызов
-- create_car_v3 / update_car_v3 в обход формы записывал сколько угодно
-- строк в car_images.
--
-- Договорённость между двумя клиентами, не подкреплённая базой, — это
-- не ограничение, а совпадение: она держится ровно до первой правки в
-- одном из клиентов и расходится молча, без ошибки.
--
-- ПОЧЕМУ ТРИГГЕР, А НЕ CHECK. Фотографии лежат не массивом в cars, а
-- отдельными строками в car_images (связь 1:N, миграция 0004).
-- Ограничение «не больше N строк на car_id» — это условие на ТАБЛИЦУ
-- целиком, а CHECK видит только одну проверяемую строку и выразить
-- его не может. Поэтому счёт ведётся в триггере перед вставкой.
--
-- ПОЧЕМУ ТРИГГЕР НА car_images, А НЕ ПРОВЕРКА В КАЖДОЙ RPC. Фотографии
-- пишут четыре функции: create_car_v2, create_car_v3, update_car_v2,
-- update_car_v3 (v2 вызывает приложение, v3 — сайт). Проверка внутри
-- каждой означала бы четыре копии одного правила — ровно та ситуация,
-- из которой миграция 0093 уже вытаскивала правило о дубликатах.
-- Триггер на таблице покрывает все четыре входа разом и не даёт копиям
-- разойтись.
--
-- КОНТРАКТ С ПРИЛОЖЕНИЕМ НЕ ЗАТРОНУТ. Сигнатуры RPC не меняются: ни
-- имён, ни порядка, ни типов параметров, ни возвращаемых колонок.
-- Меняется поведение при заведомо некорректных данных — приложение
-- столько фотографий и не отправляет (его форма принимает 10).
--
-- ЛИМИТ 15, А НЕ 20. Пятнадцать — новое значение формы подачи сайта
-- (MAX_PHOTOS в components/SellForm.tsx). Запас поверх лимита клиентов
-- намеренно НЕ закладывается: база, принимающая больше, чем умеет
-- показать любой клиент, снова превращает ограничение в формальность.
--
-- РАССИНХРОН С ПРИЛОЖЕНИЕМ — ОЖИДАЕМЫЙ И БЕЗОПАСНЫЙ. Форма приложения
-- принимает 10, форма сайта — 15, база пропускает до 15. Объявление,
-- поданное с сайта с 15 фотографиями, приложение отдаёт на просмотр
-- целиком (галерея строится по числу строк car_images), а его форма
-- РЕДАКТИРОВАНИЯ рассчитана на 10 — поведение при правке такого
-- объявления в приложении здесь не проверялось и остаётся на стороне
-- приложения. Поднятие лимита в приложении делается отдельно; эта
-- миграция ему не мешает и переписывания не потребует.
-- ============================================================

-- Лимит вынесен в отдельную функцию, а не зашит числом в тело
-- триггера: так его видно из кода и из psql (\sf), и поднимается он
-- правкой одного места. IMMUTABLE — значение константно, планировщик
-- вправе подставлять его инлайном.
create or replace function public.f_car_photo_limit()
returns integer
language sql
immutable
as $$
  select 15;
$$;

comment on function public.f_car_photo_limit() is
  'Максимум фотографий одного объявления. Дублируется константой '
  'MAX_PHOTOS в форме подачи сайта — поднимая лимит, правьте оба места.';


-- Проверка перед вставкой фотографии.
--
-- ПОЧЕМУ ТОЛЬКО INSERT. Строки car_images не переносят между
-- объявлениями: правка объявления удаляет все его фото и вставляет
-- заново (см. update_car_v3, миграция 0090). UPDATE car_id в проекте
-- не встречается, а лишний триггер на UPDATE удорожал бы каждую
-- перестановку order_index при сортировке галереи.
--
-- SECURITY DEFINER не нужен: триггер считает строки той же таблицы,
-- в которую идёт вставка, и прав вызывающего для этого достаточно.
create or replace function public.trg_car_images_limit()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  v_limit integer := public.f_car_photo_limit();
  v_count integer;
begin
  -- Считаем УЖЕ существующие фото объявления. Вставляемая строка в
  -- счёт не входит (BEFORE INSERT), поэтому сравниваем с лимитом
  -- через >=: при v_count = 15 эта строка стала бы шестнадцатой.
  select count(*) into v_count
  from public.car_images
  where car_id = new.car_id;

  if v_count >= v_limit then
    -- Текст ошибки на сербском: язык площадки. Клиенты показывают
    -- собственное сообщение (форма не даёт дойти до этой ситуации),
    -- поэтому здесь важнее диагностируемость при прямом вызове RPC.
    raise exception 'Maksimalan broj fotografija po oglasu je %.', v_limit
      using errcode = 'check_violation';
  end if;

  return new;
end;
$$;

comment on function public.trg_car_images_limit() is
  'Не даёт вставить в car_images больше f_car_photo_limit() фотографий '
  'на одно объявление. Триггер вместо CHECK: условие на число строк '
  'таблицы, а не на одну строку.';

drop trigger if exists car_images_limit on public.car_images;

create trigger car_images_limit
  before insert on public.car_images
  for each row
  execute function public.trg_car_images_limit();
