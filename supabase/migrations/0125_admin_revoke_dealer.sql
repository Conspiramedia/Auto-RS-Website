-- ============================================================
-- AUTO.RS — Миграция 0125: отзыв статуса автосалона
-- ============================================================
-- ЗАЧЕМ. Выдать статус салона администратор умеет с 0100
-- (admin_review_dealer_application), а отозвать — нет. Дыра видна
-- прямо в комментарии 0100: там написано «прежняя одобренная заявка
-- продолжает действовать, пока администратор её не отозвал», но
-- функции отзыва в кодовой базе не появилось.
--
-- ЧЕМ ЭТО ГРОЗИТ СЕЙЧАС. admin_block_dealer (0085) снимает флаг
-- доверия и убирает объявления из выдачи, но НЕ трогает
-- profiles.seller_kind и заявку. Заблокированный салон остаётся
-- дилером: у него живёт витрина /dealer/{id}, он числится в каталоге
-- салонов, а его объявления подписаны «Автосалон». Хуже того,
-- update_seller_profile (0100) пускает private → dealer при наличии
-- одобренной заявки — то есть заблокированный салон может уйти в
-- частники и тут же вернуться салоном обратно, потому что заявка
-- никуда не делась.
--
-- ЧТО ДЕЛАЕТ ЭТА МИГРАЦИЯ: одну функцию admin_revoke_dealer(uuid,
-- text), которая одной транзакцией
--   1) переводит одобренные заявки пользователя в 'rejected' с
--      причиной — именно это закрывает дорогу назад через
--      update_seller_profile;
--   2) ставит profiles.seller_kind = 'private' и затирает поля
--      витрины ровно те же, что затирает сам владелец при уходе в
--      частники (0100, блок 3);
--   3) снимает trusted_seller;
--   4) убирает активные объявления из выдачи (в archived, как
--      admin_block_dealer);
--   5) пишет в журнал и уведомляет владельца.
--
-- ПОЧЕМУ ОТЗЫВ ЗАБИРАЕТ И ОБЪЯВЛЕНИЯ. Отозвать статус, оставив
-- объявления в выдаче, значит оставить в каталоге витринные карточки
-- продавца, которого площадка только что перестала признавать
-- салоном. Это шаг строже блокировки, а не мягче.
--
-- ЧЕГО ЗДЕСЬ НЕТ:
--   • Удаления. Ни профиль, ни объявления не удаляются: отзыв —
--     административное решение, а не стирание чужой работы.
--     Объявления возвращаются существующим admin_set_car_status
--     (переход archived → active), статус — новой заявкой владельца.
--   • Нового шаблона письма. Переиспользуется существующий
--     dealer_app_rejected: у него ровно нужный смысл (что случилось,
--     причина, ссылка на профиль), он есть в chk_email_template и уже
--     задеплоен в Edge Function. Новый ключ потребовал бы деплоя
--     функции, а до него письма ложились бы в failed.
--
-- ОБРАТИМОСТЬ. Владелец подаёт заявку заново — уникальный индекс
-- uq_dealer_app_pending считает только строки в стадии pending, а
-- отозванные лежат в rejected и подаче не мешают.
--
-- СОВМЕСТИМОСТЬ С ПРИЛОЖЕНИЕМ: миграция аддитивная. Ни одна
-- существующая функция не переписана, сигнатуры не тронуты. Flutter
-- продолжает звать те же RPC.
-- ============================================================


-- ------------------------------------------------------------
-- admin_revoke_dealer — отозвать статус автосалона
-- ------------------------------------------------------------
-- Возвращает число скрытых объявлений, как admin_block_dealer:
-- интерфейсу нужно показать, что именно произошло («скрыто 12
-- объявлений»), а не просто «готово».
create or replace function public.admin_revoke_dealer(
  p_user_id uuid,
  p_reason  text
)
returns integer
language plpgsql
security definer
set search_path = public
as $fn$
declare
  v_reason  text;
  v_kind    text;
  v_company text;
  v_email   text;
  v_locale  text;
  v_apps    integer;
  v_hidden  integer;
begin
  if not public.is_admin() then
    raise exception 'Недостаточно прав: статус салона отзывает только администратор'
      using errcode = 'insufficient_privilege';
  end if;

  -- Границы причины те же, что у reject_car, admin_set_car_status и
  -- admin_block_dealer: один и тот же счётчик символов во всех
  -- диалогах админки. Причина уходит владельцу в колокольчик и
  -- письмо — отзыв без объяснения он воспримет как поломку сайта.
  v_reason := btrim(coalesce(p_reason, ''));

  if length(v_reason) < 10 then
    raise exception 'Причина обязательна и должна содержать не менее 10 символов'
      using errcode = 'check_violation';
  end if;

  if length(v_reason) > 1000 then
    raise exception 'Причина слишком длинная: % символов, максимум 1000', length(v_reason)
      using errcode = 'check_violation';
  end if;

  -- FOR UPDATE: два администратора могли открыть одно окно салона.
  -- Второй дождётся коммита первого и увидит seller_kind = 'private'
  -- вместо 'dealer' — и получит внятный отказ вместо повторного
  -- отзыва, который переписал бы причину в заявке.
  select p.seller_kind, p.company_name, p.email, p.locale
    into v_kind, v_company, v_email, v_locale
    from public.profiles p
   where p.id = p_user_id
   for update;

  if v_kind is null then
    raise exception 'Профиль % не найден', p_user_id
      using errcode = 'no_data_found';
  end if;

  if v_kind <> 'dealer' then
    raise exception 'Статус автосалона отозвать нельзя: продавец не является салоном'
      using errcode = 'check_violation';
  end if;

  -- Название запоминаем ДО затирания company_name: в журнале и в
  -- уведомлении должно стоять имя салона, которого лишили статуса, а
  -- после update оно уже null.
  v_company := coalesce(nullif(btrim(v_company), ''), 'Автосалон');

  -- ------------------------------------------------------------
  -- 1) Заявки: одобренные → отклонённые.
  -- ------------------------------------------------------------
  -- ГЛАВНЫЙ ШАГ МИГРАЦИИ. Без него всё остальное косметика:
  -- f_has_approved_dealer_application (0100) продолжила бы отдавать
  -- true, и владелец вернул бы себе статус одним сохранением профиля.
  --
  -- Обновляем ВСЕ одобренные строки, а не последнюю: в норме она
  -- одна, но блок 6 миграции 0100 выдавал заявки задним числом, и
  -- дублей там никто не запрещал. Условие проверки — exists по
  -- status = 'approved', и пропущенная строка воскресила бы статус.
  --
  -- reviewed_by = auth.uid() и reviewed_at = now(): решение принял
  -- нынешний администратор сейчас, а не тот, кто когда-то одобрил.
  -- Constraint chk_dealer_app_reviewed требует непустой reviewed_at
  -- у любой стадии кроме pending, chk_dealer_app_reason_required —
  -- причины не короче 10 символов у rejected. Оба выполнены.
  update public.dealer_applications
     set status        = 'rejected',
         reject_reason = v_reason,
         reviewed_by   = auth.uid(),
         reviewed_at   = now(),
         updated_at    = now()
   where user_id = p_user_id
     and status  = 'approved';

  get diagnostics v_apps = row_count;

  -- ------------------------------------------------------------
  -- 2) Профиль: обратно в частники, витрина затирается.
  -- ------------------------------------------------------------
  -- Набор затираемых полей СОВПАДАЕТ с тем, что затирает сам владелец
  -- при переходе dealer → private в update_seller_profile (0100).
  -- Расхождение означало бы, что после отзыва в профиле остаются
  -- обломки витрины, которых не бывает у обычного частника.
  --
  -- company_city и contact_person НЕ трогаем, в отличие от
  -- update_seller_profile: там их чистит сам владелец, здесь это
  -- рабочие пометки администратора (кто такой, где находится, с кем
  -- разговаривали), и терять их при отзыве незачем — именно они
  -- нужны для разбора, если решение будут оспаривать.
  -- contract_date по той же причине остаётся: договор существовал.
  update public.profiles
     set seller_kind    = 'private',
         company_name   = null,
         logo_url       = null,
         description    = null,
         dealer_phone   = null,
         website        = null,
         opening_hours  = null,
         cover_url      = null,
         tagline        = null,
         -- Право публиковать без модерации снимается вместе со
         -- статусом: частников оно не касается, и оставленный флаг
         -- сработал бы, вернись человек в салоны по новой заявке.
         trusted_seller = false,
         updated_at     = now()
   where id = p_user_id;

  -- ------------------------------------------------------------
  -- 3) Объявления: активные — из выдачи.
  -- ------------------------------------------------------------
  -- Как в admin_block_dealer: скрываем в archived, а не удаляем, и
  -- трогаем только опубликованные. Ждущие проверки не трогаем — они
  -- и так не видны покупателю, а модератор разберёт их обычным
  -- порядком.
  update public.cars
     set status     = 'archived',
         updated_at = now()
   where user_id = p_user_id
     and status   = 'active';

  get diagnostics v_hidden = row_count;

  -- ------------------------------------------------------------
  -- 4) Журнал.
  -- ------------------------------------------------------------
  -- Отдельный код действия, а не dealer_blocked: блокировка и отзыв
  -- статуса — разные решения с разными последствиями, и в ленте
  -- журнала их обязано быть видно порознь.
  perform public.f_admin_log(
    'dealer_revoked',
    'profiles',
    p_user_id,
    jsonb_build_object(
      'company',      v_company,
      'reason',       v_reason,
      'hidden',       v_hidden,
      'applications', v_apps
    )
  );

  -- ------------------------------------------------------------
  -- 5) Уведомление владельцу.
  -- ------------------------------------------------------------
  -- Тип dealer_app_rejected — существующий: сайт умеет его
  -- отрисовать (метка «Заявка отклонена», переход в /my/profile,
  -- см. components/NotificationRow.tsx), а кабинет покажет причину и
  -- кнопку «подать снова» — заявка теперь в стадии rejected.
  -- Заводить новый тип значило бы добавить в ленту событие, для
  -- которого у клиентов нет ни метки, ни адреса перехода.
  --
  -- Заголовок при этом СВОЙ: человек не подавал заявку, а лишился
  -- статуса, и текст «заявка отклонена» ввёл бы его в заблуждение.
  insert into public.notifications (user_id, title, body, type, action_id)
  values (
    p_user_id,
    'Статус автосалона отозван',
    format(
      '%s: страница салона отключена%s. Причина: %s',
      v_company,
      case when v_hidden > 0
           then format(', объявлений скрыто: %s', v_hidden)
           else '' end,
      v_reason
    ),
    'dealer_app_rejected',
    null
  );

  -- ------------------------------------------------------------
  -- 6) Письмо.
  -- ------------------------------------------------------------
  -- Только если почта известна: у части аккаунтов вход по телефону, и
  -- f_enqueue_email с пустым адресом положил бы в очередь строку,
  -- которую некому доставить.
  if v_email is not null and btrim(v_email) <> '' then
    perform public.f_enqueue_email(
      v_email,
      'dealer_app_rejected',
      jsonb_build_object(
        'locale',  coalesce(v_locale, 'sr'),
        'company', v_company,
        'reason',  v_reason
      ),
      p_user_id
    );
  end if;

  return v_hidden;
end;
$fn$;

comment on function public.admin_revoke_dealer(uuid, text)
  is 'Отзыв статуса автосалона: одобренные заявки → rejected, профиль → private с затиранием витрины, флаг доверия снят, активные объявления в archived. Пишет в журнал, уведомляет владельца. Только для админа';

grant execute on function public.admin_revoke_dealer(uuid, text) to authenticated;
