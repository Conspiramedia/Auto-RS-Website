-- ============================================================
-- 0084. Контактный ящик проекта
-- ============================================================
-- КОНТЕКСТ. Контактный адрес площадки — info.rsauto.rs@gmail.com.
-- Он проставлен в OPERATOR.email (lib/legal.ts) и показывается
-- пользователю в подвале, на /contact и в разделах «Контакты»
-- политики и условий.
--
-- ПРОБЛЕМА, которую закрывает миграция. Настройка app_settings.admin_email
-- задаёт ящик, КУДА фактически уходят входящие: письма формы обратной
-- связи (submit_contact_message, 0058) и заявки автосалонов. До этой
-- миграции там стоял support@rsauto.rs — ящик на домене, который не
-- заведён. То есть сайт приглашал написать по одному адресу, а
-- сообщения складывал в несуществующий второй: обращения пользователей
-- терялись бы молча, без ошибки отправки.
--
-- Это вариант «Б» из RELEASE.md (пункт 2): почта принимается напрямую
-- на Gmail, ящики на домене не заводятся.
--
-- НЕ ЗАТРАГИВАЕТ MAIL_FROM (noreply@rsauto.rs) — исходящий адрес
-- транзакционных писем через Resend. Это другая роль: с него письма
-- уходят, на него не пишут. Он живёт в секретах Supabase, не в
-- app_settings, и настоящей миграцией не меняется.
--
-- Аддитивна и идемпотентна: схема не меняется, сигнатуры функций
-- прежние, вызовы приложения не затронуты.
-- ============================================================


-- ------------------------------------------------------------
-- 1. Адрес входящих в настройках
-- ------------------------------------------------------------
-- Тот же адрес, что видит пользователь в OPERATOR.email: адрес на
-- странице и адрес доставки обязаны совпадать, иначе ответить на
-- обращение будет некому.
insert into public.app_settings (key, value, updated_at)
values ('admin_email', 'info.rsauto.rs@gmail.com', now())
on conflict (key) do update
  set value = excluded.value, updated_at = now();


-- ------------------------------------------------------------
-- 2. Страховка внутри f_admin_email()
-- ------------------------------------------------------------
-- Тело повторяет 0071, меняется только значение в coalesce:
-- support@rsauto.rs → фактический контактный ящик. Страховка нужна на
-- случай удалённой строки настроек, и указывать в ней несуществующий
-- ящик — значит терять письма ровно в той ситуации, ради которой
-- страховка и написана.
create or replace function public.f_admin_email()
returns text
language sql
stable
set search_path = public
as $$
  select coalesce(
    nullif(btrim((select s.value from public.app_settings s
                   where s.key = 'admin_email')), ''),
    'info.rsauto.rs@gmail.com'   -- страховка, если строку удалили
  );
$$;

comment on function public.f_admin_email()
  is 'Адрес служебного ящика для входящих (форма обратной связи, заявки салонов). Страховка — контактный ящик проекта (0084)';

-- Права те же, что в 0071: функция читает служебный адрес и наружу
-- не отдаётся. Повторяем revoke явно — create or replace прав не
-- сбрасывает, но полагаться на это при чтении миграции не следует.
revoke execute on function public.f_admin_email() from anon, authenticated;
