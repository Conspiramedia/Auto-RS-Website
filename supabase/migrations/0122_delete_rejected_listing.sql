-- ============================================================
-- 0122 — УДАЛЕНИЕ ОТКЛОНЁННОГО ОБЪЯВЛЕНИЯ ВЛАДЕЛЬЦЕМ
-- ============================================================
-- ЗАЧЕМ. У отклонённого объявления был единственный выход — «Снять»,
-- то есть перевод в архив. Но архив для него бессмыслен: вернуть
-- оттуда в публикацию нельзя (модерация его уже не пропустила), и
-- запись оседает в кабинете навсегда, копя мусор в списке продавца.
-- Отклонённое объявление либо правят и отправляют на проверку заново,
-- либо оно никому не нужно.
--
-- ПОЧЕМУ RPC, А НЕ ПРЯМОЙ DELETE. Политика cars_delete_own разрешает
-- владельцу удалять свои строки, и клиент мог бы удалять напрямую. Но
-- тогда правило «удалять можно ТОЛЬКО отклонённое» жило бы на
-- клиенте, а сервер принимал бы удаление активного объявления с
-- перепиской и просмотрами от любого, кто вызовет API руками.
-- Definer-функция удерживает правило на стороне базы.
--
-- ЧТО УДАЛЯЕТСЯ ВМЕСТЕ С ОБЪЯВЛЕНИЕМ. Внешние ключи стоят на cascade:
-- фотографии (car_images), избранное, скрытия, статистика и журнал
-- просмотров уходят следом. Для отклонённого это ровно то, что нужно:
-- объявление не публиковалось, и накопить там нечего.
--
-- ПЕРЕПИСКА (chats) ТОЖЕ УДАЛИЛАСЬ БЫ КАСКАДОМ, и это единственное
-- по-настоящему ценное, что может пропасть. У отклонённого её быть не
-- может: объявление ни разу не показывалось покупателям, писать по
-- нему некому. Но проверка ниже стоит явно — на случай, если правила
-- модерации когда-нибудь изменятся и отклонить смогут объявление,
-- побывавшее в выдаче. Тогда функция откажет, а не снесёт молча
-- чужие сообщения.
--
-- ФАЙЛЫ В ХРАНИЛИЩЕ каскадом НЕ удаляются: строки car_images уходят,
-- а сами картинки остаются в бакете. Это осознанно оставлено на
-- потом — чистка хранилища должна быть отдельной фоновой задачей со
-- своей логикой (объявление могло ссылаться на файл, который
-- используется и в другом месте), а не побочным эффектом нажатия
-- кнопки.
-- ============================================================

create or replace function public.delete_my_rejected_car(p_car_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_status  text;
  v_owner   uuid;
  v_chats   integer;
begin
  if v_user_id is null then
    raise exception 'Potrebna je prijava.'
      using errcode = 'insufficient_privilege';
  end if;

  select c.status::text, c.user_id
    into v_status, v_owner
    from public.cars c
   where c.id = p_car_id;

  -- Объявления нет — считаем задачу выполненной. Идемпотентность
  -- важна: продавец мог нажать дважды на медленной сети, и вторая
  -- ошибка «не найдено» выглядела бы сбоем там, где всё в порядке.
  if v_owner is null then
    return;
  end if;

  if v_owner <> v_user_id then
    raise exception 'Можно удалять только свои объявления.'
      using errcode = 'insufficient_privilege';
  end if;

  -- ТОЛЬКО ОТКЛОНЁННОЕ. Активное снимают с публикации, проданное
  -- остаётся историей сделки, архивное можно вернуть в выдачу — у всех
  -- них удаление отняло бы данные, которые ещё нужны.
  if v_status <> 'rejected' then
    raise exception 'Удалить можно только отклонённое объявление.'
      using errcode = 'check_violation';
  end if;

  -- Страховка на будущее, см. шапку: сейчас у отклонённого переписки
  -- быть не может, но если правила изменятся — лучше отказать, чем
  -- каскадом снести сообщения покупателей.
  select count(*) into v_chats
    from public.chats ch
   where ch.car_id = p_car_id;

  if v_chats > 0 then
    raise exception 'У объявления есть переписка, удаление невозможно.'
      using errcode = 'check_violation';
  end if;

  delete from public.cars c where c.id = p_car_id;
end;
$$;

comment on function public.delete_my_rejected_car(uuid)
  is 'Удаляет отклонённое объявление вызывающего. Только своё, только rejected, только без переписки (0122)';

revoke all on function public.delete_my_rejected_car(uuid) from public, anon;
grant execute on function public.delete_my_rejected_car(uuid) to authenticated;
