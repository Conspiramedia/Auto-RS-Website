-- ============================================================
-- AUTO.RS — Миграция 0136: качество описания объявления.
-- ============================================================
-- Продолжение 0135. Там барьер закрыл контактные данные, здесь
-- закрываются остальные способы испортить описание:
--   • внешние ссылки — уводят покупателя с площадки ровно так же, как
--     телефон в тексте, только через чужой сайт;
--   • HTML-теги и скрипты — приезжают при копировании с другой
--     площадки, ломают вёрстку карточки и попадают в письма, в
--     JSON-LD и в уведомления;
--   • длина — минимум 30 символов и максимум 6000.
--
-- ПОЧЕМУ ОТКЛОНЯЕМ, А НЕ ВЫЧИЩАЕМ РАЗМЕТКУ. Sanitize молча меняет
-- авторский текст: продавец написал одно, в каталоге появилось
-- другое, и он об этом не узнал. Здесь принят тот же принцип, что в
-- 0111 («НЕ трогаем регистр, пунктуацию, эмодзи и язык — описание
-- авторский текст, и приводить его к правильному виду мы не вправе»):
-- чистим только следы копирования, а всё остальное объясняем и
-- возвращаем человеку на исправление.
--
-- 6000 СТАНОВИТСЯ НАСТОЯЩИМ ПРАВИЛОМ. До этой миграции число жило
-- только в атрибуте maxLength у textarea, то есть держалось браузером:
-- колонка cars.description имеет тип text (до ~1 ГБ), а create_car_v3
-- длину не проверяла. Вызов RPC напрямую с anon-ключом, который лежит
-- в бандле, записывал описание любого размера.
--
-- МИНИМУМ ПРИМЕНЯЕТСЯ ТОЛЬКО К НЕПУСТОМУ ОПИСАНИЮ. Поле необязательное
-- с 0034 (p_description default null), и делать его обязательным —
-- другое решение, меняющее правила подачи, а не добавляющее проверку.
-- Пустое описание по-прежнему допустимо; заполненное обязано быть
-- осмысленным.
--
-- СТАРЫЕ ОБЪЯВЛЕНИЯ НЕ ТРОГАЕМ — и по той же причине, что в 0135.
-- Объявления, принятые модерацией ДО этой миграции, не обязаны
-- удовлетворять новым правилам: на момент их подачи правил не было.
-- Констрейнт добавляется как NOT VALID, а проверка длины живёт в
-- триггере и срабатывает только при ИЗМЕНЕНИИ описания. Поэтому
-- публикация, продвижение, счётчик просмотров и продление таких
-- объявлений продолжают работать, а исправить текст продавца просят
-- только тогда, когда он сам взялся его править.
--
-- Это не гипотетический случай: на момент написания миграции в
-- каталоге лежало объявление с описанием в 18 символов. Полагаться на
-- то, что подобных строк нет, нельзя — миграция обязана применяться на
-- любой базе.
-- ============================================================


-- ------------------------------------------------------------
-- 1. ПОИСК ССЫЛОК И РАЗМЕТКИ
-- ------------------------------------------------------------
-- Зеркало правил 'url' и 'html' из lib/contactGuard.ts. Функции ДВЕ,
-- потому что у отказов разные тексты на клиенте: продавцу с тегами в
-- описании нельзя показывать сообщение про ссылки, и наоборот.
create or replace function public.f_has_external_link(txt text)
returns boolean
language sql
immutable
set search_path = public
as $$
with s as (
  -- Нормализация та же, что у контактов: снимает гомоглифы и
  -- типографские пробелы. lower() внутри — поэтому правило домена
  -- ниже, которому важен регистр, работает с исходным txt напрямую.
  select public.f_normalize_contacts_scan(txt) as t
)
select
  -- --- СХЕМА ИЛИ WWW ----------------------------------------
  -- Однозначный признак ссылки, регистр значения не имеет.
  (select t ~ '(https?://|ftp://|www[[:space:]]*\.)[[:space:]]*[a-z0-9-]+' from s)

  -- --- ГОЛЫЙ ДОМЕН ------------------------------------------
  -- Ищем в ИСХОДНОМ тексте, а не в приведённом к нижнему регистру,
  -- и БЕЗ пробелов вокруг точки. Причина — сербская пунктуация:
  -- пробел после точки ставят не всегда, и следующее слово регулярно
  -- совпадает с зоной («Auto je nov.Me interesuje…», «Prodajem
  -- auto.Info na uvid…», «Cena je fiksna.Net cena…»). С допуском
  -- пробелов и без учёта регистра все три превращались бы в «ссылку»,
  -- и объявление становилось неподаваемым.
  --
  -- Зона обязана быть из ФИКСИРОВАННОГО перечня и строчными: домен в
  -- настоящей ссылке пишут строчными, а «nov.Me» с заглавной — начало
  -- нового предложения. Обход капсом («MOJAUTO.RS») теряем осознанно:
  -- он редок, а ложное срабатывание на каждой второй сербской фразе —
  -- нет.
  --
  -- Метка домена — [a-z0-9-]{2,}, и цифрой она начаться не может по
  -- построению класса-границы слева, поэтому «2.0», «1.9 TDI» и
  -- «15.03.2024» не проходят.
  --
  -- Точка в границе слева НЕ запрещена намеренно: у поддомена
  -- «slike.mojauto.rs» перед доменом второго уровня стоит именно она,
  -- и с запретом такой адрес не ловился бы вовсе.
  or (txt ~ '(^|[^a-zA-Z0-9@-])[a-z0-9-]{2,}\.(rs|com|net|org|info|biz|ru|su|by|kz|ua|me|ba|hr|si|mk|bg|ro|hu|at|de|it|fr|uk|eu|io|app|shop|site|online|store|link|gg|tv|cc)([^a-zA-Z]|$)');
$$;

comment on function public.f_has_external_link(text)
  is 'true, если в описании есть внешняя ссылка (схема, www или голый домен из фиксированного перечня зон). Числа с точкой (2.0, 15.03.2024) ссылкой НЕ считаются (0136)';


create or replace function public.f_has_markup(txt text)
returns boolean
language sql
immutable
set search_path = public
as $$
with s as (select public.f_normalize_contacts_scan(txt) as t)
select
  -- --- HTML-ТЕГ ---------------------------------------------
  -- Буква сразу после «<» обязательна, иначе правило ловило бы
  -- сравнение «<2.0 l» и стрелку «<-».
  --
  -- Хвост тега — [^<>]*, а не ([[:space:]][^<>]*)?: без этого
  -- самозакрывающийся тег без пробела («<br/>») не ловился, потому
  -- что слэш шёл сразу за именем. Класс не пускает внутрь «<» и «>»,
  -- поэтому совпадение не перепрыгнет через границу тега.
  (select t ~ '<[[:space:]]*/?[[:space:]]*[a-z][a-z0-9]*[^<>]*>' from s)

  -- --- СКРИПТ И ОБРАБОТЧИКИ ---------------------------------
  -- Опасны и без закрывающей скобки: именно так выглядит попытка
  -- обойти правило выше.
  or (select t ~ '<[[:space:]]*/?[[:space:]]*(script|iframe|object|embed|style|svg|form|input)|javascript[[:space:]]*:|on(error|load|click|mouseover|focus)[[:space:]]*=' from s)

  -- --- HTML-СУЩНОСТИ ----------------------------------------
  -- Признак того, что текст пришёл из разметки, а не набран человеком.
  or (select t ~ '&(lt|gt|quot|amp|#x?[0-9a-f]{2,6});' from s);
$$;

comment on function public.f_has_markup(text)
  is 'true, если в описании есть HTML-тег, скрипт, обработчик события или HTML-сущность (0136)';


-- ------------------------------------------------------------
-- 2. КОНСТРЕЙНТ ДЛИНЫ — 6000 СТАНОВИТСЯ ПРАВИЛОМ
-- ------------------------------------------------------------
-- Верхняя граница выносится в констрейнт: это свойство данных, а не
-- поведения, и место ему на таблице. Нижнюю границу в констрейнт НЕ
-- ставим — она проверяется в триггере только при изменении описания
-- (см. блок 3), иначе старое объявление на 18 символов нельзя было бы
-- ни опубликовать, ни продлить.
--
-- NOT VALID: существующие строки не перепроверяются. Сейчас длинных
-- описаний в каталоге нет (самое большое — 1924 символа), но
-- полагаться на это в миграции нельзя: она обязана применяться на
-- любой базе, включая ту, где такая строка появится завтра. Новые и
-- изменяемые строки констрейнт проверяет с этого момента.
do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'chk_cars_description_len'
  ) then
    alter table public.cars
      add constraint chk_cars_description_len
      check (description is null or length(description) <= 6000)
      not valid;
  end if;
end $$;

comment on constraint chk_cars_description_len on public.cars
  is 'Верхняя граница описания — 6000 символов. Раньше держалась только атрибутом maxLength в форме, то есть браузером (0136)';


-- ------------------------------------------------------------
-- 3. ТРИГГЕР: чистка → разметка → контакты → ссылки → длина → язык
-- ------------------------------------------------------------
-- Заменяем функцию из 0135, добавляя три проверки. Сам триггер
-- trg_cars_detect_lang пересоздавать не нужно: он ссылается на
-- функцию по имени.
--
-- ПОРЯДОК ПРОВЕРОК — ОТ КОНКРЕТНОГО К ОБЩЕМУ, и он ОБЯЗАН совпадать с
-- validateDescription на клиенте: иначе форма назовёт одну причину, а
-- сервер при обходе — другую. Длина проверяется последней: если в
-- тексте и номер телефона, и он же короче тридцати символов, продавцу
-- полезнее узнать про номер — дописать текст он и так собирался, а про
-- запрет контактов не догадывается.
create or replace function public.trg_set_description_lang()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  v_len integer;
begin
  if tg_op = 'INSERT'
     or new.description is distinct from old.description then
    -- 1) Чистим текст от следов копирования (0111).
    new.description := public.f_clean_description(new.description);

    -- f_clean_description возвращает NULL для пустой строки, поэтому
    -- дальше проверяем только непустое описание: поле необязательное.
    if new.description is not null then

      -- 2) РАЗМЕТКА. Проверяется ПЕРВОЙ — тот же порядок, что в
      -- validateDescription на клиенте, и расходиться они не должны:
      -- иначе форма назвала бы одну причину, а сервер при обходе —
      -- другую. Текст со сторонней площадки обычно содержит и теги, и
      -- ссылки, а убирать разметку продавцу придётся в любом случае.
      if public.f_has_markup(new.description) then
        raise exception
          'В описании нельзя использовать HTML-теги и скрипты'
          using
            errcode = 'check_violation',
            hint = 'markup_in_description';
      end if;

      -- 3) КОНТАКТЫ (0135). Ссылка на мессенджер — тоже ссылка, но
      -- причина точнее, поэтому контакты идут ПЕРЕД общим правилом
      -- про ссылки.
      if public.f_has_contact_info(new.description) then
        raise exception
          'В описании нельзя указывать телефон, email и ссылки на мессенджеры'
          using
            errcode = 'check_violation',
            hint = 'contacts_in_description';
      end if;

      -- 4) ЛЮБАЯ ДРУГАЯ ВНЕШНЯЯ ССЫЛКА (0136).
      if public.f_has_external_link(new.description) then
        raise exception
          'В описании нельзя указывать ссылки на другие сайты'
          using
            errcode = 'check_violation',
            hint = 'links_in_description';
      end if;

      -- 5) ДЛИНА. Считаем по тексту без крайних пробелов — так же, как
      -- клиент: строка из сорока пробелов описанием не является.
      -- f_clean_description крайние пробелы уже снял, btrim здесь —
      -- страховка на случай прямого UPDATE в обход чистки.
      v_len := length(btrim(new.description));

      if v_len < 30 then
        raise exception
          'Описание слишком короткое: % символов, нужно не менее 30', v_len
          using
            errcode = 'check_violation',
            hint = 'description_too_short';
      end if;

      if v_len > 6000 then
        raise exception
          'Описание слишком длинное: % символов, допустимо не более 6000', v_len
          using
            errcode = 'check_violation',
            hint = 'description_too_long';
      end if;
    end if;

    -- 6) Язык определяем по чистому и допущенному тексту (0110).
    new.description_lang := public.f_detect_lang(new.description);
  end if;

  return new;
end;
$$;

comment on function public.trg_set_description_lang()
  is 'BEFORE-триггер cars: нормализует описание (0111), отклоняет контакты (0135), ссылки, разметку и негодную длину (0136), проставляет description_lang (0110)';
