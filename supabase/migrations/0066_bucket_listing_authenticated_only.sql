-- ============================================================
-- AUTO.RS — Миграция 0066: листинг бакетов только для authenticated
-- ============================================================
-- ПРОБЛЕМА (Supabase Advisor, public_bucket_allows_listing, 2 шт).
-- Политики car_images_read_all и avatars_read_all давали SELECT на
-- storage.objects роли anon. Для публичных бакетов это лишнее: прямая
-- ссылка на файл отдаётся по флагу bucket.public = true, а не по
-- RLS-политике. SELECT на storage.objects нужен только для ЛИСТИНГА —
-- перечисления содержимого бакета через storage.from(...).list().
--
-- То есть гость мог получить список всех файлов в car-images и
-- avatars: имена, размеры, даты, структуру папок (первый сегмент пути —
-- UUID владельца). Сами картинки и так публичны, но перечень файлов
-- вместе с идентификаторами владельцев публиковать незачем.
--
-- ИСПРАВЛЕНИЕ. Сужаем роль с (anon, authenticated) до authenticated.
-- Условие using не меняется — только список ролей.
--
-- ЧТО ПРОДОЛЖИТ РАБОТАТЬ:
--   · отдача картинок по прямой ссылке гостю — идёт через
--     bucket.public = true (миграции 0014 и 0038), политики не участвуют;
--   · уборка временных фото объявления —
--     lib/data/repositories/cars_repository.dart, deleteTempCarImages:
--     вызывает .list(path: '<uid>/<tempCarUuid>') и делает это ТОЛЬКО
--     от имени авторизованного пользователя (в начале метода стоит
--     проверка currentUser?.id == null → return), поэтому роли
--     authenticated достаточно.
--
-- ЧТО НЕ ТРОГАЕМ: бакет user-documents (он уже приватный: public=false
-- и политика user_docs_select_owner_or_admin), политики INSERT/UPDATE/
-- DELETE обоих бакетов, флаги public самих бакетов.
--
-- ЕСЛИ ПОСЛЕ ПРИМЕНЕНИЯ фото у гостя всё же пропадут (проверка в
-- инкогнито: каталог, карточка объявления, аватарки) — откат ровно
-- один: вернуть в обеих политиках список ролей «to anon, authenticated».
-- Готовый SQL отката лежит в supabase/checks/0066_rollback.sql.
-- ============================================================

begin;

-- ------------------------------------------------------------
-- car-images: фотографии объявлений.
-- ------------------------------------------------------------
drop policy if exists "car_images_read_all" on storage.objects;
create policy "car_images_read_all"
  on storage.objects
  for select
  to authenticated
  using (bucket_id = 'car-images');

-- ------------------------------------------------------------
-- avatars: аватары пользователей.
-- ------------------------------------------------------------
drop policy if exists "avatars_read_all" on storage.objects;
create policy "avatars_read_all"
  on storage.objects
  for select
  to authenticated
  using (bucket_id = 'avatars');

commit;

