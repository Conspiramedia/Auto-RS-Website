-- ============================================================
-- AUTO.RS — Миграция 0135: запрет контактов в описании объявления.
-- ============================================================
-- ЗАЧЕМ. Телефон в тексте описания уводит сделку мимо площадки: чат и
-- кнопка «Позвонить» перестают работать, статистика обращений врёт, а
-- покупатель звонит по номеру, который никто не проверял. Номер для
-- связи у объявления УЖЕ ЕСТЬ — отдельным полем contact_phone, оно
-- проверяется при подаче и показывается вошедшему покупателю
-- (0116/0117). Описание — про машину, а не про то, как обойти чат.
--
-- ЭТО ЖЁСТКИЙ БАРЬЕР, А НЕ ПОДСКАЗКА. Верхний слой — проверка при
-- вводе в форме (lib/contactGuard.ts): она подсвечивает найденное и
-- не даёт нажать «Далее». Но клиент обходится тривиально — RPC
-- вызывается напрямую с anon-ключом, который лежит в бандле, — и
-- последнее слово обязано остаться за базой. Правила обоих слоёв
-- намеренно совпадают: разойдись они, форма пропускала бы текст,
-- который сервер отвергнет уже ПОСЛЕ загрузки фотографий, то есть в
-- самом дорогом месте сценария.
--
-- ГДЕ ЭТО ЖИВЁТ. В BEFORE-триггере на cars, а не в create_car_v3 /
-- update_car_v3 — ровно по причинам из 0111:
--   1) описание пишут несколько путей (два RPC, админские правки,
--      будущий импорт), и в каждом легко забыть повторить проверку;
--   2) сигнатуры RPC остаются нетронутыми — приложение и сайт
--      продолжают вызывать их как раньше, менять клиенты не нужно.
--
-- Переиспользуем ТОТ ЖЕ триггер trg_cars_detect_lang, что чистит
-- описание и определяет язык: второй триггер на то же поле означал бы
-- зависимость от порядка их выполнения (алфавитного — то есть
-- случайного по смыслу). Порядок внутри функции важен: сначала
-- f_clean_description, потом проверка — иначе номер, разбитый
-- табуляциями из чужого редактора, проскочил бы мимо правил.
--
-- ГЛАВНАЯ ТРУДНОСТЬ — НЕ ПОЙМАТЬ ЛИШНЕГО. Описание машины состоит из
-- чисел: «2020», «86 500 km», «1.9 TDI», «2.0», «205/55 R16», цена
-- «12 500». Наивное «шесть цифр подряд» ловит и пробег, и цену, и
-- объявление становится неподаваемым — а продавец не понимает, за
-- что. Поэтому цифры сами по себе НЕ запрещены здесь никогда:
-- запрещены признаки КОНТАКТА — телефонная форма номера (+381, 06x,
-- 8/7 с кодом), доменная ссылка на мессенджер, адрес почты, @никнейм,
-- название мессенджера рядом с длинной группой цифр.
--
-- СТАРЫЕ ОБЪЯВЛЕНИЯ НЕ ТРОГАЕМ. Обратной чистки, как в 0111, здесь
-- НЕТ и быть не должно: там правился мусор от копирования, а тут
-- пришлось бы вырезать куски авторского текста или, хуже, снимать с
-- публикации уже проверенные модератором объявления. Проверка
-- срабатывает только когда описание МЕНЯЮТ (см. условие в триггере) —
-- то есть на новых и на правках. Существующие номера в описаниях —
-- задача модерации, а не миграции.
-- ============================================================


-- ------------------------------------------------------------
-- 1. НОРМАЛИЗАЦИЯ ПОД АНАЛИЗ
-- ------------------------------------------------------------
-- Зеркало normalizeForScan из lib/contactGuard.ts.
--
-- Снимаем типографские подмены, которыми номер маскируется — иногда
-- умышленно, а чаще просто потому, что текст скопировали из другого
-- объявления вместе с неразрывными пробелами и длинными тире.
-- Кириллические гомоглифы («vibеr» с русской «е») неотличимы на вид,
-- но латинской регуляркой не ловятся, поэтому приводим их к латинице.
--
-- Длину строки функция НЕ сохраняет (translate работает посимвольно,
-- но lower() на некоторых парах может дать иную длину) — и не должна:
-- на сервере подсветка не нужна, нужен только факт находки.
create or replace function public.f_normalize_contacts_scan(txt text)
returns text
language sql
immutable
set search_path = public
as $$
  select lower(
    translate(
      coalesce(txt, ''),
      -- Кириллические гомоглифы латиницы + типографские тире и пробелы.
      'аАеЕоОрРсСхХуУкКмМтТ' ||
      U&'\2010\2011\2012\2013\2014\2015\2212' ||
      U&'\00A0\2007\2008\2009\200A\202F\205F\3000',
      'aaeeooppccxxyykkmmtt' ||
      '-------' ||
      '        '
    )
  );
$$;

comment on function public.f_normalize_contacts_scan(text)
  is 'Готовит описание к поиску контактов: кириллические гомоглифы → латиница, типографские тире и пробелы → обычные, нижний регистр (0135)';


-- ------------------------------------------------------------
-- 2. ПОИСК КОНТАКТОВ
-- ------------------------------------------------------------
-- Возвращает true, если в описании есть телефон, почта, ссылка на
-- мессенджер или @никнейм.
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ ФУНКЦИЯ, А НЕ ТЕЛО ТРИГГЕРА. Её вызывает SQL-тест
-- (supabase/checks/0135_contact_guard_test.sql) на два десятка
-- описаний разом — через триггер это означало бы два десятка вставок
-- и откатов. Плюс её можно позвать из админки, чтобы показать
-- модератору, за что объявление задержано.
--
-- Регулярки — синтаксис POSIX (~), а не PCRE: lookbehind в нём нет,
-- поэтому там, где в TypeScript стоит (?<!\d), здесь используется
-- граница-класс с явной альтернативой «начало строки или не-цифра».
create or replace function public.f_has_contact_info(txt text)
returns boolean
language sql
immutable
set search_path = public
as $$
with s as (select public.f_normalize_contacts_scan(txt) as t)
select
  -- --- ПОЧТА ------------------------------------------------
  -- Обычная запись и обходы через «(at)» / «[собака]».
  -- Домен верхнего уровня — от двух букв: «name@2» почтой не
  -- считается, «name@mail.ru» считается.
  (select t ~ '[a-z0-9._%+-]+[[:space:]]*(@|\([[:space:]]*(at|собака|majmun)[[:space:]]*\)|\[[[:space:]]*(at|собака|majmun)[[:space:]]*\])[[:space:]]*[a-z0-9.-]+[[:space:]]*(\.|\([[:space:]]*(dot|тчк|точка)[[:space:]]*\))[[:space:]]*[a-z]{2,}' from s)

  -- --- ССЫЛКИ НА МЕССЕНДЖЕРЫ --------------------------------
  -- Схема-ссылки: viber://, whatsapp://, tg://.
  or (select t ~ '(viber|whatsapp|tg|telegram|skype|sgnl)[[:space:]]*:[[:space:]]*//' from s)

  -- Доменные ссылки-приглашения. Перечень доменов ЗАКРЫТЫЙ:
  -- запрещать любой домен нельзя — продавцы законно ссылаются на
  -- отчёт истории машины или на видео с осмотром.
  or (select t ~ '(^|[^a-z0-9])(t|telegram|wa|api\.whatsapp|chat\.whatsapp|fb|facebook|instagram|instagr|vk|viber|signal|join\.skype)[[:space:]]*(\.|\([[:space:]]*(dot|точка|тчк)[[:space:]]*\))[[:space:]]*(me|com|ru|am|gg|link)[[:space:]]*/+[[:space:]]*[a-z0-9_.+-]+' from s)

  -- --- @НИКНЕЙМ ---------------------------------------------
  -- Минимум пять символов — столько требует сам Telegram; такой порог
  -- не задевает «шины 4@2000». Перед @ не должно быть символа
  -- почтового адреса: иначе это хвост e-mail, а его ловит правило выше.
  or (select t ~ '(^|[^a-z0-9._%+-])@[a-z0-9_]{5,32}([^a-z0-9_]|$)' from s)

  -- --- МЕССЕНДЖЕР РЯДОМ С ЦИФРАМИ ---------------------------
  -- «Whatsapp 060…», «Viber: 123456», «телеграм — 89161234567».
  -- Не меньше шести цифр в группе: «WhatsApp 24/7» и «Viber 2 часа»
  -- остаются в тексте, номер — нет. До цифр не больше 12 символов:
  -- помещается «viber ili whatsapp:», но не предложение целиком.
  or (select t ~ '(whats[[:space:]]*app|wattsapp|vats[[:space:]]*ap|вотсап|ватсап|вацап|viber|вайбер|telegram|телеграм|телега|signal|instagram|инстаграм|инста|messenger|мессенджер)[^0-9[:cntrl:]]{0,12}(\+?[0-9][[:space:].()/-]{0,2}){6,}' from s)

  -- Зеркало: сначала номер, потом слово («060 123 4567 вайбер»).
  or (select t ~ '(\+?[0-9][[:space:].()/-]{0,2}){6,}[^0-9[:cntrl:]]{0,12}(whats[[:space:]]*app|wattsapp|vats[[:space:]]*ap|вотсап|ватсап|вацап|viber|вайбер|telegram|телеграм|телега|signal|instagram|инстаграм|инста)' from s)

  -- --- «ЗВОНИТЕ / ПИШИТЕ» + ЦИФРЫ ---------------------------
  -- Глагол связи рядом с длинной группой цифр. Порог тот же — шесть
  -- цифр: «звоните после 18» и «машина 2015 года» проходят.
  or (select t ~ '(^|[^a-zа-я])(звоните|звонить|звони|позвоните|перезвоню|пишите|пиши|напишите|набирайте|наберите|тел|телефон|моб|мобильный|контакт|связь|zovite|zovi|pozovite|javite|pisite|pisete|kontakt|telefon|mob|broj)([^0-9[:cntrl:]]{0,15})(\+?[0-9][[:space:].()/-]{0,2}){6,}' from s)

  -- --- ТЕЛЕФОН ПО ФОРМЕ -------------------------------------
  -- Международная запись: + и код страны. Однозначный признак
  -- телефона — никакая характеристика машины так не пишется.
  -- 8–15 цифр после плюса покрывает любой номер мира (E.164).
  or (select t ~ '\+[[:space:]]*([0-9][[:space:].()/-]{0,2}){8,15}' from s)

  -- Сербский мобильный без плюса: 06x и ещё 6–8 цифр. «06» в начале —
  -- не число из описания: пробег и цена с нуля не начинаются, год тем
  -- более.
  or (select t ~ '(^|[^0-9])0[[:space:]]*6[[:space:]]*[0-9]([[:space:].()/-]{0,2}[0-9]){6,8}([^0-9]|$)' from s)

  -- Сербский городской: 0 + код города (11 Белград, 21 Нови-Сад,
  -- 18 Ниш, 24 Суботица, 34 Крагуевац…) + номер.
  or (select t ~ '(^|[^0-9])0[[:space:]]*(1[1-9]|2[0-9]|3[0-9])([[:space:].()/-]{1,2}[0-9]){5,9}([^0-9]|$)' from s)

  -- Русский/казахский формат: 8 или 7 с кодом — «8 (999) 123-45-67»,
  -- «89161234567». Ровно 11 цифр всего: это отличает номер от суммы
  -- «8 500 000».
  or (select t ~ '(^|[^0-9])[78][[:space:].()/-]{0,3}(9|8|4|3)[0-9]{2}[[:space:].()/-]{0,3}[0-9]{3}[[:space:].()/-]{0,3}[0-9]{2}[[:space:].()/-]{0,3}[0-9]{2}([^0-9]|$)' from s);
$$;

comment on function public.f_has_contact_info(text)
  is 'true, если в описании есть телефон, e-mail, ссылка на мессенджер или @никнейм. Голые числа (год, пробег, цена, объём) контактом НЕ считаются (0135)';


-- ------------------------------------------------------------
-- 3. ТРИГГЕР: чистка + проверка на контакты + определение языка
-- ------------------------------------------------------------
-- Заменяем функцию из 0111, добавляя проверку между нормализацией и
-- определением языка. Сам триггер trg_cars_detect_lang пересоздавать
-- не нужно: он ссылается на функцию по имени.
--
-- ПОРЯДОК ВНУТРИ ФУНКЦИИ:
--   1) f_clean_description — снимает следы копирования. Обязательно
--      ДО проверки: номер, разбитый табуляциями из чужого редактора,
--      иначе проскочил бы мимо правил;
--   2) f_has_contact_info — отказ, если контакты найдены;
--   3) f_detect_lang — язык уже чистого и допущенного текста.
create or replace function public.trg_set_description_lang()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if tg_op = 'INSERT'
     or new.description is distinct from old.description then
    -- 1) Чистим текст от следов копирования (0111).
    new.description := public.f_clean_description(new.description);

    -- 2) ЖЁСТКИЙ БАРЬЕР. Срабатывает только при ВСТАВКЕ и при РЕАЛЬНОМ
    -- изменении описания: смена статуса, продвижение и счётчик
    -- просмотров сюда не попадают, и уже опубликованные объявления со
    -- старыми номерами в тексте не ломаются при первом же UPDATE.
    --
    -- Текст исключения — по-русски, как и у прочих серверных гейтов
    -- (см. create_car_v3). Продавцу его показывают НЕ ТАК: клиент
    -- ловит errcode и подставляет перевод для своей локали
    -- (sell_err_contacts в lib/i18n.ts, обе локали). Сообщение здесь —
    -- для журнала и для того, кто вызвал RPC напрямую.
    if public.f_has_contact_info(new.description) then
      raise exception
        'В описании нельзя указывать телефон, email и ссылки на мессенджеры'
        using
          errcode = 'check_violation',
          -- hint читается клиентом: по нему humanOtpError отличает
          -- этот отказ от прочих check_violation (цена, год, залог),
          -- у которых свои сообщения.
          hint = 'contacts_in_description';
    end if;

    -- 3) Язык определяем по чистому и допущенному тексту (0110).
    new.description_lang := public.f_detect_lang(new.description);
  end if;

  return new;
end;
$$;

comment on function public.trg_set_description_lang()
  is 'BEFORE-триггер cars: нормализует описание (0111), отклоняет контактные данные в нём (0135) и проставляет description_lang (0110)';
