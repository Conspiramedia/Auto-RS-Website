-- 0134 — РАСПИСАНИЕ ОЧЕРЕДИ ПИСЕМ: send-email каждые 5 минут
-- ============================================================
-- ЧТО БЫЛО СЛОМАНО. Письма не уходили НИ РАЗУ за всё время работы
-- почтового канала. На 03.09.2026 в email_queue лежало 26 строк:
--
--   status 'pending'   26
--   status 'sent'       0
--   status 'failed'     0
--   attempts            0 у всех
--
-- Ноль попыток — ключевой признак. Он означает, что claim_email_batch
-- (0071) не вызывался вообще: функция увеличивает attempts в момент
-- выдачи пачки, и любая неудача провайдера оставила бы attempts > 0 и
-- текст в error. Значит, дело не в Resend, не в адресах и не в коде
-- функции, а в том, что send-email никто не запускал.
--
-- Ручной вызов это подтвердил: {"processed":26,"sent":26,"failed":0} —
-- вся очередь ушла с первого раза, без единой ошибки.
--
-- ПРИЧИНА — РАСХОЖДЕНИЕ ИНСТРУКЦИИ С РЕАЛЬНОСТЬЮ ПАНЕЛИ. И RELEASE.md,
-- и supabase/functions/README.md отправляли заводить расписание в
-- Dashboard → Edge Functions → Schedules. Такой вкладки в панели этого
-- проекта нет — то же самое уже выяснилось при настройке daily-cleanup
-- (0124), и там расписание в итоге завели через pg_cron. Для
-- send-email этот вывод перенесён не был, и функция осталась
-- задеплоенной, но никем не вызываемой.
--
-- Отдельно: README (раздел «Альтернатива: pg_cron») утверждал, что
-- send-email и send-push через pg_cron вызвать НЕЛЬЗЯ, потому что им
-- нужен HTTP наружу. Утверждение неверное — наружу ходит не база, а
-- Edge Function; база лишь дёргает её через net.http_post, ровно как
-- это делает работающее задание daily-cleanup-job. Текст исправлен
-- вместе с этой миграцией.
--
-- ПОЧЕМУ ПЯТЬ МИНУТ, А НЕ ЧАЩЕ. Интервал взят из проектного решения,
-- зафиксированного при создании канала (send-email/index.ts, шапка):
-- функция — зеркало send-push, и отличается от него, помимо провайдера,
-- меньшим размером пачки. Письмо тяжелее пуша: это отдельный исходящий
-- HTTP-запрос к Resend на каждое сообщение. Пуш ходит раз в минуту
-- потому, что задержка уведомления о новом сообщении в чате
-- чувствительна для пользователя; письмо о решении модерации пять
-- минут ждёт безболезненно.
--
-- Коды входа по почте этим расписанием НЕ затронуты: они уходят
-- синхронно через Edge Function auth-email-hook (0082, 0106), минуя
-- очередь, и десятиминутный срок жизни кода интервалу разбора
-- очереди ничем не обязан.
--
-- ТАЙМАУТ 120 СЕКУНД — тот же урок, что в 0124. По умолчанию
-- net.http_post рвёт соединение через 5000 мс, и прежнее задание
-- daily-cleanup из-за этого не отрабатывало, числясь при этом
-- «успешным»: cron считает запуск удавшимся, как только запрос
-- поставлен в очередь. Пачка писем — до 50 последовательных запросов
-- к Resend (EMAIL_BATCH_LIMIT), в пять секунд она не укладывается
-- заведомо. Две минуты дают запас и одновременно сохраняют предел:
-- зависшая функция оборвётся, а не будет висеть бесконечно.
--
-- КЛЮЧ БЕРЁТСЯ ИЗ ДЕЙСТВУЮЩЕГО ЗАДАНИЯ daily-cleanup-job, а не
-- вписывается в файл: service_role key — секрет, его место в базе, а
-- не в репозитории. Приём тот же, что в 0124.
--
-- ИДЕМПОТЕНТНОСТЬ. Перед созданием снимаем задание с тем же именем,
-- если оно есть: повторный прогон миграции не должен плодить дубли,
-- иначе очередь будет разбираться двумя заданиями сразу. Само по себе
-- это безопасно (claim_email_batch держит FOR UPDATE SKIP LOCKED, и
-- письмо не уйдёт дважды), но лишние вызовы никому не нужны.
-- ============================================================

do $$
declare
  v_key text;
begin
  -- Ключ из работающего задания чисток. Если его нет (свежая база,
  -- накатывающая миграции с нуля), расписание не создаём: на такой
  -- базе оно заводится вручную при развёртывании вместе с секретами,
  -- и выдуманный ключ был бы хуже отсутствующего задания.
  select (regexp_match(j.command, 'Bearer ([A-Za-z0-9._-]+)'))[1]
    into v_key
    from cron.job j
   where j.jobname = 'daily-cleanup-job';

  if v_key is null then
    raise notice 'daily-cleanup-job не найден или без ключа — расписание send-email не создано';
    return;
  end if;

  -- Снимаем прежнее задание, если оно каким-то образом уже заведено.
  if exists (select 1 from cron.job where jobname = 'send-email-job') then
    perform cron.unschedule('send-email-job');
  end if;

  perform cron.schedule(
    'send-email-job',
    '*/5 * * * *',
    format(
      $job$
      select net.http_post(
        url := 'https://nedjfdswonnbhuxaxjsv.supabase.co/functions/v1/send-email',
        headers := jsonb_build_object(
          'Authorization', 'Bearer %s',
          'Content-Type', 'application/json'
        ),
        timeout_milliseconds := 120000
      );
      $job$,
      v_key
    )
  );
end
$$;
