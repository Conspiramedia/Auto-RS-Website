-- ============================================================
-- 0123 — ПОИСК ОСИРОТЕВШИХ ФАЙЛОВ В БАКЕТЕ car-images
-- ============================================================
-- ЗАЧЕМ. Строки car_images уходят каскадом вместе с объявлением
-- (удаление отклонённого — 0122, удаление аккаунта, замена фотографий
-- при правке), а сами файлы остаются в бакете навсегда. Через год
-- работы площадки это десятки гигабайт, за которые платят, и никто их
-- никогда не откроет.
--
-- ПОЧЕМУ SQL ТОЛЬКО ИЩЕТ, А УДАЛЯЕТ EDGE FUNCTION. Postgres не умеет
-- удалять объекты хранилища: это HTTP-операция к Storage API, а не
-- запись в таблицу. Строку из storage.objects удалить технически
-- можно, но сам файл в S3 при этом останется висеть — то есть
-- метаданные разойдутся с содержимым бакета, и место не освободится.
-- Поэтому здесь только поиск, а удаление делает daily-cleanup через
-- storage.remove().
--
-- КАК ОПОЗНАЁТСЯ СИРОТА. По ОТСУТСТВИЮ ССЫЛКИ из car_images, а не по
-- структуре пути. В бакете уживаются два формата, оставшиеся от
-- разных версий загрузчика:
--   uid/carId/0.jpg      — текущий (папка на объявление);
--   uid/1788278469843_0.jpg — прежний (плоский, с меткой времени).
-- Правило «путь не встречается ни в одном image_url» покрывает оба и
-- переживёт появление третьего.
--
-- ОТСРОЧКА В СУТКИ — ГЛАВНАЯ ЗАЩИТА. Файл считается сиротой только
-- если он старше суток. Причина: продавец загружает фотографии ДО
-- создания объявления (PhotoPicker кладёт их в бакет, а car_images
-- заполняется в create_car_v3 после нажатия «Опубликовать»). Между
-- этими шагами файл существует без единой ссылки — и без отсрочки
-- чистка удалила бы фотографии человека прямо во время заполнения
-- формы. Сутки с запасом покрывают самую медленную подачу.
--
-- ВОЗВРАЩАЕТ ИМЕНА, А НЕ УДАЛЯЕТ САМА. Функция ничего не меняет: она
-- stable и её безопасно звать для проверки, чтобы посмотреть, что
-- именно чистка собирается снести, прежде чем разрешать ей это.
-- ============================================================

create or replace function public.find_orphan_car_images(
  -- Сколько имён вернуть за раз. Батч, а не всё сразу: Storage API
  -- удаляет пачками, и запрос на десять тысяч файлов упёрся бы в
  -- таймаут Edge Function. Дневная норма чистки — несколько батчей.
  p_limit integer default 100,
  -- Возраст, с которого файл считается брошенным. Вынесен параметром,
  -- а не зашит константой: при разборе инцидента бывает нужно
  -- посмотреть, что удалилось бы с другой границей.
  p_older_than interval default interval '1 day'
)
returns table (name text)
language sql
stable
security definer
set search_path = public, storage
as $$
  select o.name
    from storage.objects o
   where o.bucket_id = 'car-images'
     -- Отсрочка: см. шапку. created_at, а не updated_at — пересохранение
     -- метаданных не должно продлевать жизнь брошенному файлу.
     and o.created_at < now() - p_older_than
     -- Ни одно объявление на файл не ссылается.
     --
     -- Сравнение по окончанию image_url, а не по равенству: в базе
     -- лежит полный публичный URL с доменом проекта, а в storage.objects
     -- — путь внутри бакета. Собирать URL здесь строкой значило бы
     -- зашить в функцию домен, который меняется вместе с проектом.
     and not exists (
       select 1
         from public.car_images ci
        where ci.image_url like '%/' || o.name
     )
   order by o.created_at
   limit greatest(coalesce(p_limit, 100), 1);
$$;

comment on function public.find_orphan_car_images(integer, interval)
  is 'Имена файлов в car-images, на которые не ссылается ни одно объявление и которые старше указанного возраста. Ничего не удаляет (0123)';

-- Только service_role: список чужих файлов наружу не отдаём, а чистку
-- запускает Edge Function под сервисным ключом.
revoke all on function public.find_orphan_car_images(integer, interval)
  from public, anon, authenticated;
