-- ============================================================
-- AUTO.RS — Миграция 0069: UPDATE только на колонку is_read
-- ============================================================
-- ПРОБЛЕМА (долг из аудита кабинета сайта, п.4).
-- Политики messages_update_participant (0016) и notifications_update_own
-- (0024) написаны БЕЗ WITH CHECK и без ограничения набора колонок.
-- Задумывались они под одну операцию — «пометить прочитанным», но
-- фактически разрешают участнику чата переписать ЛЮБОЕ поле строки,
-- к которой политика его пускает:
--
--   * messages: участник может отредактировать text ЧУЖОГО сообщения
--     (политика USING проверяет участие в чате, а не авторство) и
--     подменить created_at — то есть задним числом переписать диалог,
--     на который вторая сторона могла бы сослаться в споре;
--   * notifications: получатель может переписать title/body/type своего
--     уведомления. Ущерб меньше, но поле подставляется в интерфейс,
--     и «уведомление от площадки» с произвольным текстом — плохой
--     материал для скриншота.
--
-- ПОЧЕМУ КОЛОНОЧНЫЕ ГРАНТЫ, А НЕ ПРАВКА ПОЛИТИК.
-- Переписать политику на WITH CHECK, запрещающий изменение прочих
-- колонок, в Postgres нельзя без обращения к OLD-строке, а в WITH CHECK
-- доступна только NEW: пришлось бы вешать триггер BEFORE UPDATE и
-- сверять поля вручную. Колоночный грант решает ту же задачу штатным
-- механизмом СУБД и на рубеже РАНЬШЕ политик: запрос, трогающий чужую
-- колонку, отклоняется по правам ещё до вычисления RLS.
--
-- ВАЖНО ПРО ПОРЯДОК ПРОВЕРОК: гранты и RLS — независимые рубежи, оба
-- обязательны. Политики остаются нетронутыми и продолжают отвечать на
-- вопрос «какие СТРОКИ доступны»; гранты отвечают «какие КОЛОНКИ
-- разрешено писать». Задача миграции — только второй вопрос.
--
-- СОВМЕСТИМОСТЬ С КЛИЕНТАМИ. Обе операции, которые реально выполняются
-- сегодня, пишут ровно is_read и продолжат работать:
--   · приложение: notifications_repository.dart — update({'is_read': true})
--     (markRead и markAllRead), chat_repository.dart — пометка входящих
--     сообщений прочитанными;
--   · сайт: те же операции появятся в кабинете (/my/messages).
-- Ни один клиент не обновляет text, title, body или created_at — правка
-- сообщений и уведомлений в продукте не предусмотрена вовсе.
--
-- SELECT и INSERT НЕ ЗАТРАГИВАЮТСЯ. Снимается только UPDATE: чтение
-- лент и отправка новых сообщений идут прежним путём.
-- ============================================================

begin;

-- ------------------------------------------------------------
-- 1) messages — писать разрешено только is_read.
-- ------------------------------------------------------------
-- Сначала снимаем табличный UPDATE целиком: без этого шага колоночный
-- грант ничего не ограничит — права на таблицу и на колонку
-- складываются по ИЛИ, и более широкое табличное разрешение победило бы.
revoke update on public.messages from authenticated;

-- anon сообщений не пишет никогда (RLS пускает только authenticated),
-- но грант мог достаться ему из ранних миграций — снимаем явно.
revoke update on public.messages from anon;

grant update (is_read) on public.messages to authenticated;

-- ------------------------------------------------------------
-- 2) notifications — писать разрешено только is_read.
-- ------------------------------------------------------------
-- Сами строки уведомлений создают ТРИГГЕРЫ в режиме SECURITY DEFINER
-- (notify_on_message, notify_on_booking_status, notify_on_kyc_status,
-- approve_car/reject_car). Они выполняются от владельца функции, на
-- которого клиентские гранты не распространяются, поэтому генерация
-- уведомлений после этой миграции работает без изменений.
revoke update on public.notifications from authenticated;
revoke update on public.notifications from anon;

grant update (is_read) on public.notifications to authenticated;

commit;

-- ============================================================
-- ПРОВЕРКА ПОСЛЕ ПРИМЕНЕНИЯ
-- ============================================================
-- 1) Разрешённая операция — должна пройти:
--      update public.notifications set is_read = true where id = '<свой id>';
--
-- 2) Запрещённая операция — должна упасть с ошибкой
--    «permission denied for table messages»:
--      update public.messages set text = 'подмена' where id = '<любой>';
--
-- 3) Фактические колоночные права:
--      select table_name, column_name, privilege_type
--        from information_schema.column_privileges
--       where grantee = 'authenticated'
--         and table_name in ('messages', 'notifications')
--         and privilege_type = 'UPDATE';
--    Ожидается ровно две строки — обе с column_name = 'is_read'.
-- ============================================================
