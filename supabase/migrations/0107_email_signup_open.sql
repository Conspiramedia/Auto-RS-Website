-- ============================================================
-- RS AUTO — регистрация по почте открыта, а не только вход.
-- ============================================================
-- ЧТО БЫЛО СЛОМАНО. Миграция 0106 открыла почтовый вход всем профилям
-- с почтой, и этого оказалось недостаточно: гейт пропускал адрес,
-- только если профиль УЖЕ СУЩЕСТВУЕТ. Требование осталось от 0082, где
-- канал был служебным входом администратора — «вход в существующий
-- аккаунт, регистрации по почте нет».
--
-- В результате получился замкнутый круг. Чтобы войти на /login, нужен
-- аккаунт; чтобы завести аккаунт, нужно пройти форму подачи объявления
-- до четвёртого шага (там shouldCreateUser: true). Новый человек,
-- пришедший просто зарегистрироваться, получал «Для этого адреса вход
-- по почте не настроен» и не мог сделать ничего.
--
-- ЧТО МЕНЯЕТСЯ. email_login_allowed перестаёт спрашивать базу и
-- проверяет только форму адреса. Почта становится полноценной
-- регистрацией: незнакомый адрес получает код и заводит аккаунт.
--
-- ------------------------------------------------------------
-- ЧТО С ЗАЩИТОЙ ОТ ПЕРЕБОРА АДРЕСОВ.
-- ------------------------------------------------------------
-- Гейт больше не отсекает чужие адреса — но он и не был главным
-- рубежом. Смысл проверки в 0082 был в другом: не подсказывать, кто
-- зарегистрирован на площадке. Эта задача решена сильнее прежнего —
-- теперь ответ ОДИНАКОВ для всех адресов, и по нему нельзя отличить
-- существующий аккаунт от несуществующего. Раньше разница была видна
-- по allowed, несмотря на «нейтральный» ответ.
--
-- От собственно перебора защищают квоты, заведённые в 0082 и здесь
-- нетронутые: 5 писем на адрес за 24 часа и 20 запросов с IP за час.
-- Попытка по-прежнему пишется в журнал ДО проверки, поэтому перебор
-- не бесплатен.
--
-- Второй рубеж в Send Email Hook (auth-email-hook) тоже остаётся: он
-- зовёт эту же функцию, и правка действует на оба рубежа сразу.
--
-- ПОЧЕМУ ФУНКЦИЯ НЕ УДАЛЕНА, РАЗ ОНА БОЛЬШЕ НЕ СМОТРИТ В БАЗУ.
-- Её зовут два места (RPC и Edge Function), и обе — по имени. Удаление
-- потребовало бы синхронной правки функции, развёрнутой отдельно от
-- миграций, и любой рассинхрон оставил бы почтовый вход сломанным.
-- Проверка формы адреса в ней осмысленна и сама по себе.
-- ============================================================

create or replace function public.email_login_allowed(p_email text)
returns boolean
language sql
immutable
as $fn$
  -- Только форма адреса. Регулярное выражение то же, что в
  -- rpc_check_email_login: расхождение означало бы, что один рубеж
  -- пропускает то, что отвергает второй.
  select lower(btrim(coalesce(p_email, '')))
         ~ '^[^@[:space:]]+@[^@[:space:]]+\.[a-z]{2,}$';
$fn$;

comment on function public.email_login_allowed(text)
  is 'true, если адрес похож на почтовый. Существование профиля НЕ проверяется: вход по почте является и регистрацией.';

-- Права те же, что были: наружу не выдаётся. Клиент ходит через
-- rpc_check_email_login, которая списывает квоту на каждую попытку.
revoke all on function public.email_login_allowed(text) from public, anon, authenticated;
