-- ============================================================
-- RS AUTO — вход по почте для всех, телефон как контакт объявления.
-- ============================================================
-- ЧТО МЕНЯЕТСЯ И ПОЧЕМУ.
--
-- Вход по SMS на сайте больше не работает: Twilio требует одобренного
-- Primary Compliance Profile для сербских номеров, и до его получения
-- ни один продавец не может ни зарегистрироваться, ни войти. Воронка
-- закрыта полностью, а срок одобрения не зависит от нас.
--
-- Поэтому единственным входом НА САЙТЕ становится почта — канал,
-- который уже построен (миграция 0082: гейт, журнал квот, Send Email
-- Hook через Resend) и работает, но был открыт только администраторам.
--
-- ТЕЛЕФОН ПРИ ЭТОМ НЕ ИСЧЕЗАЕТ. Он перестаёт быть способом входа и
-- становится тем, чем всегда был по смыслу, — контактом в объявлении:
-- покупателю нужно, куда звонить. Спрашивается один раз при первой
-- подаче и сохраняется в профиль (RPC ниже), дальше подставляется сам.
--
-- ПРИЛОЖЕНИЕ НЕ ЗАТРОНУТО. Оно продолжает логинить по SMS через тот же
-- GoTrue; сигнатуры существующих RPC не меняются, миграция аддитивная.
-- Следствие, принятое заказчиком осознанно: один человек, вошедший в
-- приложении по телефону и на сайте по почте, получает ДВА аккаунта.
-- Раньше их связывал уникальный номер — блок 1 эту связь снимает.
-- ============================================================


-- ============================================================
-- 1) СНЯТИЕ УНИКАЛЬНОСТИ ТЕЛЕФОНА
-- ------------------------------------------------------------
-- profiles_phone_unique (0035) требовал «один номер — один профиль».
-- Ограничение имело смысл, пока номер БЫЛ идентификатором входа: его
-- подтверждали кодом, и двух аккаунтов на один номер возникнуть не
-- могло.
--
-- Теперь номер вводится руками как контакт, и уникальность начинает
-- мешать честным случаям: семья продаёт две машины с одного телефона,
-- у салона один номер на несколько сотрудников. Второй продавец
-- получал бы отказ на ровном месте — причём с невнятной ошибкой
-- нарушения индекса на последнем шаге формы.
--
-- Гарантия «один номер — один аккаунт» при этом теряется. Это
-- осознанный размен: телефон больше не средство аутентификации, и
-- защищать его уникальностью незачем.
-- ============================================================
drop index if exists public.profiles_phone_unique;


-- ============================================================
-- 2) ГЕЙТ ПОЧТОВОГО ВХОДА — ОТКРЫТ ВСЕМ, У КОГО ЕСТЬ ПОЧТА
-- ------------------------------------------------------------
-- Ровно та правка, которую предусматривал автор 0082: условие
-- p.is_admin заменяется на p.email is not null.
--
-- УСЛОВИЕ БЕЗОПАСНОСТИ ИЗ 0082 ВЫПОЛНЕНО. Там стояло предупреждение:
-- открывать канал всем можно только после того, как смена почты в
-- профиле перестанет быть бесконтрольной, иначе перехваченная на
-- минуту сессия позволяет вписать чужой адрес и войти по нему в любой
-- момент — угон аккаунта без единого подтверждения.
--
-- Закрыто запретом: смена почты убрана из профиля целиком (поле стало
-- read-only, как телефон). Почта фиксируется при регистрации и
-- меняется только через поддержку. Это осознанно выбранный размен —
-- полноценное подтверждение нового адреса кодом остаётся отдельной
-- задачей на потом, когда появятся живые пользователи и реальная
-- потребность менять адрес.
--
-- ЧТО ОСТАЁТСЯ НЕИЗМЕННЫМ: нейтральный ответ клиенту (allowed=false и
-- для чужого адреса, и для исчерпанной квоты), два рубежа проверки
-- (клиентская RPC и повторная в Send Email Hook), нормализация адреса
-- через lower+btrim. Меняется ровно одно условие.
-- ============================================================
create or replace function public.email_login_allowed(p_email text)
returns boolean
language sql
stable
security definer
set search_path = public
as $fn$
  select exists (
    select 1
      from public.profiles p
     where lower(btrim(p.email)) = lower(btrim(coalesce(p_email, '')))
       and p.email is not null
  );
$fn$;

comment on function public.email_login_allowed(text)
  is 'true, если адресу разрешён вход по почте (любому профилю с почтой)';

-- Права те же, что были: наружу функция не выдаётся. Голая проверка
-- «есть ли такой адрес» — готовый перебор; клиент ходит только через
-- rpc_check_email_login, которая отвечает нейтрально и тратит квоту.
revoke all on function public.email_login_allowed(text) from public, anon, authenticated;


-- ============================================================
-- 3) set_profile_phone — ЗАПИСЬ КОНТАКТНОГО ТЕЛЕФОНА В ПРОФИЛЬ
-- ------------------------------------------------------------
-- Телефон спрашивается один раз при первой подаче и дальше
-- подставляется в форму сам. Для этого его нужно где-то хранить, и
-- профиль — единственное правильное место: номер принадлежит
-- продавцу, а не конкретному объявлению.
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ RPC, А НЕ ПРЯМОЙ UPDATE ИЗ КЛИЕНТА. Прямая запись
-- в profiles потребовала бы политики RLS на UPDATE, а та открыла бы
-- клиенту ВСЕ колонки строки — включая is_admin и role. Узкая
-- definer-функция меняет ровно одно поле и не может быть использована
-- для повышения прав.
--
-- ПОЧЕМУ НЕ ТРОГАЕТ auth.users.phone. Там номер означает «способ
-- входа», и запись туда сделала бы телефон логином в обход всей этой
-- миграции. Контакт живёт в profiles и только там.
--
-- Нормализация: пустая строка → NULL. Иначе профиль с '' считался бы
-- заполненным, и форма перестала бы спрашивать номер, отправляя в
-- объявление пустоту.
--
-- Формат НЕ проверяется на сервере намеренно: маска «+381 6X XXX XXX»
-- и валидация живут на клиенте (lib/phone.ts), а приложение
-- пользуется собственной. Дублировать регулярное выражение в трёх
-- местах значило бы гарантированно их рассинхронизировать. Ограничена
-- только длина — от мусора в колонке.
-- ============================================================
create or replace function public.set_profile_phone(p_phone text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_clean   text := nullif(btrim(coalesce(p_phone, '')), '');
begin
  -- Гость номер не сохраняет: писать его некуда, профиля ещё нет.
  if v_user_id is null then
    raise exception 'Potrebna je prijava.'
      using errcode = 'insufficient_privilege';
  end if;

  if v_clean is not null and length(v_clean) > 40 then
    raise exception 'Broj telefona je predugačak.'
      using errcode = 'check_violation';
  end if;

  update public.profiles
     set phone      = v_clean,
         updated_at = now()
   where id = v_user_id;
end;
$$;

comment on function public.set_profile_phone(text)
  is 'Сохраняет контактный телефон в профиль вызывающего. Только своя строка, только колонка phone.';

-- Вызывать может только вошедший: гостю сохранять номер некуда.
revoke all on function public.set_profile_phone(text) from public, anon;
grant execute on function public.set_profile_phone(text) to authenticated;


-- ============================================================
-- 4) get_profile_phone — ЧТЕНИЕ СВОЕГО НОМЕРА
-- ------------------------------------------------------------
-- Форма подачи должна знать, спрашивать ли телефон. Раньше она
-- смотрела в session.user.phone — поле auth-аккаунта, которое
-- заполняется ТОЛЬКО при входе по SMS. У почтового пользователя оно
-- пустое всегда, поэтому номер приходилось бы вводить при каждой
-- подаче.
--
-- Читаем из profiles и только свою строку. Отдельная функция, а не
-- select из таблицы: политика SELECT на profiles отдаёт клиенту всю
-- строку, а форме нужно одно поле.
-- ============================================================
create or replace function public.get_profile_phone()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select p.phone
    from public.profiles p
   where p.id = auth.uid();
$$;

comment on function public.get_profile_phone()
  is 'Контактный телефон вызывающего из его профиля (NULL, если не задан).';

revoke all on function public.get_profile_phone() from public, anon;
grant execute on function public.get_profile_phone() to authenticated;
