-- ============================================================
-- AUTO.RS — Миграция 0126: удаление аккаунта владельцем
-- ============================================================
-- ЗАЧЕМ. Политика конфиденциальности (lib/legal.ts) обещает право на
-- полное забвение: «направить запрос на полное удаление аккаунта и
-- всех связанных с ним персональных данных». Механизма не было ни на
-- сайте, ни в приложении — обещание исполнялось вручную через
-- Dashboard, то есть на практике не исполнялось никак.
--
-- ------------------------------------------------------------
-- ПОЧЕМУ ОБЕЗЛИЧИВАНИЕ, А НЕ DELETE FROM auth.users.
-- ------------------------------------------------------------
-- Удалить строку auth.users из SQL нельзя честно: таблицей владеет
-- GoTrue, у неё свои связанные таблицы (identities, sessions,
-- refresh_tokens, mfa_*), и правильный способ — Admin API, то есть
-- Edge Function с сервисным ключом. Сервисный ключ сайту на Vercel
-- недоступен ПО ЗАМЫСЛУ проекта (.env.example: «Сайту эти ключи НЕ
-- нужны»), и заводить его ради одной кнопки значило бы отдать
-- фронтенду ключ, обходящий RLS целиком.
--
-- Обезличивание даёт тот же результат по существу требования: после
-- него в базе не остаётся ни одного персонального данного человека.
-- Строка auth.users остаётся пустой оболочкой (id и служебные поля
-- GoTrue), но она не персональные данные — по ней нельзя ни узнать,
-- кто это был, ни связаться с ним, ни войти.
--
-- ------------------------------------------------------------
-- ПОЧЕМУ ЗАТИРАНИЯ profiles.email НЕДОСТАТОЧНО, И ЧТО ЗАКРЫВАЕТ ВХОД.
-- ------------------------------------------------------------
-- Это неочевидно и стоило бы дыры, будь сделано наивно. С 0107 гейт
-- email_login_allowed НЕ смотрит в базу вовсе: вход по почте является
-- и регистрацией, поэтому проверяется только форма адреса. Значит
-- затирание profiles.email вход НЕ закрывает: GoTrue ищет человека по
-- СВОЕЙ таблице, а не по нашей, и пустил бы его в обезличенный
-- аккаунт.
--
-- Поэтому запрет входа держится на явном признаке deleted_at, и его
-- проверяет Send Email Hook (supabase/functions/auth-email-hook) —
-- тот самый рубеж, через который проходит КАЖДЫЙ код входа по почте.
-- Функция f_account_deleted ниже — общая точка этой проверки.
--
-- ЭТОГО ОКАЗАЛОСЬ МАЛО, и продолжение — в 0127: строка auth.users
-- сохраняет прежнюю почту, то есть адрес остаётся занят навсегда и
-- человек не может даже зарегистрироваться заново. 0127 освобождает
-- учётные данные и гасит сессии.
--
-- ------------------------------------------------------------
-- ЧТО УДАЛЯЕТСЯ НАСОВСЕМ, А ЧТО ОБЕЗЛИЧИВАЕТСЯ.
-- ------------------------------------------------------------
-- Удаляются (физически, каскадом от cars и по user_id):
--   • объявления со всем содержимым — фотографии (строки car_images),
--     избранное, скрытия, статистика, журнал просмотров;
--   • ЧАТЫ И СООБЩЕНИЯ по этим объявлениям — вместе с репликами
--     собеседников. Решение сознательное: сообщения удаляемого это
--     его персональные данные, а вырезать из диалога половину строк
--     значит оставить собеседнику разговор с самим собой;
--   • заявки на статус автосалона (реквизиты компании, ИНН, телефон);
--   • избранное, скрытые объявления, сохранённые поиски, push-токены,
--     уведомления, закрепления и блокировки чатов.
--
-- Обезличивается:
--   • profiles — имя, почта, телефон, аватар, витрина салона, поля
--     KYC. Строка остаётся: на неё ссылаются cars (уже удалённые) и,
--     что важнее, она обязана существовать для FK из auth.users.
--
-- НЕ ТРОГАЕТСЯ:
--   • admin_action_log — журнал действий администратора. FK actor_id
--     стоит on delete restrict именно затем, чтобы решения модерации
--     пережили удаление того, кто их принимал (0078). Обезличивание
--     этого не нарушает: журнал хранит id, а не имя.
--
-- ФАЙЛЫ В ХРАНИЛИЩЕ. Фотографии объявлений подхватит ежедневная
-- чистка: find_orphan_car_images (0123) ищет файлы, на которые не
-- ссылается ни один car_images, и её шапка прямо называет удаление
-- аккаунта среди источников сирот. Аватар удаляется здесь же строкой
-- из storage.objects — он один, путь известен («uid/...»), и ждать
-- сутки ради него незачем.
--
-- ------------------------------------------------------------
-- НЕОБРАТИМОСТЬ И ЗАЩИТА ОТ СЛУЧАЙНОСТИ.
-- ------------------------------------------------------------
-- Отменить нельзя: данные удаляются, а не помечаются. Поэтому функция
-- требует ПОДТВЕРЖДЕНИЯ СЛОВОМ (p_confirm) — не как замену диалогу в
-- интерфейсе, а как второй рубеж на стороне базы: вызов RPC руками из
-- консоли браузера одной строкой не должен стирать аккаунт.
--
-- АДМИНИСТРАТОР СЕБЯ УДАЛИТЬ НЕ МОЖЕТ. Его действия связаны журналом
-- (restrict), а сам он — единственный, кто раздаёт права модерации.
-- Случайное самоудаление админа обошлось бы площадке дороже, чем
-- неудобство обратиться к другому администратору.
--
-- СОВМЕСТИМОСТЬ С ПРИЛОЖЕНИЕМ: миграция аддитивная. Существующие
-- функции не переписаны, сигнатуры не тронуты. Новая колонка
-- profiles.deleted_at nullable с default null — на существующие
-- строки и на запросы приложения не влияет.
-- ============================================================


-- ============================================================
-- БЛОК 1. ПРИЗНАК УДАЛЁННОГО АККАУНТА
-- ============================================================
-- Момент удаления, а не boolean: «когда» отвечает на вопрос службы
-- поддержки «человек жалуется, что не может войти» — по дате видно,
-- что и когда произошло. Boolean на такой вопрос не отвечает.
alter table public.profiles
  add column if not exists deleted_at timestamptz;

comment on column public.profiles.deleted_at
  is 'Момент удаления аккаунта владельцем. Не null — профиль обезличен, вход запрещён (0126)';

-- Индекс частичный: удалённых на площадке единицы, и полный индекс по
-- колонке, которая почти везде null, был бы платой без выгоды.
create index if not exists idx_profiles_deleted
  on public.profiles (deleted_at)
  where deleted_at is not null;


-- ------------------------------------------------------------
-- f_account_deleted — общая проверка «аккаунт удалён»
-- ------------------------------------------------------------
-- Отдельной функцией, потому что нужна в двух местах: в Send Email
-- Hook (запрет входа) и в delete_my_account (защита от повторного
-- удаления). Две копии одного условия разошлись бы при первой правке.
--
-- Принимает id, а не почту: хук знает id пользователя из полезной
-- нагрузки GoTrue, а искать по затёртой почте всё равно нечего.
create or replace function public.f_account_deleted(p_user_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $fn$
  select exists (
    select 1
      from public.profiles p
     where p.id = p_user_id
       and p.deleted_at is not null
  );
$fn$;

comment on function public.f_account_deleted(uuid)
  is 'true, если аккаунт удалён владельцем и вход в него запрещён (0126)';

-- Наружу не выдаётся: голая проверка «жив ли аккаунт» — подсказка
-- перебирающему. Зовёт её Edge Function под сервисным ключом.
revoke all on function public.f_account_deleted(uuid)
  from public, anon, authenticated;


-- ============================================================
-- БЛОК 2. delete_my_account — удаление своего аккаунта
-- ============================================================
-- Возвращает jsonb со счётчиками: сколько объявлений, диалогов и
-- сообщений удалено. Интерфейсу это нужно не для красоты — человек,
-- нажавший необратимую кнопку, должен увидеть, что именно исчезло, а
-- не «готово».
create or replace function public.delete_my_account(p_confirm text)
returns jsonb
language plpgsql
security definer
set search_path = public, storage
as $fn$
declare
  v_user     uuid := auth.uid();
  v_is_admin boolean;
  v_deleted  timestamptz;
  v_cars     integer;
  v_chats    integer;
  v_messages integer;
begin
  if v_user is null then
    raise exception 'Требуется авторизация'
      using errcode = 'insufficient_privilege';
  end if;

  -- ------------------------------------------------------------
  -- Подтверждение словом. См. шапку: второй рубеж на стороне базы.
  -- ------------------------------------------------------------
  -- Слово ОДНО И ТО ЖЕ для обеих локалей и обоих клиентов: это не
  -- текст интерфейса, а константа протокола. Локализованное слово
  -- пришлось бы сверять со списком переводов, и добавление третьего
  -- языка молча сломало бы удаление.
  if upper(btrim(coalesce(p_confirm, ''))) <> 'DELETE' then
    raise exception 'Удаление не подтверждено'
      using errcode = 'check_violation';
  end if;

  -- Блокируем строку: два одновременных нажатия не должны
  -- обезличивать профиль дважды и слать два уведомления.
  select p.is_admin, p.deleted_at
    into v_is_admin, v_deleted
    from public.profiles p
   where p.id = v_user
   for update;

  if v_is_admin is null then
    raise exception 'Профиль не найден'
      using errcode = 'no_data_found';
  end if;

  -- Повторный вызов — не ошибка, но и делать нечего. Идемпотентность
  -- важна: человек мог нажать дважды на медленной сети.
  if v_deleted is not null then
    return jsonb_build_object(
      'already_deleted', true,
      'cars', 0, 'chats', 0, 'messages', 0
    );
  end if;

  -- Администратор себя удалить не может. См. шапку.
  if v_is_admin then
    raise exception 'Аккаунт администратора нельзя удалить из кабинета'
      using errcode = 'insufficient_privilege';
  end if;

  -- ------------------------------------------------------------
  -- 1) Считаем то, что уйдёт каскадом, ДО удаления.
  -- ------------------------------------------------------------
  -- После delete считать будет нечего, а числа нужны в ответе.
  -- Диалоги и сообщения считаем по ОБЕ стороны: человек мог и
  -- продавать, и писать другим продавцам, и уходит то и другое.
  select count(*)::integer into v_cars
    from public.cars c where c.user_id = v_user;

  select count(*)::integer into v_chats
    from public.chats ch
   where ch.buyer_id = v_user or ch.seller_id = v_user;

  select count(*)::integer into v_messages
    from public.messages m
    join public.chats ch on ch.id = m.chat_id
   where ch.buyer_id = v_user or ch.seller_id = v_user;

  -- ------------------------------------------------------------
  -- 2) Диалоги.
  -- ------------------------------------------------------------
  -- ЯВНО, А НЕ КАСКАДОМ. Каскад от cars забрал бы только диалоги по
  -- ЕГО объявлениям — те, где он продавец. Диалоги, где он писал
  -- другим продавцам, остались бы жить с его сообщениями внутри, и
  -- «полное удаление» оказалось бы неполным ровно в той части,
  -- которая и есть переписка.
  --
  -- messages и chat_prefs (закрепления) уходят каскадом от chats.
  delete from public.chats ch
   where ch.buyer_id = v_user or ch.seller_id = v_user;

  -- ------------------------------------------------------------
  -- 3) Объявления.
  -- ------------------------------------------------------------
  -- Каскад забирает car_images, favorites, hidden_cars, listing_stats
  -- и журнал просмотров. Файлы фотографий остаются в бакете и уходят
  -- ежедневной чисткой (0123) — см. шапку.
  delete from public.cars c where c.user_id = v_user;

  -- ------------------------------------------------------------
  -- 4) Прочие следы пользователя.
  -- ------------------------------------------------------------
  -- Всё это ушло бы каскадом при удалении auth.users, но мы строку
  -- auth.users не трогаем — значит убираем явно. Порядок между
  -- таблицами не важен: связей между ними нет.
  --
  -- Списки, где он что-то отмечал:
  delete from public.favorites        f where f.user_id    = v_user;
  delete from public.hidden_cars      h where h.user_id    = v_user;
  delete from public.notifications    n where n.user_id    = v_user;
  delete from public.saved_searches   s where s.user_id    = v_user;
  -- Журнал просмотров ЧУЖИХ объявлений: строки по его собственным ушли
  -- каскадом от cars, а «что он смотрел у других» — это история
  -- поведения, то есть ровно то, от чего он и уходит.
  delete from public.listing_view_log v where v.viewer_id  = v_user;

  -- Пуши: очередь неотправленных и токены устройств. Токен — это
  -- идентификатор конкретного телефона, и оставленный он означал бы,
  -- что удалённому аккаунту всё ещё можно что-то доставить.
  delete from public.push_queue       q where q.user_id    = v_user;
  delete from public.user_push_tokens t where t.user_id    = v_user;

  -- Личные настройки диалогов (закрепления) уже ушли каскадом от
  -- chats. Блокировки живут отдельно от диалогов и не привязаны ни к
  -- одному из них — их убираем явно, в обе стороны: и кого он
  -- заблокировал, и кто заблокировал его.
  delete from public.user_blocks      b where b.blocker_id = v_user
                                           or b.blocked_id = v_user;

  -- Заявки на статус салона: реквизиты компании, ИНН, регистрационный
  -- номер, телефон — всё это персональные данные заявителя.
  delete from public.dealer_applications a where a.user_id = v_user;

  -- ------------------------------------------------------------
  -- ЧТО ЗДЕСЬ СОЗНАТЕЛЬНО НЕ УДАЛЯЕТСЯ.
  -- ------------------------------------------------------------
  -- wallet_transactions и transactions — финансовая история. Её
  -- сохранность прямо заложена в схеме: в обеих таблицах ссылки на
  -- удаляемые сущности стоят on delete set null именно с пометкой
  -- «финансовая история должна сохраняться» (0009, 0043). Записи о
  -- движении денег хранятся по требованиям учёта и не являются
  -- персональными данными сами по себе: после обезличивания профиля
  -- по ним нельзя установить человека — остаётся только id.
  --
  -- reviews — отзывы по завершённым арендам. Каскад от cars уже забрал
  -- отзывы о его объявлениях; отзывы, которые он оставил другим,
  -- остаются как часть их рейтинга. Удалить их значило бы задним
  -- числом переписать репутацию людей, которые к его уходу отношения
  -- не имеют. Имя автора в них не хранится — только customer_id.

  -- ------------------------------------------------------------
  -- 5) Аватар из хранилища.
  -- ------------------------------------------------------------
  -- Единственный файл, который удаляем прямо здесь: путь известен
  -- («<uid>/...», см. 0038), он один, и ждать ради него суточной
  -- отсрочки чистки незачем. Строка storage.objects удаляется, а сам
  -- файл в S3 остаётся — Postgres не умеет HTTP к Storage API. Для
  -- аватара это приемлемо: без строки он недоступен по публичному
  -- адресу и не связан ни с чем.
  delete from storage.objects o
   where o.bucket_id = 'avatars'
     and o.name like v_user::text || '/%';

  -- ------------------------------------------------------------
  -- 6) Обезличивание профиля.
  -- ------------------------------------------------------------
  -- ПОЧТА ЗАМЕНЯЕТСЯ ЗАГЛУШКОЙ, А НЕ ОБНУЛЯЕТСЯ: колонка объявлена
  -- not null unique (0002). Заглушка построена на id, поэтому
  -- уникальна по определению, и домен example.invalid — специально
  -- зарезервированный RFC 2606 несуществующий: письмо по такому
  -- адресу не уйдёт даже случайно.
  --
  -- Освобождение прежнего адреса — не побочный эффект, а требование:
  -- человек имеет право вернуться на площадку и завести новый аккаунт
  -- на ту же почту, а уникальный индекс не пустил бы его, останься
  -- адрес в строке.
  update public.profiles p
     set email                = 'deleted+' || p.id::text || '@example.invalid',
         full_name            = null,
         phone                = null,
         avatar_url           = null,
         locale               = null,
         -- Витрина салона (0043, 0095, 0098) и реквизиты (0085).
         seller_kind          = 'private',
         company_name         = null,
         logo_url             = null,
         description          = null,
         dealer_phone         = null,
         website              = null,
         opening_hours        = null,
         company_city         = null,
         cover_url            = null,
         tagline              = null,
         contact_person       = null,
         contract_date        = null,
         trusted_seller       = false,
         -- Документы KYC (0019): ссылки на паспорт и права — самые
         -- чувствительные данные во всей таблице.
         passport_url         = null,
         driver_license_url   = null,
         verification_comment = null,
         deleted_at           = now(),
         updated_at           = now()
   where p.id = v_user;

  -- ПРОДОЛЖЕНИЕ — В МИГРАЦИИ 0127. Здесь функция ещё не освобождает
  -- учётные данные в auth.users, и из-за этого прежний адрес остаётся
  -- занят мёртвой строкой: вернуться на площадку с той же почты
  -- нельзя. 0127 дописывает этот шаг.

  return jsonb_build_object(
    'already_deleted', false,
    'cars',     coalesce(v_cars, 0),
    'chats',    coalesce(v_chats, 0),
    'messages', coalesce(v_messages, 0)
  );
end;
$fn$;

comment on function public.delete_my_account(text)
  is 'Удаление своего аккаунта: объявления, диалоги, заявки и прочие следы удаляются, профиль обезличивается, вход запрещается (deleted_at). Требует p_confirm = DELETE. Необратимо (0126)';

grant execute on function public.delete_my_account(text) to authenticated;
