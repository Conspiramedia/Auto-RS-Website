-- ============================================================
-- 0142. Сверка списка объявлений по id: cars_by_ids_public.
-- ============================================================
-- ЗАЧЕМ. Блок «Недавно смотрели» на сайте хранит СНИМОК карточки в
-- localStorage браузера (components/RecentlyViewed.tsx) и не обращался
-- к базе вовсе. Из-за этого снятое с публикации объявление продолжало
-- висеть в блоке: продавец нажал «снять» в кабинете, объявление ушло
-- из каталога, а в истории просмотров оно осталось — с прежней ценой,
-- прежним фото и ссылкой, которая ведёт на страницу «не найдено».
--
-- Ровно та же беда у проданных, отклонённых, просроченных и удалённых
-- объявлений, а также у машин, которые продавец успел подешеветь:
-- снимок не обновлялся никогда с момента просмотра.
--
-- ПОЧЕМУ НЕ ХРАНИТЬ ТОЛЬКО ID И ЧИТАТЬ ВСЁ С СЕРВЕРА. Так и делаем
-- теперь, но снимок из хранилища остаётся как «первый кадр»: он даёт
-- блоку отрисоваться сразу, без ожидания сети, а ответ этой функции
-- его заменяет и вычищает всё, чего в выдаче нет. Один запрос на
-- четыре id — цена, которую блок стоит.
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ ФУНКЦИЯ, А НЕ ПАРАМЕТР В search_cars_public.
-- Там сортировка, пагинация, перемешка промо и два десятка фильтров —
-- всё это здесь мешает: порядок задаёт клиент (история просмотров),
-- а не сервер. Добавлять к чужой сигнатуре параметр ради обратной
-- задачи значило бы усложнить функцию, которую вызывают оба клиента.
--
-- ВИДИМОСТЬ ТА ЖЕ, ЧТО У КАТАЛОГА: только status = 'active'. Всё
-- остальное — снятое, проданное, на модерации, отклонённое,
-- просроченное — из выдачи выпадает, и клиент по отсутствию id
-- понимает, что запись пора выбросить.
--
-- БИТЫЕ И РАЗБОРКА (0139) ЗДЕСЬ НЕ СКРЫВАЮТСЯ, в отличие от каталога.
-- Причина: человек это объявление уже открывал сам — прятать от него
-- то, что он осознанно смотрел, значит сделать вид, что объявление
-- исчезло. Фильтр каталога защищает выдачу от мусора при СРАВНЕНИИ
-- цен, а история просмотров ничего не сравнивает.
--
-- ФУНКЦИЯ ТОЛЬКО ДОБАВЛЯЕТСЯ: существующие сигнатуры не трогаются,
-- контракт с мобильным приложением не меняется.
-- ============================================================

create or replace function public.cars_by_ids_public(
  -- Ограничение сверху ставит сама функция (см. limit ниже): вызов с
  -- тысячей id не должен превращаться в бесплатную выгрузку каталога.
  p_ids uuid[]
)
returns table (
  id               uuid,
  brand            text,
  model            text,
  year             integer,
  mileage          integer,
  currency         text,
  sale_price       numeric,
  rent_price_daily numeric,
  is_for_sale      boolean,
  is_for_rent      boolean,
  city             text,
  status           text,
  is_promoted      boolean,
  availability     text,
  condition        text,
  seller_kind      text,
  photo_url        text
)
language sql
stable
security definer
set search_path = public
as $$
  select
    c.id, c.brand, c.model, c.year, c.mileage,
    c.currency::text, c.sale_price, c.rent_price_daily,
    c.is_for_sale, c.is_for_rent, c.city,
    c.status::text,
    -- Действует ли продвижение прямо сейчас — то же выражение, что в
    -- get_my_favorites (0130) и get_seller_listings (0050).
    (c.is_vip and c.boosted_until is not null and c.boosted_until > now()),
    c.availability::text,
    c.condition::text,
    p.seller_kind::text,
    -- site_url здесь НЕТ намеренно, в отличие от get_my_favorites:
    -- ссылку на объявление карточка сайта строит сама из id и локали
    -- (localeHref в CarCard), а абсолютный адрес нужен только письмам.
    (select ci.image_url from public.car_images ci
      where ci.car_id = c.id
      order by ci.order_index asc
      limit 1)
  from public.cars c
  -- left join: у объявления удалённой учётной записи профиля нет
  -- (0126), и внутреннее соединение выбросило бы его молча.
  left join public.profiles p on p.id = c.user_id
  where c.id = any(coalesce(p_ids, '{}'::uuid[]))
    and c.status::text = 'active'
  -- Порядок не задаём намеренно: его определяет клиент по своей
  -- истории просмотров. Сортировать здесь по created_at значило бы
  -- навязать блоку чужой порядок, который клиенту всё равно пришлось
  -- бы переставлять.
  limit 50;
$$;

comment on function public.cars_by_ids_public(uuid[])
  is 'Сверка списка объявлений по id: возвращает только активные, с полями карточки каталога. Для блока «Недавно смотрели» (0142)';

-- Публичное чтение: блок работает и у гостя, который не входил в
-- аккаунт, — история просмотров живёт в его браузере.
grant execute on function public.cars_by_ids_public(uuid[]) to anon, authenticated;
