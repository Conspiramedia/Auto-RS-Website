-- ============================================================
-- AUTO.RS — Миграция 0111: нормализация описания при подаче
-- ============================================================
-- ЗАЧЕМ. Продавцы копируют описание с других площадок вместе с
-- разметкой. В первом же реальном объявлении оказалось 19 табуляций
-- вида «Pogon:<TAB>4x4 (stalni pogon na sva četiri točka)»: текст
-- вставлен таблицей характеристик. На сайте описание выводится с
-- whitespace-pre-line, табуляция по умолчанию равна восьми символам,
-- и такая строка не влезала в ширину телефона — страница уезжала за
-- правый край экрана.
--
-- Вёрстка это уже переживает ([tab-size:2] и break-words в
-- CarPageView), но чинить на выводе каждое кривое вхождение — путь в
-- никуда: то же описание читают мобильное приложение, письма,
-- Telegram-уведомления и JSON-LD для поисковика, и в каждом месте
-- пришлось бы повторять защиту. Чистим один раз на входе.
--
-- ЧТО ДЕЛАЕМ И ЧЕГО НЕ ДЕЛАЕМ:
--   • табуляция → пробел. Колоночная вёрстка в описании бессмысленна:
--     ширина колонки нигде не воспроизводится, а сам факт разделения
--     «поле — значение» остаётся виден по двоеточию;
--   • \r\n и \r → \n. Windows-переносы дают лишние пустые строки при
--     выводе и ломают подсчёт длины;
--   • три и более переноса подряд → два. Пустая строка между абзацами
--     нужна, десять подряд — след копирования;
--   • пробелы и табы в конце строки → убираем;
--   • крайние пробелы всего текста → убираем (btrim, как и раньше).
--
--   НЕ трогаем: регистр, пунктуацию, эмодзи, сам язык и одиночные
--   переносы строк. Описание — авторский текст продавца, и приводить
--   его к «правильному» виду мы не вправе: это его объявление и его
--   интонация. Убираем только следы переноса из чужого редактора.
--
-- ГДЕ ЭТО ЖИВЁТ. В BEFORE-триггере, а не в create_car_v3 /
-- update_car_v3. Причин две:
--   1) описание пишут несколько путей (два RPC, админские правки,
--      будущий импорт), и в каждом легко забыть повторить обработку;
--   2) сигнатуры RPC остаются нетронутыми — приложение и сайт
--      продолжают вызывать их как раньше, менять клиенты не нужно.
--
-- Переиспользуем триггер из 0110: он уже срабатывает ровно тогда,
-- когда меняется описание, и второй триггер на то же поле означал бы
-- зависимость от порядка их выполнения (алфавитного — то есть
-- случайного по смыслу).
--
-- ВАЖНО: нормализация идёт ДО определения языка. f_detect_lang ищет
-- слова по границам \m…\M, и таб между «Pogon:» и «4x4» границей
-- является — на результат это не влияет, но порядок «сначала чистим,
-- потом анализируем» надёжнее на будущее.
-- ============================================================

-- ------------------------------------------------------------
-- 1. ФУНКЦИЯ НОРМАЛИЗАЦИИ
-- ------------------------------------------------------------
create or replace function public.f_clean_description(txt text)
returns text
language sql
immutable
set search_path = public
as $$
  select nullif(
    btrim(
      -- 4) три и более переноса подряд → ровно два (один пустой абзац)
      regexp_replace(
        -- 3) пробелы и табы в конце каждой строки — убрать
        regexp_replace(
          -- 2) CRLF и одиночный CR → LF
          regexp_replace(
            -- 1) табуляция → обычный пробел
            replace(coalesce(txt, ''), E'\t', ' '),
            E'\r\n?', E'\n', 'g'
          ),
          E'[ \t]+\n', E'\n', 'g'
        ),
        E'\n{3,}', E'\n\n', 'g'
      )
    ),
    ''
  );
$$;

comment on function public.f_clean_description(text)
  is 'Чистит описание от следов копирования: табуляции → пробелы, CRLF → LF, хвостовые пробелы строк, 3+ переносов → 2. Авторский текст (регистр, пунктуацию, язык) не трогает';

-- ------------------------------------------------------------
-- 2. ТРИГГЕР: чистка + определение языка
-- ------------------------------------------------------------
-- Заменяем функцию из 0110, добавляя нормализацию перед анализом.
-- Сам триггер trg_cars_detect_lang пересоздавать не нужно: он
-- ссылается на функцию по имени.
create or replace function public.trg_set_description_lang()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if tg_op = 'INSERT'
     or new.description is distinct from old.description then
    -- Сначала чистим текст, затем определяем язык уже по чистому.
    new.description      := public.f_clean_description(new.description);
    new.description_lang := public.f_detect_lang(new.description);
  end if;
  return new;
end;
$$;

comment on function public.trg_set_description_lang()
  is 'BEFORE-триггер cars: нормализует описание (f_clean_description) и проставляет description_lang (f_detect_lang) при вставке и изменении описания';

-- ------------------------------------------------------------
-- 3. ЧИСТКА УЖЕ СОХРАНЁННЫХ ОПИСАНИЙ
-- ------------------------------------------------------------
-- Триггер работает только на новые записи и правки, поэтому
-- существующие объявления чистим разом. Условие where не даёт
-- переписать строки, которым чистка ничего не меняет: лишние UPDATE
-- дёргали бы updated_at и, через него, сортировку каталога.
--
-- Идемпотентно: повторный накат не найдёт строк для обновления.
update public.cars
   set description = public.f_clean_description(description)
 where description is not null
   and description is distinct from public.f_clean_description(description);
