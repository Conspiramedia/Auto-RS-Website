-- ============================================================
-- AUTO.RS — Миграция 0128: удаление аккаунта подтверждается почтой
-- ============================================================
-- ЧТО МЕНЯЕТСЯ. Раньше удаление подтверждалось набором слова DELETE
-- (0126). Слово одинаково у всех, набирается не глядя и не отвечает
-- на главный вопрос — «точно ли это ваш аккаунт». По заданию
-- заказчика подтверждением становится ПОЧТА, на которую человек
-- регистрировался: её знает владелец аккаунта и не знает тот, кто
-- сел за чужую незакрытую сессию.
--
-- ------------------------------------------------------------
-- ЛЕСТНИЦА, А НЕ ОДНА ПОЧТА, И ЭТО НЕ УСЛОЖНЕНИЕ РАДИ УСЛОЖНЕНИЯ.
-- ------------------------------------------------------------
-- profiles.email стала nullable ещё в 0035: у аккаунтов, заведённых
-- по SMS до перехода на почтовый вход, почты нет вовсе. Потребуй мы
-- почту безусловно — такой человек не смог бы удалить аккаунт
-- никогда, и право на забвение, ради которого всё это делалось,
-- снова превратилось бы в обращение в поддержку. Поэтому:
--
--   есть почта             → вводит почту;
--   почты нет, есть номер  → вводит номер телефона;
--   нет ни того ни другого → слово DELETE, как раньше.
--
-- Последняя ступень не лазейка: у такого профиля просто нечего
-- сверять. Запретить ему удаление значило бы наказать человека за
-- то, каким способом он когда-то зарегистрировался.
--
-- РЕШАЕТ СЕРВЕР. Какую ступень применить, определяется внутри
-- функции по данным профиля, а не приходит от клиента: иначе
-- достаточно было бы прислать «у меня нет почты», чтобы проверка
-- свелась к слову DELETE.
--
-- ------------------------------------------------------------
-- ЗАЧЕМ ОТДЕЛЬНАЯ get_my_delete_confirmation.
-- ------------------------------------------------------------
-- Интерфейс обязан сказать, ЧТО набирать, до того как человек начнёт
-- набирать. Показывать «введите почту» тому, у кого её нет, —
-- тупик, из которого нет выхода: поле не примет ничего.
--
-- Функция отдаёт ТОЛЬКО ВИД подтверждения ('email' | 'phone' |
-- 'word'), но не само значение. Возвращать почту было бы удобнее для
-- вёрстки (подставить в подсказку), и именно поэтому так делать
-- нельзя: подсказка с готовым ответом отменяет смысл проверки —
-- сидящий в чужой сессии просто прочитал бы адрес с экрана.
--
-- СОВМЕСТИМОСТЬ С ПРИЛОЖЕНИЕМ. Сигнатура delete_my_account(text) и
-- набор полей ответа не изменились: меняется только то, ЧТО функция
-- ждёт в p_confirm. Приложение эту RPC пока не зовёт вовсе (удаление
-- есть только на сайте), так что ломать нечего; когда позовёт —
-- спросит вид подтверждения той же новой функцией.
-- ============================================================


-- ------------------------------------------------------------
-- get_my_delete_confirmation — что человек должен ввести
-- ------------------------------------------------------------
-- stable и без побочных действий: интерфейс зовёт её при открытии
-- профиля, а не в момент удаления.
create or replace function public.get_my_delete_confirmation()
returns text
language plpgsql
stable
security definer
set search_path = public
as $fn$
declare
  v_user  uuid := auth.uid();
  v_email text;
  v_phone text;
begin
  if v_user is null then
    raise exception 'Требуется авторизация'
      using errcode = 'insufficient_privilege';
  end if;

  select p.email, p.phone
    into v_email, v_phone
    from public.profiles p
   where p.id = v_user;

  -- Профиля нет — отвечаем 'word'. Ошибку бросать незачем: до
  -- удаления такой человек всё равно не дойдёт (там своя проверка),
  -- а экран профиля из-за подсказки падать не должен.
  if nullif(btrim(coalesce(v_email, '')), '') is not null then
    return 'email';
  elsif nullif(btrim(coalesce(v_phone, '')), '') is not null then
    return 'phone';
  else
    return 'word';
  end if;
end;
$fn$;

comment on function public.get_my_delete_confirmation()
  is 'Вид подтверждения удаления аккаунта для текущего пользователя: email | phone | word. Само значение НЕ возвращает (0128)';

grant execute on function public.get_my_delete_confirmation() to authenticated;


-- ------------------------------------------------------------
-- delete_my_account — подтверждение учётными данными
-- ------------------------------------------------------------
-- Тело переписано целиком: проверка подтверждения переехала ПОСЛЕ
-- чтения профиля (ей нужны почта и телефон), остальные шаги не
-- изменились.
create or replace function public.delete_my_account(p_confirm text)
returns jsonb
language plpgsql
security definer
set search_path = public, storage
as $fn$
declare
  v_user     uuid := auth.uid();
  v_is_admin boolean;
  v_deleted  timestamptz;
  -- Учётные данные профиля. Нужны дважды: сверить подтверждение (блок
  -- ниже) и, если сверка прошла, затереть их при обезличивании.
  v_email    text;
  v_phone    text;
  -- Что человек прислал в качестве подтверждения, после обрезки
  -- пробелов: сравнивается по-разному в зависимости от ступени.
  v_given    text;
  v_cars     integer;
  v_chats    integer;
  v_messages integer;
begin
  if v_user is null then
    raise exception 'Требуется авторизация'
      using errcode = 'insufficient_privilege';
  end if;

  -- Блокируем строку: два одновременных нажатия не должны
  -- обезличивать профиль дважды и слать два уведомления.
  select p.is_admin, p.deleted_at, p.email, p.phone
    into v_is_admin, v_deleted, v_email, v_phone
    from public.profiles p
   where p.id = v_user
   for update;

  if v_is_admin is null then
    raise exception 'Профиль не найден'
      using errcode = 'no_data_found';
  end if;

  -- Повторный вызов — не ошибка, но и делать нечего. Идемпотентность
  -- важна: человек мог нажать дважды на медленной сети.
  if v_deleted is not null then
    return jsonb_build_object(
      'already_deleted', true,
      'cars', 0, 'chats', 0, 'messages', 0
    );
  end if;

  -- Администратор себя удалить не может. См. шапку.
  if v_is_admin then
    raise exception 'Аккаунт администратора нельзя удалить из кабинета'
      using errcode = 'insufficient_privilege';
  end if;

  -- ------------------------------------------------------------
  -- ПОДТВЕРЖДЕНИЕ УЧЁТНЫМИ ДАННЫМИ (0128).
  -- ------------------------------------------------------------
  -- Второй рубеж на стороне базы: RPC можно позвать из консоли
  -- браузера одной строкой, и без этой проверки диалог защищал бы
  -- только от случайного клика.
  --
  -- ЧТО ИМЕННО ЖДЁМ — РЕШАЕТ СЕРВЕР, А НЕ КЛИЕНТ. Почта в profiles
  -- стала nullable ещё в 0035: у аккаунтов, заведённых по SMS, её нет
  -- вовсе. Требуй мы почту безусловно, такой человек не смог бы
  -- удалить аккаунт НИКОГДА — право на забвение снова стало бы
  -- ручным обращением в поддержку. Поэтому лестница:
  --   есть почта            → вводит почту;
  --   почты нет, есть номер → вводит номер;
  --   нет ни того ни другого → слово DELETE.
  -- Последняя ступень — не лазейка: у такого профиля просто нет
  -- данных, которые можно было бы сверить, а запретить ему удаление
  -- значило бы наказать за то, как он когда-то регистрировался.
  --
  -- ПОЧЕМУ ЭТО ЛУЧШЕ СЛОВА DELETE, которое стояло здесь раньше. Слово
  -- одинаково у всех, его можно набрать не глядя, и оно не отвечает
  -- на вопрос «а точно ли это мой аккаунт». Почта отвечает: человек,
  -- сидящий в чужой открытой сессии, её не знает. Ту же роль играет
  -- номер.
  --
  -- СРАВНЕНИЕ НОРМАЛИЗОВАНО. Почта — регистронезависимо (адреса на
  -- практике регистр не различают, а RFC-строгость тут обернулась бы
  -- отказом человеку, набравшему Ivan@ вместо ivan@). Телефон — по
  -- цифрам: в профиле он может лежать как «+381 61 234 567», а
  -- набирают его без пробелов. Пустой ввод не проходит ни в одной
  -- ветке.
  v_given := btrim(coalesce(p_confirm, ''));

  if nullif(btrim(coalesce(v_email, '')), '') is not null then
    if lower(btrim(v_email)) <> lower(v_given) then
      raise exception 'Введённая почта не совпадает с почтой аккаунта'
        using errcode = 'check_violation';
    end if;

  elsif nullif(btrim(coalesce(v_phone, '')), '') is not null then
    -- regexp_replace с флагом g оставляет одни цифры: так «+381 61 234
    -- 567», «381612 34567» и «+381612 34567» сравниваются как один и
    -- тот же номер.
    if regexp_replace(v_phone, '[^0-9]', '', 'g')
       <> regexp_replace(v_given, '[^0-9]', '', 'g')
       or btrim(v_given) = '' then
      raise exception 'Введённый номер не совпадает с номером аккаунта'
        using errcode = 'check_violation';
    end if;

  else
    if upper(v_given) <> 'DELETE' then
      raise exception 'Удаление не подтверждено'
        using errcode = 'check_violation';
    end if;
  end if;

  -- ------------------------------------------------------------
  -- 1) Считаем то, что уйдёт каскадом, ДО удаления.
  -- ------------------------------------------------------------
  -- После delete считать будет нечего, а числа нужны в ответе.
  -- Диалоги и сообщения считаем по ОБЕ стороны: человек мог и
  -- продавать, и писать другим продавцам, и уходит то и другое.
  select count(*)::integer into v_cars
    from public.cars c where c.user_id = v_user;

  select count(*)::integer into v_chats
    from public.chats ch
   where ch.buyer_id = v_user or ch.seller_id = v_user;

  select count(*)::integer into v_messages
    from public.messages m
    join public.chats ch on ch.id = m.chat_id
   where ch.buyer_id = v_user or ch.seller_id = v_user;

  -- ------------------------------------------------------------
  -- 2) Диалоги.
  -- ------------------------------------------------------------
  -- ЯВНО, А НЕ КАСКАДОМ. Каскад от cars забрал бы только диалоги по
  -- ЕГО объявлениям — те, где он продавец. Диалоги, где он писал
  -- другим продавцам, остались бы жить с его сообщениями внутри, и
  -- «полное удаление» оказалось бы неполным ровно в той части,
  -- которая и есть переписка.
  --
  -- messages и chat_prefs (закрепления) уходят каскадом от chats.
  delete from public.chats ch
   where ch.buyer_id = v_user or ch.seller_id = v_user;

  -- ------------------------------------------------------------
  -- 3) Объявления.
  -- ------------------------------------------------------------
  -- Каскад забирает car_images, favorites, hidden_cars, listing_stats
  -- и журнал просмотров. Файлы фотографий остаются в бакете и уходят
  -- ежедневной чисткой (0123) — см. шапку.
  delete from public.cars c where c.user_id = v_user;

  -- ------------------------------------------------------------
  -- 4) Прочие следы пользователя.
  -- ------------------------------------------------------------
  -- Всё это ушло бы каскадом при удалении auth.users, но мы строку
  -- auth.users не трогаем — значит убираем явно. Порядок между
  -- таблицами не важен: связей между ними нет.
  --
  -- Списки, где он что-то отмечал:
  delete from public.favorites        f where f.user_id    = v_user;
  delete from public.hidden_cars      h where h.user_id    = v_user;
  delete from public.notifications    n where n.user_id    = v_user;
  delete from public.saved_searches   s where s.user_id    = v_user;
  -- Журнал просмотров ЧУЖИХ объявлений: строки по его собственным ушли
  -- каскадом от cars, а «что он смотрел у других» — это история
  -- поведения, то есть ровно то, от чего он и уходит.
  delete from public.listing_view_log v where v.viewer_id  = v_user;

  -- Пуши: очередь неотправленных и токены устройств. Токен — это
  -- идентификатор конкретного телефона, и оставленный он означал бы,
  -- что удалённому аккаунту всё ещё можно что-то доставить.
  delete from public.push_queue       q where q.user_id    = v_user;
  delete from public.user_push_tokens t where t.user_id    = v_user;

  -- Личные настройки диалогов (закрепления) уже ушли каскадом от
  -- chats. Блокировки живут отдельно от диалогов и не привязаны ни к
  -- одному из них — их убираем явно, в обе стороны: и кого он
  -- заблокировал, и кто заблокировал его.
  delete from public.user_blocks      b where b.blocker_id = v_user
                                           or b.blocked_id = v_user;

  -- Заявки на статус салона: реквизиты компании, ИНН, регистрационный
  -- номер, телефон — всё это персональные данные заявителя.
  delete from public.dealer_applications a where a.user_id = v_user;

  -- ------------------------------------------------------------
  -- ЧТО ЗДЕСЬ СОЗНАТЕЛЬНО НЕ УДАЛЯЕТСЯ.
  -- ------------------------------------------------------------
  -- wallet_transactions и transactions — финансовая история. Её
  -- сохранность прямо заложена в схеме: в обеих таблицах ссылки на
  -- удаляемые сущности стоят on delete set null именно с пометкой
  -- «финансовая история должна сохраняться» (0009, 0043). Записи о
  -- движении денег хранятся по требованиям учёта и не являются
  -- персональными данными сами по себе: после обезличивания профиля
  -- по ним нельзя установить человека — остаётся только id.
  --
  -- reviews — отзывы по завершённым арендам. Каскад от cars уже забрал
  -- отзывы о его объявлениях; отзывы, которые он оставил другим,
  -- остаются как часть их рейтинга. Удалить их значило бы задним
  -- числом переписать репутацию людей, которые к его уходу отношения
  -- не имеют. Имя автора в них не хранится — только customer_id.

  -- ------------------------------------------------------------
  -- 5) Аватар из хранилища.
  -- ------------------------------------------------------------
  -- Единственный файл, который удаляем прямо здесь: путь известен
  -- («<uid>/...», см. 0038), он один, и ждать ради него суточной
  -- отсрочки чистки незачем. Строка storage.objects удаляется, а сам
  -- файл в S3 остаётся — Postgres не умеет HTTP к Storage API. Для
  -- аватара это приемлемо: без строки он недоступен по публичному
  -- адресу и не связан ни с чем.
  delete from storage.objects o
   where o.bucket_id = 'avatars'
     and o.name like v_user::text || '/%';

  -- ------------------------------------------------------------
  -- 6) Обезличивание профиля.
  -- ------------------------------------------------------------
  -- ПОЧТА ЗАМЕНЯЕТСЯ ЗАГЛУШКОЙ, А НЕ ОБНУЛЯЕТСЯ: колонка объявлена
  -- not null unique (0002). Заглушка построена на id, поэтому
  -- уникальна по определению, и домен example.invalid — специально
  -- зарезервированный RFC 2606 несуществующий: письмо по такому
  -- адресу не уйдёт даже случайно.
  --
  -- Освобождение прежнего адреса — не побочный эффект, а требование:
  -- человек имеет право вернуться на площадку и завести новый аккаунт
  -- на ту же почту, а уникальный индекс не пустил бы его, останься
  -- адрес в строке.
  update public.profiles p
     set email                = 'deleted+' || p.id::text || '@example.invalid',
         full_name            = null,
         phone                = null,
         avatar_url           = null,
         locale               = null,
         -- Витрина салона (0043, 0095, 0098) и реквизиты (0085).
         seller_kind          = 'private',
         company_name         = null,
         logo_url             = null,
         description          = null,
         dealer_phone         = null,
         website              = null,
         opening_hours        = null,
         company_city         = null,
         cover_url            = null,
         tagline              = null,
         contact_person       = null,
         contract_date        = null,
         trusted_seller       = false,
         -- Документы KYC (0019): ссылки на паспорт и права — самые
         -- чувствительные данные во всей таблице.
         passport_url         = null,
         driver_license_url   = null,
         verification_comment = null,
         deleted_at           = now(),
         updated_at           = now()
   where p.id = v_user;

  -- ------------------------------------------------------------
  -- 7) Освобождение учётных данных в auth.users (0127).
  -- ------------------------------------------------------------
  -- БЕЗ ЭТОГО ШАГА ЧЕЛОВЕК ЗАПЕРТ НАВСЕГДА — см. шапку 0127. Кратко:
  -- GoTrue ищет пользователя по своей таблице, и оставленный там адрес
  -- означал бы, что повторная регистрация с той же почты открывает
  -- старую удалённую строку вместо новой.
  --
  -- Заглушка та же, что и в профиле: домен example.invalid
  -- зарезервирован RFC 2606 и не существует, письмо по нему не уйдёт
  -- даже случайно.
  update auth.users u
     set email              = 'deleted+' || u.id::text || '@example.invalid',
         phone              = null,
         -- Метаданные регистрации: там лежит full_name, переданный при
         -- заведении аккаунта (см. handle_new_user, 0002).
         raw_user_meta_data = '{}'::jsonb,
         updated_at         = now()
   where u.id = v_user;

  -- Идентичности провайдеров — записи «этот адрес принадлежит этому
  -- пользователю», по которым GoTrue и сопоставляет вход. Оставленная
  -- запись свела бы на нет освобождение почты выше: поиск шёл бы по
  -- ней и снова находил старую строку.
  delete from auth.identities i where i.user_id = v_user;

  -- Действующие сессии и токены обновления. Человек мог быть залогинен
  -- на другом устройстве или в приложении — без этого он продолжал бы
  -- ходить по площадке уже удалённым, пока не истечёт токен.
  --
  -- refresh_tokens.user_id объявлен там как text, а не uuid — это
  -- особенность схемы GoTrue, отсюда приведение типа.
  delete from auth.refresh_tokens r where r.user_id = v_user::text;
  delete from auth.sessions       s where s.user_id = v_user;

  return jsonb_build_object(
    'already_deleted', false,
    'cars',     coalesce(v_cars, 0),
    'chats',    coalesce(v_chats, 0),
    'messages', coalesce(v_messages, 0)
  );
end;
$fn$;

comment on function public.delete_my_account(text)
  is 'Удаление своего аккаунта: объявления, диалоги, заявки и прочие следы удаляются, профиль обезличивается, учётные данные в auth.users освобождаются, вход запрещается (deleted_at). Подтверждение — почта аккаунта, при её отсутствии телефон, иначе слово DELETE. Необратимо (0126, 0127, 0128)';

grant execute on function public.delete_my_account(text) to authenticated;
