-- ============================================================
-- RS AUTO — 0074. Счётчики бейджа шапки: сообщения + уведомления.
-- ============================================================
-- ЗАЧЕМ. Иконка кабинета в шапке убрана, и её место занял бейдж на
-- бургер-меню: один красный кружок с ОБЩИМ числом непрочитанного —
-- два сообщения плюс три уведомления показываются как «5». Внутри
-- меню те же цифры разложены по своим пунктам («Сообщения»,
-- «Уведомления»), поэтому клиенту нужны обе составляющие, а не
-- только сумма.
--
-- ПОЧЕМУ ОДНА RPC, А НЕ ДВЕ. Бейдж запрашивается на КАЖДОЙ странице
-- сайта у каждого вошедшего пользователя — это самый частый вызов из
-- всех, что есть у шапки. Две отдельные функции означали бы два
-- round-trip к базе на каждый переход; здесь оба счётчика считаются
-- в одном запросе и возвращаются одной строкой.
--
-- Существующая get_unread_count() НЕ ТРОГАЕТСЯ: её вызывает
-- приложение (бейдж таба «Сообщения»), и менять её сигнатуру
-- значило бы сломать выпущенные версии. Логика непрочитанных
-- сообщений здесь повторена дословно, включая исключение
-- заблокированных отправителей.
-- ============================================================

create or replace function public.get_badge_counts()
returns table (
  messages integer,
  notifications integer,
  total integer
)
language sql
stable
security definer
set search_path = public
as $$
  with m as (
    -- Непрочитанные входящие сообщения. Условия дословно совпадают
    -- с get_unread_count() из миграции 0044: чужие сообщения в моих
    -- чатах, без отправителей, которых я заблокировал.
    select count(*)::int as cnt
    from public.messages msg
    join public.chats ch on ch.id = msg.chat_id
    where msg.is_read = false
      and msg.sender_id <> auth.uid()
      and (ch.buyer_id = auth.uid() or ch.seller_id = auth.uid())
      and not exists (
        select 1 from public.user_blocks b
        where b.blocker_id = auth.uid()
          and b.blocked_id = msg.sender_id
      )
  ),
  n as (
    -- Непрочитанные уведомления. Идёт по частичному индексу
    -- idx_notifications_unread (user_id) where not is_read.
    select count(*)::int as cnt
    from public.notifications
    where user_id = auth.uid()
      and is_read = false
  )
  select
    m.cnt,
    n.cnt,
    -- Сумма считается на СЕРВЕРЕ, а не на клиенте: цифра в бейдже
    -- должна быть одна и та же в вебе и в приложении, а складывать
    -- её в двух клиентах — верный способ получить расхождение.
    (m.cnt + n.cnt)::int
  from m, n;
$$;

comment on function public.get_badge_counts()
  is 'Непрочитанные сообщения и уведомления одной строкой: бейдж бургер-меню в шапке сайта';

-- ------------------------------------------------------------
-- ПРАВА. Сначала revoke, потом grant — порядок обязателен.
-- ------------------------------------------------------------
-- Новая функция создаётся с execute для PUBLIC по умолчанию, а
-- миграция 0065 отзывала эти права РАЗОВО, по всем существовавшим
-- на тот момент функциям: на всё, что создано позже, её revoke не
-- распространяется. Без явного отзыва здесь get_badge_counts()
-- оказалась бы доступна анониму — проверено, аноним получал ответ.
--
-- Функция security definer, то есть исполняется с правами владельца,
-- и оставлять её открытой нельзя тем более. Данных анонима она не
-- раскроет (auth.uid() у него пуст, и вернутся нули), но это лишний
-- незащищённый вызов на публичном эндпоинте.
revoke execute on function public.get_badge_counts() from public;
revoke execute on function public.get_badge_counts() from anon;

-- Только вошедшим: функция целиком построена на auth.uid(),
-- у анонима она вернула бы нули и стоила бы лишнего запроса.
grant execute on function public.get_badge_counts() to authenticated;
