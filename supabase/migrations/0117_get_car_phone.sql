-- ============================================================
-- 0117 — get_car_phone: НОМЕР ПРОДАВЦА ПО ЗАПРОСУ ИЗ БРАУЗЕРА
-- ============================================================
-- ЗАЧЕМ ОТДЕЛЬНАЯ ФУНКЦИЯ, ЕСЛИ ТЕЛЕФОН ЕСТЬ В get_car_details.
--
-- Карточка объявления рендерится НА СЕРВЕРЕ и всегда под анонимным
-- ключом (lib/supabase.ts: persistSession false) — иначе страница
-- перешла бы в динамический рендер и потеряла кэш, на котором держится
-- SEO. Значит, при рендере auth.uid() пуст ДАЖЕ У ВОШЕДШЕГО, и после
-- 0116 телефон в серверных данных карточки всегда null: кнопка
-- «Показать номер» пропала у всех, включая покупателей с сессией.
--
-- Возвращать телефон в серверный рендер нельзя — он попал бы в HTML
-- страницы, которую отдают и краулеру, и это ровно то, что 0116
-- закрывала. Поэтому номер запрашивается ОТДЕЛЬНО и из браузера, где
-- сессия есть, в момент нажатия кнопки.
--
-- ПОЧЕМУ НЕ ПОВТОРНЫЙ ВЫЗОВ get_car_details. Та отдаёт три десятка
-- колонок, включая описание и данные продавца; тянуть их ради одного
-- поля на каждое нажатие — лишний трафик. Узкая функция отдаёт ровно
-- то, что нужно, и её права проще читать.
--
-- УСЛОВИЯ ВЫДАЧИ ТЕ ЖЕ, ЧТО В 0116, и это принципиально: разойдись они
-- — и одна из функций стала бы обходом другой.
--   * вошедший (auth.uid() is not null) — иначе anon собирал бы
--     контакты обходом каталога;
--   * объявление опубликовано (active или sold) — снятое не должно
--     приводить продавцу звонки;
--   * владелец и администратор — всегда, в том числе у снятого.
-- ============================================================

create or replace function public.get_car_phone(p_car_id uuid)
returns text
language sql
stable
security definer
set search_path = public
as $$
  select c.contact_phone
    from public.cars c
   where c.id = p_car_id
     and (
       -- Владельцу и администратору — без оглядки на статус.
       c.user_id = auth.uid()
       or public.is_admin()
       -- Остальным: только вошедшим и только по живому объявлению.
       or (auth.uid() is not null and c.status in ('active', 'sold'))
     );
$$;

comment on function public.get_car_phone(uuid)
  is 'Контактный телефон объявления. Только вошедшим и только по опубликованному объявлению; владельцу и админу — всегда (0117)';

-- Гостю функция недоступна на уровне прав, а не только логики: пустой
-- ответ он получил бы и так, но лишний вызов не должен доходить до
-- тела функции.
revoke all on function public.get_car_phone(uuid) from public, anon;
grant execute on function public.get_car_phone(uuid) to authenticated;
