-- ============================================================
-- AUTO.RS — Миграция 0114: шаблоны писем о сроке публикации
-- ============================================================
-- ЗАЧЕМ. email_queue.chk_email_template — белый список допустимых
-- template_key. Миграция 0113 добавила job expire_listings, который
-- ставит в очередь письма 'listing_expiring' и 'listing_expired', но
-- в список их не внесла.
--
-- ЧЕМ ЭТО ГРОЗИЛО. Вставка неизвестного ключа роняет не письмо, а
-- ТРАНЗАКЦИЮ ВЫЗЫВАЮЩЕГО: job падал бы целиком на первом же
-- объявлении с почтой у владельца, и не скрывалось бы НИ ОДНО
-- объявление — молча, ночью, до первой жалобы. Поймано тестом
-- (supabase/checks/0113_listing_expiry_test.sql) до попадания в
-- рабочий цикл: код 23514, chk_email_template.
--
-- Отдельной миграцией, а не правкой 0113: та уже применена, и
-- переписывать применённый файл нельзя — база и репозиторий разошлись
-- бы, а db push не заметил бы изменения.
--
-- ПОЛНЫЙ СПИСОК берётся из 0101 — это последняя редакция
-- ограничения, добавившая ключи заявок на статус салона
-- (dealer_app_approved / dealer_app_rejected). Скопировать список из
-- 0080, как сделано было сначала, значит потерять их: constraint
-- пересоздаётся целиком, и отсутствующий ключ роняет ALTER на уже
-- лежащих в очереди строках. Именно это и произошло при первом
-- накате — ошибка 23514 на строке с dealer_app_rejected.
--
-- Приём тот же, что в 0080 и 0101: constraint пересоздаётся с полным
-- списком. Порядок значений — как в 0080 плюс два новых в конец.
--
-- ВНИМАНИЕ ПРИ ДЕПЛОЕ: оба шаблона должны появиться и в Edge Function
-- (supabase/functions/send-email/templates.ts). Пока функция не
-- задеплоена, renderEmail вернёт null и письмо ляжет в failed с
-- внятной ошибкой — оно не потеряется, но и не уйдёт. Диспетчер
-- функции написан именно с расчётом на такое расхождение.
-- ============================================================

alter table public.email_queue
  drop constraint if exists chk_email_template;

alter table public.email_queue
  add constraint chk_email_template check (
    template_key in (
      'car_approved',           -- объявление одобрено, ссылка на карточку
      'car_rejected',           -- отклонено: причина + ссылка на /my
      'car_archived_by_admin',  -- снято администратором: причина + ссылка на /my
      'contact_received',       -- копия обращения автору
      'contact_admin',          -- обращение — администратору
      'dealer_lead_admin',      -- заявка салона — администратору
      'dealer_app_approved',    -- статус салона выдан: ссылка на витрину
      'dealer_app_rejected',    -- отказ по заявке салона: причина + профиль
      -- Новое (0114). Срок жизни объявления.
      'listing_expiring',       -- срок публикации истекает, ссылка на продление
      'listing_expired'         -- объявление скрыто, ссылка на продление
    )
  );
