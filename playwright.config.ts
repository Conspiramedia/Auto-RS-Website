// ЗАПУСК ВСЕГДА ПРОТИВ ЛОКАЛЬНОЙ СБОРКИ. baseURL смотрит на
// 127.0.0.1:3000, а сервер поднимается блоком webServer ниже. Боевой
// домен в тестах не участвует ни при каких условиях: подставить его
// нельзя даже переменной окружения — см. защиту в tests/env.ts, она
// падает с ошибкой, если адрес указывает наружу.
//
// ПОЧЕМУ 127.0.0.1, А НЕ localhost. На Windows localhost резолвится и
// в ::1, и в 127.0.0.1, и Node с Chromium периодически выбирают разные
// варианты — сервер слушает один адрес, браузер стучится в другой, и
// прогон падает с ECONNREFUSED без внятной причины. Числовой адрес
// снимает вопрос.
// ============================================================

import { defineConfig, devices } from '@playwright/test';

import { TEST_BASE_URL, TEST_PORT } from './tests/env';

// В CI ретраи нужны: на общей машине тест иногда падает из-за таймингов,
// и один повтор отличает мигание от настоящей поломки. Локально ретраев
// нет — там падение должно быть видно сразу.
const isCI = !!process.env.CI;

export default defineConfig({
  testDir: './tests/e2e',

  // Полный прогон не должен висеть вечно, если сервер не поднялся.
  timeout: 30_000,
  expect: { timeout: 10_000 },

  // Тесты внутри файла идут параллельно: они только читают страницы и
  // друг другу не мешают. Исключение помечается test.describe.serial.
  fullyParallel: true,

  // В CI запрет на .only: забытый .only тихо превращает прогон из
  // сотни тестов в один зелёный и создаёт ложное чувство покрытия.
  forbidOnly: isCI,
  retries: isCI ? 1 : 0,
  workers: isCI ? 2 : undefined,

  reporter: isCI
    ? [['github'], ['html', { open: 'never' }], ['list']]
    : [['html', { open: 'never' }], ['list']],

  use: {
    baseURL: TEST_BASE_URL,
    // Трейс и скриншот — только при падении: это артефакты для
    // разбора, а не для каждого зелёного прогона (иначе гигабайты).
    trace: 'retain-on-failure',
    screenshot: 'only-on-failure',
    video: 'retain-on-failure',
    // Сербская локаль по умолчанию: сайт живёт в Сербии, и часть
    // форматирования (числа, даты) зависит от локали браузера.
    locale: 'sr-RS',
    timezoneId: 'Europe/Belgrade',
  },

  projects: [
    // ------------------------------------------------------------
    // Desktop и mobile — оба обязательны (требование ТЗ и CLAUDE.md:
    // каждый экран проверяется на 360/768/1280).
    // ------------------------------------------------------------
    {
      name: 'chromium-desktop',
      use: {
        ...devices['Desktop Chrome'],
        // 1280×800 — целевой десктопный брейкпоинт проекта.
        viewport: { width: 1280, height: 800 },
      },
    },
    {
      name: 'chromium-mobile',
      use: {
        // Pixel 5 — 393px. Близко к целевым 360px и при этом реальное
        // устройство с настоящим user-agent и эмуляцией касаний:
        // hover-состояния на нём не срабатывают, а именно на этом
        // построено правило hover:* в tailwind.config.ts.
        ...devices['Pixel 5'],
      },
    },
  ],

  // ------------------------------------------------------------
  // Сервер под тесты.
  // ------------------------------------------------------------
  // Гоняем ПРОДАКШЕН-СБОРКУ (next build && next start), а не next dev.
  // Причина принципиальная: dev-сборка не делает статическую
  // генерацию, отдаёт другой HTML и вставляет дев-оверлеи, из-за
  // которых проверки SEO-тегов и hydration-ошибок теряют смысл —
  // мы бы тестировали то, что никогда не поедет на прод.
  // Порт 3100 (см. tests/env.ts): на 3000 обычно работает `next dev`
  // разработчика, и переиспользование его сервера означало бы прогон
  // тестов против дев-сборки.
  webServer: {
    command: `npm run build && npm run start -- --port ${TEST_PORT} --hostname 127.0.0.1`,
    url: TEST_BASE_URL,
    // Сборка Next занимает заметно больше дефолтных 60 секунд.
    timeout: 300_000,
    // Локально переиспользуем уже поднятый сервер — не пересобирать
    // сайт на каждый запуск отдельного теста. Риска подхватить чужой
    // процесс больше нет: порт 3100 занят только нашими прогонами.
    // В CI сервер всегда поднимается заново.
    reuseExistingServer: !isCI,
    stdout: 'pipe',
    stderr: 'pipe',
  },
});
