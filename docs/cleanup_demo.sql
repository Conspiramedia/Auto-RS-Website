-- ============================================================
-- RS AUTO — Удаление демо-данных сайта
-- ============================================================
-- КОГДА ВЫПОЛНЯТЬ: один раз, ПЕРЕД публичным запуском сайта.
-- Демо-объявления созданы миграцией 0054_seed_site_demo.sql
-- (репозиторий приложения) и предназначались только для проверки
-- вёрстки каталога, SEO-страниц и sitemap на непустой базе.
--
-- ГДЕ ВЫПОЛНЯТЬ: Supabase Dashboard → SQL Editor, под ролью владельца
-- проекта. Анонимный ключ сайта здесь не подойдёт: RLS запрещает
-- удаление чужих объявлений, а демо-продавец — не текущий пользователь.
--
-- ЧТО БУДЕТ УДАЛЕНО: 27 объявлений демо-продавца
-- 00000000-0000-4000-a000-0000000000de и сам этот пользователь.
--
-- ЧТО НЕ ПОСТРАДАЕТ: объявления реальных продавцов. Все демо-записи
-- принадлежат одному служебному пользователю и дополнительно помечены
-- строкой «[DEMO]» в описании — двойной признак, по которому их нельзя
-- перепутать с живыми данными.
--
-- СВЯЗАННЫЕ ЗАПИСИ удаляются автоматически внешними ключами
-- on delete cascade: car_images, favorites, listing_stats,
-- listing_view_log, hidden_cars, chats/messages, reviews.
-- Исключение — wallet_transactions.car_id (on delete set null):
-- финансовая история намеренно переживает удаление объявления.
-- У демо-продавца операций по балансу нет, но правило указано,
-- чтобы поведение не оказалось неожиданным.
-- ============================================================


-- ------------------------------------------------------------
-- ШАГ 1. ПРОВЕРКА ПЕРЕД УДАЛЕНИЕМ (ничего не меняет)
-- ------------------------------------------------------------
-- Выполните сначала этот запрос и убедитесь, что числа совпадают:
--   demo_cars = 27 (или сколько демо-объявлений вы ожидаете),
--   real_cars = число объявлений живых продавцов — они НЕ будут затронуты,
--   demo_marked_other_owner = 0 (метка [DEMO] не попала к реальному продавцу).
select
  (select count(*) from public.cars
    where user_id = '00000000-0000-4000-a000-0000000000de')  as demo_cars,
  (select count(*) from public.cars
    where user_id <> '00000000-0000-4000-a000-0000000000de') as real_cars,
  (select count(*) from public.cars
    where description like '%[DEMO]%'
      and user_id <> '00000000-0000-4000-a000-0000000000de') as demo_marked_other_owner;


-- ------------------------------------------------------------
-- ШАГ 2. УДАЛЕНИЕ
-- ------------------------------------------------------------
-- Обёрнуто в транзакцию: либо удаляется всё, либо ничего.
-- Если ШАГ 1 показал demo_marked_other_owner > 0 — не выполняйте этот
-- блок, сначала разберитесь, откуда у реального объявления метка [DEMO].

begin;

-- Объявления демо-продавца. Условие по user_id — основное: оно
-- гарантирует, что мы не заденем чужие записи. Проверка описания
-- добавлена как второй предохранитель на случай, если этим служебным
-- id по ошибке воспользовались для чего-то ещё.
delete from public.cars
where user_id = '00000000-0000-4000-a000-0000000000de'
  and description like '%[DEMO]%';

-- Сам демо-пользователь. profiles удалится каскадно
-- (profiles.id → auth.users.id on delete cascade).
delete from auth.users
where id = '00000000-0000-4000-a000-0000000000de';

commit;


-- ------------------------------------------------------------
-- ШАГ 3. КОНТРОЛЬ ПОСЛЕ УДАЛЕНИЯ
-- ------------------------------------------------------------
-- Оба числа должны быть 0.
select
  (select count(*) from public.cars
    where user_id = '00000000-0000-4000-a000-0000000000de') as demo_cars_left,
  (select count(*) from auth.users
    where id = '00000000-0000-4000-a000-0000000000de')      as demo_user_left;


