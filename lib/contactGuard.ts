// ПОИСК СОВПАДЕНИЙ.
// ------------------------------------------------------------
/**
 * Находит в описании все контактные данные.
 *
 * Возвращает совпадения, отсортированные по позиции и без пересечений:
 * один и тот же номер часто ловится двумя правилами сразу («вайбер
 * 060…» — и правилом мессенджера, и телефонным), и подсвечивать его
 * дважды незачем. Из пересекающихся оставляем более длинное — оно
 * описывает находку полнее.
 */
export function findContacts(text: string): ContactMatch[] {
  if (!text) return [];

  const scan = normalizeForScan(text);
  const found: ContactMatch[] = [];

  for (const { kind, re, raw } of RULES) {
    // Регулярки объявлены с флагом g и хранят lastIndex между
    // вызовами: создаём копию, иначе второй вызов findContacts начал бы
    // поиск с середины прошлого совпадения.
    const rx = new RegExp(re.source, re.flags);
    // Правила с raw смотрят на исходный текст: им важен регистр.
    // Индексы совпадают в обоих случаях — нормализация сохраняет длину.
    const haystack = raw ? text : scan;
    let m: RegExpExecArray | null;

    while ((m = rx.exec(haystack)) !== null) {
      // Пустое совпадение не сдвинуло бы lastIndex и зациклило цикл.
      // При текущих правилах невозможно, но защита стоит одну строку.
      if (m[0].length === 0) {
        rx.lastIndex += 1;
        continue;
      }

      found.push({
        kind,
        start: m.index,
        end: m.index + m[0].length,
        // Текст берём ИЗ ИСХОДНОЙ строки: нормализация сохраняет
        // длину, поэтому индексы совпадают, а показать продавцу надо
        // то, что он написал, а не приведённый к нижнему регистру
        // вариант.
        text: text.slice(m.index, m.index + m[0].length),
      });
    }
  }

  if (found.length === 0) return [];

  // Схлопывание пересечений: сортируем по началу, при равном начале —
  // длинное вперёд, затем отбрасываем всё, что попало внутрь уже
  // принятого совпадения.
  found.sort((a, b) => a.start - b.start || b.end - a.end);

  const merged: ContactMatch[] = [];
  for (const item of found) {
    const last = merged[merged.length - 1];
    if (last && item.start < last.end) {
      // Пересекается с предыдущим. Если новое кончается позже —
      // расширяем предыдущее, чтобы подсветка накрыла номер целиком.
      if (item.end > last.end) {
        last.end = item.end;
        last.text = text.slice(last.start, last.end);
      }
      continue;
    }
    merged.push({ ...item });
  }

  return merged;
}

/**
 * Быстрая проверка «есть ли контакты» — для гейта отправки формы.
 */
export function hasContacts(text: string): boolean {
  return findContacts(text).length > 0;
}

// ------------------------------------------------------------
// ДЛИНА ОПИСАНИЯ.
// ------------------------------------------------------------
// Границы вынесены в константы: их знают форма (счётчик и maxLength),
// валидатор ниже и SQL-констрейнт chk_cars_description_len (0136).
// Держать три копии одного числа в трёх местах — верный способ
// однажды поменять его в двух.
//
// МИНИМУМ 30 СИМВОЛОВ. «Продаю» и «срочно» — не описание: покупатель
// уходит на объявление, где написано про состояние и комплектацию.
// Тридцати хватает на осмысленную фразу и не хватает на отписку.
//
// МАКСИМУМ 6000. Столько же стоит в maxLength формы и в констрейнте
// базы. Раньше это число держалось ТОЛЬКО браузером: колонка имеет
// тип text, и вызов RPC напрямую записывал описание любой длины.
export const DESCRIPTION_MIN = 30;
export const DESCRIPTION_MAX = 6000;

// Длину считаем по тексту БЕЗ крайних пробелов: строка из сорока
// пробелов описанием не является. Та же логика на сервере — там
// btrim в констрейнте.
export function descriptionLength(text: string): number {
  return text.trim().length;
}

// ------------------------------------------------------------
// ОБЩИЙ ВАЛИДАТОР ОПИСАНИЯ.
// ------------------------------------------------------------
// Возвращает КЛЮЧ словаря i18n, а не готовый текст: модуль не знает
// про локали и не должен. Форма переводит ключ сама.
//
// null означает «описание допустимо».
export type DescriptionProblem =
  | 'sell_err_desc_short'
  | 'sell_err_desc_long'
  | 'sell_err_desc_links'
  | 'sell_err_desc_html'
  | 'sell_err_contacts';

/**
 * Проверяет описание целиком: длина, ссылки, разметка, контакты.
 *
 * ОПИСАНИЕ НЕОБЯЗАТЕЛЬНО. Пустое поле — это «продавец не стал
 * заполнять», и таких объявлений в каталоге сейчас большинство пути:
 * требовать текст от всех значило бы менять правила подачи, а не
 * добавлять проверку. Поэтому минимум применяется только к НЕПУСТОМУ
 * описанию.
 *
 * ПОРЯДОК ПРОВЕРОК — от конкретного к общему. Если в тексте и номер
 * телефона, и он же короче тридцати символов, продавцу полезнее
 * узнать про номер: дописать текст он и так собирался, а про запрет
 * контактов не догадывается.
 */
export function validateDescription(text: string): DescriptionProblem | null {
  const trimmed = text.trim();

  // Пустое описание допустимо — поле необязательное.
  if (trimmed === '') return null;

  // Разметка и ссылки проверяются раньше длины: текст, вставленный со
  // сторонней площадки вместе с тегами, обычно длинный, и сообщение
  // про короткое описание сбило бы с толку.
  const matches = findContacts(trimmed);

  if (matches.some((m) => m.kind === 'html')) return 'sell_err_desc_html';

  // Ссылка на мессенджер — тоже ссылка, но причина точнее, поэтому
  // сообщение про контакты имеет приоритет над общим про ссылки.
  const hasContactKind = matches.some(
    (m) => m.kind !== 'url' && m.kind !== 'html',
  );
  if (hasContactKind) return 'sell_err_contacts';

  if (matches.some((m) => m.kind === 'url')) return 'sell_err_desc_links';

  if (trimmed.length < DESCRIPTION_MIN) return 'sell_err_desc_short';
  if (trimmed.length > DESCRIPTION_MAX) return 'sell_err_desc_long';

  return null;
}

/**
 * Разбивает текст на куски для подсветки: чистые фрагменты и найденные
 * контакты. Форма рисует по этому списку — сама она про правила ничего
 * не знает.
 */
export type DescriptionChunk = {
  text: string;
  match: ContactMatch | null;
};

export function splitByContacts(text: string): DescriptionChunk[] {
  const matches = findContacts(text);
  if (matches.length === 0) return [{ text, match: null }];

  const chunks: DescriptionChunk[] = [];
  let cursor = 0;

  for (const m of matches) {
    if (m.start > cursor) {
      chunks.push({ text: text.slice(cursor, m.start), match: null });
    }
    chunks.push({ text: text.slice(m.start, m.end), match: m });
    cursor = m.end;
  }

  if (cursor < text.length) {
    chunks.push({ text: text.slice(cursor), match: null });
  }

  return chunks;
}

// ------------------------------------------------------------
// СООБЩЕНИЯ В ЧАТЕ.
// ------------------------------------------------------------
// Те же правила, что у описания, но БЕЗ длины и без деления причин:
// в переписке запрещено всё контактное разом — ссылки, телефоны,
// почта, никнеймы.
//
// ЗАЧЕМ ЗАПРЕЩАТЬ В ЧАТЕ, ЕСЛИ ТЕЛЕФОН ПРОДАВЦА И ТАК ВИДЕН В
// ОБЪЯВЛЕНИИ. Правило защищает не от обмена контактами как таковыми, а
// от УВОДА переписки из чата — это типовая схема мошенничества:
// «продолжим в вайбере», дальше ссылка на поддельную страницу оплаты
// или доставки, и никаких следов на площадке. Честной сделке запрет не
// мешает: номер продавца показан в карточке по кнопке «Позвонить», и
// покупателю не нужно просить его в переписке.
//
// РАЗМЕТКУ В ЧАТЕ НЕ ПРОВЕРЯЕМ. Сообщения выводятся как текст, без
// dangerouslySetInnerHTML, поэтому теги в них безобидны — а вот
// разговор «поставь <b> для жирного» вполне возможен. Правило, которое
// не защищает, но мешает, заводить незачем.
export function findMessageContacts(text: string): ContactMatch[] {
  return findContacts(text).filter((m) => m.kind !== 'html');
}

/**
 * Можно ли отправить сообщение. false — в тексте есть контакты или
 * ссылка.
 */
export function isMessageAllowed(text: string): boolean {
  return findMessageContacts(text).length === 0;
}

/**
 * Разбивка сообщения на куски для подсветки — как splitByContacts, но
 * по правилам чата (без разметки).
 */
export function splitMessageByContacts(text: string): DescriptionChunk[] {
  const matches = findMessageContacts(text);
  if (matches.length === 0) return [{ text, match: null }];

  const chunks: DescriptionChunk[] = [];
  let cursor = 0;

  for (const m of matches) {
    if (m.start > cursor) {
      chunks.push({ text: text.slice(cursor, m.start), match: null });
    }
    chunks.push({ text: text.slice(m.start, m.end), match: m });
    cursor = m.end;
  }

  if (cursor < text.length) {
    chunks.push({ text: text.slice(cursor), match: null });
  }

  return chunks;
}

