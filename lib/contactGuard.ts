// ЧЕГО ЭТОТ МОДУЛЬ НЕ ЛОВИТ — И ЭТО ОСОЗНАННО.
// ------------------------------------------------------------
//   • номер словами («ноль шесть ноль…») и заведомо изощрённые обходы.
//     Ловить их означало бы разбирать числительные двух языков, а
//     ложное срабатывание на «шесть подушек безопасности» стоило бы
//     дороже пропущенного номера: упорный обходчик всё равно найдёт
//     способ, а модерация читает текст глазами;
//   • голые числа без телефонных признаков. «12500» — это цена, а не
//     номер, и запрещать такое нельзя;
//   • имя профиля без @ («ищите меня в инстаграме»). Без адреса это
//     не контакт, а фраза.
//
// Пропущенное здесь ловит модерация: объявление всё равно проходит
// проверку человеком перед публикацией. Задача этих правил — снять
// массовый и неумышленный случай, а не построить стену.
