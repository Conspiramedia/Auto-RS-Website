// ============================================================
// RS AUTO — Запрет контактных данных в описании объявления.
// ============================================================
// ЗАЧЕМ. Телефон в тексте описания уводит сделку мимо площадки: чат и
// кнопка звонка перестают работать, статистика обращений врёт, а
// покупатель звонит по номеру, который никто не проверял. Номер для
// связи у объявления уже есть — отдельным полем contact_phone, и
// показывается он по кнопке «Позвонить». Описание — про машину.
//
// ДВА СЛОЯ, И ЭТОТ — ВЕРХНИЙ. Здесь живут правила, общие для проверки
// при вводе и для подсветки в форме. Жёсткий барьер — в базе
// (f_has_contact_info, миграция 0135): клиент можно обойти, отправив
// RPC напрямую, и последнее слово обязано быть за сервером. Оба слоя
// намеренно повторяют одни правила: расхождение означало бы, что
// форма пропускает текст, который сервер отвергнет уже после загрузки
// фотографий — самое дорогое место сценария.
//
// ГЛАВНАЯ ТРУДНОСТЬ — НЕ ПОЙМАТЬ ЛИШНЕГО. Описание машины состоит из
// чисел: «2020», «86 500 км», «1.9 TDI», «2.0», «19 колёса», цена
// «12 500 €». Простое «шесть цифр подряд» ловит и пробег, и цену, и
// объявление становится неподаваемым — а продавец не понимает, за что.
// Поэтому цифры сами по себе НЕ запрещены никогда: запрещены признаки
// КОНТАКТА — телефонная форма номера, доменные ссылки на мессенджеры,
// адрес почты, никнейм через @. Числовые правила ниже везде опираются
// либо на явный телефонный признак (+381, префикс мобильного оператора,
// международная запись), либо на соседство со словом «звоните/пишите/
// whatsapp/viber».
//
// СЕРБСКАЯ СПЕЦИФИКА. Мобильные номера страны начинаются с 06x
// (060–069), городские — с 0 и кода города (011 Белград, 021 Нови-Сад).
// Международная запись — +381 с отброшенным ведущим нулём. Русские
// продавцы пишут привычные +7/8 — их ловим тоже.
// ============================================================

// ------------------------------------------------------------
// Нормализация под анализ.
// ------------------------------------------------------------
// Продавцы, знающие про запрет, разбивают номер чем угодно: пробелами,
// точками, дефисами, скобками, а самые упорные — словами и похожими на
// цифры символами. Словесную запись мы не ловим намеренно (см. «ЧЕГО
// ЭТОТ МОДУЛЬ НЕ ЛОВИТ» внизу), а вот типографские подмены снимаем:
// они появляются и без злого умысла, когда текст копируют из другого
// объявления.
//
// ВАЖНО: возвращается строка ТОЙ ЖЕ ДЛИНЫ, что и вход — каждая замена
// посимвольная. На этом держится подсветка: индексы совпадений,
// найденные в нормализованном тексте, указывают на те же места в
// исходном.
function normalizeForScan(text: string): string {
  return (
    text
      // Гомоглифы кириллицы в латинских словах: «vibеr» с русской «е»
      // выглядит неотличимо, но латинской регуляркой не ловится.
      .replace(/[аА]/g, 'a')
      .replace(/[еЕ]/g, 'e')
      .replace(/[оО]/g, 'o')
      .replace(/[рР]/g, 'p')
      .replace(/[сС]/g, 'c')
      .replace(/[хХ]/g, 'x')
      .replace(/[уУ]/g, 'y')
      .replace(/[кК]/g, 'k')
      .replace(/[мМ]/g, 'm')
      .replace(/[тТ]/g, 't')
      // Полноширинные цифры и арабо-индийские — в обычные.
      .replace(/[０-９]/g, (d) =>
        String(d.charCodeAt(0) - 0xff10),
      )
      .replace(/[٠-٩]/g, (d) =>
        String(d.charCodeAt(0) - 0x0660),
      )
      // Типографские тире и минусы — в обычный дефис.
      .replace(/[‐-―−]/g, '-')
      // Неразрывные и прочие экзотические пробелы — в обычный.
      .replace(/[  -​  　]/g, ' ')
      .toLowerCase()
  );
}

// ------------------------------------------------------------
// Что именно нашли: причина нужна и для подсветки, и для отчёта.
// ------------------------------------------------------------
export type ContactMatchKind =
  | 'phone' // телефонный номер в любой записи
  | 'email' // адрес электронной почты
  | 'link' // ссылка на мессенджер или соцсеть
  | 'nickname' // @никнейм
  | 'messenger' // название мессенджера рядом с цифрами
  | 'url' // любая внешняя ссылка (http/https/www/домен)
  | 'html'; // HTML-тег или скрипт

export type ContactMatch = {
  kind: ContactMatchKind;
  /** Индекс начала совпадения в ИСХОДНОЙ строке. */
  start: number;
  /** Индекс конца (не включая) в исходной строке. */
  end: number;
  /** Найденный фрагмент исходного текста — для подсветки и логов. */
  text: string;
};

// ------------------------------------------------------------
// ПРАВИЛА.
// ------------------------------------------------------------
// Каждое правило — регулярка и вид находки. Порядок важен только для
// читаемости: пересечения схлопываются в findContacts.
//
// Общий приём телефонных правил — РАЗДЕЛИТЕЛЬ [\s.\-()/]{0,2} между
// группами цифр. Он покрывает «060 123 45 67», «060-123-4567»,
// «060/1234567», «(060) 1234567» и слитную запись, но не даёт склеить
// два независимых числа из соседних предложений: больше двух знаков
// подряд между цифрами — это уже текст, а не запись номера.
// raw: правило ищет в ИСХОДНОМ тексте, а не в нормализованном. Нужно
// там, где значим регистр (см. правило голого домена).
const RULES: ReadonlyArray<{
  kind: ContactMatchKind;
  re: RegExp;
  raw?: boolean;
}> = [
  // --- ПОЧТА ------------------------------------------------
  // Ловим и обычную запись, и обход через «(at)», «[собака]».
  // Домен верхнего уровня — от двух букв: «name@2» почтой не считается,
  // «name@mail.ru» считается.
  {
    kind: 'email',
    re: /[a-z0-9._%+-]+\s*(?:@|\(\s*(?:at|собака|majmun)\s*\)|\[\s*(?:at|собака|majmun)\s*\]|\s+(?:at|собака)\s+)\s*[a-z0-9.-]+\s*(?:\.|\(\s*(?:dot|тчк|точка)\s*\))\s*[a-z]{2,}/g,
  },

  // --- ССЫЛКИ НА МЕССЕНДЖЕРЫ И СОЦСЕТИ ----------------------
  // Схема-ссылки мессенджеров: viber://, whatsapp://, tg://.
  {
    kind: 'link',
    re: /\b(?:viber|whatsapp|tg|telegram|skype|sgnl)\s*:\s*\/\//g,
  },
  // Доменные ссылки-приглашения. Точка допускает обход «t (точка) me»,
  // но перечень доменов держим ЗАКРЫТЫМ: запрещать любой домен нельзя —
  // продавцы законно ссылаются на отчёт истории машины или на видео.
  {
    kind: 'link',
    re: /\b(?:t|telegram|wa|api\.whatsapp|chat\.whatsapp|fb|facebook|instagram|instagr|vk|viber|signal|join\.skype)\s*(?:\.|\(\s*(?:dot|точка|тчк)\s*\))\s*(?:me|com|ru|am|gg|link)\s*\/+\s*[a-z0-9_.+-]+/g,
  },

  // --- ЛЮБАЯ ВНЕШНЯЯ ССЫЛКА ---------------------------------
  // Правило ШИРЕ закрытого списка доменов выше и делает его почти
  // излишним. Оставляем оба намеренно: список мессенджеров даёт
  // ТОЧНУЮ причину отказа («ссылки на мессенджеры»), а это правило —
  // общую. Продавцу полезнее конкретная формулировка, когда она есть.
  //
  // Схема или www — однозначный признак ссылки.
  {
    kind: 'url',
    re: /\b(?:https?:\/\/|ftp:\/\/|www\s*\.)\s*[a-z0-9-]+/g,
  },
  // Голый домен без схемы: «avito.ru», «mojauto.rs/oglas».
  //
  // ЗДЕСЬ ЖИВЁТ ГЛАВНЫЙ РИСК ЛОЖНЫХ СРАБАТЫВАНИЙ, и защита от него —
  // в списке зон, а не в форме слова. Совпадение по «что угодно с
  // точкой» ловило бы «1.9 TDI», «15.03.2024», «5.5 litara» и
  // сокращения вида «g.od». Поэтому зона обязана быть из
  // ФИКСИРОВАННОГО перечня реальных TLD, а перед точкой — не цифра:
  // так «2.0» и «225/45» не проходят по определению.
  //
  // Перечень намеренно короткий: зоны Сербии и соседей, зоны СНГ и
  // ходовые международные. Экзотику (.xyz, .top) не ловим — цена
  // ошибки на «Golf.top комплектация» выше выгоды.
  //
  // ПРОБЕЛОВ ВОКРУГ ТОЧКИ ЗДЕСЬ НЕТ — и это не упущение. Сербы часто
  // не ставят пробел после точки в конце предложения, и следующее
  // слово регулярно совпадает с зоной: «Auto je nov.Me interesuje…»,
  // «Prodajem auto.Info na uvid…», «Cena je fiksna.Net cena…». С
  // допуском пробелов все три превращались в «ссылку» и объявление
  // становилось неподаваемым.
  //
  // Отсюда же требование СТРОЧНОЙ зоны (регистр проверяется до
  // приведения — см. ниже про rawFlags): в реальной ссылке домен
  // пишут строчными, а «nov.Me» с заглавной — это начало нового
  // предложения. Обход «MOJAUTO.RS» капсом теряем сознательно: он
  // редок, а ложное срабатывание на каждой второй сербской фразе —
  // нет.
  // Перед доменом не должно быть @ (это хвост почты — её ловит своё
  // правило) и не должно быть цифры с точкой («2.0», «15.03.2024»).
  // Точка сама по себе ПРОПУСКАЕТСЯ: у поддомена «slike.mojauto.rs»
  // перед доменом второго уровня стоит именно она.
  {
    kind: 'url',
    re: /(?<![a-z0-9@-])(?<![0-9]\.)(?![0-9])[a-z0-9-]{2,}\.(?:rs|com|net|org|info|biz|ru|su|by|kz|ua|me|ba|hr|si|mk|bg|ro|hu|at|de|it|fr|uk|eu|io|app|shop|site|online|store|link|gg|tv|cc)\b(?![a-z])/g,
    // Ищем в ИСХОДНОМ тексте, а не в приведённом к нижнему регистру:
    // иначе «nov.Me» и «mojauto.me» неразличимы.
    raw: true,
  },

  // --- HTML-ТЕГИ И СКРИПТЫ ----------------------------------
  // Парный или одиночный тег: <b>, <br>, <br/>, </div>, <img src=…>.
  // Требуем букву сразу после «<» (или после «/»), иначе правило
  // сработало бы на сравнение «<2.0 l» и на стрелку «<-».
  //
  // Хвост тега — `[^<>]*`, а не `(?:\s[^<>]*)?`: без этого
  // самозакрывающийся тег без пробела («<br/>») не ловился, потому что
  // слэш шёл сразу за именем. Класс не пускает внутрь «<» и «>»,
  // поэтому совпадение не может перепрыгнуть через границу тега.
  {
    kind: 'html',
    re: /<\s*\/?\s*[a-z][a-z0-9]*[^<>]*>/g,
  },
  // Незакрытый или обфусцированный скрипт и обработчики событий:
  // «<script», «javascript:», «onerror=», «onclick=».
  // Ловим ОТДЕЛЬНО от тегов: такой текст опасен и без закрывающей
  // скобки, а именно так выглядит попытка обойти правило выше.
  {
    kind: 'html',
    re: /<\s*\/?\s*(?:script|iframe|object|embed|style|svg|form|input)\b|javascript\s*:|\bon(?:error|load|click|mouseover|focus)\s*=/g,
  },
  // HTML-сущности: «&lt;script&gt;», «&#60;». Признак того, что текст
  // пришёл из разметки, а не набран человеком.
  {
    kind: 'html',
    re: /&(?:lt|gt|quot|amp|#x?[0-9a-f]{2,6});/g,
  },

  // --- @НИКНЕЙМ ---------------------------------------------
  // Телеграм-ник: @ и минимум пять символов — столько требует сам
  // Telegram, и такой порог не задевает «шины 4@2000».
  //
  // (?<![a-z0-9._%+-]) — не хвост почтового адреса: у «ivan@mail.ru»
  // перед @ стоит имя, и как никнейм это считать нельзя (почту поймало
  // правило выше, и совпадения схлопнутся).
  {
    kind: 'nickname',
    re: /(?<![a-z0-9._%+-])@[a-z0-9_]{5,32}\b/g,
  },

  // --- НАЗВАНИЕ МЕССЕНДЖЕРА РЯДОМ С ЦИФРАМИ -----------------
  // «Whatsapp 060...», «Viber: 123456», «телеграм — 89991234567».
  // Требуем не меньше шести цифр в группе: «WhatsApp 24/7» и «Viber
  // 2 часа» так остаются в тексте, а номер — нет.
  //
  // Расстояние до цифр — до 12 символов: помещается «viber или
  // whatsapp:», но не целое предложение между словом и годом выпуска.
  {
    kind: 'messenger',
    re: /\b(?:whats\s*app|wattsapp|vats\s*ap|вотсап|ватсап|вацап|viber|вайбер|telegram|телеграм|телега|signal|instagram|инстаграм|инста|messenger|мессенджер)\b[^\d\n]{0,12}(?:\+?\d[\s.\-()/]{0,2}){6,}/g,
  },
  // Зеркало: сначала номер, потом слово («060 123 4567 вайбер»).
  {
    kind: 'messenger',
    re: /(?:\+?\d[\s.\-()/]{0,2}){6,}[^\d\n]{0,12}\b(?:whats\s*app|wattsapp|vats\s*ap|вотсап|ватсап|вацап|viber|вайбер|telegram|телеграм|телега|signal|instagram|инстаграм|инста)\b/g,
  },

  // --- «ЗВОНИТЕ / ПИШИТЕ» + ЦИФРЫ ---------------------------
  // Глагол связи рядом с длинной группой цифр. Порог тот же — шесть
  // цифр: «звоните после 18» и «пишите, машина 2015 года» проходят.
  {
    kind: 'phone',
    re: /\b(?:звоните|звонить|звони|позвоните|перезвоню|пишите|пиши|напишите|набирайте|наберите|тел|телефон|моб|мобильный|контакт|связь|zovite|zovi|pozovite|javite|pisite|pisete|kontakt|telefon|mob|broj)\b[^\d\n]{0,15}(?:\+?\d[\s.\-()/]{0,2}){6,}/g,
  },

  // --- ТЕЛЕФОННЫЕ НОМЕРА ПО ФОРМЕ ---------------------------
  // Международная запись: + и код страны. Это однозначный признак
  // телефона — никакая характеристика машины так не пишется.
  // 8–15 цифр после плюса покрывает любой номер мира (E.164).
  {
    kind: 'phone',
    re: /\+\s*(?:\d[\s.\-()/]{0,2}){8,15}/g,
  },
  // Сербский мобильный без плюса: 06x и ещё 6–8 цифр.
  // «06» в начале — не число из описания: пробег и цена с нуля не
  // начинаются, а год — тем более.
  {
    kind: 'phone',
    re: /(?<!\d)0\s*6\s*[0-9](?:[\s.\-()/]{0,2}\d){6,8}(?!\d)/g,
  },
  // Сербский городской: 0 + код города (11 Белград, 21 Нови-Сад,
  // 18 Ниш, 24 Суботица, 34 Крагуевац…) + номер.
  {
    kind: 'phone',
    re: /(?<!\d)0\s*(?:1[1-9]|2[0-9]|3[0-9])(?:[\s.\-()/]{1,2}\d){5,9}(?!\d)/g,
  },
  // Русский/казахский формат: 8 или 7 с кодом в скобках либо через
  // разделители — «8 (999) 123-45-67», «89991234567».
  // Требуем ровно 11 цифр: это отличает номер от суммы «8 500 000».
  {
    kind: 'phone',
    re: /(?<!\d)[78][\s.\-()/]{0,3}(?:9|8|4|3)\d{2}[\s.\-()/]{0,3}\d{3}[\s.\-()/]{0,3}\d{2}[\s.\-()/]{0,3}\d{2}(?!\d)/g,
  },
];

