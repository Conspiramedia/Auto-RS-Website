// RS AUTO — Запрет контактных данных в описании объявления.
// ============================================================
// ЗАЧЕМ. Телефон в тексте описания уводит сделку мимо площадки: чат и
// кнопка звонка перестают работать, статистика обращений врёт, а
// покупатель звонит по номеру, который никто не проверял. Номер для
// связи у объявления уже есть — отдельным полем contact_phone, и
// показывается он по кнопке «Позвонить». Описание — про машину.
//
// ДВА СЛОЯ, И ЭТОТ — ВЕРХНИЙ. Здесь живут правила, общие для проверки
// при вводе и для подсветки в форме. Жёсткий барьер — в базе
// (f_has_contact_info, миграция 0135): клиент можно обойти, отправив
// RPC напрямую, и последнее слово обязано быть за сервером. Оба слоя
// намеренно повторяют одни правила: расхождение означало бы, что
// форма пропускает текст, который сервер отвергнет уже после загрузки
// фотографий — самое дорогое место сценария.
//
// ГЛАВНАЯ ТРУДНОСТЬ — НЕ ПОЙМАТЬ ЛИШНЕГО. Описание машины состоит из
// чисел: «2020», «86 500 км», «1.9 TDI», «2.0», «19 колёса», цена
// «12 500 €». Простое «шесть цифр подряд» ловит и пробег, и цену, и
// объявление становится неподаваемым — а продавец не понимает, за что.
// Поэтому цифры сами по себе НЕ запрещены никогда: запрещены признаки
// КОНТАКТА — телефонная форма номера, доменные ссылки на мессенджеры,
// адрес почты, никнейм через @. Числовые правила ниже везде опираются
// либо на явный телефонный признак (+381, префикс мобильного оператора,
// международная запись), либо на соседство со словом «звоните/пишите/
// whatsapp/viber».
//
// СЕРБСКАЯ СПЕЦИФИКА. Мобильные номера страны начинаются с 06x
// (060–069), городские — с 0 и кода города (011 Белград, 021 Нови-Сад).
// Международная запись — +381 с отброшенным ведущим нулём. Русские
// продавцы пишут привычные +7/8 — их ловим тоже.
// ============================================================

// ------------------------------------------------------------
// Нормализация под анализ.
// ------------------------------------------------------------
// Продавцы, знающие про запрет, разбивают номер чем угодно: пробелами,
// точками, дефисами, скобками, а самые упорные — словами и похожими на
// цифры символами. Словесную запись мы не ловим намеренно (см. «ЧЕГО
// ЭТОТ МОДУЛЬ НЕ ЛОВИТ» внизу), а вот типографские подмены снимаем:
// они появляются и без злого умысла, когда текст копируют из другого
// объявления.
//
// ВАЖНО: возвращается строка ТОЙ ЖЕ ДЛИНЫ, что и вход — каждая замена
// посимвольная. На этом держится подсветка: индексы совпадений,
// найденные в нормализованном тексте, указывают на те же места в
// исходном.
function normalizeForScan(text: string): string {
  return (
    text
      // Гомоглифы кириллицы в латинских словах: «vibеr» с русской «е»
      // выглядит неотличимо, но латинской регуляркой не ловится.
      .replace(/[аА]/g, 'a')
      .replace(/[еЕ]/g, 'e')
      .replace(/[оО]/g, 'o')
      .replace(/[рР]/g, 'p')
      .replace(/[сС]/g, 'c')
      .replace(/[хХ]/g, 'x')
      .replace(/[уУ]/g, 'y')
      .replace(/[кК]/g, 'k')
      .replace(/[мМ]/g, 'm')
      .replace(/[тТ]/g, 't')
      // Полноширинные цифры и арабо-индийские — в обычные.
      .replace(/[０-９]/g, (d) =>
        String(d.charCodeAt(0) - 0xff10),
      )
      .replace(/[٠-٩]/g, (d) =>
        String(d.charCodeAt(0) - 0x0660),
      )
      // Типографские тире и минусы — в обычный дефис.
      .replace(/[‐-―−]/g, '-')
      // Неразрывные и прочие экзотические пробелы — в обычный.
      .replace(/[  -​  　]/g, ' ')
      .toLowerCase()
  );
}

