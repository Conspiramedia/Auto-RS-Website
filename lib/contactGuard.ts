// Что именно нашли: причина нужна и для подсветки, и для отчёта.
// ------------------------------------------------------------
export type ContactMatchKind =
  | 'phone' // телефонный номер в любой записи
  | 'email' // адрес электронной почты
  | 'link' // ссылка на мессенджер или соцсеть
  | 'nickname' // @никнейм
  | 'messenger'; // название мессенджера рядом с цифрами

export type ContactMatch = {
  kind: ContactMatchKind;
  /** Индекс начала совпадения в ИСХОДНОЙ строке. */
  start: number;
  /** Индекс конца (не включая) в исходной строке. */
  end: number;
  /** Найденный фрагмент исходного текста — для подсветки и логов. */
  text: string;
};

// ------------------------------------------------------------
// ПРАВИЛА.
// ------------------------------------------------------------
// Каждое правило — регулярка и вид находки. Порядок важен только для
// читаемости: пересечения схлопываются в findContacts.
//
// Общий приём телефонных правил — РАЗДЕЛИТЕЛЬ [\s.\-()/]{0,2} между
// группами цифр. Он покрывает «060 123 45 67», «060-123-4567»,
// «060/1234567», «(060) 1234567» и слитную запись, но не даёт склеить
// два независимых числа из соседних предложений: больше двух знаков
// подряд между цифрами — это уже текст, а не запись номера.
const RULES: ReadonlyArray<{ kind: ContactMatchKind; re: RegExp }> = [
  // --- ПОЧТА ------------------------------------------------
  // Ловим и обычную запись, и обход через «(at)», «[собака]».
  // Домен верхнего уровня — от двух букв: «name@2» почтой не считается,
  // «name@mail.ru» считается.
  {
    kind: 'email',
    re: /[a-z0-9._%+-]+\s*(?:@|\(\s*(?:at|собака|majmun)\s*\)|\[\s*(?:at|собака|majmun)\s*\]|\s+(?:at|собака)\s+)\s*[a-z0-9.-]+\s*(?:\.|\(\s*(?:dot|тчк|точка)\s*\))\s*[a-z]{2,}/g,
  },

  // --- ССЫЛКИ НА МЕССЕНДЖЕРЫ И СОЦСЕТИ ----------------------
  // Схема-ссылки мессенджеров: viber://, whatsapp://, tg://.
  {
    kind: 'link',
    re: /\b(?:viber|whatsapp|tg|telegram|skype|sgnl)\s*:\s*\/\//g,
  },
  // Доменные ссылки-приглашения. Точка допускает обход «t (точка) me»,
  // но перечень доменов держим ЗАКРЫТЫМ: запрещать любой домен нельзя —
  // продавцы законно ссылаются на отчёт истории машины или на видео.
  {
    kind: 'link',
    re: /\b(?:t|telegram|wa|api\.whatsapp|chat\.whatsapp|fb|facebook|instagram|instagr|vk|viber|signal|join\.skype)\s*(?:\.|\(\s*(?:dot|точка|тчк)\s*\))\s*(?:me|com|ru|am|gg|link)\s*\/+\s*[a-z0-9_.+-]+/g,
  },

  // --- @НИКНЕЙМ ---------------------------------------------
  // Телеграм-ник: @ и минимум пять символов — столько требует сам
  // Telegram, и такой порог не задевает «шины 4@2000».
  //
  // (?<![a-z0-9._%+-]) — не хвост почтового адреса: у «ivan@mail.ru»
  // перед @ стоит имя, и как никнейм это считать нельзя (почту поймало
  // правило выше, и совпадения схлопнутся).
  {
    kind: 'nickname',
    re: /(?<![a-z0-9._%+-])@[a-z0-9_]{5,32}\b/g,
  },

  // --- НАЗВАНИЕ МЕССЕНДЖЕРА РЯДОМ С ЦИФРАМИ -----------------
  // «Whatsapp 060...», «Viber: 123456», «телеграм — 89991234567».
  // Требуем не меньше шести цифр в группе: «WhatsApp 24/7» и «Viber
  // 2 часа» так остаются в тексте, а номер — нет.
  //
  // Расстояние до цифр — до 12 символов: помещается «viber или
  // whatsapp:», но не целое предложение между словом и годом выпуска.
  {
    kind: 'messenger',
    re: /\b(?:whats\s*app|wattsapp|vats\s*ap|вотсап|ватсап|вацап|viber|вайбер|telegram|телеграм|телега|signal|instagram|инстаграм|инста|messenger|мессенджер)\b[^\d\n]{0,12}(?:\+?\d[\s.\-()/]{0,2}){6,}/g,
  },
  // Зеркало: сначала номер, потом слово («060 123 4567 вайбер»).
  {
    kind: 'messenger',
    re: /(?:\+?\d[\s.\-()/]{0,2}){6,}[^\d\n]{0,12}\b(?:whats\s*app|wattsapp|vats\s*ap|вотсап|ватсап|вацап|viber|вайбер|telegram|телеграм|телега|signal|instagram|инстаграм|инста)\b/g,
  },

  // --- «ЗВОНИТЕ / ПИШИТЕ» + ЦИФРЫ ---------------------------
  // Глагол связи рядом с длинной группой цифр. Порог тот же — шесть
  // цифр: «звоните после 18» и «пишите, машина 2015 года» проходят.
  {
    kind: 'phone',
    re: /\b(?:звоните|звонить|звони|позвоните|перезвоню|пишите|пиши|напишите|набирайте|наберите|тел|телефон|моб|мобильный|контакт|связь|zovite|zovi|pozovite|javite|pisite|pisete|kontakt|telefon|mob|broj)\b[^\d\n]{0,15}(?:\+?\d[\s.\-()/]{0,2}){6,}/g,
  },

  // --- ТЕЛЕФОННЫЕ НОМЕРА ПО ФОРМЕ ---------------------------
  // Международная запись: + и код страны. Это однозначный признак
  // телефона — никакая характеристика машины так не пишется.
  // 8–15 цифр после плюса покрывает любой номер мира (E.164).
  {
    kind: 'phone',
    re: /\+\s*(?:\d[\s.\-()/]{0,2}){8,15}/g,
  },
  // Сербский мобильный без плюса: 06x и ещё 6–8 цифр.
  // «06» в начале — не число из описания: пробег и цена с нуля не
  // начинаются, а год — тем более.
  {
    kind: 'phone',
    re: /(?<!\d)0\s*6\s*[0-9](?:[\s.\-()/]{0,2}\d){6,8}(?!\d)/g,
  },
  // Сербский городской: 0 + код города (11 Белград, 21 Нови-Сад,
  // 18 Ниш, 24 Суботица, 34 Крагуевац…) + номер.
  {
    kind: 'phone',
    re: /(?<!\d)0\s*(?:1[1-9]|2[0-9]|3[0-9])(?:[\s.\-()/]{1,2}\d){5,9}(?!\d)/g,
  },
  // Русский/казахский формат: 8 или 7 с кодом в скобках либо через
  // разделители — «8 (999) 123-45-67», «89991234567».
  // Требуем ровно 11 цифр: это отличает номер от суммы «8 500 000».
  {
    kind: 'phone',
    re: /(?<!\d)[78][\s.\-()/]{0,3}(?:9|8|4|3)\d{2}[\s.\-()/]{0,3}\d{3}[\s.\-()/]{0,3}\d{2}[\s.\-()/]{0,3}\d{2}(?!\d)/g,
  },
];

