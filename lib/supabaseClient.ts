'use client';

// ============================================================
// RS AUTO — Клиент Supabase для браузера.
// ============================================================
// Отдельный клиент от серверного (lib/supabase.ts) нужен потому, что здесь
// сессия ОБЯЗАНА сохраняться: подача объявления идёт в несколько шагов —
// вход по SMS-коду, затем загрузка фото в Storage от имени вошедшего
// пользователя, затем вызов create_car_v2. Серверный клиент намеренно
// работает без сессии, и переиспользовать его здесь нельзя.
//
// Клиент создаётся один раз (синглтон): каждый новый экземпляр заводит
// собственную подписку на обновление токена, что приводит к гонкам обновления.
//
// ------------------------------------------------------------
// СЕССИЯ ХРАНИТСЯ В COOKIE, А НЕ В localStorage.
// ------------------------------------------------------------
// Это ключевое отличие от прежней версии клиента. Причина — кабинет
// (/my): его страницы рендерятся на СЕРВЕРЕ, где виден только
// заголовок Cookie входящего запроса. Токен в localStorage браузер
// серверу не отправляет вовсе, поэтому при таком хранении сервер
// считал бы вошедшего продавца гостем и отдавал бы пустой кабинет.
//
// createBrowserClient из @supabase/ssr пишет ту же сессию в cookie и
// держит её в согласии с серверным клиентом (lib/supabaseServer.ts),
// который эти же cookie читает. Оба конца работают с одним форматом,
// поэтому вход, выполненный на клиенте, немедленно виден серверу.
//
// ЧТО ЭТО МЕНЯЕТ ДЛЯ ПОДАЧИ ОБЪЯВЛЕНИЯ (components/SellForm.tsx):
// ничего. Публичный API тот же (auth.signInWithOtp, auth.verifyOtp,
// auth.getSession, storage, rpc), сессия так же переживает перезагрузку
// страницы и закрытие вкладки. Меняется только место хранения токена.
// ============================================================

import { createBrowserClient } from '@supabase/ssr';
import type { SupabaseClient } from '@supabase/supabase-js';

let client: SupabaseClient | null = null;

export function getBrowserClient(): SupabaseClient {
  if (client) return client;

  const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
  const key = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;

  if (!url || !key) {
    throw new Error(
      'Не заданы NEXT_PUBLIC_SUPABASE_URL / NEXT_PUBLIC_SUPABASE_ANON_KEY.',
    );
  }

  // createBrowserClient сам настраивает хранение в cookie, автообновление
  // токена и синхронизацию между вкладками. Разбор сессии из адресной
  // строки не нужен: вход идёт по OTP, а не по magic-link, и разбор URL
  // здесь только создал бы лишнюю поверхность.
  client = createBrowserClient(url, key, {
    auth: {
      detectSessionInUrl: false,
    },
  });

  return client;
}
