// Текст причины на языке получателя. Локаль приходит из
// profiles.locale и бывает null — тогда сербский, как и в шаблонах
// писем (f_enqueue_email, 0071).
export function reasonText(
  reason: RejectionReason,
  locale: string | null,
): string {
  return locale === 'ru' ? reason.ru : reason.sr;
}
