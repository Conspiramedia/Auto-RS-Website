// RS AUTO — Общий рендер дефолтной OG-картинки сайта.
// ============================================================
// ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Превью нужно на двух языках: со страницы
// /ru ссылку пересылают русскоязычному собеседнику, с корня —
// сербскому. Язык адреса, с которого делятся, — это и есть сигнал о
// языке получателя, и игнорировать его значит показывать половине
// аудитории чужой текст.
//
// Раньше картинка была одна на обе локали, сербская. Довод был в том,
// что язык получателя неизвестен; на деле он известен ровно настолько,
// насколько известен язык отправителя, — а тот выбрал зеркало сам.
//
// Роуты app/opengraph-image.tsx и app/ru/opengraph-image.tsx стали
// тонкими обёртками над этой функцией: разметка, фон и композиция
// живут в одном месте и правятся один раз.
//
// СТАТИЧНО. Обращений к базе нет, поэтому обе картинки генерируются
// один раз на сборке и дальше отдаются из кэша.
// ============================================================

import { readFile } from 'node:fs/promises';
import { join } from 'node:path';

import { ImageResponse } from 'next/og';

import { brand } from '@/lib/brand';
import type { Locale } from '@/lib/i18n';
import { getT } from '@/lib/i18n';

// Стандартный размер OG-превью, который ожидают соцсети.
export const OG_SIZE = { width: 1200, height: 630 };

export async function renderOgCover(locale: Locale) {
  const t = getT(locale);
  const size = OG_SIZE;

  // Фон читается с диска и кодируется в data-URI, а не отдаётся
  // ссылкой вида '/images/og-cover.jpg'. Satori (движок ImageResponse)
  // рисует на сервере во время сборки, когда сайт сам себе ещё
  // недоступен, и относительный путь ему разрешать не от чего.
  //
  // JPEG, а не WebP: Satori декодирует только PNG и JPEG — на WebP
  // сборка падает с «TypeError: u2 is not iterable». Остальные
  // картинки сайта лежат в WebP, и этот файл — намеренное исключение
  // ради генератора превью.
  const bg = await readFile(join(process.cwd(), 'public/images/og-cover.jpg'));
  const bgSrc = `data:image/jpeg;base64,${bg.toString('base64')}`;

  return new ImageResponse(
    (
      <div
        style={{
          width: '100%',
          height: '100%',
          display: 'flex',
          flexDirection: 'column',
          // Текст прижат к низу, а не по центру: машина занимает
          // середину кадра, и надписи поверх неё перекрывали именно
          // то, ради чего фотография тут стоит.
          justifyContent: 'flex-end',
          // Фирменный синий остаётся подложкой под фотографией: если
          // файл фона однажды не прочитается, превью деградирует до
          // прежней сплошной плашки, а не до белого прямоугольника.
          background: brand.colors.primary,
          // Нижний отступ больше боковых: под зелёной чертой нужен
          // воздух, иначе она читается как обрезанный край картинки.
          padding: '0 80px 56px',
          position: 'relative',
        }}
      >
        {/* ФОТОГРАФИЯ ФОНОМ. Машина на снимке стоит по центру и справа,
            поэтому текст уходит в левую треть — иначе логотип лёг бы
            поверх капота.
            eslint-disable: next/image здесь неприменим, Satori понимает
            только обычный <img>. */}
        {/* eslint-disable-next-line @next/next/no-img-element */}
        <img
          src={bgSrc}
          alt=""
          width={size.width}
          height={size.height}
          style={{
            position: 'absolute',
            top: 0,
            left: 0,
            // Размеры числом, а не в процентах: Satori раскладывает
            // абсолютные элементы без родительского контекста
            // процентов, и '100%' у него схлопывается в ноль.
            width: size.width,
            height: size.height,
            objectFit: 'cover',
          }}
        />

        {/* ГРАДИЕНТ ПОД ТЕКСТОМ — снизу вверх, а не слева направо.
            Раньше плёнка гасила левую треть, и надписи стояли поверх
            переднего колеса: машина — главное на снимке, закрывать её
            текстом незачем.

            Теперь затемняется только нижняя часть кадра, где у этой
            фотографии отражение и пустой пол. Верхние 45% остаются
            чистыми — машина видна целиком.

            Именно градиент, а не сплошная полоса: резкая граница
            посреди превью читалась бы как артефакт вёрстки. */}
        <div
          style={{
            position: 'absolute',
            top: 0,
            left: 0,
            width: size.width,
            height: size.height,
            background:
              'linear-gradient(180deg, rgba(9,26,48,0) 45%, rgba(9,26,48,0.72) 68%, rgba(9,26,48,0.92) 100%)',
          }}
        />

        {/* Текстовый блок поверх плёнки. position/zIndex обязательны:
            без них абсолютные слои выше перекрыли бы надписи. */}
        <div
          style={{
            display: 'flex',
            flexDirection: 'column',
            position: 'relative',
            zIndex: 1,
            // Ширины больше не ограничиваем: текст стоит в нижней
            // полосе, где ему никто не мешает, и слоган укладывается
            // в одну строку — переносить его теперь не на чем.

          }}
            >
            {/* Логотип набран текстом, а не картинкой: PNG знака пришлось
              бы читать с диска и кодировать в data-URI, а Satori всё
              равно нарисовал бы его как изображение без прироста
              качества.
              Надпись ЦЕЛЬНАЯ и одноцветная — ровно как в
              components/ui/Logo.tsx (вариант full). Разбивать её на
              «RS» + «Auto» разных цветов нельзя: на сайте логотип
              выглядит иначе, и превью показывало бы другой бренд.
              Белый вместо брендового синего — по той же причине, что
              inverted в Logo: на синей плашке синий не читается. */}
            <div
            style={{
              display: 'flex',
              // 72 вместо 96: на 96 надпись доходила до переднего
              // колеса и спорила с ним за внимание.
              fontSize: 72,
              fontWeight: 700,
              color: '#FFFFFF',
            }}
            >
            {brand.name}
            </div>

            {/* Слоган — единственная строка, объясняющая, что это за сайт.
              Берётся из словаря, а не пишется здесь константой: он же
              стоит в подвале и в описании сайта. */}
            <div
            style={{
              display: 'flex',
              fontSize: 36,
              color: 'rgba(255,255,255,0.92)',
              marginTop: 20,
              lineHeight: 1.3,
            }}
            >
            {t('site_tagline')}
            </div>

            {/* Зелёная черта под слоганом — тот же акцент, что у главного
              действия на сайте. Держит композицию: без неё нижняя треть
              плашки остаётся пустой. */}
            <div
              style={{
                display: 'flex',
                width: 160,
                height: 8,
                background: brand.colors.green,
                borderRadius: 999,
                marginTop: 28,
              }}
            />
        </div>
      </div>
    ),
    size,
  );
}
