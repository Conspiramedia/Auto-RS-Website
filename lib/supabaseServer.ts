// ============================================================
// RS AUTO — Серверный клиент Supabase С СЕССИЕЙ пользователя.
// ============================================================
// ТРЕТИЙ клиент проекта, и у каждого своя роль — путать их нельзя:
//
//   lib/supabase.ts       — анонимный, БЕЗ сессии, общий на все запросы.
//                           Каталог, карточки, SEO-страницы. Намеренно
//                           не помнит никого: общий клиент с чужой
//                           сессией подмешал бы данные одного посетителя
//                           в рендер страницы другого.
//   lib/supabaseClient.ts — браузерный синглтон, сессия в localStorage.
//                           Подача объявления, действия в кабинете.
//   lib/supabaseServer.ts — ЭТОТ. Сессия читается из cookie запроса,
//                           поэтому Server Components кабинета видят
//                           пользователя и получают его данные под его
//                           же RLS.
//
// ЗАЧЕМ ОН НУЖЕН. Кабинет (/my) обязан рендериться на сервере: список
// диалогов и объявлений — это данные под RLS, и без сессии на сервере
// первый экран пришлось бы рисовать пустым, а затем дозагружать с
// клиента. Отсюда «прыгающий» интерфейс и лишний раунд-трип на каждом
// открытии страницы.
//
// ВАЖНО ПРО ЗАПИСЬ COOKIE. В Server Components Next.js запрещает
// cookies().set() — заголовки к моменту рендера уже отправлены. Поэтому
// setAll здесь намеренно ГЛУШИТСЯ (см. комментарий в коде), а обновление
// протухшего токена берёт на себя proxy.ts, который выполняется ДО
// рендера и имеет право писать в ответ. Такое разделение — штатная схема
// @supabase/ssr, а не обход ограничения.
//
// НОВЫЙ КЛИЕНТ НА КАЖДЫЙ ЗАПРОС. Синглтон здесь недопустим: клиент
// держит cookie конкретного запроса, и переиспользование означало бы
// утечку сессии между посетителями.
//
// Переменные окружения: NEXT_PUBLIC_SUPABASE_URL,
//                       NEXT_PUBLIC_SUPABASE_ANON_KEY.
// ============================================================

import { createServerClient } from '@supabase/ssr';
import { cookies } from 'next/headers';
import type { SupabaseClient } from '@supabase/supabase-js';

// Клиент для Server Components и Server Actions кабинета.
// Асинхронный, потому что cookies() в Next 16 возвращает промис.
export async function getServerClient(): Promise<SupabaseClient> {
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
  const key = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;

  if (!url || !key) {
    throw new Error(
      'Не заданы NEXT_PUBLIC_SUPABASE_URL / NEXT_PUBLIC_SUPABASE_ANON_KEY.',
    );
  }

  const cookieStore = await cookies();

  return createServerClient(url, key, {
    cookies: {
      // Отдаём библиотеке ВСЕ cookie запроса: токен сессии Supabase
      // разбит на несколько частей (chunk'ов), когда не помещается в
      // одну, и выборка по одному имени потеряла бы хвост.
      getAll() {
        return cookieStore.getAll();
      },

      // Запись намеренно пустая. Server Component не может выставить
      // заголовок Set-Cookie: HTTP не разрешает это после начала
      // стриминга ответа, и Next.js бросил бы исключение прямо посреди
      // рендера страницы кабинета.
      //
      // Ничего не теряется: обновлённый токен пишет proxy.ts на
      // предыдущем шаге обработки запроса — там ответ ещё формируется.
      // Здесь достаточно молча принять вызов, иначе библиотека
      // предупредит в консоль на каждом рендере.
      setAll() {
        /* запись cookie выполняется в proxy.ts — см. комментарий выше */
      },
    },
  });
}

// ------------------------------------------------------------
// Текущий пользователь или null.
// ------------------------------------------------------------
// getUser(), а НЕ getSession(): getSession отдаёт содержимое cookie как
// есть, без проверки подписи — то есть доверяет данным, пришедшим от
// клиента. getUser сверяет токен с сервером Supabase, и только его
// результату можно верить, принимая решение «пускать в кабинет или нет».
//
// Ошибка (протухший или подделанный токен) — это не аварийная ситуация,
// а обычный «гость»: возвращаем null, и вызывающая страница уводит
// человека на вход.
export async function getCurrentUser() {
  const supabase = await getServerClient();
  const { data, error } = await supabase.auth.getUser();

  if (error) return null;
  return data.user ?? null;
}
