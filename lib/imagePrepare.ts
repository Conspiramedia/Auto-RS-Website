// ============================================================
// RS AUTO — Подготовка фотографий перед загрузкой в Storage.
// ============================================================
// Зеркало того, что делает приложение одной строкой:
//
//   _picker.pickMultiImage(maxWidth: 1600, imageQuality: 80)
//
// image_picker во Flutter перекодирует снимок ПЕРЕД отправкой: ужимает
// длинную сторону до 1600, жмёт в JPEG качества 80 и — важное следствие —
// применяет EXIF-поворот, записывая уже развёрнутые пиксели. В бакете
// оказывается нормализованный JPEG весом в сотни килобайт.
//
// Сайт до этого модуля отправлял ОРИГИНАЛ. Снимок современного телефона
// (6000×4000, 8–12 МБ) уходил в Storage как есть, и это давало три
// проблемы сразу:
//   1) десять фотографий — это ~100 МБ выгрузки с мобильного интернета,
//      то есть минуты ожидания на сербском 4G и брошенная форма подачи;
//   2) бакет рос в 10–20 раз быстрее необходимого;
//   3) оптимизатор next/image на каждый новый размер скачивал и
//      декодировал эти 10 МБ заново.
//
// Теперь тот же конвейер работает и на сайте.
//
// ------------------------------------------------------------
// ПОЧЕМУ createImageBitmap, А НЕ <img> + onload
// ------------------------------------------------------------
// Через <img> тоже можно нарисовать файл на canvas, но у этого пути нет
// управления ориентацией: браузер применит EXIF при показе, а при
// отрисовке в canvas поведение исторически расходилось между движками.
// createImageBitmap принимает imageOrientation явным параметром —
// 'from-image' означает «примени EXIF и отдай уже развёрнутые пиксели».
// Это ровно то, что делает image_picker, и результат одинаков во всех
// браузерах, которые вообще поддерживают этот вызов.
//
// Второе: createImageBitmap декодирует HEIC там, где системный кодек
// доступен (Safari на iOS/macOS). То есть тот же самый конвейер, без
// единой дополнительной строки, принимает фотографии с айфона в
// исходном формате и отдаёт из них обычный JPEG.
//
// ------------------------------------------------------------
// EXIF ПРИМЕНЯЕТСЯ ОДНОКРАТНО, ЗДЕСЬ
// ------------------------------------------------------------
// После canvas.toBlob получается JPEG вообще без EXIF-секции: canvas
// метаданные не переносит. Пиксели уже повёрнуты правильно, поэтому
// ни next/image, ни Satori (OG-картинка), ни любой будущий серверный
// обработчик про ориентацию знать не обязаны.
//
// Это чинит заодно давнюю проблему OG-превью: Satori EXIF игнорирует,
// и портретное фото с айфона уходило в WhatsApp лежащим на боку.
// Разворачивать на чтении было бы ежедневной работой вместо однократной.
// ============================================================

// Длинная сторона результата. 1600 — та же константа, что maxWidth
// в create_car_screen.dart: снимок остаётся пригодным для галереи на
// десктопе (кадр там ~1280px), но перестаёт быть файлом с камеры.
export const MAX_DIMENSION = 1600;

// Качество JPEG. 0.82 против 80 у Flutter — шкалы разные (canvas берёт
// долю, image_picker — целые), на глаз это одна и та же ступень.
export const JPEG_QUALITY = 0.82;

// Предел НА ВХОД. Поднят с прежних 10 МБ: после пережатия исходный вес
// значения не имеет, а отказ на 12-мегабайтном снимке с хорошей камеры
// выглядел бы придиркой. 25 МБ отсекает уже не фотографии — RAW,
// многостраничные сканы, видео с подменённым расширением.
export const MAX_INPUT_BYTES = 25 * 1024 * 1024;

// Предел ПОСЛЕ пережатия. Нормальный кадр 1600px укладывается в
// 300–500 КБ, так что 2 МБ — не рабочий лимит, а сигнал «что-то пошло
// не так»: например, конвейер не сработал и файл проехал как есть.
// Совпадает с file_size_limit бакета avatars и вдвое меньше car-images
// (5 МБ) — серверный предел обязан быть с запасом, иначе граничный
// случай упирался бы в него раньше, чем в клиентскую проверку.
export const MAX_OUTPUT_BYTES = 2 * 1024 * 1024;

// Типы, которые принимаем от пользователя. HEIC/HEIF добавлены к
// прежней тройке: Safari их декодирует, а для остальных браузеров
// ниже предусмотрено объясняющее сообщение вместо глухого отказа.
//
// Пустая строка в списке НЕ случайна: Windows и часть Android-прошивок
// отдают для .heic пустой file.type (системного MIME для формата нет),
// и проверка по типу отбраковывала бы файл ещё до попытки декодирования.
// Такие файлы опознаются по расширению — см. isHeic.
export const ALLOWED_INPUT_TYPES = [
  'image/jpeg',
  'image/png',
  'image/webp',
  'image/heic',
  'image/heif',
];

// Значение для атрибута accept. image/* открывает диалог со всеми
// изображениями (иначе на Android часть галерей не покажет ничего),
// расширения дописаны для iOS: там .heic мимо image/* проходит не
// всегда.
export const ACCEPT_ATTR = 'image/*,.heic,.heif';

// Причина, по которой файл не принят. Строку сообщения выбирает
// вызывающий код через словарь i18n: модуль не знает про локали.
export type PrepareError =
  // Формат не картинка либо картинка неизвестного типа.
  | 'type'
  // Больше MAX_INPUT_BYTES ещё до обработки.
  | 'size'
  // HEIC в браузере без системного декодера (всё, кроме Safari).
  | 'heic'
  // Декодирование или кодирование сорвалось на неожиданном месте.
  | 'decode';

export class PhotoPrepareError extends Error {
  constructor(readonly reason: PrepareError) {
    super(reason);
    this.name = 'PhotoPrepareError';
  }
}

// HEIC опознаётся и по типу, и по расширению: см. комментарий к
// ALLOWED_INPUT_TYPES про пустой file.type.
function isHeic(file: File): boolean {
  const type = file.type.toLowerCase();
  if (type === 'image/heic' || type === 'image/heif') return true;
  return /\.(heic|heif)$/i.test(file.name);
}

// Файл вообще похож на фотографию? Пустой type допускается только для
// HEIC — там его отсутствие штатно.
function looksLikeImage(file: File): boolean {
  if (isHeic(file)) return true;
  return ALLOWED_INPUT_TYPES.includes(file.type.toLowerCase());
}

// ------------------------------------------------------------
// ПРОПОРЦИЯ ОБЛОЖКИ ВИТРИНЫ САЛОНА: КВАДРАТ.
// ------------------------------------------------------------
// Квадрат выбран не потому, что окно квадратное, а потому, что окон
// ДВА и они противоположны. Плитка делится по-разному в зависимости
// от ширины экрана (см. DealerShowcaseCard):
//
//   360px  — деление горизонтальное, обложка сверху: 328 × 159, 2.06:1
//   768px  — деление вертикальное, обложка слева:    243 × 302, 0.80:1
//   1280px — то же вертикальное:                     276 × 327, 0.84:1
//
// Между 2.06 и 0.80 середины нет: широкий кадр на десктопе обрезался
// бы до узкой вертикальной полосы, вертикальный на мобильном — до
// горизонтальной. Квадрат — единственная форма, которая теряет по
// краям примерно поровну в обе стороны, и ни одно из окон не
// вырезает из него полоску.
//
// ПРАКТИЧЕСКИЙ ВЫВОД ДЛЯ САЛОНА: снимать обложку нужно так, чтобы
// главное было В ЦЕНТРЕ кадра. Края срежутся на одном из экранов
// в любом случае — на широком сверху и снизу, на узком по бокам.
// Ровно об этом говорит подсказка в форме профиля.
//
// История значения: 8:3 (под вёрстку, где обложка занимала верхнюю
// половину), затем 9:4 (полосу ужали, окно стало выше), теперь
// квадрат — плитка делится по вертикали.
//
// Кадрируем ПРИ ЗАГРУЗКЕ, а не только через object-cover в разметке.
// Причина в том, что салон грузит что попало — чаще всего снимок
// шоурума с телефона, вертикальный. При обрезке только на показе
// владелец сохранял бы фотографию, видел её целиком в форме и лишь
// потом обнаруживал в каталоге узкую полосу из середины кадра.
// Обрезав сразу, мы показываем ему в превью ровно то, что увидит
// покупатель: сюрприза в выдаче не будет.
export const COVER_ASPECT = 1;

// Кадр внутри исходника: берём максимальный прямоугольник нужной
// пропорции и центрируем его. Что именно окажется лишним, зависит от
// того, чем исходник «длиннее» нужной формы.
function coverCrop(width: number, height: number, aspect: number) {
  if (width / height > aspect) {
    // Исходник шире рамки — режем по бокам, высота целиком.
    const w = Math.round(height * aspect);
    return { sx: Math.round((width - w) / 2), sy: 0, sw: w, sh: height };
  }
  // Исходник выше рамки — режем сверху и снизу, ширина целиком.
  const h = Math.round(width / aspect);
  return { sx: 0, sy: Math.round((height - h) / 2), sw: width, sh: h };
}

// ------------------------------------------------------------
// Новые размеры: длинная сторона к MAX_DIMENSION, пропорции целы.
// ------------------------------------------------------------
// Снимок МЕНЬШЕ предела не растягиваем — апскейл добавил бы вес, не
// добавив ни одной детали. Такие файлы всё равно проходят через canvas:
// ради EXIF-нормализации и приведения к JPEG.
function targetSize(width: number, height: number) {
  const longest = Math.max(width, height);
  if (longest <= MAX_DIMENSION) return { width, height };

  const scale = MAX_DIMENSION / longest;
  return {
    // round, а не floor: floor на нечётных размерах терял пиксель и
    // менял пропорцию на доли процента — при contain в галерее это
    // давало полоску подложки шириной в пиксель.
    width: Math.round(width * scale),
    height: Math.round(height * scale),
  };
}

// ------------------------------------------------------------
// Декодирование. Возвращает готовый к отрисовке битмап.
// ------------------------------------------------------------
async function decode(file: File): Promise<ImageBitmap> {
  try {
    // imageOrientation: 'from-image' — тот самый однократный EXIF-поворот.
    return await createImageBitmap(file, { imageOrientation: 'from-image' });
  } catch {
    // Сюда попадает HEIC в браузере без системного кодека — то есть
    // всё, кроме Safari. Отличаем его от прочих сбоев: пользователю
    // нужно не «не удалось обработать», а конкретное действие.
    if (isHeic(file)) throw new PhotoPrepareError('heic');
    throw new PhotoPrepareError('decode');
  }
}

// ------------------------------------------------------------
// Кодирование canvas → JPEG.
// ------------------------------------------------------------
// JPEG, а не WebP: приложение кладёт в бакет строго image/jpeg
// (fileOptions в cars_repository.dart), и расхождение форматов между
// двумя клиентами одного бакета ничего не даёт, кроме лишней ветки
// в любом будущем серверном обработчике.
//
// Прозрачность при этом теряется — для PNG-скриншота фон станет
// чёрным, поэтому холст предварительно заливается белым.
function encode(canvas: HTMLCanvasElement): Promise<Blob> {
  return new Promise((resolve, reject) => {
    canvas.toBlob(
      (blob) => {
        if (blob) resolve(blob);
        else reject(new PhotoPrepareError('decode'));
      },
      'image/jpeg',
      JPEG_QUALITY,
    );
  });
}

// ------------------------------------------------------------
// ГЛАВНАЯ ФУНКЦИЯ: файл с устройства → нормализованный JPEG.
// ------------------------------------------------------------
// Бросает PhotoPrepareError с полем reason — вызывающий код переводит
// его в текст на языке интерфейса.
//
// aspect — необязательное кадрирование под заданную пропорцию
// (COVER_ASPECT для обложки витрины). Без него поведение прежнее:
// пропорции исходника сохраняются, меняется только масштаб. Параметр
// добавлен последним и со значением по умолчанию, поэтому все
// существующие вызовы — аватар, логотип, фотографии объявления —
// продолжают работать без правок.
export async function preparePhoto(
  file: File,
  aspect?: number,
): Promise<File> {
  if (!looksLikeImage(file)) throw new PhotoPrepareError('type');
  if (file.size > MAX_INPUT_BYTES) throw new PhotoPrepareError('size');

  const bitmap = await decode(file);

  try {
    // Область исходника, которая попадёт в кадр. Без aspect — весь
    // снимок целиком, и дальше всё идёт как раньше.
    const crop = aspect
      ? coverCrop(bitmap.width, bitmap.height, aspect)
      : { sx: 0, sy: 0, sw: bitmap.width, sh: bitmap.height };

    // Размер считаем ОТ КАДРА, а не от исходника: у вертикального
    // снимка 3000×4000 длинная сторона принадлежит той части, которую
    // мы отрезаем, и масштабирование по ней дало бы обложку шириной
    // всего 1200px вместо 1600.
    const { width, height } = targetSize(crop.sw, crop.sh);

    const canvas = document.createElement('canvas');
    canvas.width = width;
    canvas.height = height;

    const ctx = canvas.getContext('2d');
    if (!ctx) throw new PhotoPrepareError('decode');

    // Белая подложка под прозрачность PNG: без неё JPEG получает
    // чёрный фон там, где был альфа-канал.
    ctx.fillStyle = '#ffffff';
    ctx.fillRect(0, 0, width, height);

    // Сглаживание высокого качества: уменьшение в 4 раза без него
    // даёт заметный алиасинг на решётке радиатора и на номерах.
    ctx.imageSmoothingEnabled = true;
    ctx.imageSmoothingQuality = 'high';
    ctx.drawImage(
      bitmap,
      crop.sx,
      crop.sy,
      crop.sw,
      crop.sh,
      0,
      0,
      width,
      height,
    );

    const blob = await encode(canvas);

    // Страховка, а не рабочая ветка: см. комментарий к MAX_OUTPUT_BYTES.
    if (blob.size > MAX_OUTPUT_BYTES) throw new PhotoPrepareError('size');

    // Имя приводим к .jpg — содержимое теперь JPEG независимо от того,
    // что было на входе. SellForm берёт расширение из имени файла,
    // и оставить там .heic значило бы положить в бакет JPEG под чужим
    // расширением.
    const base = file.name.replace(/\.[^.]+$/, '') || 'photo';

    return new File([blob], `${base}.jpg`, {
      type: 'image/jpeg',
      lastModified: Date.now(),
    });
  } finally {
    // Битмап держит декодированные пиксели вне кучи JS: для снимка
    // 6000×4000 это ~96 МБ. Без close() десять фотографий подряд
    // способны уронить вкладку на телефоне.
    bitmap.close();
  }
}
