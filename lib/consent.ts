// ============================================================
// RS AUTO — Согласие с политикой: локальная фиксация.
// ============================================================
// Зачем вообще хранить. Согласие принимается перед отправкой SMS —
// то есть при КАЖДОМ входе. Пока факт принятия жил в useState формы,
// продавец, подающий второе объявление, снова видел непринятый чекбокс
// и снова не мог нажать кнопку, хотя документы уже принял.
//
// Почему localStorage, а не таблица в БД: аккаунт создаётся самим
// входом по SMS, а согласие даётся ДО него — записывать его в базу
// пока некуда.
//
// Сравнение идёт по версии, а не по флагу: подняли текст политики —
// подняли POLICY_VERSION, и согласие запрашивается заново.
// ============================================================

// Версия принятой редакции. РЕЭКСПОРТ из lib/legal, а не собственная
// константа: раньше здесь стоял свой литерал, и правка текста политики
// поднимала версию в одном файле из двух — согласие продолжало
// считаться действующим для редакции, которой пользователь не видел.
// Теперь источник версии один — тот же файл, где лежит сам текст.
export { POLICY_VERSION } from './legal';
import { POLICY_VERSION } from './legal';

const KEY_PREFIX = 'policy_accepted_version';

// Ключ включает идентификатор пользователя, чтобы согласие одного
// человека не переносилось на другого на общем устройстве.
// До входа пользователь — 'guest'.
function key(userId?: string | null): string {
  return `${KEY_PREFIX}:${userId ? userId : 'guest'}`;
}

// Принята ли ТЕКУЩАЯ версия политики.
export function hasAcceptedPolicy(userId?: string | null): boolean {
  // Форма — Client Component, но рендерится и на сервере: без проверки
  // обращение к localStorage упало бы при серверном рендере.
  if (typeof window === 'undefined') return false;

  try {
    return localStorage.getItem(key(userId)) === POLICY_VERSION;
  } catch {
    // Приватный режим и запрет хранилища не должны ломать подачу:
    // не смогли прочитать — считаем, что согласия нет, и спросим.
    return false;
  }
}

// Зафиксировать согласие с текущей версией.
export function acceptPolicy(userId?: string | null): void {
  if (typeof window === 'undefined') return;

  try {
    localStorage.setItem(key(userId), POLICY_VERSION);
  } catch {
    // Не сохранилось — согласие просто спросят в следующий раз.
  }
}

// Перенести гостевое согласие на аккаунт после входа.
// Согласие даётся до создания аккаунта (под ключом 'guest'); после
// успешного входа копируем его на реальный uid, иначе тот же человек
// увидит непринятый чекбокс при следующей подаче.
//
// Гостевую запись НЕ удаляем. Она означает «на этом устройстве
// документы приняты» и нужна, когда сессии нет: пользователь вышел,
// сессия истекла или подача открыта до входа. Раньше запись стиралась,
// и в этих случаях чекбокс снова оказывался пустым, хотя тот же
// человек на том же устройстве политику уже принял.
export function migrateGuestConsent(userId: string): void {
  if (typeof window === 'undefined' || !userId) return;

  try {
    if (localStorage.getItem(key(null)) === POLICY_VERSION) {
      localStorage.setItem(key(userId), POLICY_VERSION);
    }
  } catch {
    // См. выше: отказ хранилища не критичен.
  }
}

// Принята ли политика на этом устройстве — под аккаунтом ИЛИ гостем.
// Форма подачи проставляет галочку по этому признаку: человек, уже
// принявший документы, не должен ставить её заново при каждом входе.
// Юридически это то же согласие: та же редакция (POLICY_VERSION),
// то же устройство, тот же человек.
export function hasAcceptedPolicyHere(userId?: string | null): boolean {
  return hasAcceptedPolicy(userId) || hasAcceptedPolicy(null);
}

// ============================================================
// СОГЛАСИЕ НА КУКИ — локальный флаг баннера.
// ============================================================
// ОТДЕЛЬНАЯ СУЩНОСТЬ, а не переиспользование ключа выше. Согласие с
// документами (POLICY_VERSION выше) даётся галочкой перед отправкой
// SMS и означает «принимаю условия и политику»; согласие на куки
// даётся кнопкой в баннере при первом заходе и означает «согласен с
// использованием куки». События разные, происходят в разное время и
// у разных людей: гость, ни разу не подававший объявление, даёт
// второе и никогда не даёт первое. Общий ключ скрыл бы баннер тому,
// кто его не видел, — и запись в журнале не появилась бы вовсе.
//
// СРАВНЕНИЕ ПО ВЕРСИИ, а не по булеву флагу. Хранится не «да», а
// строка версии: подняли POLICY_VERSION — баннер показывается снова
// всем, включая принявших прежнюю редакцию. Это и есть требование
// «если политика обновилась, спросить заново», и оно выполняется
// сравнением, а не отдельной проверкой.
//
// Ключ БЕЗ идентификатора пользователя — в отличие от ключа согласия с
// документами. Куки ставятся браузеру, а не аккаунту: они уже лежат на
// устройстве к моменту входа, и показывать баннер заново после
// авторизации значило бы спрашивать согласие на то, что уже произошло.
// ============================================================

const COOKIE_KEY = 'cookie_consent_version';

// ------------------------------------------------------------
// РЕШЕНИЕ ПОЛЬЗОВАТЕЛЯ, А НЕ ФАКТ ПОКАЗА БАННЕРА.
// ------------------------------------------------------------
// Раньше хранилась только версия принятой редакции, и это отвечало на
// один вопрос: «баннер уже закрывали?». Пока аналитика не требовала
// согласия (Plausible не ставит куки), большего и не требовалось.
//
// С подключением GA4 вопросов стало три, и ответы у них разные:
//   * решения ещё нет   — баннер показываем, GA4 НЕ грузим;
//   * согласие дано     — баннера нет, GA4 грузим;
//   * отказ             — баннера нет, GA4 НЕ грузим.
// Булев флаг третье состояние выразить не может: «нет согласия» у него
// неотличимо от «ещё не спрашивали», и отказавшийся видел бы баннер
// при каждом заходе.
//
// Поэтому в хранилище лежит строка «<версия>:<решение>». Версия
// сохраняет прежнее поведение — подняли POLICY_VERSION, и спрашиваем
// заново всех, включая отказавшихся: новая редакция документов это
// новый вопрос.
export type ConsentDecision = 'accepted' | 'rejected';

// Разбор сохранённого значения. Возвращает null, когда решения нет:
// записи не было, версия устарела или хранилище недоступно.
export function getCookieConsent(): ConsentDecision | null {
  // Баннер — Client Component, но рендерится и на сервере: без
  // проверки обращение к localStorage упало бы при серверном рендере.
  if (typeof window === 'undefined') return null;

  try {
    const raw = localStorage.getItem(COOKIE_KEY);
    if (!raw) return null;

    // СОВМЕСТИМОСТЬ С ПРЕЖНИМ ФОРМАТОМ. До этой правки хранилась голая
    // версия без решения — те, кто нажал «Хорошо» на старом баннере,
    // имеют в хранилище просто «1.0». Считаем это согласием: человек
    // нажал единственную кнопку, которая тогда означала принятие.
    // Иначе им всем пришлось бы отвечать заново без причины.
    if (raw === POLICY_VERSION) return 'accepted';

    const [version, decision] = raw.split(':');
    if (version !== POLICY_VERSION) return null;

    return decision === 'accepted' || decision === 'rejected'
      ? decision
      : null;
  } catch {
    // Приватный режим и запрет хранилища: прочитать не смогли —
    // считаем, что решения нет, и показываем баннер. Ошибиться в эту
    // сторону безопаснее: лишний показ раздражает, пропущенный показ
    // означает отсутствие согласия вовсе.
    return null;
  }
}

// Дано ли согласие на куки для ТЕКУЩЕЙ редакции документов.
// Именно этот признак решает, грузить ли GA4.
export function hasCookieConsent(): boolean {
  return getCookieConsent() === 'accepted';
}

// Ответил ли пользователь на вопрос баннера — неважно, как именно.
// Баннер скрывается по этому признаку, а не по согласию: отказавшийся
// не должен видеть плашку снова.
export function hasCookieDecision(): boolean {
  return getCookieConsent() !== null;
}

// Имя события, которым баннер сообщает о принятом решении.
//
// Нужно потому, что localStorage НЕ уведомляет вкладку о собственных
// изменениях: штатное событие storage приходит только в СОСЕДНИЕ
// вкладки. Без своего события слой GA4 в текущей вкладке узнал бы о
// согласии лишь при следующей загрузке страницы — то есть первый визит,
// ради которого аналитика и нужна, остался бы неучтённым.
export const CONSENT_CHANGE_EVENT = 'cookie-consent-change';

// Зафиксировать решение локально.
// Возвращает управление молча и при отказе хранилища: баннер обязан
// скрыться в любом случае — см. комментарий в CookieBanner.
export function setCookieConsent(decision: ConsentDecision): void {
  if (typeof window === 'undefined') return;

  try {
    localStorage.setItem(COOKIE_KEY, `${POLICY_VERSION}:${decision}`);
  } catch {
    // Не сохранилось — баннер появится в следующий визит. Запись в
    // журнале при этом уже есть: доказательство живёт на сервере, а
    // не здесь.
  }

  // Оповещаем текущую вкладку ДАЖЕ ЕСЛИ запись не удалась: слой GA4
  // ориентируется на hasCookieConsent(), и тот при недоступном
  // хранилище честно вернёт false — скрипт не подключится. Событие
  // здесь лишь повод перечитать состояние, а не источник истины.
  try {
    window.dispatchEvent(new Event(CONSENT_CHANGE_EVENT));
  } catch {
    // Совсем экзотический отказ окружения: молча, аналитика не повод
    // ронять интерфейс.
  }
}
