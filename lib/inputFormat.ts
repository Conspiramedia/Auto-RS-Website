// RS AUTO — Форматирование и валидация числового ввода.
// ============================================================
// ПЕРЕНОС ИЗ ПРИЛОЖЕНИЯ. Правила обязаны совпадать: продавец, подавший
// объявление в приложении и на сайте, должен вводить цену и телефон
// одинаково, а бэкенд получает одни и те же значения.
//
// Источники (D:\Project\Auto.RS):
//   lib/shared/utils/serbian_phone.dart      — SerbianPhoneFormatter,
//                                              serbianPhoneToE164,
//                                              serbianNationalDigits
//   lib/features/listings/screens/
//     create_car_screen.dart                 — _ThousandsFormatter
//
// Общий принцип из приложения: поле хранит и показывает ФОРМАТИРОВАННУЮ
// строку («12 500», «+381 60 123 4567»), а наружу отдаётся чистое число
// или E.164. Разделять эти два представления обязательно — иначе в БД
// уедет строка с пробелами.
// ============================================================

// ------------------------------------------------------------
// Числа с разделителем тысяч (цена, пробег, залог).
// ------------------------------------------------------------
// Перенос _ThousandsFormatter: оставляем только цифры и группируем по
// три справа налево.
//
// В приложении разделитель — обычный пробел (' '): поле рисует Flutter,
// и перенос строки внутри TextField невозможен в принципе. В браузере
// обычный пробел в узком поле переносится, и «12 500» рвётся на две
// строки, поэтому здесь стоит НЕРАЗРЫВНЫЙ пробел. Видимый результат
// тот же — группа из трёх цифр, отделённая пробелом.
export const GROUP_SEPARATOR = ' ';

// Лимиты задаются В ЦИФРАХ, а не в значении. Так работает и поле:
// восьмая цифра просто не появляется, и человек видит это в момент
// нажатия — в отличие от молчаливого приведения к максимуму.
//
// Границы намеренно щедрые — это защита от опечатки в десять знаков,
// а не бизнес-ограничение:
//   цена   — 7 цифр, до 9 999 999 € (дороже легкового не бывает);
//   пробег — 7 цифр, до 9 999 999 км;
//   залог  — та же граница, что у цены;
//   год    — ровно 4 цифры.
export const MAX_PRICE_DIGITS = 7;
export const MAX_MILEAGE_DIGITS = 7;
export const YEAR_DIGITS = 4;

// Те же границы значением — для проверок, где сравнивают число, а не
// длину строки. Выводятся из длины, чтобы два лимита не разъехались:
// 7 цифр это ровно 9 999 999.
export const MAX_PRICE = 10 ** MAX_PRICE_DIGITS - 1;
export const MAX_MILEAGE = 10 ** MAX_MILEAGE_DIGITS - 1;

// Единственное место, где задаётся, что считать цифрой. Вставка
// «12 500», «12.500», «12,500 €» и «12 500» с неразрывным пробелом из
// нашего же поля обязана давать одни и те же цифры — этого требует
// пункт про paste.
export function digitsOnly(raw: string): string {
  return raw.replace(/[^0-9]/g, '');
}

// Форматирование по мере ввода: «12500» → «12 500».
export function formatThousands(raw: string): string {
  const digits = digitsOnly(raw);
  if (digits === '') return '';

  // Ведущие нули убираем: «007» — это 7. Иначе продавец может
  // отправить «0500» и получить цену 500 при видимом «0 500».
  const normalized = digits.replace(/^0+(?=\d)/, '');

  let out = '';
  for (let i = 0; i < normalized.length; i += 1) {
    if (i > 0 && (normalized.length - i) % 3 === 0) out += GROUP_SEPARATOR;
    out += normalized[i];
  }
  return out;
}

// Обратное преобразование для отправки на сервер: «12 500» → 12500.
// Пустая строка даёт null, а не 0: ноль в цене БД прочитает как
// «отдаю бесплатно», а в пробеге — как «новая машина».
export function parseThousands(formatted: string): number | null {
  const digits = digitsOnly(formatted);
  if (digits === '') return null;
  return Number(digits);
}

// Ввод числа: вызывается прямо в onChange и возвращает готовую к показу
// строку. Ограничение — по КОЛИЧЕСТВУ ЦИФР, а не сравнением с числом:
// лишняя цифра просто не попадает в поле, и человек видит это в момент
// нажатия. Прежний вариант сравнивал результат с max и при превышении
// делил на 10 — то есть уже принятая цифра исчезала вместе с последней
// значащей, и «99999999» превращалось в «9 999 999» незаметно.
export function handleNumberInput(
  raw: string,
  maxDigits: number = MAX_PRICE_DIGITS,
): string {
  // Ведущие нули снимаем ДО обрезки по длине: иначе «0001234567»
  // израсходовало бы лимит на нули и потеряло бы хвост числа.
  const digits = digitsOnly(raw).replace(/^0+(?=\d)/, '');
  return formatThousands(digits.slice(0, maxDigits));
}

// ------------------------------------------------------------
// Позиция курсора при живом форматировании.
// ------------------------------------------------------------
// Приложение ставит курсор В КОНЕЦ строки на каждом изменении
// (TextSelection.collapsed в ThousandsFormatter) — там это приемлемо:
// правка середины суммы в мобильной форме редка. В браузере курсор
// прыгал бы в конец при любой правке — например при исправлении первой
// цифры в уже набранной сумме, — поэтому позицию мы восстанавливаем.
//
// Считаем не символы, а ЦИФРЫ слева от курсора: разделители добавляются
// и исчезают при каждом нажатии, и смещение в символах бессмысленно.
// «12 5|00» → слева три цифры → после переформатирования ставим курсор
// туда, где слева окажутся те же три цифры.
export function caretAfterFormat(
  formatted: string,
  digitsBeforeCaret: number,
): number {
  if (digitsBeforeCaret <= 0) return 0;

  let seen = 0;
  for (let i = 0; i < formatted.length; i += 1) {
    if (formatted[i] >= '0' && formatted[i] <= '9') {
      seen += 1;
      if (seen === digitsBeforeCaret) return i + 1;
    }
  }
  return formatted.length;
}

// Сколько цифр стоит левее курсора в исходной строке. Парная функция
// к caretAfterFormat: одна снимает позицию до правки, вторая
// восстанавливает её после.
export function digitsBefore(value: string, caret: number): number {
  return digitsOnly(value.slice(0, caret)).length;
}

// ------------------------------------------------------------
// Год выпуска.
// ------------------------------------------------------------
// Ровно четыре цифры и БЕЗ разделителя разрядов: «2019», а не «2 019».
// Год — не количество, а метка на шкале; группировать его разрядами
// незачем, и Intl.NumberFormat для года тоже не применяется (см.
// formatYear в lib/format.ts).
//
// Здесь сайт СОЗНАТЕЛЬНО расходится с приложением: там фильтр года
// собран тем же _numField с ThousandsFormatter, что и цена, и показывает
// «2 019». Это ошибка эталона, а не правило — форма подачи в приложении
// выбирает год списком и разделителя не рисует.
// Диапазон проверяется отдельно (validateYear): «19» в процессе набора
// — ещё не ошибка.
export function handleYearInput(raw: string): string {
  return digitsOnly(raw).slice(0, YEAR_DIGITS);
}

// Проверка года. Границы те же, что в constraint chk_year таблицы cars:
// от 1900 до следующего года включительно.
export function validateYear(
  value: string,
  min: number,
  max: number,
): boolean {
  if (value.length !== 4) return false;
  const year = Number(value);
  return year >= min && year <= max;
}

// ------------------------------------------------------------
// Сербский телефон. Полный перенос serbian_phone.dart.
// ------------------------------------------------------------
// Национальная часть без кода страны и ведущего нуля: «6XXXXXXXX».
// Отбрасываем 00381 / 381 / ведущий 0, оставляем максимум 9 цифр.
export function serbianNationalDigits(raw: string): string {
  let digits = digitsOnly(raw);

  if (digits.startsWith('00381')) {
    digits = digits.slice(5);
  } else if (digits.startsWith('381')) {
    digits = digits.slice(3);
  } else if (digits.startsWith('0')) {
    digits = digits.slice(1);
  }

  return digits.slice(0, 9);
}

// Стартовое значение поля телефона. Код страны стоит в поле СРАЗУ, а не
// подсказкой в placeholder: в Сербии он один на всех, и заставлять
// набирать его девять раз из десяти — лишняя работа. Пустое поле с
// подсказкой «+381 6X XXX XXX» вдобавок неоднозначно: часть людей
// набирает код страны сама, часть начинает с ведущего нуля.
//
// Экспортируется константой, потому что от неё зависят все три формы
// ввода телефона (вход, подача, заявка дилера) — расходиться им нельзя.
export const SERBIAN_PHONE_PREFIX = '+381 ';

// Маска ввода «+381 6X XXX XXX(X)»: пробелы после 2-й и 5-й цифры
// национальной части. Точная копия SerbianPhoneFormatter.
export function formatSerbianPhone(raw: string): string {
  const digits = serbianNationalDigits(raw);

  if (digits === '') {
    // Национальная часть пуста — оставляем в поле код страны, что бы
    // человек ни стирал. Раньше здесь возвращалась пустая строка (кроме
    // случая, когда набрано ровно «381»), и backspace на первой цифре
    // сносил префикс целиком: поле оказывалось пустым, а следующая
    // введённая цифра трактовалась как начало номера БЕЗ кода страны.
    return SERBIAN_PHONE_PREFIX;
  }

  let out = SERBIAN_PHONE_PREFIX;
  for (let i = 0; i < digits.length; i += 1) {
    if (i === 2 || i === 5) out += ' ';
    out += digits[i];
  }
  return out;
}

// Приведение к E.164 для Supabase Auth: «+3816XXXXXXXX».
// null — номер не похож на сербский мобильный. Требования из приложения:
// 8–9 цифр национальной части, первая цифра 6 (мобильные операторы).
export function serbianPhoneToE164(raw: string): string | null {
  const d = serbianNationalDigits(raw);
  if (d.length < 8 || d.length > 9) return null;
  if (!d.startsWith('6')) return null;
  return `+381${d}`;
}

// Валиден ли номер как сербский мобильный.
export function isValidSerbianPhone(raw: string): boolean {
  return serbianPhoneToE164(raw) !== null;
}
