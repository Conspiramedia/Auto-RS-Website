// ============================================================
// RS AUTO — Общие правила входа по SMS-коду.
// ============================================================
// Вход по OTP нужен в двух местах сайта, и они обязаны вести себя
// одинаково: подача объявления (components/SellForm.tsx) и вход в
// кабинет (components/AuthGate.tsx). Раньше логика жила внутри SellForm
// локальными функциями; с появлением кабинета копировать её во второй
// файл нельзя — тексты ошибок и правила разошлись бы при первой же
// правке.
//
// Здесь только то, что действительно общее: перевод ошибок Supabase на
// человеческий язык и задержка перед повторной отправкой. Разметка и
// состояние остаются в компонентах — они разные.
// ============================================================

import type { DictKey, Translate } from '@/lib/i18n';

// Задержка перед повторной отправкой кода, секунды. Значение из
// приложения (login_screen.dart): без таймера продавец выжжет суточную
// квоту в пять SMS за минуту.
export const RESEND_DELAY_SEC = 60;

// ------------------------------------------------------------
// Длина кода подтверждения.
// ------------------------------------------------------------
// SMS-код у провайдера всегда шестизначный — здесь ограничение жёсткое.
//
// Email-код выдаёт GoTrue, и его длина НАСТРАИВАЕТСЯ на стороне
// Supabase (допустимый диапазон — 6–10 цифр). Поле с maxLength={6}
// молча обрезало код длиннее шести: пользователь вставлял правильный
// код из письма, видел в поле шесть цифр и получал «неверный код» без
// объяснения причины. Поэтому для почты принимаем диапазон, а не одно
// число.
//
// Верхняя граница 8, а не 10: значения выше в настройках GoTrue не
// используются, а более широкое поле провоцирует опечатки. Если длину
// когда-нибудь поднимут выше — правится ровно эта константа.
//
// Ключи совпадают с состоянием mode в AuthGate ('phone' | 'email'),
// чтобы обращение было прямым OTP_LEN[mode], без промежуточной
// таблицы соответствия: лишний маппинг — лишнее место для расхождения.
export const OTP_LEN = {
  phone: { min: 6, max: 6 },
  email: { min: 6, max: 8 },
} as const;

// Готов ли код к отправке на проверку. Отдельная функция, а не
// сравнение длины прямо в разметке: правило «от min до max» зависит от
// канала, и держать его рядом с самими границами надёжнее, чем
// повторять условие в JSX.
export function isOtpComplete(code: string, mode: keyof typeof OTP_LEN) {
  const len = code.trim().length;
  return len >= OTP_LEN[mode].min && len <= OTP_LEN[mode].max;
}

// ------------------------------------------------------------
// Человеческий текст ошибки OTP.
// ------------------------------------------------------------
// Перенос _humanOtpError из приложения (login_screen.dart). Supabase
// отдаёт эти сообщения по-английски и техническим языком; показывать их
// продавцу нельзя ни на сербской, ни на русской версии сайта.
//
// Неизвестную ошибку возвращаем как есть: молча заменять её общей
// фразой хуже — пропадёт единственная подсказка о том, что случилось.
// ------------------------------------------------------------
// Текст произвольной ошибки Supabase.
// ------------------------------------------------------------
// ЗАЧЕМ ОТДЕЛЬНАЯ ФУНКЦИЯ. Клиент бросал ошибки как
// `new Error(err.message)`, и этого достаточно ровно до тех пор, пока
// message непустой. Но у ошибок Supabase он пустым БЫВАЕТ:
//   * PostgrestError при отказе на уровне прав или сети приходит с
//     заполненными code/details/hint и пустым message;
//   * StorageError при ответе без тела (413 от лимита бакета, 403 от
//     политики) несёт только statusCode.
// В этих случаях `new Error('')` давал Error с пустым текстом: в Alert
// продавцу — пустое место, в консоли — `{stage:'create', message:''}`,
// то есть отладочная запись, по которой нельзя понять вообще ничего.
// Ровно этот симптом и наблюдался при сохранении правки.
//
// Собираем текст из всех полей, какие есть, и только если не нашлось
// ни одного — отдаём явную заглушку с типом значения. Пустой строки
// эта функция не возвращает никогда: это её главное свойство, на него
// опираются и лог, и показ пользователю.
export function supabaseErrorText(e: unknown): string {
  if (e === null || e === undefined) return 'неизвестная ошибка (пусто)';

  if (typeof e === 'string') {
    return e.trim() || 'неизвестная ошибка (пустая строка)';
  }

  if (typeof e === 'object') {
    const err = e as Record<string, unknown>;
    const parts: string[] = [];

    // Порядок важен: message первым, потому что он единственный
    // пригоден для показа пользователю, остальное — уточнения.
    for (const key of ['message', 'details', 'hint', 'error'] as const) {
      const value = err[key];
      if (typeof value === 'string' && value.trim()) parts.push(value.trim());
    }

    // Код добавляем в скобках: '23514' или 'PGRST202' сами по себе
    // ничего не значат для продавца, но именно они делают сообщение
    // пригодным для разбора, когда человек присылает скриншот.
    const code = err.code ?? err.statusCode;
    if (typeof code === 'string' || typeof code === 'number') {
      const asText = String(code).trim();
      if (asText) parts.push(`(${asText})`);
    }

    if (parts.length > 0) return parts.join(' · ');

    // Error без message и без полей Supabase — берём имя класса, оно
    // хотя бы называет природу сбоя (TypeError, AbortError).
    if (e instanceof Error && e.name) return e.name;
  }

  return 'неизвестная ошибка';
}

export function humanOtpError(e: unknown, t: Translate): string {
  const raw = supabaseErrorText(e);
  const message = raw.toLowerCase();

  // ------------------------------------------------------------
  // Отказ по дублю объявления.
  // ------------------------------------------------------------
  // Гейт дублей (trg_cars_prevent_duplicate, миграция 0093) бросает
  // unique_violation, а PostgREST доносит его как code '23505'.
  //
  // ПОЧЕМУ ЭТА ВЕТКА ПЕРВАЯ. Без неё ошибка проваливалась в `return
  // raw` внизу, и сербский продавец получал РУССКИЙ текст из RPC
  // вместе с «(23505)» в скобках — причём на последнем шаге формы,
  // уже после загрузки фотографий и SMS. Это была самая дорогая
  // точка сценария и самое неудачное место для сырого текста.
  //
  // Проверяем и код, и подстроку: код приходит отдельным полем у
  // PostgrestError, но supabaseErrorText склеивает всё в одну строку,
  // и опираться только на неё нельзя — формат склейки может
  // измениться.
  const code = String(
    (typeof e === 'object' && e !== null
      ? ((e as Record<string, unknown>).code ?? '')
      : '') || '',
  );

  if (code === '23505' || message.includes('23505')) {
    return t('sell_err_duplicate');
  }

  // ------------------------------------------------------------
  // Отказ по контактным данным в описании.
  // ------------------------------------------------------------
  // Барьер f_has_contact_info (миграция 0135) бросает check_violation
  // с hint = 'contacts_in_description'. Именно по hint эту ветку и
  // отличаем: код 23514 у объявления означает ещё и цену, и год, и
  // залог, и подставлять им текст про телефоны было бы враньём.
  //
  // hint приходит отдельным полем PostgrestError, а supabaseErrorText
  // склеивает все поля в строку — проверяем оба места по той же
  // причине, что и у дубля выше: формат склейки может измениться.
  //
  // Форма до сервера обычно не доводит (contactGuard проверяет при
  // вводе), но клиент обходится, и текст отказа нужен человеческий
  // на обеих локалях, а не русская строка из базы с «(23514)».
  const hint = String(
    (typeof e === 'object' && e !== null
      ? ((e as Record<string, unknown>).hint ?? '')
      : '') || '',
  );

  if (
    hint === 'contacts_in_description' ||
    message.includes('contacts_in_description')
  ) {
    return t('sell_err_contacts');
  }

  // Остальные отказы того же барьера (миграция 0136): ссылки и
  // разметка, слишком короткое и слишком длинное описание. Различаем
  // их так же — по hint, а не по коду 23514.
  //
  // До сервера они доходят редко: форма проверяет то же самое при
  // вводе. Но клиент обходится, и тогда текст должен остаться
  // человеческим на обеих локалях.
  const DESCRIPTION_HINTS: Record<string, DictKey> = {
    links_in_description: 'sell_err_desc_links',
    markup_in_description: 'sell_err_desc_html',
    description_too_short: 'sell_err_desc_short',
    description_too_long: 'sell_err_desc_long',
  };

  for (const [needle, key] of Object.entries(DESCRIPTION_HINTS)) {
    if (hint === needle || message.includes(needle)) return t(key);
  }

  // ------------------------------------------------------------
  // Отказ по лимиту активных объявлений (миграции 0143/0144).
  // ------------------------------------------------------------
  // f_check_listing_limit бросает check_violation с
  // hint = 'listing_limit'. Различаем по hint по той же причине, что
  // и ветки выше: код 23514 у объявления означает ещё и цену, и год.
  //
  // ЧИСЛО ВЫНИМАЕМ ИЗ ТЕКСТА СЕРВЕРА. Лимит зависит от уровня
  // продавца, и знает его только база; спрашивать её вторым запросом
  // ради одной цифры в сообщении об ошибке — лишний поход туда же,
  // откуда ошибка только что пришла. Если разобрать не удалось,
  // показываем подсказку без числа: она остаётся верной и полезной,
  // а «лимит в NaN объявлений» был бы хуже отсутствия цифры.
  if (hint === 'listing_limit' || message.includes('listing_limit')) {
    const found = raw.match(/\d+/);
    const limitText = found
      ? t('tier_limit_reached').replace('{n}', found[0])
      : null;

    return [limitText, t('tier_limit_hint')].filter(Boolean).join(' ');
  }

  if (message.includes('expired')) return t('otp_err_expired');

  if (message.includes('invalid') || message.includes('incorrect')) {
    return t('otp_err_invalid');
  }

  // Серверный лимит Supabase на частоту отправки (отдельный от нашей
  // суточной квоты в rpc_check_otp_quota) — сообщаем как о лимите,
  // а не англоязычной ошибкой.
  if (message.includes('rate limit') || message.includes('too many')) {
    return t('otp_err_quota');
  }

  return raw;
}
