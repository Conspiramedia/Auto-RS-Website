// ============================================================
// RS AUTO — Правила подсветки активного раздела навигации.
// ============================================================
// ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Одно и то же правило «где мы находимся»
// применяется в трёх местах: вкладки кабинета (MyTabs), меню шапки
// (HeaderMenu) и ряд разделов на десктопе (SiteHeader). Пока правило
// было переписано в каждом из них своими словами, они разошлись:
// в меню '/my' подсвечивался на /my/listing/{id}/edit, а во вкладках
// того же кабинета — нет, хотя комментарий в меню утверждал, что
// правила совпадают. Здесь правило существует физически один раз.
//
// Локаль на вход НЕ подаётся: все функции ждут путь, с которого
// префикс уже снят через stripLocale. Иначе каждое сравнение пришлось
// бы дублировать для '/cars' и '/ru/cars'.
// ============================================================

// ------------------------------------------------------------
// Обычный раздел: точное совпадение или вложенный путь.
// ------------------------------------------------------------
// '/cars' обязан оставаться подсвеченным на странице марки
// '/cars/bmw' — это тот же раздел каталога. Проверка именно на
// `${linkPath}/`, а не на голый префикс строки: без слэша '/car'
// совпал бы с '/cars', то есть карточка объявления подсвечивала бы
// каталог.
export function isSectionActive(currentPath: string, linkPath: string): boolean {
  return currentPath === linkPath || currentPath.startsWith(`${linkPath}/`);
}

// ------------------------------------------------------------
// Раздел, чей адрес является началом адресов соседей.
// ------------------------------------------------------------
// Случай ровно один — '/my' в кабинете, но правило описано общо, раз
// уж оно вынесено в общий модуль.
//
// Ни одна из простых проверок здесь не годится:
//   * по префиксу — «Мои объявления» горели бы вместе с «Сообщениями»
//     на /my/messages: два активных пункта вместо ориентира дают
//     путаницу;
//   * по точному совпадению — на /my/listing/{id}/edit не
//     подсвечивался бы ни один пункт, хотя человек находится внутри
//     своих объявлений.
//
// Поэтому: точное совпадение ИЛИ вложенный путь, который не забрал
// себе никто из соседей. siblingPaths — адреса остальных пунктов той
// же группы; каждый из них подсвечивается сам по isSectionActive.
export function isParentSectionActive(
  currentPath: string,
  linkPath: string,
  siblingPaths: string[],
): boolean {
  if (currentPath === linkPath) return true;

  const ownedByOthers = siblingPaths.some(
    (other) => other !== linkPath && isSectionActive(currentPath, other),
  );

  return currentPath.startsWith(`${linkPath}/`) && !ownedByOthers;
}
