'use client';

// ============================================================
// RS AUTO — Каретка в поле телефона: только в конец номера.
// ============================================================
// ЧТО БЫЛО НЕ ТАК. В поле всегда стоит код страны «+381 » (см.
// SERBIAN_PHONE_PREFIX в lib/inputFormat.ts), а маска расставляет
// пробелы после 2-й и 5-й цифры. Тап ставит каретку туда, куда попал
// палец: в середину префикса, между «+3» и «81», на пробел-разделитель.
// Дальше происходит одно из двух, и оба варианта человек читает как
// поломку поля:
//
//   * набранная цифра уходит внутрь кода страны — «+3 815 60…»;
//   * backspace съедает часть префикса, и следующая цифра трактуется
//     как начало номера БЕЗ кода страны.
//
// Заметить причину невозможно: поле выглядит обычным, а результат
// зависит от того, на какой пиксель пришёлся палец.
//
// ЧТО ДЕЛАЕТ ХУК. Возвращает обработчики, которые после клика, тапа и
// получения фокуса ставят каретку В КОНЕЦ значения — туда, где
// продолжается набор. Выделение при этом схлопывается: диапазон
// «от и до» в поле с маской всё равно нельзя осмысленно заменить.
//
// ПОЧЕМУ НЕ ЗАПРЕТИТЬ ПЕРЕМЕЩЕНИЕ ВОВСЕ. Каретку двигают не только
// мышью: стрелки, Home/End, Shift+стрелки — обычные инструменты
// правки, и человек, исправляющий одну цифру в середине номера,
// вправе ими пользоваться. Хук трогает только клик, тап и фокус, то
// есть ровно те случаи, где позиция выбирается вслепую. Нажатия
// клавиш не перехватываются.
//
// ПОЧЕМУ requestAnimationFrame, А НЕ ПРЯМОЙ ВЫЗОВ. Браузер выставляет
// свою позицию каретки ПОСЛЕ обработчика mouseup/focus: установи мы
// её синхронно, он тут же перезапишет значение, и на мобильных
// поле повело бы себя по-разному в зависимости от скорости тапа.
// Кадр спустя поле уже своё отработало, и последнее слово за нами.
//
// ПОЧЕМУ ЭТО ХУК, А НЕ ПОВТОР В КАЖДОЙ ФОРМЕ. Полей с этой маской
// пять в четырёх файлах (профиль — два, подача, /dealers, заявка в
// кабинете). Скопированное поведение разошлось бы при первой правке,
// а разница здесь не косметическая: одно поле «съедает» цифры, другое
// нет, и понять, чем они отличаются, снаружи нельзя.
// ============================================================

import { useCallback, useRef } from 'react';
import type { FocusEvent, MouseEvent, TouchEvent } from 'react';

type PhoneCaretHandlers = {
  onFocus: (e: FocusEvent<HTMLInputElement>) => void;
  onClick: (e: MouseEvent<HTMLInputElement>) => void;
  onTouchEnd: (e: TouchEvent<HTMLInputElement>) => void;
};

export function usePhoneCaret(): PhoneCaretHandlers {
  // Кадр, запланированный прошлым событием. Клик по полю рождает и
  // focus, и click — без отмены мы поставили бы каретку дважды.
  const frameRef = useRef<number | null>(null);

  const moveToEnd = useCallback((input: HTMLInputElement) => {
    if (frameRef.current !== null) {
      cancelAnimationFrame(frameRef.current);
    }

    frameRef.current = requestAnimationFrame(() => {
      frameRef.current = null;

      // Поле могло исчезнуть, пока ждали кадр: форма перерисовалась,
      // шаг подачи сменился. Проверка дешевле, чем исключение в
      // обработчике, которое React покажет оверлеем поверх формы.
      if (!input.isConnected) return;

      const end = input.value.length;

      // setSelectionRange на input[type="tel"] разрешён; на других
      // типах (email, number) браузер бросает InvalidStateError, а
      // хук может быть однажды повешен и на такое поле. Молчаливый
      // отказ здесь честнее падения: каретка встанет как встала, но
      // форма продолжит работать.
      try {
        input.setSelectionRange(end, end);
      } catch {
        // Тип поля не поддерживает выделение — оставляем как есть.
      }
    });
  }, []);

  const onFocus = useCallback(
    (e: FocusEvent<HTMLInputElement>) => moveToEnd(e.currentTarget),
    [moveToEnd],
  );

  const onClick = useCallback(
    (e: MouseEvent<HTMLInputElement>) => moveToEnd(e.currentTarget),
    [moveToEnd],
  );

  // Тап на мобильном: click приходит и здесь, но с задержкой и не
  // всегда — на части браузеров экранная клавиатура успевает открыться
  // раньше, и человек видит каретку в середине префикса до того, как
  // мы её сдвинем. Отдельный обработчик убирает это мигание.
  const onTouchEnd = useCallback(
    (e: TouchEvent<HTMLInputElement>) => moveToEnd(e.currentTarget),
    [moveToEnd],
  );

  return { onFocus, onClick, onTouchEnd };
}
