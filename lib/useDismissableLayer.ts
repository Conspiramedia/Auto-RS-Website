'use client';

// ============================================================
// RS AUTO — Поведение закрываемого слоя: Escape, блокировка
// прокрутки и возврат фокуса на кнопку-открывашку.
// ============================================================
// Три слоя сайта (меню шапки, шторка фильтров, диалог выхода) вели
// себя по-разному: у меню и диалога прокрутка блокировалась, у шторки
// нет — палец прокручивал страницу под ней, и при закрытии человек
// оказывался в другом месте документа. Возврата фокуса не было нигде:
// закрыв слой с клавиатуры, пользователь терял место в странице и
// продолжал табуляцию с самого начала.
//
// Хук собирает всё в одном месте, потому что расхождение здесь —
// не косметика: каждый пункт закрыт стандартом доступности, и
// «забыли в одном из трёх» означает сломанный слой, а не мелкую
// непоследовательность.
//
// ЧТО ДЕЛАЕТ, пока слой открыт:
//   * Escape — закрывает (кроме случая, когда закрытие запрещено:
//     диалог выхода не даёт себя убрать, пока запрос в пути);
//   * прокрутка страницы под слоем заблокирована;
//   * при закрытии фокус возвращается на элемент, с которого слой
//     открыли.
//
// ЧЕГО НЕ ДЕЛАЕТ: не рисует подложку и не вешает клик по ней —
// разметка у слоёв разная (шторка снизу, меню справа, диалог по
// центру), и навязывать её из хука значило бы описывать вёрстку
// пропами. Клик по затемнению каждый слой ставит сам.
// ============================================================

import { useEffect, useRef } from 'react';

type Options = {
  // Слой открыт. Пока false, хук не делает ничего.
  open: boolean;
  // Закрыть слой. Вызывается по Escape.
  onClose: () => void;
  // Закрытие временно запрещено: диалог выхода не убирается, пока
  // идёт запрос — Escape в этот момент не должен ничего делать.
  locked?: boolean;
  // Гасить Escape, не давая ему всплыть дальше. Нужно вложенным
  // слоям: диалог выхода открыт ИЗ меню, у которого свой слушатель
  // на document, и без остановки одно нажатие закрыло бы оба.
  stopEscapePropagation?: boolean;
};

export function useDismissableLayer({
  open,
  onClose,
  locked = false,
  stopEscapePropagation = false,
}: Options) {
  // Элемент, которому вернём фокус. Запоминается в момент открытия:
  // это всегда кнопка, с которой слой вызвали.
  const opener = useRef<HTMLElement | null>(null);

  // Колбэк и флаг блокировки держим в ref, а не в зависимостях эффекта.
  // Иначе вызывающему пришлось бы оборачивать onClose в useCallback:
  // стрелка, написанная прямо в вызове, создаётся заново на каждый
  // рендер, эффект перезапускался бы, и запомненная открывашка
  // терялась бы вместе с ним.
  const onCloseRef = useRef(onClose);
  const lockedRef = useRef(locked);
  onCloseRef.current = onClose;
  lockedRef.current = locked;

  useEffect(() => {
    if (!open) return;

    // document.activeElement на момент открытия и есть открывашка.
    opener.current =
      document.activeElement instanceof HTMLElement
        ? document.activeElement
        : null;

    // Возвращаем исходное значение, а не пустую строку: страница
    // могла иметь собственный overflow, и затирать его нельзя.
    const previousOverflow = document.body.style.overflow;
    document.body.style.overflow = 'hidden';

    const onKey = (e: KeyboardEvent) => {
      if (e.key !== 'Escape') return;
      // Гасим ДО проверки блокировки: пока идёт запрос, Escape не
      // закрывает этот слой, но и родительскому доставаться не должен.
      if (stopEscapePropagation) e.stopPropagation();
      if (!lockedRef.current) onCloseRef.current();
    };

    // ФАЗА СЛУШАТЕЛЯ РЕШАЕТ ПОВЕДЕНИЕ ВЛОЖЕННЫХ СЛОЁВ, и по умолчанию
    // она обязана быть всплывающей (capture = false).
    //
    // Внутри шторки фильтров живёт ListPicker со своим Escape на
    // document: он закрывает список и гасит событие, чтобы шторка
    // осталась открытой. Работает это только потому, что оба
    // слушателя всплывающие, а ListPicker смонтирован глубже.
    // Поставь шторка capture — она закрылась бы ПЕРВОЙ, до того как
    // ListPicker успеет вызвать stopPropagation, и одно нажатие
    // сносило бы оба слоя вместе с заполненной формой.
    //
    // capture нужен ровно там, где слой обязан перехватить Escape
    // РАНЬШЕ родителя, — это диалог выхода, открытый из меню. Он и
    // просит его флагом stopEscapePropagation.
    const capture = stopEscapePropagation;
    document.addEventListener('keydown', onKey, capture);

    return () => {
      document.body.style.overflow = previousOverflow;
      document.removeEventListener('keydown', onKey, capture);

      // Фокус возвращаем, только если он остался внутри закрытого
      // слоя или потерялся на body. Если пользователь тем временем
      // сам перевёл фокус в другое место страницы — не отбираем.
      const active = document.activeElement;
      if (!active || active === document.body) opener.current?.focus();
    };
    // Зависит ТОЛЬКО от open: всё изменчивое читается через ref, и
    // эффект обязан отработать ровно дважды за жизнь слоя — на
    // открытии и на закрытии. Лишний перезапуск стёр бы запомненную
    // открывашку и вернул фокус не туда.
  }, [open, stopEscapePropagation]);
}
