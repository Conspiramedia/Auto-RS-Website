// ============================================================
// RS AUTO — Аналитика. Единая точка отправки событий.
// ============================================================
// ДВА ИНСТРУМЕНТА РЯДОМ, И РОЛИ У НИХ РАЗНЫЕ.
//
// Plausible — базовый счётчик. Не использует cookie и не собирает
// персональные данные: не строит профиль посетителя и не хранит
// идентификаторы между визитами. Из этого следует главное — согласия
// он не требует ни по GDPR, ни по сербскому Закону о защите личных
// данных: согласие нужно для хранения информации на устройстве
// пользователя, а его здесь нет. Поэтому Plausible работает ВСЕГДА,
// в том числе у отказавшегося от куки.
//
// GA4 — глубина: воронки, сегменты, источники трафика. Ставит куки,
// поэтому грузится ТОЛЬКО после явного согласия в баннере. Отказ
// означает, что по этому посетителю не будет GA4-данных, — базовые
// цифры при этом не теряются, их собирает Plausible.
//
// ОБА ПОДКЛЮЧАЮТСЯ ТОЛЬКО ПРИ ЗАДАННОЙ ПЕРЕМЕННОЙ ОКРУЖЕНИЯ. Нет
// домена Plausible или Measurement ID — соответствующего слоя нет
// вовсе, ни запроса, ни глобальной функции. Это нужно и для локальной
// разработки (не наливать в статистику заходы разработчика), и для
// деплоя: сайт выкатывается до того, как ключ добавлен в Vercel.
//
// ИМЕНА СОБЫТИЙ У ИНСТРУМЕНТОВ РАЗНЫЕ — см. GA4_EVENT_NAMES ниже.
// ============================================================

import { hasCookieConsent } from './consent';

// Домен, зарегистрированный в Plausible. Пустое значение = аналитика
// выключена. Задаётся в .env.local и в переменных Vercel.
export const PLAUSIBLE_DOMAIN =
  process.env.NEXT_PUBLIC_PLAUSIBLE_DOMAIN ?? '';

// Адрес скрипта. Вынесен в переменную на случай self-hosted установки:
// у Plausible это официально поддерживаемый сценарий, и менять его
// придётся ровно в одном месте.
export const PLAUSIBLE_SRC =
  process.env.NEXT_PUBLIC_PLAUSIBLE_SRC ??
  'https://plausible.io/js/script.js';

export const analyticsEnabled = PLAUSIBLE_DOMAIN !== '';

// ------------------------------------------------------------
// GA4. Measurement ID вида G-XXXXXXXXXX.
// ------------------------------------------------------------
// Пустое значение = слой GA4 выключен целиком: скрипт не подключается,
// события в него не уходят. Ключ живёт в переменных окружения и НЕ
// хардкодится в компонентах — ресурс GA4 может смениться, а правка
// тогда нужна в одном месте.
export const GA_MEASUREMENT_ID = process.env.NEXT_PUBLIC_GA_ID ?? '';

export const gaConfigured = GA_MEASUREMENT_ID !== '';

// ------------------------------------------------------------
// Перечень событий. Закрытый список — не строка.
// ------------------------------------------------------------
// Опечатка в имени события создаёт в Plausible новое «событие-призрак»,
// которое никто не заметит месяцами. Тип не даст этого сделать.
//
// События покрывают воронку продавца целиком (главная бизнес-цель
// сайта) и два второстепенных сценария — заявку салона и обращение
// в поддержку.
export type AnalyticsEvent =
  // Просмотр карточки объявления.
  | 'card_view'
  // Открыта форма подачи (/sell).
  | 'sell_start'
  // Отправлен SMS-код: продавец дошёл до подтверждения номера.
  | 'otp_sent'
  // Объявление создано и ушло на модерацию — целевое действие.
  | 'listing_submitted'
  // Заявка автосалона отправлена.
  | 'dealer_lead_submitted'
  // Обращение через форму обратной связи отправлено.
  | 'contact_submitted'
  // ---------- Воронка покупателя ----------
  // Нажата «Написать продавцу» на карточке. Событие ставится ДО
  // создания диалога и приходит от гостя тоже: клик по кнопке — и есть
  // намерение связаться, а уйдёт ли человек после этого на вход, само
  // по себе показатель. Свойство guest различает эти два случая.
  | 'seller_contact_click'
  // Нажата «Показать номер» на карточке. Парное к предыдущему: до него
  // площадка видела только переписку и не могла сказать, какой канал
  // покупатели выбирают на самом деле. Ставится в момент раскрытия
  // номера — дальше человек уходит в звонилку, и о самом звонке
  // браузер уже не сообщит. Свойство guest различает вошедшего и того,
  // кого кнопка отправила на вход.
  | 'seller_call_click'
  // Диалог создан: start_chat вернул чат, покупатель попал в переписку.
  // Отличается от предыдущего ровно на потери при входе — сравнение
  // двух чисел и показывает, сколько людей теряется на форме.
  | 'chat_started'
  // Вход выполнен: код подтверждён, сессия создана.
  | 'login_success'
  // Оставлена почта в листе ожидания приложения (/app). Показывает,
  // есть ли вообще спрос на приложение до того, как его выпустили.
  | 'app_waitlist_subscribed'
  // Применены фильтры каталога. Ставится на ОТПРАВКУ формы, а не на
  // изменение поля: человек выбирает марку, коробку и год одним
  // заходом, и событие на каждом поле дало бы десяток срабатываний
  // вместо одного поиска.
  | 'search_performed';

// ------------------------------------------------------------
// ИМЕНА ТЕХ ЖЕ СОБЫТИЙ В GA4.
// ------------------------------------------------------------
// Инструменты получают РАЗНЫЕ имена одного и того же события, и это
// сделано намеренно.
//
// В Plausible имена остаются историческими (card_view, listing_submitted
// и т.д.): там уже накоплена статистика, и переименование разорвало бы
// ряды — старое имя перестало бы пополняться, новое началось бы с нуля,
// а сравнить периоды стало бы невозможно.
//
// В GA4 события идут под именами, по которым размечаются цели в
// интерфейсе: view_car, submit_listing, dealer_application, login,
// contact_seller. Ресурс новый, история там пустая, и правильные имена
// стоит задать сразу.
//
// Отдельно про login: это РЕКОМЕНДОВАННОЕ имя GA4 (не произвольное) —
// платформа понимает его сама и показывает в готовых отчётах, поэтому
// переименовывать его во что-то своё было бы ошибкой.
//
// Событие без записи в этой таблице уходит в GA4 под собственным
// именем — Record<AnalyticsEvent, string> заставил бы перечислять все,
// включая те, для которых переименование не нужно.
const GA4_EVENT_NAMES: Partial<Record<AnalyticsEvent, string>> = {
  card_view: 'view_car',
  listing_submitted: 'submit_listing',
  dealer_lead_submitted: 'dealer_application',
  login_success: 'login',
  seller_contact_click: 'contact_seller',
  seller_call_click: 'call_seller',
};

// Свойства события. Plausible принимает только плоский объект из
// строк и чисел — вложенные структуры он молча отбросит.
type EventProps = Record<string, string | number | boolean>;

// Глобальные функции, которые объявляют скрипты аналитики: plausible —
// счётчик Plausible, gtag — GA4 (его ставит GoogleAnalytics из
// @next/third-parties).
declare global {
  interface Window {
    plausible?: (
      event: string,
      options?: { props?: EventProps; callback?: () => void },
    ) => void;
    gtag?: (
      command: 'event' | 'config' | 'consent',
      target: string,
      params?: Record<string, unknown>,
    ) => void;
  }
}

// ------------------------------------------------------------
// Отправка события.
// ------------------------------------------------------------
// Безопасна к вызову откуда угодно: на сервере, при выключенной
// аналитике и до загрузки скриптов — просто ничего не делает.
// Аналитика не должна быть способна уронить страницу, поэтому каждый
// вызов обёрнут в try/catch.
//
// СОБЫТИЕ УХОДИТ В ОБА ИНСТРУМЕНТА, но по разным правилам:
//   * Plausible — всегда, пока задан домен. Согласия не требует;
//   * GA4 — только при заданном Measurement ID И данном согласии.
// Проверки независимы: выключенный Plausible не мешает GA4 и наоборот.
export function trackEvent(
  event: AnalyticsEvent,
  props?: EventProps,
): void {
  // Единственная общая проверка: на сервере нет ни window, ни скриптов.
  // Так функцию можно звать из любого обработчика, не думая о том,
  // выполнится ли он при серверном рендере.
  if (typeof window === 'undefined') return;

  // ---------- Plausible ----------
  if (analyticsEnabled) {
    try {
      // Скрипт мог ещё не загрузиться (или быть заблокирован адблоком) —
      // тогда функции нет, и событие просто теряется. Ставить очередь
      // ради этого не стоит: статистика не бухгалтерия.
      window.plausible?.(event, props ? { props } : undefined);
    } catch {
      // Молча: ошибка аналитики не должна попадать ни в интерфейс,
      // ни в консоль пользователя.
    }
  }

  // ---------- GA4 ----------
  // Согласие проверяется ПРИ КАЖДОЙ отправке, а не один раз при
  // загрузке модуля. Человек отвечает на баннер посреди сессии, и
  // значение, прочитанное на старте, к этому моменту устарело бы:
  // события до ответа не ушли бы вовсе, даже после согласия.
  if (!gaConfigured || !hasCookieConsent()) return;

  try {
    // gtag появляется только после загрузки скрипта GA4. До неё (и при
    // блокировке адблоком) функции нет — событие теряется так же, как
    // у Plausible, и по той же причине очередь не заводим.
    window.gtag?.('event', GA4_EVENT_NAMES[event] ?? event, props);
  } catch {
    // Молча, см. выше.
  }
}
