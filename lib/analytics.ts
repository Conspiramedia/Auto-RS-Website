// ============================================================
// RS AUTO — Аналитика. Единая точка отправки событий.
// ============================================================
// ПОЧЕМУ PLAUSIBLE, А НЕ GA4.
// Plausible не использует cookie и не собирает персональные данные:
// он не строит профиль посетителя и не хранит идентификаторы между
// визитами. Из этого следует главное практическое обстоятельство —
// баннер согласия НЕ требуется ни по GDPR, ни по сербскому Закону о
// защите личных данных: согласие нужно для хранения информации на
// устройстве пользователя, а его здесь нет.
//
// GA4 потребовал бы cookie-баннера, а баннер — это минус к конверсии
// на каждом входе и лишний слой согласия поверх того, который у нас
// уже есть при подаче объявления.
//
// СКРИПТ ПОДКЛЮЧАЕТСЯ ТОЛЬКО КОГДА ЗАДАН ДОМЕН (env). Без переменной
// аналитики нет вовсе — ни запроса, ни глобальной функции. Это нужно
// для локальной разработки: наливать в статистику собственные заходы
// разработчика бессмысленно.
// ============================================================

// Домен, зарегистрированный в Plausible. Пустое значение = аналитика
// выключена. Задаётся в .env.local и в переменных Vercel.
export const PLAUSIBLE_DOMAIN =
  process.env.NEXT_PUBLIC_PLAUSIBLE_DOMAIN ?? '';

// Адрес скрипта. Вынесен в переменную на случай self-hosted установки:
// у Plausible это официально поддерживаемый сценарий, и менять его
// придётся ровно в одном месте.
export const PLAUSIBLE_SRC =
  process.env.NEXT_PUBLIC_PLAUSIBLE_SRC ??
  'https://plausible.io/js/script.js';

export const analyticsEnabled = PLAUSIBLE_DOMAIN !== '';

// ------------------------------------------------------------
// Перечень событий. Закрытый список — не строка.
// ------------------------------------------------------------
// Опечатка в имени события создаёт в Plausible новое «событие-призрак»,
// которое никто не заметит месяцами. Тип не даст этого сделать.
//
// События покрывают воронку продавца целиком (главная бизнес-цель
// сайта) и два второстепенных сценария — заявку салона и обращение
// в поддержку.
export type AnalyticsEvent =
  // Просмотр карточки объявления.
  | 'card_view'
  // Открыта форма подачи (/sell).
  | 'sell_start'
  // Отправлен SMS-код: продавец дошёл до подтверждения номера.
  | 'otp_sent'
  // Объявление создано и ушло на модерацию — целевое действие.
  | 'listing_submitted'
  // Заявка автосалона отправлена.
  | 'dealer_lead_submitted'
  // Обращение через форму обратной связи отправлено.
  | 'contact_submitted'
  // ---------- Воронка покупателя ----------
  // Нажата «Написать продавцу» на карточке. Событие ставится ДО
  // создания диалога и приходит от гостя тоже: клик по кнопке — и есть
  // намерение связаться, а уйдёт ли человек после этого на вход, само
  // по себе показатель. Свойство guest различает эти два случая.
  | 'seller_contact_click'
  // Диалог создан: start_chat вернул чат, покупатель попал в переписку.
  // Отличается от предыдущего ровно на потери при входе — сравнение
  // двух чисел и показывает, сколько людей теряется на форме.
  | 'chat_started'
  // Вход выполнен: код подтверждён, сессия создана.
  | 'login_success';

// Свойства события. Plausible принимает только плоский объект из
// строк и чисел — вложенные структуры он молча отбросит.
type EventProps = Record<string, string | number | boolean>;

// Глобальная функция, которую объявляет скрипт Plausible.
declare global {
  interface Window {
    plausible?: (
      event: string,
      options?: { props?: EventProps; callback?: () => void },
    ) => void;
  }
}

// ------------------------------------------------------------
// Отправка события.
// ------------------------------------------------------------
// Безопасна к вызову откуда угодно: на сервере, при выключенной
// аналитике и до загрузки скрипта — просто ничего не делает.
// Аналитика не должна быть способна уронить страницу, поэтому вызов
// целиком обёрнут в try/catch.
export function trackEvent(
  event: AnalyticsEvent,
  props?: EventProps,
): void {
  if (typeof window === 'undefined') return;
  if (!analyticsEnabled) return;

  try {
    // Скрипт мог ещё не загрузиться (или быть заблокирован адблоком) —
    // тогда функции нет, и событие просто теряется. Ставить очередь
    // ради этого не стоит: статистика не бухгалтерия.
    window.plausible?.(event, props ? { props } : undefined);
  } catch {
    // Молча: ошибка аналитики не должна попадать ни в интерфейс,
    // ни в консоль пользователя.
  }
}
