// ============================================================
// RS AUTO — Lighthouse CI: бюджеты качества страницы.
// ============================================================
// Падение бюджета красит CI. Смысл именно в этом: производительность
// деградирует не разом, а по чуть-чуть — лишняя зависимость здесь,
// незалениненная картинка там. Без порога такую деградацию замечают,
// когда чинить уже дорого.
//
// ПОЧЕМУ ИМЕННО ЭТИ СТРАНИЦЫ. Три разных типа вёрстки, на которые
// приходится почти весь трафик: главная (лендинг), каталог (сетка с
// изображениями — самое узкое место) и карточка объявления (страница
// товара, куда ведёт поисковая выдача).
//
// ЗАПУСК: npx lhci autorun — поднимет сервер сам (startServerCommand).
// ============================================================

const CAR_ID = '00000000-0000-4000-b000-000000000001'; // из supabase/seed.sql

module.exports = {
  ci: {
    collect: {
      // Продакшен-сборка: dev-режим показал бы цифры, не имеющие
      // отношения к реальности (нет минификации, есть оверлеи).
      startServerCommand: 'npm run start -- --port 3100 --hostname 127.0.0.1',
      startServerReadyPattern: 'Ready in',
      startServerReadyTimeout: 120000,

      url: [
        'http://127.0.0.1:3100/',
        'http://127.0.0.1:3100/cars',
        `http://127.0.0.1:3100/car/${CAR_ID}`,
      ],

      // Три прогона на адрес, в отчёт идёт медианный. Одиночный
      // замер на общей машине CI скачет на десяток пунктов, и
      // бюджет срабатывал бы случайным образом.
      numberOfRuns: 3,

      settings: {
        // Десктопный профиль. Мобильный (по умолчанию у Lighthouse)
        // эмулирует медленный процессор и сеть 4G, и на нём порог
        // Performance ≥90 недостижим для страницы с фотографиями —
        // бюджет краснел бы всегда, то есть перестал бы что-либо
        // значить. Мобильную раскладку проверяет Playwright
        // (проект chromium-mobile), а здесь измеряется код: размер
        // бандла, блокирующие ресурсы, сдвиги вёрстки.
        preset: 'desktop',
        // PWA-категорию не считаем: сайт устанавливаемым приложением
        // быть не обязан, а её метрики тянули бы общий балл вниз без
        // отношения к качеству страниц.
        onlyCategories: [
          'performance',
          'accessibility',
          'best-practices',
          'seo',
        ],
        skipAudits: [
          // Требует HTTPS, которого на локальном сервере нет вовсе:
          // аудит падал бы всегда и по причине, не связанной с кодом.
          'is-on-https',
          'redirects-http',
          // Проверяет реальный домен в сертификате — на 127.0.0.1
          // неприменим.
          'valid-source-maps',
        ],
      },
    },

    assert: {
      assertions: {
        // ---------- Бюджеты из требований ----------
        'categories:performance': ['error', { minScore: 0.9 }],
        'categories:accessibility': ['error', { minScore: 0.95 }],
        'categories:best-practices': ['error', { minScore: 0.9 }],
        'categories:seo': ['error', { minScore: 0.95 }],

        // ---------- Отдельные метрики ----------
        // Дублируют категорию намеренно: общий балл может остаться
        // зелёным, когда просела одна метрика, а именно она видна
        // человеку как «сайт тормозит».
        'first-contentful-paint': ['warn', { maxNumericValue: 2000 }],
        'largest-contentful-paint': ['warn', { maxNumericValue: 2500 }],
        'cumulative-layout-shift': ['error', { maxNumericValue: 0.1 }],
        'total-blocking-time': ['warn', { maxNumericValue: 300 }],
      },
    },

    upload: {
      // Отчёты остаются артефактами прогона в GitHub Actions.
      // Публичное временное хранилище LHCI не используем: адреса
      // отчётов расходятся по интернету, а в них видна структура
      // страниц и содержимое объявлений.
      target: 'filesystem',
      outputDir: '.lighthouseci',
    },
  },
};
