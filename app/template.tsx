'use client';

// ============================================================
// RS AUTO — Проявление страницы при смене маршрута.
// ============================================================
// template.tsx, а не layout.tsx, и в этом весь смысл файла: Next даёт
// шаблону НОВЫЙ ключ на каждый маршрут, то есть монтирует его заново
// при каждом переходе. Layout, напротив, переживает навигацию — его
// анимация проиграла бы ровно один раз, при первой загрузке сайта,
// и больше никогда.
//
// ЧТО ДЕЛАЕТ. При переходе между страницами содержимое проявляется за
// 150мс. Переход перестаёт быть подменой кадра: глазу дают понять,
// что показано новое, — особенно на страницах со схожей раскладкой
// (каталог марки → каталог модели), где иначе меняются только
// подписи и трудно заметить, что переход вообще состоялся.
//
// ------------------------------------------------------------
// ПЕРВАЯ ЗАГРУЗКА СТРАНИЦЫ НЕ АНИМИРУЕТСЯ. Это главное здесь.
// ------------------------------------------------------------
// Шаблон оборачивает страницу ЦЕЛИКОМ, а значит и её LCP-элемент —
// изображение героя на главной, фотографию объявления на карточке.
// Анимация с opacity: 0 в первом кадре означает, что браузер не
// считает элемент отрисованным, пока прозрачность не поднялась.
//
// Это не теория, а измеренное: с fade на первой загрузке LCP главной
// вырос с 932мс до 1098мс, причём крупнейшим элементом вместо
// картинки героя (536×335) Lighthouse начинал считать строку баннера
// о куках (262×20) — картинка просто выпадала из подсчёта, и метрика
// начинала описывать вообще не тот элемент.
//
// КЛАСС СТАВИТСЯ ТОЛЬКО В БРАУЗЕРЕ И ТОЛЬКО СО ВТОРОГО ПЕРЕХОДА.
// В отдаваемом сервером HTML его нет вовсе — ни на главной, ни на
// любой другой странице, — поэтому первая отрисовка идёт обычным
// порядком и LCP остаётся на своём элементе.
//
// ПОЧЕМУ НЕ МОДУЛЬНЫЙ ФЛАГ (let navigated = false на уровне файла).
// Так было в первой версии, и это ошибка: серверный процесс Next
// живёт долго и держит модули загруженными между запросами. Первый
// же посетитель выставлял флаг, и ВСЕ последующие получали HTML уже
// с классом анимации — то есть ровно то, чего файл призван избежать.
//
// Поэтому признак хранится там, где он и должен: в самой вкладке.
// sessionStorage переживает переход между страницами (в отличие от
// состояния компонента — шаблон перемонтируется каждой навигацией) и
// исчезает с закрытием вкладки, что и требуется: новый визит начнётся
// с непроанимированной первой страницы.
//
// ТОЛЬКО OPACITY. Ни сдвига, ни масштаба: страница целиком — самый
// крупный элемент на экране, и любое её движение читается как рывок
// вёрстки. Прозрачность геометрию не трогает, поэтому CLS ровно ноль.
//
// При prefers-reduced-motion анимация гасится общим правилом
// globals.css до 0.01мс, и страница появляется мгновенно.
//
// ВЛОЖЕННЫЕ template.tsx НЕ ЗАВОДЯТСЯ. Один файл в корне app/
// обслуживает обе локали: /ru лежит внутри того же дерева, и шаблон
// оборачивает его страницы наравне с сербскими.
// ============================================================

import { useEffect, useState } from 'react';

// Ключ признака «в этой вкладке уже был хотя бы один рендер шаблона».
const KEY = 'rs-navigated';

export default function Template({
  children,
}: {
  children: React.ReactNode;
}) {
  // Начальное значение — false ВСЕГДА, и на сервере, и в браузере:
  // иначе первый клиентский рендер разошёлся бы с серверным HTML и
  // React выдал бы ошибку гидратации.
  const [animate, setAnimate] = useState(false);

  useEffect(() => {
    // Приватный режим и заблокированное хранилище бросают исключение
    // на самом обращении к sessionStorage. Анимация перехода — не та
    // вещь, ради которой можно уронить страницу.
    try {
      if (sessionStorage.getItem(KEY)) {
        setAnimate(true);
      } else {
        sessionStorage.setItem(KEY, '1');
      }
    } catch {
      // Хранилище недоступно — анимации переходов не будет.
      // Функциональность страницы это не затрагивает.
    }
  }, []);

  // Обёртка — div без единого класса раскладки: он встаёт между
  // layout и страницей, и любые flex/grid здесь порвали бы вёрстку
  // каждой страницы сайта разом.
  return (
    <div className={animate ? 'animate-fade-in' : undefined}>{children}</div>
  );
}
