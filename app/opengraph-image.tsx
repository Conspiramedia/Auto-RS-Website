// ЗАЧЕМ. До этого динамическая OG-картинка была только у карточки
// объявления (app/car/[id]/opengraph-image.tsx). Всё остальное —
// главная, каталог, /sell, страницы марок и моделей, /dealers, FAQ —
// репостилось в мессенджеры вообще без превью: серый прямоугольник с
// голым адресом. Для площадки, которую пересылают ссылкой, это прямая
// потеря переходов.
//
// ПОЧЕМУ ФАЙЛ В КОРНЕ app/ И БОЛЬШЕ НИЧЕГО НЕ НУЖНО. Next наследует
// файловые роуты метаданных вниз по дереву: opengraph-image в корне
// автоматически подставляется КАЖДОЙ странице, у которой нет своей.
// Прописывать openGraph.images в layout не только лишнее, но и вредно —
// явный ключ images отключает автоподстановку файлового роута, и
// карточка объявления лишилась бы собственного превью (об этом же
// предупреждает комментарий в lib/seo.ts).
//
// ПОЧЕМУ ОДНА КАРТИНКА НА ДВЕ ЛОКАЛИ. Слоган здесь сербский: это
// основной рынок, а превью видит тот, кому ссылку переслали, — его
// язык нам неизвестен. Заводить /ru/opengraph-image ради перевода
// одной строки не стоит: марка и цифры в превью и так интернациональны.
//
// СТАТИЧНА. В отличие от карточки объявления, здесь нет обращений к
// базе, поэтому картинка генерируется один раз на сборке и дальше
// отдаётся из кэша.
// ============================================================

import { ImageResponse } from 'next/og';

import { brand } from '@/lib/brand';
import { getT } from '@/lib/i18n';

// Стандартный размер OG-превью, который ожидают соцсети.
export const size = { width: 1200, height: 630 };
export const contentType = 'image/png';
export const alt = `${brand.name} — automobili u Srbiji`;

export default function Image() {
  const t = getT('sr');

  return new ImageResponse(
    (
      <div
        style={{
          width: '100%',
          height: '100%',
          display: 'flex',
          flexDirection: 'column',
          justifyContent: 'center',
          // Фирменный синий во всю плашку: превью должно узнаваться
          // цветом раньше, чем прочитан текст. Логотип на сайте стоит
          // на белом, но белое превью в ленте мессенджера сливается с
          // фоном самого мессенджера.
          background: brand.colors.primary,
          padding: '0 80px',
        }}
      >
        {/* Логотип набран текстом, а не картинкой: PNG знака пришлось
            бы читать с диска и кодировать в data-URI, а Satori всё
            равно нарисовал бы его как изображение без прироста
            качества.
            Надпись ЦЕЛЬНАЯ и одноцветная — ровно как в
            components/ui/Logo.tsx (вариант full). Разбивать её на
            «RS» + «Auto» разных цветов нельзя: на сайте логотип
            выглядит иначе, и превью показывало бы другой бренд.
            Белый вместо брендового синего — по той же причине, что
            inverted в Logo: на синей плашке синий не читается. */}
        <div
          style={{
            display: 'flex',
            fontSize: 96,
            fontWeight: 700,
            color: '#FFFFFF',
          }}
        >
          {brand.name}
        </div>

        {/* Слоган — единственная строка, объясняющая, что это за сайт.
            Берётся из словаря, а не пишется здесь константой: он же
            стоит в подвале и в описании сайта. */}
        <div
          style={{
            display: 'flex',
            fontSize: 40,
            color: 'rgba(255,255,255,0.9)',
            marginTop: 24,
          }}
        >
          {t('site_tagline')}
        </div>

        {/* Зелёная черта под слоганом — тот же акцент, что у главного
            действия на сайте. Держит композицию: без неё нижняя треть
            плашки остаётся пустой. */}
        <div
          style={{
            display: 'flex',
            width: 160,
            height: 8,
            background: brand.colors.green,
            borderRadius: 999,
            marginTop: 40,
          }}
        />
      </div>
    ),
    size,
  );
}
