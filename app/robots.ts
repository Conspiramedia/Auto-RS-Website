// ============================================================
// RS AUTO — robots.txt. Генерируется на сервере.
// ============================================================
// Что закрыто от обхода и почему:
//   фильтрующие параметры — брендовые, ценовые, ГОДОВЫЕ и прочие сужения
//           выдачи. Они порождают комбинаторно много почти одинаковых
//           адресов; без запрета краулинговый бюджет уходит на них, а не
//           на карточки объявлений. Список параметров ниже повторяет
//           buildQuery (lib/searchParams) — источник этих адресов.
//   /my   — кабинет продавца (обе локали). Личные данные: свои
//           объявления, переписка, профиль. Индексировать нечего, а
//           обходить — значит тратить бюджет на страницы, которые для
//           краулера всё равно выглядят формой входа.
//
// ПОЧЕМУ НЕ /*?* ЦЕЛИКОМ. Раньше здесь стоял слепой запрет на любую
// строку запроса. Он решал задачу фильтров, но заодно закрывал
// ПАГИНАЦИЮ: и каталог (Pagination → buildQuery), и витрина салона
// (PagerLinks) адресуют страницы через ?page=N. То есть всё, кроме
// первой страницы каждой выдачи, было закрыто от обхода.
//
// Пока карточки целиком перечислены в sitemap.xml, дыры нет — краулер
// берёт их оттуда. Но карта сайта обрезается по лимиту в 50 000 URL
// (см. app/sitemap.ts), и с ростом базы обрезанный хвост остался бы
// вообще без входящих ссылок: в карте его нет, а долистать до него
// запрещено. Поэтому запрет сузили до конкретных фильтрующих
// параметров, а пагинацию открыли.
//
// ДУБЛЕЙ ЭТО НЕ СОЗДАЁТ. Страницы с фильтрами И страницы со второго
// номера отдают noindex — он проставляется в самих страницах
// (hasActiveFilters(filters) || page > 1). robots.txt здесь управляет
// только обходом: краулер проходит по ?page=N вглубь к карточкам, но
// саму листалку в индекс не берёт.
//
// ИСКЛЮЧЕНИЯ. Два адреса обязаны обходиться, и общее правило их не
// задевает:
//
//   /*opengraph-image* — картинки превью. Next добавляет к ним хеш
//     версии query-параметром (/opengraph-image?bb44468a…), и под общим
//     запретом Facebook и Twitter не забирали превью: обе сети сверяются
//     с robots.txt перед выборкой. Ссылка на сайт уходила в ленту
//     голым текстом.
//
//   /cars?q= — адрес внутреннего поиска. Он же стоит в SearchAction
//     (lib/seo, WebSite JSON-LD): Google обязан суметь его проверить,
//     иначе разметка поисковой строки бесполезна. Разрешён ТОЛЬКО
//     поисковый параметр — комбинации фильтров остаются закрытыми.
//
// ПОРЯДОК ПРАВИЛ. Google применяет самое длинное совпадение и на
// порядок не смотрит, но часть краулеров читает файл сверху вниз и
// останавливается на первом подходящем. Поэтому Allow идут ДО
// Disallow — так правило читается однозначно всеми.
//
// РОБОТ — ВТОРОЙ РУБЕЖ, А НЕ ЕДИНСТВЕННЫЙ. robots.txt лишь просит не
// обходить; запрет на индексацию даёт мета-тег noindex в layout кабинета
// (app/my/layout.tsx), а доступ к самим данным закрыт сессией и RLS.
// ============================================================

import type { MetadataRoute } from 'next';

import { siteBaseUrl } from '@/lib/supabase';

export default function robots(): MetadataRoute.Robots {
  return {
    rules: [
      {
        userAgent: '*',
        // Порядок значим для части краулеров (см. шапку файла):
        // сначала общее разрешение и точечные исключения, затем запреты.
        allow: [
          '/',
          // Превью для соцсетей: и корневая картинка, и динамические
          // картинки карточек (/car/{id}/opengraph-image).
          '/*opengraph-image*',
          // Цель SearchAction. Обе локали: русское зеркало несёт ту же
          // разметку со своим адресом поиска.
          '/cars?q=*',
          '/ru/cars?q=*',
        ],
        // Обе локали перечислены явно: русский кабинет живёт по адресу
        // с префиксом, и правило для /my его не покрывает.
        //
        // /admin — админ-комната. Зеркала /ru/admin у неё нет (раздел
        // одноязычный), поэтому строка одна. Гость получает там 404,
        // так что краулеру и без запрета ловить нечего, — но тратить
        // на неё бюджет обхода незачем, а сам факт запрета ничего не
        // выдаёт: адрес /admin предсказуем и так.
        // /login — страница входа. Мета-тег noindex на ней уже стоит
        // (app/login/page.tsx), но робот узнаёт о нём, только СКАЧАВ
        // страницу: запрет обхода экономит бюджет заранее. Форма кода
        // из письма содержимого для поиска не несёт вовсе, а ссылки на
        // неё стоят в шапке каждой страницы сайта — без этой строки
        // краулер добирается до неё с любого раздела.
        //
        // Обе локали перечислены явно по той же причине, что и /my:
        // правило для /login не покрывает /ru/login.
        // ФИЛЬТРУЮЩИЕ ПАРАМЕТРЫ. Список повторяет buildQuery
        // (lib/searchParams) — там и только там собираются эти адреса.
        // Заводя новый фильтр, добавьте его сюда: пропущенный параметр
        // молча вернёт комбинаторный обход, ради запрета которого
        // правило и существует.
        //
        // Шаблон '/*?*<имя>=' ловит параметр в любой позиции строки
        // запроса — и первым ('?brand=audi'), и после других
        // ('?page=2&brand=audi'). Поэтому связка «фильтр + номер
        // страницы» тоже остаётся закрытой, а открытой оказывается
        // ровно чистая пагинация вида '/cars?page=2'.
        //
        // 'q' в списке НЕТ намеренно: поисковый адрес разрешён выше
        // как цель SearchAction.
        disallow: [
          '/*?*type=',
          '/*?*brand=',
          '/*?*model=',
          '/*?*city=',
          '/*?*year_from=',
          '/*?*year_to=',
          '/*?*mileage_max=',
          '/*?*price_from=',
          '/*?*price_to=',
          '/*?*body=',
          '/*?*gearbox=',
          '/*?*fuel=',
          // Ступень объёма двигателя (0133) и показ битых машин
          // (0138). Оба параметра пишет buildQuery, и без них
          // комбинаторный обход возвращался бы ровно так, как
          // описано выше.
          '/*?*engine=',
          '/*?*damaged=',
          '/*?*sort=',
          '/my',
          '/my/',
          '/ru/my',
          '/ru/my/',
          '/admin',
          '/admin/',
          '/login',
          '/ru/login',
        ],
      },
    ],
    sitemap: `${siteBaseUrl}/sitemap.xml`,
    host: siteBaseUrl,
  };
}
