// ============================================================
// ТРИ СЛОЯ, И РЕШАЮЩИЙ — НЕ ЭТОТ:
//   1) proxy.ts — только локаль, ролями не занимается (документация
//      Next прямо запрещает использовать proxy как авторизацию:
//      он выполняется до рендера и его легко обойти при неверной
//      конфигурации matcher);
//   2) ЭТОТ ФАЙЛ — не рисует интерфейс тому, кто не админ;
//   3) is_admin() первой строкой в КАЖДОЙ админской RPC — вот это и
//      есть настоящая защита. Даже если слои 1–2 обойти целиком,
//      сервер не выполнит ни одного действия модерации.
//
// ПОЧЕМУ notFound(), А НЕ 403. 403 подтверждает: раздел существует, вы
// просто не в списке. 404 не подтверждает ничего — гость и обычный
// пользователь получают одинаковый ответ и неразличимы между собой.
// Разница нужна не против серьёзной атаки (адрес /admin предсказуем), а
// против перебора: страница, отвечающая «нет прав», приглашает искать
// учётные данные, страница, отвечающая «нет такой страницы», — нет.
//
// force-dynamic — обязателен: layout читает cookie сессии и вызывает
// RPC. Закэшированная разметка админки, отданная гостю, свела бы всю
// конструкцию на нет.
// ============================================================

import type { Metadata } from 'next';
import { notFound } from 'next/navigation';

import AdminShell from '@/components/admin/AdminShell';
import { getServerClient } from '@/lib/supabaseServer';

export const dynamic = 'force-dynamic';

export const metadata: Metadata = {
  title: 'Админка — RS Auto',
  // buildMetadata из lib/seo не используется намеренно: он проставляет
  // canonical и hreflang, а служебному разделу не нужно ни то, ни
  // другое — он не часть языкового графа сайта.
  robots: {
    index: false,
    follow: false,
    // nocache закрывает сохранённую копию, noimageindex — фотографии
    // объявлений, попадающие в карточки очереди. Без них раздел
    // остаётся вне выдачи, но содержимое может осесть в кэше.
    nocache: true,
    noimageindex: true,
  },
};

export default async function AdminLayout({
  children,
}: {
  children: React.ReactNode;
}) {
  const supabase = await getServerClient();

  // getUser(), а не getSession(): getSession читает cookie как есть, без
  // проверки подписи, то есть доверяет данным от клиента. Для решения
  // «пускать или нет» годится только сверенный с сервером ответ.
  const {
    data: { user },
  } = await supabase.auth.getUser();

  if (!user) notFound();

  // Роль спрашиваем у базы, а не у токена: is_admin() читает
  // profiles.is_admin, и снятие флага действует немедленно, не дожидаясь
  // истечения access-токена. С ролью в raw_app_meta_data уволенный
  // модератор сохранял бы доступ до конца жизни токена.
  const { data: isAdmin, error } = await supabase.rpc('admin_guard');

  // Ошибка RPC — это тоже «не пускать». Отдавать интерфейс, когда
  // проверка прав не отработала, нельзя ни при каких обстоятельствах:
  // на любой сбой отвечаем так же, как не-админу.
  if (error || isAdmin !== true) notFound();

  // Счётчик очереди для сайдбара. Читается здесь, а не в компоненте
  // навигации: layout серверный и уже держит клиента с сессией, а
  // сайдбару из-за подсветки активного пункта пришлось бы стать
  // клиентским обработчиком запроса.
  //
  // head: true + count: 'exact' — запрос только за числом, без строк:
  // цифра в бейдже не стоит того, чтобы тянуть объявления целиком.
  // Сбой счётчика не должен ронять раздел: показываем 0 и идём дальше,
  // очередь всё равно откроется по ссылке.
  const { count } = await supabase
    .from('cars')
    .select('id', { count: 'exact', head: true })
    .eq('status', 'moderation');

  return <AdminShell queueCount={count ?? 0}>{children}</AdminShell>;
}
