// ============================================================
// RS AUTO — Сьют: честная сортировка каталога «Сначала новые».
// ============================================================
// ЧТО ПРОВЕРЯЕТСЯ. Что подпись «Сначала новые» / «Najnovije» не врёт:
// объявление, поданное сегодня, видно в начале выдачи, а не на
// случайной позиции среди сотен.
//
// ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ ТЕСТ, А НЕ ПУНКТ В public.spec.ts. Там
// проверяется, что страница вообще открывается; здесь — ПОРЯДОК строк
// на ней. Это разные поломки: каталог может открываться идеально и при
// этом сортировать случайно — ровно так и было до миграции 0088.
//
// ------------------------------------------------------------
// ОТКУДА БЕРУТСЯ ДАННЫЕ
// ------------------------------------------------------------
// Из демо-объявлений миграции 0054: она создаёт 27 активных карточек с
// created_at = now() - i часов, i от 1 до 27. Три важных следствия,
// на которых стоит весь тест:
//   * их больше двадцати — требование «каталог с 20+ объявлениями»
//     выполняется без своей сеялки;
//   * все они моложе трёх дней, то есть целиком попадают в окно
//     свежести, которое ввела 0088;
//   * их возраст СТРОГО РАЗЛИЧЕН и известен заранее, поэтому
//     правильный порядок можно вычислить, а не угадать.
//
// СВОЕЙ СЕЯЛКИ НЕТ НАМЕРЕННО. Записать объявления из теста можно было
// бы только service-role-ключом: RLS не даёт анонимному клиенту
// вставлять чужие строки. Ключ пришлось бы завести в .env.test — то
// есть выдать тестам право писать в базу мимо всех политик ради
// одной проверки порядка. Данные, которые уже есть и уже пригодны,
// этого не стоят.
//
// ГРАНИЦА ОТВЕТСТВЕННОСТИ. Здесь проверяется, что ПОЛЬЗОВАТЕЛЬ ВИДИТ
// на странице. Сама формула — промо-блок, его лимит, порядок по
// boosted_until, поведение при shuffle_all — проверяется на настоящей
// базе в supabase/checks/0088_fresh_sort_test.sql. Дублировать её
// здесь через браузер значило бы проверять то же самое дороже и
// менее надёжно.
// ============================================================

import { expect, test } from '@playwright/test';

import { TEST_SUPABASE_URL } from '../env';

// Сколько верхних карточек считаем «топом». Пять — из формулировки
// задачи; это меньше первого экрана даже на 360px, где в две колонки
// помещается шесть карточек.
const TOP_N = 5;

// ------------------------------------------------------------
// Объявление, как его отдаёт RPC каталога.
// ------------------------------------------------------------
type CatalogRow = {
  id: string;
  created_at: string;
  is_promoted: boolean;
};

// ------------------------------------------------------------
// Выдача каталога напрямую из RPC — «эталон» для сверки с HTML.
// ------------------------------------------------------------
// Тест сравнивает то, что отрисовано на странице, с тем, что вернул
// сервер. Так поломка сразу делится надвое: разошлись — виноват
// фронтенд, совпали и оба неверны — виновата сортировка в SQL.
//
// Ключ берётся из окружения тестов (.env.test → локальный стек).
// Анонимного достаточно: search_cars_public гранчена anon, потому что
// каталог обязан читаться краулером.
async function fetchCatalogRows(
  request: import('@playwright/test').APIRequestContext,
  limit = 24,
): Promise<CatalogRow[] | null> {
  const anonKey = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;
  if (!anonKey) return null;

  const response = await request.post(
    `${TEST_SUPABASE_URL}/rest/v1/rpc/search_cars_public`,
    {
      headers: {
        apikey: anonKey,
        Authorization: `Bearer ${anonKey}`,
        'Content-Type': 'application/json',
      },
      data: {
        p_listing_type: 'sale',
        p_sort: 'fresh',
        p_offset: 0,
        p_limit: limit,
      },
      failOnStatusCode: false,
    },
  );

  if (!response.ok()) return null;

  return (await response.json()) as CatalogRow[];
}

test.describe('Каталог: сортировка «Сначала новые»', () => {
  // ------------------------------------------------------------
  // 1) Сервер отдаёт свежие объявления первыми.
  // ------------------------------------------------------------
  // Основная проверка формулы на реальных данных: внутри окна
  // свежести порядок обязан идти строго по убыванию created_at.
  // До 0088 здесь была перемешка по md5, и тест падал бы на второй
  // карточке.
  test('внутри окна свежести порядок строго по дате подачи', async ({
    request,
  }) => {
    const rows = await fetchCatalogRows(request);

    test.skip(
      rows === null,
      'Нет данных: локальный Supabase не поднят (npm run supabase:start)',
    );
    test.skip(
      rows!.length < 20,
      `В каталоге ${rows!.length} объявлений, нужно 20+. ` +
        'Примените демо-данные: supabase db reset',
    );

    // Промо-блок стоит выше окна свежести и живёт по своим правилам —
    // его карточки из проверки порядка по дате исключаем. Их лимит и
    // внутренний порядок проверяет SQL-тест.
    const fresh = rows!.filter((r) => !r.is_promoted);

    expect(
      fresh.length,
      'После отсева промо не осталось объявлений для проверки порядка',
    ).toBeGreaterThan(1);

    // Границу окна берём с запасом в час: демо-данные создаются
    // относительно момента применения миграции, а прогон идёт позже.
    const windowStart = Date.now() - (3 * 24 + 1) * 60 * 60 * 1000;

    const inWindow = fresh.filter(
      (r) => new Date(r.created_at).getTime() > windowStart,
    );

    expect(
      inWindow.length,
      'Ни одно объявление не попало в окно свежести — ' +
        'демо-данные слишком старые, нужен supabase db reset',
    ).toBeGreaterThan(1);

    // Объявления в окне обязаны идти подряд с начала выдачи: попади
    // между ними старое — окно свежести не работает.
    const positions = inWindow.map((r) => fresh.indexOf(r));
    expect(
      positions,
      'Свежие объявления идут не подряд — между ними попало старое',
    ).toEqual(positions.map((_, i) => i));

    // И строго по убыванию даты.
    for (let i = 1; i < inWindow.length; i += 1) {
      const prev = new Date(inWindow[i - 1].created_at).getTime();
      const curr = new Date(inWindow[i].created_at).getTime();

      expect(
        prev,
        `Объявление на позиции ${i} подано позже предыдущего: ` +
          `${inWindow[i].created_at} после ${inWindow[i - 1].created_at}. ` +
          'Сортировка «Сначала новые» не работает.',
      ).toBeGreaterThanOrEqual(curr);
    }
  });

  // ------------------------------------------------------------
  // 2) Самое новое объявление видно в топ-5 НА СТРАНИЦЕ.
  // ------------------------------------------------------------
  // Прямая формулировка задачи и то, ради чего всё делалось: продавец
  // подал машину и обязан увидеть её сразу, не листая каталог.
  //
  // Проверяем разметку, а не ответ RPC: между корректной выдачей и
  // тем, что видит человек, стоит рендер, и он тоже может переставить
  // карточки.
  test(`самое новое объявление — в топ-${TOP_N} каталога`, async ({
    page,
    request,
  }) => {
    const rows = await fetchCatalogRows(request);

    test.skip(
      rows === null,
      'Нет данных: локальный Supabase не поднят (npm run supabase:start)',
    );
    test.skip(
      rows!.length < 20,
      `В каталоге ${rows!.length} объявлений, нужно 20+. ` +
        'Примените демо-данные: supabase db reset',
    );

    // Самое новое объявление среди НЕ продвигаемых: промо стоит выше
    // по другой причине, и попади оно в проверку — тест подтверждал
    // бы работу промо-блока, а не окна свежести.
    const newest = rows!
      .filter((r) => !r.is_promoted)
      .reduce((best, row) =>
        new Date(row.created_at) > new Date(best.created_at) ? row : best,
      );

    await page.goto('/cars', { waitUntil: 'domcontentloaded' });
    await page.waitForLoadState('load');

    // Каталог отдаётся потоково: сервер присылает скелет, карточки
    // приходят после гидратации. Ждём первую ссылку на объявление,
    // а не фиксированную паузу.
    const cards = page.locator('a[href*="/car/"]');
    await expect(
      cards.first(),
      'Каталог не отрисовал ни одной карточки',
    ).toBeVisible();

    // Собираем идентификаторы в порядке отрисовки. Карточка —
    // ссылка на /car/{id}, других ссылок такого вида на странице нет.
    const hrefs = await cards.evaluateAll((nodes) =>
      nodes.map((n) => (n as HTMLAnchorElement).getAttribute('href') ?? ''),
    );

    const idsOnPage = hrefs
      .map((href) => href.match(/\/car\/([0-9a-f-]{36})/i)?.[1])
      .filter((id): id is string => Boolean(id));

    expect(
      idsOnPage.length,
      'На странице каталога не нашлось карточек объявлений',
    ).toBeGreaterThanOrEqual(TOP_N);

    const position = idsOnPage.indexOf(newest.id);

    expect(
      position,
      `Самое новое объявление (${newest.id}, подано ${newest.created_at}) ` +
        `не найдено на первой странице каталога вовсе.`,
    ).toBeGreaterThanOrEqual(0);

    expect(
      position,
      `Самое новое объявление на позиции ${position + 1}, ожидалось в ` +
        `первых ${TOP_N}. Подпись «Сначала новые» не соответствует выдаче.`,
    ).toBeLessThan(TOP_N);
  });

  // ------------------------------------------------------------
  // 3) Явная сортировка по цене не нарушена промо-блоком.
  // ------------------------------------------------------------
  // Правило было до 0088 и обязано было её пережить: человек попросил
  // «сначала дешёвые», и реклама поверх этого выглядит как обман.
  // Проверяется здесь, потому что менялся общий order by — сломать
  // соседний уровень правкой было легко.
  test('при сортировке по цене порядок строго по возрастанию', async ({
    page,
  }) => {
    const response = await page.goto('/cars?sort=price_asc', {
      waitUntil: 'domcontentloaded',
    });
    await page.waitForLoadState('load');

    const isErrorPage =
      (response?.status() ?? 500) >= 500 ||
      (await page.getByText('500', { exact: true }).count()) > 0;

    test.skip(
      isErrorPage,
      'Нет данных: локальный Supabase не поднят (npm run supabase:start)',
    );

    const cards = page.locator('a[href*="/car/"]');
    await expect(cards.first()).toBeVisible();

    // Цены берём из разметки карточек. Формат сербской локали
    // («12.500 €», неразрывные пробелы), поэтому оставляем только
    // цифры: разделители тысяч разные, а порядок величин один.
    const prices = await cards.evaluateAll((nodes) =>
      nodes.map((n) => {
        const text = n.textContent ?? '';
        const match = text.match(/(\d[\d.\s  ]*)\s*€/);
        return match ? Number(match[1].replace(/[^\d]/g, '')) : null;
      }),
    );

    const numeric = prices.filter((p): p is number => p !== null && p > 0);

    test.skip(
      numeric.length < 2,
      'В каталоге меньше двух карточек с ценой — проверять порядок не на чем',
    );

    for (let i = 1; i < numeric.length; i += 1) {
      expect(
        numeric[i],
        `Цена ${numeric[i]} € идёт после ${numeric[i - 1]} € — ` +
          'сортировка по возрастанию нарушена (промо поднялось поверх?)',
      ).toBeGreaterThanOrEqual(numeric[i - 1]);
    }
  });
});
